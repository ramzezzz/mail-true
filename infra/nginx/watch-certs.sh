#!/bin/sh
# ------------------------------------------------------------------
# Слежение за файлом сертификата для nginx.
#
# Монтируется в /docker-entrypoint.d/ штатного образа nginx: тот выполняет
# оттуда все *.sh перед запуском самого сервера. Скрипт уходит в фон и
# живёт рядом с nginx до конца контейнера.
#
# Зачем. Сертификат меняют трижды за жизнь сервера: при установке, при
# продлении Let's Encrypt и когда приносят свой (раздел «Сертификат» в
# панели). nginx читает файл при старте и сам об изменении не узнаёт — до
# сих пор это лечили командой `docker compose restart nginx` с хоста.
#
# Из панели такой команды не отдать: сокета Docker у сервера приложения
# нет и не будет — он равен правам root на всей машине. Поэтому nginx
# следит за файлом сам, а `nginx -s reload` подхватывает новый сертификат,
# не разрывая уже открытых соединений.
#
# Интервал в 10 секунд выбран из того, что замена сертификата — событие
# редкое и не срочное: лишний десяток секунд на старом сертификате никому
# не мешает, а проверка раз в секунду грела бы диск круглые сутки.
# ------------------------------------------------------------------
set -eu

CERT_WATCH_INTERVAL="${CERT_WATCH_INTERVAL:-10}"
case "$CERT_WATCH_INTERVAL" in
    ''|0|*[!0-9]*) exit 0 ;;
esac

(
    prev=''
    while true; do
        now=$(cat /certs/mail.crt /certs/mail.key 2>/dev/null | md5sum)
        if [ -n "$prev" ] && [ "$now" != "$prev" ]; then
            echo "Сертификат изменился — перечитываем (nginx -s reload)"
            nginx -s reload >/dev/null 2>&1 || true
        fi
        prev="$now"
        sleep "$CERT_WATCH_INTERVAL"
    done
) &
