--[[
  От чужого имени письмо не уйдёт — и подписано нашим ключом не будет.

  ------------------------------------------------------------------
  ЧТО БЫЛО
  ------------------------------------------------------------------
  Postfix проверяет право на адрес отправителя строкой
  `reject_sender_login_mismatch` (infra/postfix/conf/master.cf). Проверяет
  он ОДИН адрес — тот, что стоит в конверте SMTP (MAIL FROM). А получатель
  видит совсем другой: заголовок `From:` внутри письма. По нему же
  выбирается домен для подписи DKIM (`use_domain = "header"` в
  entrypoint.sh).

  Отсюда дыра, ради которой и написан этот файл. Вошедший ivanov@домен
  ставит `MAIL FROM: ivanov@домен` — проверка Postfix проходит, — а в самом
  письме пишет `From: director@домен`. Домены совпадают, поэтому штатная
  защита rspamd `allow_hdrfrom_mismatch` молчит, и письмо уходит
  ПОДПИСАННЫМ ключом d=домен. У получателя: SPF ok (ушло с нашего IP),
  DKIM valid, DMARC выровнен по заголовку From — три зелёные проверки на
  подделке, причём подлинность ей придал наш собственный сервер. Отличить
  такое письмо от настоящего технически невозможно.

  Проверка infra/test-sender-spoofing.sh этого не ловила: swaks с одним
  только `--from` ставит конверт и заголовок ОДИНАКОВЫМИ, то есть сам
  сценарий с расхождением там не исполнялся ни разу.

  ------------------------------------------------------------------
  ПОЧЕМУ СРАВНИВАЕМ С КОНВЕРТОМ, А НЕ СПРАШИВАЕМ БАЗУ
  ------------------------------------------------------------------
  Право на адрес — это «свой ящик плюс адреса алиасов, которые на него
  ведут» (infra/postfix/conf/pgsql/sender_login.cf.template). Спрашивать
  тот же список у базы отсюда означало бы второй источник правды: два
  места, отвечающих на один вопрос, однажды разойдутся — и разойдутся
  молча, в сторону «разрешить».

  Этого не нужно. Postfix уже отверг письмо, если конверт не принадлежит
  вошедшему. Значит адрес конверта ГАРАНТИРОВАННО входит в список
  разрешённых для этого логина. Потребовав, чтобы заголовок совпадал с
  конвертом, мы получаем то же самое право без единого запроса: заголовок
  тоже окажется разрешённым.

  Побочная выгода — выравнивание по DMARC: у писем, ушедших отсюда,
  конверт и заголовок совпадают всегда, то есть проверка выравнивания у
  получателя проходит по обоим путям.

  ------------------------------------------------------------------
  КОГО ПРАВИЛО НЕ КАСАЕТСЯ
  ------------------------------------------------------------------
  * Писем без аутентификации — то есть всей входящей почты из интернета.
    Там свой отправитель не при чём, и решают SPF/DKIM/DMARC.
  * Служебных писем самого сервера: автоответчик, уведомления,
    самопроверка. Они кладутся локально и SASL-логина не имеют.
  * Отправки от адреса своего алиаса: и веб-интерфейс, и почтовые
    программы ставят в конверт тот же адрес, что и в заголовок.

  Отказ — постоянный (5.7.1), а не временный: повтор ничего не изменит,
  и человеку надо прочитать причину, а не ждать. Текст объясняет, что
  именно поправить, и называет оба адреса.
]] --

local rspamd_logger = require 'rspamd_logger'

--[[
  Адрес письма в сравнимом виде.

  Регистр не значим (RFC 5321 оставляет локальную часть на усмотрение
  сервера, но Dovecot и наши карты сравнивают без учёта регистра —
  значит и здесь так же), пробелы по краям тоже.
]]
local function addr_of(list)
  if not list or not list[1] then
    return nil
  end
  local addr = list[1].addr
  if not addr or addr == '' then
    return nil
  end
  return addr:lower():gsub('^%s+', ''):gsub('%s+$', '')
end

rspamd_config.MT_SENDER_IDENTITY = {
  callback = function(task)
    -- Без аутентификации правило не применяется вовсе: см. разбор выше.
    local user = task:get_user()
    if not user then
      return false
    end

    local envelope = addr_of(task:get_from('smtp'))
    local header = addr_of(task:get_from('mime'))

    --[[
      Заголовка `From:` нет вовсе.

      Это не подделка, а сломанное письмо: без `From:` его отвергнет
      половина принимающих серверов. Здесь молчим — есть кому сказать об
      этом отдельно, и подменять один отказ другим незачем.
    ]]
    if not header then
      return false
    end

    --[[
      Конверта нет — письмо от нулевого отправителя (отчёт о доставке).
      Аутентифицированным такое не шлют, но если вдруг: сравнивать не с
      чем, а отвергать по «не с чем сравнить» неправильно.
    ]]
    if not envelope then
      return false
    end

    if envelope == header then
      return false
    end

    rspamd_logger.warnx(
      task,
      'отправка от чужого имени: логин %s, конверт %s, заголовок From %s',
      user,
      envelope,
      header
    )
    task:set_pre_result(
      'reject',
      'Поле «От кого» (' ..
        header ..
        ') не совпадает с адресом отправителя (' ..
        envelope ..
        '). Письмо от чужого имени сервер не отправит: укажите свой адрес или адрес своего псевдонима.',
      'sender_identity'
    )
    return true
  end,
  score = 0.0,
  description = 'Заголовок From у своего отправителя не совпадает с конвертом',
  group = 'policies',
}
