-- Миграция 0028: одноразовые адреса владельца ящика.
--
--   docker compose -f infra/docker-compose.yml exec -T postgres \
--     psql -v ON_ERROR_STOP=1 -U mailserver -d mailserver \
--     < infra/postgres/migrations/0028_disposable_aliases.sql
--
-- Скрипт идемпотентен (IF NOT EXISTS везде), повторное применение безвредно.
--
-- ------------------------------------------------------------------
-- ЧТО ЭТО И ЗАЧЕМ
-- ------------------------------------------------------------------
-- Человек регистрируется в магазине и не хочет отдавать основной адрес.
-- Он заводит `shop-2026@свой-домен`, письма приходят в его же ящик, а
-- когда адрес начинает получать спам — выключает его одним нажатием.
-- Основной адрес при этом не трогается вовсе, и по имени адреса видно,
-- КТО именно продал его спамерам.
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ ЭТО НЕ ВТОРАЯ ТАБЛИЦА АДРЕСОВ, А ПРИСТРОЙКА К virtual_aliases
-- ------------------------------------------------------------------
-- Соблазн завести свою таблицу `disposable_addresses(source, mailbox,
-- active)` велик и неверен: у Postfix уже есть КОНТРАКТ на адреса —
-- карта virtual_alias_maps, которая читает virtual_aliases напрямую
-- (infra/postfix/conf/pgsql/virtual_aliases.cf.template). Своя таблица
-- означала бы вторую карту в main.cf, второй порядок разбора и второе
-- место, где адрес может оказаться занят. А главное — два механизма
-- разошлись бы: проверка «адрес свободен» смотрела бы в одну таблицу,
-- а почта ходила бы по другой.
--
-- Поэтому сам адрес живёт там же, где все остальные, — в virtual_aliases,
-- строкой `shop-2026@mail.local -> ivanov@mail.local`. Postfix о новой
-- сущности не знает вовсе, менять его настройки не потребовалось ни на
-- строку, и одноразовый адрес работает ровно так же надёжно, как алиас,
-- заведённый администратором.
--
-- Здесь же лежит только то, чему в virtual_aliases места нет и быть не
-- должно: чей это адрес с точки зрения интерфейса, кому он выдан и когда
-- выключен. Ключ — сам alias_id, связь один-к-одному.
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ ПРИЗНАК «ОДНОРАЗОВЫЙ» — ЭТО НАЛИЧИЕ СТРОКИ ЗДЕСЬ
-- ------------------------------------------------------------------
-- Алиасы бывают двух пород: заведённые администратором (`support@` на
-- отдел) и заведённые владельцем ящика для себя. Путать их нельзя в обе
-- стороны: владелец ящика не должен уметь выключить служебный `support@`
-- только потому, что тот ведёт на его ящик, а администратор не должен
-- удивляться сотне адресов вида `shop-2026@` в общем списке.
--
-- Строка в этой таблице и есть та самая граница: раздел «Одноразовые
-- адреса» показывает и меняет ТОЛЬКО те алиасы, у которых она есть.
-- Алиас без строки для владельца ящика невидим и неприкосновенен.
--
-- ------------------------------------------------------------------
-- ЧТО ПРОИСХОДИТ ПРИ ВЫКЛЮЧЕНИИ
-- ------------------------------------------------------------------
-- Ничего сверх того, что уже умеет Postfix: снимается `active` у строки
-- virtual_aliases. Карта алиасов перестаёт отвечать по этому адресу,
-- карта ящиков про него не знает никогда, домен наш — и Postfix отвечает
-- отправителю на команде RCPT TO:
--
--   550 5.1.1 <shop-2026@mail.local>: Recipient address rejected:
--       User unknown in virtual mailbox table
--
-- Это ровно то, что нужно, и досталось бесплатно. Отказ ЧЕСТНЫЙ: почта
-- не пропадает молча, отправитель узнаёт сразу, а не ждёт ответа неделю.
-- И при этом отказ НИЧЕГО НЕ ВЫДАЁТ: он дословно совпадает с ответом на
-- адрес, которого не существовало никогда, — по нему нельзя отличить
-- «адрес был и выключен» от «адреса не было». Тихое удаление принятого
-- письма было бы хуже по обоим счётам сразу.
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ ВЫКЛЮЧЕННЫЙ АДРЕС ПРОДОЛЖАЕТ ЗАНИМАТЬ ИМЯ
-- ------------------------------------------------------------------
-- Строка остаётся в virtual_aliases с active = false, а не удаляется.
-- Так надо: освободить имя — значит позволить завести `shop-2026@` кому-то
-- другому, и почта, которую магазин ещё шлёт на старый адрес, попала бы
-- ЧУЖОМУ человеку. Выключенный адрес обязан оставаться занятым.
--
-- Отсюда же следует, что предел на число адресов (DISPOSABLE_ALIAS_LIMIT)
-- считает и выключенные тоже: иначе предела нет вовсе — выключил и заводи
-- следующий, а домен всё равно засоряется.

BEGIN;

CREATE TABLE IF NOT EXISTS disposable_aliases (
    -- Ключ и он же связь: одна строка на один алиас.
    -- ON DELETE CASCADE — чтобы удаление алиаса администратором не
    -- оставляло здесь висящую строку про несуществующий адрес.
    alias_id    INT PRIMARY KEY REFERENCES virtual_aliases(id) ON DELETE CASCADE,

    -- Чей это адрес. Дублирует destination алиаса намеренно: по нему идёт
    -- отбор списка, и он не должен зависеть от того, не переписал ли кто-то
    -- destination в обход раздела. Если эти два значения разойдутся,
    -- владельцем считается тот, кто здесь, а адрес показывается как
    -- испорченный — молча отдать чужой адрес нельзя.
    owner_email VARCHAR(320) NOT NULL,

    -- Кому выдан: «Магазин обуви», «форум по рыбалке». Личная пометка
    -- владельца ящика, чтобы через год понять, кто продал адрес.
    -- Администратору НЕ показывается: для разбора жалоб нужен маршрут
    -- (кто→куда), а не заметки человека о своей жизни.
    note        TEXT NOT NULL DEFAULT '',

    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- Когда выключен. NULL — работает. Хранится ради одной фразы в
    -- интерфейсе: «выключен 3 марта» отвечает на вопрос «я его точно
    -- выключил или забыл?» лучше, чем серый переключатель.
    disabled_at TIMESTAMPTZ
);

-- Список владельца: все его адреса, свежие сверху.
CREATE INDEX IF NOT EXISTS idx_disposable_owner
    ON disposable_aliases (owner_email, created_at DESC);

COMMIT;
