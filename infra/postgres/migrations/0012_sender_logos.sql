-- Миграция 0010: логотипы доменов вместо букв в кружках списка писем.
--
-- ------------------------------------------------------------------
-- ЧТО ДОБАВЛЯЕТСЯ
-- ------------------------------------------------------------------
-- Одна колонка в настройках ящика: показывать ли логотипы доменов
-- отправителей. Отдельной таблицы нет намеренно — это такая же настройка
-- ящика, как поведение после удаления письма, и живёт она ровно столько же.
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ ВЫКЛЮЧЕНО ПО УМОЛЧАНИЮ
-- ------------------------------------------------------------------
-- Включение означает, что СЕРВЕР начнёт ходить в интернет за картинками
-- доменов, с которых пришли письма конкретному человеку. Сами письма
-- никуда не уходят, браузер к чужим сайтам не обращается (иначе владелец
-- сайта узнавал бы, что его письмо сейчас читают, и с какого адреса), но
-- сам факт исходящих запросов — это решение человека, а не наше за него.
-- Поэтому 'false', и включается оно в настройках почты.
--
-- ------------------------------------------------------------------
-- ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ
-- ------------------------------------------------------------------
-- Таблицы КЭША логотипов (sender_logo_cache) здесь нет: её заводит сам код
-- при первом обращении (apps/api/src/logos/store.ts). Это кэш, а не данные:
-- его можно потерять целиком без последствий, он ничего не значит в отрыве
-- от сети, и в резервную копию настроек ему не место (install/backup.sh
-- исключает его содержимое из выгрузки отдельной строкой).
--
-- А вот РУЧНЫЕ решения администратора — данные, и таблица для них заводится
-- здесь: восстановить их неоткуда. Исходник картинки остался у того, кто её
-- загружал, а «этому домену логотипа не показывать» не выводится ниоткуда
-- вовсе. Потеря такой таблицы должна быть заметна, а не молча исправлена
-- кодом при следующем запуске.
--
-- Миграция идемпотентна (IF NOT EXISTS): каталог миграций монтируется
-- в docker-entrypoint-initdb.d и на уже поднятой базе применяется руками.

ALTER TABLE mail_user_settings
    ADD COLUMN IF NOT EXISTS sender_logos BOOLEAN NOT NULL DEFAULT false;

-- ------------------------------------------------------------------
-- Ручные логотипы доменов и запреты
-- ------------------------------------------------------------------
-- Порядок действия источников (apps/api/src/logos/overrides.ts):
--   1) blocked = true      — логотипа не будет ни при каких условиях;
--   2) image IS NOT NULL   — картинка администратора, сильнее найденной;
--   3) иначе               — то, что нашлось само (BIMI, значок сайта).
--
-- Запрет и картинка живут в одной строке, но НЕЗАВИСИМО: «выключить логотип
-- домену» и «убрать то, что я загрузил» — разные намерения, и одно не должно
-- отменять другое. Строка удаляется, когда не осталось ни того, ни другого.
CREATE TABLE IF NOT EXISTS sender_logo_overrides (
    domain      VARCHAR(255) PRIMARY KEY,
    -- Логотипа у домена не будет ни при каких источниках.
    blocked     BOOLEAN      NOT NULL DEFAULT false,
    mime        VARCHAR(64),
    image       BYTEA,
    width       INTEGER,
    height      INTEGER,
    -- Отпечаток картинки: попадает в адрес, поэтому кэш браузера не врёт.
    version     VARCHAR(32)  NOT NULL DEFAULT '',
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- Кто изменил: для списка в панели и для разбора «кто это поставил».
    updated_by  VARCHAR(255)
);
