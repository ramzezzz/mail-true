-- Миграция 0038: очередь строк, которые панель обязана убрать из infra/.env.
--
-- ------------------------------------------------------------------
-- ЧТО БЫЛО НЕ ТАК
-- ------------------------------------------------------------------
-- Настройка сервера живёт в двух местах: в базе (её пишет панель) и в
-- infra/.env (его правит человек с доступом по SSH — руками или
-- установщиком). База сильнее файла, поэтому «вернуть к умолчанию»
-- обязано убрать строку и из файла: иначе панель показывает умолчание, а
-- служба поднимается с прежним значением.
--
-- Строку убирает посредник (service-agent). Он бывает недоступен —
-- перезапускается, не настроен, сеть моргнула, — и тогда сброс оставался
-- сделанным наполовину: из базы значение ушло, в файле осталось.
--
-- Догоняли это при следующем ПЕРЕСОЗДАНИИ службы, и вот там был настоящий
-- дефект. Список «что убрать» собирался по признаку «значение сейчас
-- берётся из файла, а не из базы» — а под этот признак попадает не только
-- забытый след панели, но и ЛЮБАЯ настройка, которую человек прописал в
-- infra/.env своей рукой и панелью никогда не трогал.
--
-- То есть: администратор прописал при установке GEOIP_LOGIN_POLICY=allow
-- и список стран, полгода всё работало, а первое же нажатие «Пересоздать»
-- ради совершенно другой настройки молча стирало обе строки — и защита по
-- стране выключалась. Ни предупреждения, ни следа в панели: с её точки
-- зрения ничего не менялось, значение «и так было умолчанием».
--
-- ------------------------------------------------------------------
-- ЧТО ВМЕСТО
-- ------------------------------------------------------------------
-- Помним ровно то, что и надо помнить: КАКИЕ строки панель хотела убрать
-- и не смогла. Долг ставится при отказе посредника, гасится при успешной
-- уборке. Всё, чего в этом списке нет, панель не трогает — потому что
-- отличить «моё, забытое» от «чужого, написанного руками» по содержимому
-- файла невозможно, и гадать здесь нельзя.
CREATE TABLE IF NOT EXISTS server_settings_env_debt (
    -- Имя переменной — то же, что в infra/.env и в server_settings.
    key        VARCHAR(128) NOT NULL,
    -- Служба, чей .env-ключ убираем: у посредника список ключей свой у
    -- каждой службы, и убирать надо ровно там, где разрешено.
    service    VARCHAR(64)  NOT NULL,
    -- Когда долг возник. Нужен человеку в разборе «почему настройка
    -- вернулась к умолчанию только после перезапуска».
    queued_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (key, service)
);

COMMENT ON TABLE server_settings_env_debt IS
    'Строки infra/.env, которые панель сбросила в базе, но не смогла убрать из файла. '
    'Гасятся при ближайшем пересоздании службы. Пустая таблица — обычное состояние.';

/*
 * Самозапись в журнал миграций.
 *
 * Каталог миграций примонтирован в /docker-entrypoint-initdb.d, поэтому на
 * ПУСТОЙ базе этот файл выполняет сам Postgres при первичной инициализации.
 * Журнал об этом не знал: строку о себе писала только базовая схема, и
 * установщик, читая журнал, применял такие миграции ВТОРОЙ раз. Пока они
 * идемпотентны, это сходит с рук, но 0039 — уже DELETE по пользовательским
 * данным, а следующая такая миграция отработает дважды на каждом новом
 * сервере. Ровно от этого журнал и заведён (см. 0000_schema_migrations.sql).
 *
 * Контрольная сумма ставится 'initdb': настоящую сумму файла внутри SQL не
 * вычислить. Установщик такую строку узнаёт, повторно файл не применяет и
 * заменяет сумму на настоящую.
 */
DO $mt_journal$
BEGIN
    IF to_regclass('public.schema_migrations') IS NOT NULL THEN
        INSERT INTO schema_migrations (filename, version, name, checksum, applied_by)
        VALUES ('0038_env_unset_debt.sql', '0038', 'env_unset_debt', 'initdb', 'initdb')
        ON CONFLICT (filename) DO NOTHING;
    END IF;
END
$mt_journal$;
