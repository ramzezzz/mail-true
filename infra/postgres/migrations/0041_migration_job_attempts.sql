-- Счётчик сорвавшихся попыток у задания переноса почты.
--
-- ------------------------------------------------------------------
-- ЗАЧЕМ
-- ------------------------------------------------------------------
-- Работник переноса перестал завершать задание при неожиданном отказе:
-- «закончено» в SQL означает ещё и «пароли исходных ящиков больше не
-- нужны» (secret_enc = NULL), а секундный перерыв в работе базы не повод
-- уничтожать заново собранную выгрузку паролей сотен чужих ящиков.
--
-- Взамен подразумевалось, что безнадёжное задание упрётся в срок молчания
-- и его пометит брошенным сторож. На деле это невозможно: работник берёт
-- задание каждые десять секунд и тем же запросом обновляет отметку
-- «жив», поэтому «молчит дольше 48 часов» не наступает никогда. Задание с
-- детерминированным отказом подготовки (неверная строка подключения к
-- хранилищу состояния, отсутствующая таблица курсоров, права) крутилось
-- бы вечно: каждые десять секунд новая попытка, обращения к чужому
-- серверу, и пароли хранятся бессрочно. Выхода не было ни одного —
-- повтор для идущего задания запрещён, а «Остановить» только взводит
-- флаг, который читается уже после подготовки.
--
-- Столбец позволяет отличить «сорвалось разок» от «не получается вовсе»:
-- после нескольких подряд сорвавшихся попыток задание честно
-- завершается с ошибкой, и пароли стираются осознанно, а не по случайности.
ALTER TABLE mail_migration_jobs
    ADD COLUMN IF NOT EXISTS attempts INT NOT NULL DEFAULT 0;

COMMENT ON COLUMN mail_migration_jobs.attempts IS
    'Сколько раз подряд попытка выполнить задание срывалась неожиданной ошибкой. '
    'Обнуляется при удачном проходе; по достижении предела задание завершается.';

/*
 * Самозапись в журнал миграций.
 *
 * Каталог миграций примонтирован в /docker-entrypoint-initdb.d, поэтому на
 * ПУСТОЙ базе этот файл выполняет сам Postgres при первичной инициализации.
 * Без этой записи установщик применил бы миграцию второй раз (разбор — в
 * 0000_schema_migrations.sql). Контрольная сумма ставится 'initdb':
 * настоящую внутри SQL не вычислить, установщик такую строку узнаёт и
 * заменяет сумму на настоящую.
 */
DO $mt_journal$
BEGIN
    IF to_regclass('public.schema_migrations') IS NOT NULL THEN
        INSERT INTO schema_migrations (filename, version, name, checksum, applied_by)
        VALUES ('0041_migration_job_attempts.sql', '0041', 'migration_job_attempts', 'initdb', 'initdb')
        ON CONFLICT (filename) DO NOTHING;
    END IF;
END
$mt_journal$;
