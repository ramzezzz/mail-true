-- Миграция 0027: сохранённые поисковые запросы.
--
--   docker compose -f infra/docker-compose.yml exec -T postgres \
--     psql -v ON_ERROR_STOP=1 -U mailserver -d mailserver \
--     < infra/postgres/migrations/0027_saved_searches.sql
--
-- Скрипт идемпотентен (IF NOT EXISTS везде), повторное применение безвредно.
--
-- ------------------------------------------------------------------
-- ЧТО ЭТО И ЗАЧЕМ
-- ------------------------------------------------------------------
-- Один и тот же поиск человек повторяет неделями: «от Волковой с
-- вложением за этот год», «непрочитанные счета». Каждый раз он набирает
-- строку заново и каждый раз чуть иначе — и получает чуть другую выдачу,
-- не понимая почему. Здесь эта строка лежит под именем, а нажатие на имя
-- открывает ровно тот же поиск.
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ ЗДЕСЬ ЛЕЖИТ СТРОКА, А НЕ РАЗОБРАННЫЕ ПОЛЯ
-- ------------------------------------------------------------------
-- Соблазн разложить запрос по колонкам (from, subject, has_attachment,
-- since, before) велик и неверен. Язык запросов растёт: сегодня в нём нет
-- `больше:`, завтра появится `метка:`. Разложенный по колонкам запрос
-- потребовал бы миграции на каждый новый оператор, а старые сохранённые
-- запросы после такой миграции значили бы уже не то, что человек сохранял.
--
-- Строка же значит ровно то, что человек видел в поисковой строке, и
-- разбирается тем же самым разборщиком (packages/shared/src/search.ts),
-- что и живой ввод. Побочная выгода: сохранённый запрос можно показать
-- человеку целиком, и он его узнает.
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ ЭТО НЕ ПАПКА
-- ------------------------------------------------------------------
-- В Thunderbird сохранённый поиск выглядит папкой, и это сбивает: в такую
-- «папку» нельзя переложить письмо, её нельзя очистить, а письмо из неё
-- лежит совсем не там, где показано. Здесь сохранённый запрос — отдельная
-- сущность и в интерфейсе показан отдельной группой со значком лупы, а не
-- значком папки. Ничего «папочного» с ним сделать нельзя, и потому нечему
-- обмануть ожидание.
CREATE TABLE IF NOT EXISTS mail_saved_searches (
    id            BIGSERIAL    PRIMARY KEY,
    account_email VARCHAR(320) NOT NULL,

    -- Имя, которое человек дал запросу: «Счета от Волковой».
    name          VARCHAR(64)  NOT NULL,

    -- Сама строка поиска со всеми операторами, как её набрали.
    -- Предел тот же, что у параметра `search` в API (500 символов):
    -- сохранить нельзя то, что нельзя выполнить.
    query         VARCHAR(500) NOT NULL,

    -- Искать ли в Спаме и Корзине. Единственное, что НЕ выражается
    -- строкой запроса: это не условие отбора писем, а выбор области,
    -- куда поиск вообще заглядывает (в фоне эти папки не индексируются,
    -- см. docs/search.md).
    include_junk  BOOLEAN      NOT NULL DEFAULT FALSE,

    -- Порядок показа в левой колонке.
    position      INT          NOT NULL DEFAULT 0,

    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Имя уникально в пределах ящика и без учёта регистра: два «Счета» и
-- «счета» в одном списке человек различить не сможет, а нажимать будет
-- наугад. Проверка в базе, а не только в коде, — потому что повтор
-- запроса при обрыве связи прошёл бы мимо проверки в коде.
CREATE UNIQUE INDEX IF NOT EXISTS mail_saved_searches_name_idx
    ON mail_saved_searches (lower(account_email), lower(name));

-- Список запросов одного ящика в порядке показа.
CREATE INDEX IF NOT EXISTS mail_saved_searches_account_idx
    ON mail_saved_searches (lower(account_email), position, id);
