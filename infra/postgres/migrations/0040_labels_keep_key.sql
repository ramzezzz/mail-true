-- Ключ удалённой метки остаётся занятым.
--
-- Удаление метки БЕЗ снятия её с писем (purge=0) — законный путь: он
-- обещает, что пометка на письмах останется, просто станет безымянной.
-- Но ключ при этом освобождался, и следующая метка с тем же (или
-- созвучным) именем получала его снова: `mt-scheta` выдавался повторно, а
-- «Счета» и «Счёта» дают один и тот же ключ. Новая метка мгновенно
-- оказывалась на всех письмах, помеченных прежней, — человек их так не
-- помечал.
--
-- Поэтому строка теперь не исчезает, а помечается удалённой: из
-- справочника метка уходит, ключ остаётся занятым. Полное удаление
-- (purge=1) по-прежнему стирает строку — слов на письмах больше нет, и
-- ключ можно выдавать заново.
ALTER TABLE mail_labels ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMPTZ;

-- Отбор живых меток идёт по этому условию, и он же самый частый.
CREATE INDEX IF NOT EXISTS mail_labels_live_idx
    ON mail_labels (lower(account_email), position)
    WHERE deleted_at IS NULL;
