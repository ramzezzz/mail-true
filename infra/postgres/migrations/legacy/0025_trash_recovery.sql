-- Миграция 0025: «восстановление после очистки корзины».
--
--   docker compose -f infra/docker-compose.yml exec -T postgres \
--     psql -v ON_ERROR_STOP=1 -U mailserver -d mailserver \
--     < infra/postgres/migrations/0025_trash_recovery.sql
--
-- Скрипт идемпотентен (IF NOT EXISTS везде), повторное применение безвредно.
--
-- ------------------------------------------------------------------
-- ЧТО МЕНЯЕТСЯ В ПОВЕДЕНИИ
-- ------------------------------------------------------------------
-- Раньше «Очистить корзину» звало IMAP EXPUNGE, и письма исчезали с диска
-- в ту же секунду. Восстановить их было нельзя ничем, кроме резервной
-- копии всего сервера, — а её у владельца ящика нет и быть не может.
--
-- Теперь очистка НЕ УДАЛЯЕТ, а переносит письма в служебную папку
-- «Recovery» и заводит здесь запись со сроком. Настоящее удаление делает
-- работник сервера, когда срок вышел. У Fastmail на это семь дней, у нас
-- столько же по умолчанию и настраивается человеком (0 — не хранить
-- вовсе, то есть прежнее поведение).
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ ПАПКА В ЯЩИКЕ, А НЕ ХРАНИЛИЩЕ СБОКУ
-- ------------------------------------------------------------------
-- Соблазн — сложить удалённое куда-нибудь рядом с Maildir, чтобы оно не
-- ело квоту. Это была бы ложь дважды:
--
--   1. Место на диске сервера не бесконечно, а «сбоку» его не считает
--      никто: квота ящика перестала бы что-либо значить, и ящик с квотой
--      в гигабайт занимал бы на диске сколько угодно.
--   2. Из ящика письмо ушло бы «в никуда» — ни один почтовый клиент его
--      бы не увидел, и восстановление работало бы только через наш
--      веб-интерфейс. Почта у нас никогда так не устроена: всё, что
--      мы делаем с письмом, видно любой почтовой программе.
--
-- Поэтому письма остаются в ящике, обычной папкой IMAP, и ЧЕСТНО ЕДЯТ
-- КВОТУ. Раздел настроек говорит об этом первой же строкой и показывает
-- занятый объём: человек, у которого кончается место, должен понимать,
-- что часть его занята уже выброшенным, и уметь освободить это одним
-- нажатием.
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ ПИСЬМО ОПОЗНАЁТСЯ ДВУМЯ СПОСОБАМИ СРАЗУ
-- ------------------------------------------------------------------
-- Ровно по той же причине, что и отложенное письмо (см. 0015): пара
-- (UIDVALIDITY, UID) точна, но живёт до пересоздания папки, а Message-ID
-- к папке не привязан. Сверка идёт сперва по UID, при несовпадении
-- UIDVALIDITY — поиском по Message-ID. Не нашлось ни так, ни так —
-- письма в «Recovery» больше нет (человек убрал его почтовой программой),
-- и запись молча закрывается состоянием 'gone'.
CREATE TABLE IF NOT EXISTS trash_recovery_items (
    id                   BIGSERIAL    PRIMARY KEY,
    account_email        VARCHAR(320) NOT NULL,

    -- Где письмо лежит СЕЙЧАС. Путь хранится явно: имя служебной папки
    -- в IMAP может отличаться от нашего умолчания (ящик мог приехать
    -- с чужого сервера).
    recovery_path        TEXT         NOT NULL,
    recovery_uid         BIGINT       NOT NULL,
    recovery_uidvalidity BIGINT       NOT NULL DEFAULT 0,

    -- Куда вернуть. Путь IMAP, а не наш идентификатор папки — по той же
    -- причине, что у отложенных писем. Обычно это «Trash»: человек
    -- восстанавливает в корзину, а уже оттуда решает, куда положить.
    origin_path          TEXT         NOT NULL,

    -- Запасной ключ поиска, см. пояснение выше. Пусто — письмо пришло
    -- без Message-ID; тогда остаётся только UID.
    message_id           TEXT,

    -- Только ради строки списка: показать, что именно можно вернуть,
    -- не открывая каждое письмо по IMAP.
    subject              TEXT         NOT NULL DEFAULT '',
    from_address         TEXT         NOT NULL DEFAULT '',
    sent_at              TIMESTAMPTZ,
    -- Размер письма. Нужен, чтобы честно показать, сколько квоты занято
    -- уже выброшенным.
    size_bytes           BIGINT       NOT NULL DEFAULT 0,

    -- Когда человек очистил корзину и когда письмо исчезнет по-настоящему.
    -- Срок считается ОДИН РАЗ, при очистке, по действовавшей тогда
    -- настройке: уменьшив срок с семи дней до одного, человек не должен
    -- задним числом потерять то, что уже лежит.
    deleted_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    purge_at             TIMESTAMPTZ  NOT NULL,

    -- 'pending'  — лежит и ждёт (единственное живое состояние);
    -- 'restored' — человек вернул письмо;
    -- 'purged'   — срок вышел, письмо удалено по-настоящему;
    -- 'gone'     — письма в «Recovery» больше нет (убрали мимо нас).
    state                VARCHAR(16)  NOT NULL DEFAULT 'pending',

    -- Сколько раз удаление срывалось. Не повод сдаться: срыв — это почти
    -- всегда недоступный Dovecot, и он проходит сам.
    attempts             INT          NOT NULL DEFAULT 0,
    last_error           TEXT,

    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    closed_at            TIMESTAMPTZ
);

-- Главный запрос работника: «кому пора». Частичный индекс по состоянию:
-- закрытых записей со временем станет на порядки больше живых.
CREATE INDEX IF NOT EXISTS trash_recovery_due_idx
    ON trash_recovery_items (purge_at)
    WHERE state = 'pending';

-- Список «что можно вернуть» одного человека: свежее сверху.
CREATE INDEX IF NOT EXISTS trash_recovery_account_idx
    ON trash_recovery_items (lower(account_email), deleted_at DESC, id DESC)
    WHERE state = 'pending';

-- Одно письмо — одна живая запись. Без этого повтор очистки при обрыве
-- связи заводил бы вторую запись на то же письмо, и вторая после
-- удаления первой искала бы письмо, которого уже нет.
CREATE UNIQUE INDEX IF NOT EXISTS trash_recovery_live_key
    ON trash_recovery_items (lower(account_email), recovery_path, recovery_uidvalidity, recovery_uid)
    WHERE state = 'pending';

-- ------------------------------------------------------------------
-- СРОК ХРАНЕНИЯ — НАСТРОЙКА ЯЩИКА, А НЕ СЕРВЕРА
-- ------------------------------------------------------------------
-- Место в ящике — это место ЧЕЛОВЕКА, и распоряжаться им должен он.
-- Кому-то нужен запас на неделю, кому-то ящик забит под завязку и любой
-- запас лишний. Поэтому срок лежит рядом с остальными настройками ящика,
-- а не в переменной окружения; сервер задаёт только потолок
-- (TRASH_RECOVERY_MAX_DAYS), чтобы никто не заказал хранение на год.
--
-- Значение по умолчанию — 7, как у Fastmail. Ноль означает «не хранить»:
-- очистка снова удаляет сразу, ровно как до появления возможности.
ALTER TABLE mail_user_settings
    ADD COLUMN IF NOT EXISTS trash_recovery_days INT NOT NULL DEFAULT 7;
