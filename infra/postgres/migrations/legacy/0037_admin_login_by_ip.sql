-- Миграция 0037: подбор пароля к панели считается по АДРЕСУ, а не по учётке.
--
-- ------------------------------------------------------------------
-- ЧТО БЫЛО НЕ ТАК
-- ------------------------------------------------------------------
-- Счётчик неудачных входов висел на учётной записи: пять промахов подряд —
-- и вход закрыт на пятнадцать минут. Кому закрыт, при этом не различалось:
-- закрыт ВСЕМ, включая настоящего администратора за соседним столом.
--
-- Из этого следует простая вещь, которую замечает всякий, кто про неё
-- подумает: зная логин (а он «admin» на каждой второй установке), чужой
-- человек держит администратора запертым бесконечно — пять неверных
-- паролей раз в пятнадцать минут. Защита от подбора превращается в
-- кнопку «выключить админу доступ», и нажимать её может кто угодно из
-- интернета.
--
-- ------------------------------------------------------------------
-- ЧТО ВМЕСТО
-- ------------------------------------------------------------------
-- Считаем промахи по паре «учётная запись + адрес». Перебирающий запирает
-- САМ СЕБЯ: его адрес перестают слушать, а администратор со своего места
-- входит как ни в чём не бывало.
--
-- Распределённый подбор (когда адресов много) этим не ловится — для него
-- остаётся счётчик на учётной записи, но с порогом заметно выше и с одной
-- оговоркой: адреса, с которых недавно входили УСПЕШНО, под эту блокировку
-- не попадают. Иначе распределённый подбор снова становится способом
-- запереть администратора, только подороже.
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ АДРЕС — text, А НЕ inet
-- ------------------------------------------------------------------
-- Адрес сюда приходит от Fastify (request.ip) и уже нормализован им.
-- Тип inet дал бы проверку формата и красивые операции над сетями, но
-- потребовал бы разбирать «::ffff:192.168.1.5» и пустые значения в SQL:
-- на пути входа в панель это лишний повод для отказа там, где отказывать
-- нельзя. Сравнение здесь всегда точное, диапазоны не нужны.
--
-- Скрипт идемпотентен, повторное применение безвредно.

BEGIN;

-- ------------------------------------------------------------------
-- Промахи по паре «учётка + адрес»
-- ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS admin_login_failures (
    -- Логин строкой, а не ссылкой на admin_users: перебирают и
    -- несуществующие имена, и такие попытки тоже надо считать — иначе
    -- перебор логинов ничем не ограничен.
    login        text        NOT NULL,
    ip           text        NOT NULL,

    attempts     integer     NOT NULL DEFAULT 0,
    /** Пока не наступило — с этого адреса вход в эту учётку не принимается. */
    locked_until timestamptz,
    first_at     timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),

    PRIMARY KEY (login, ip)
);

COMMENT ON TABLE admin_login_failures IS
    'Неудачные входы в панель по паре «учётная запись + адрес». Блокируется адрес, а не учётка.';

-- Уборка старого: строки живут не вечно, а таблицу читают на каждом входе.
CREATE INDEX IF NOT EXISTS idx_admin_login_failures_updated
    ON admin_login_failures (updated_at);

-- ------------------------------------------------------------------
-- Адреса, с которых успешно входили
-- ------------------------------------------------------------------
-- Нужны ровно для одного: не запирать своих при распределённом подборе.
-- Здесь нет ничего, чего не было бы в журнале аудита, — но журнал
-- обрезается по объёму, а этот список нужен ровно в момент отказа.
CREATE TABLE IF NOT EXISTS admin_known_ips (
    admin_id     integer     NOT NULL REFERENCES admin_users(id) ON DELETE CASCADE,
    ip           text        NOT NULL,
    last_success timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (admin_id, ip)
);

COMMENT ON TABLE admin_known_ips IS
    'Адреса, с которых администратор успешно входил. Им не мешает блокировка учётной записи.';

CREATE INDEX IF NOT EXISTS idx_admin_known_ips_seen
    ON admin_known_ips (last_success DESC);

COMMIT;
