-- Миграция 0016: отмена отправки («Письмо отправлено · Отменить»).
--
-- ------------------------------------------------------------------
-- ЧТО ДОБАВЛЯЕТСЯ
-- ------------------------------------------------------------------
-- Одна колонка в настройках ящика: сколько секунд письмо ждёт на сервере,
-- прежде чем уйти получателю. Ноль — не ждёт вовсе, то есть возможность
-- выключена и отправка ведёт себя ровно как до её появления.
--
-- Отдельной таблицы для очереди здесь НЕТ и не будет: очередь писем у нас
-- уже есть — файлы на постоянном томе рядом с вложениями
-- (apps/api/src/mail/deferred-send.ts), та же, что у отложенной отправки
-- «завтра в девять». Отмена — это она же с малым сроком. Две очереди писем
-- в одном продукте разойдутся в поведении при первом же дефекте.
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ ПЯТЬ СЕКУНД, А НЕ НОЛЬ
-- ------------------------------------------------------------------
-- Возможность, которую надо сперва найти в настройках, не спасёт никого,
-- а спасает она от ошибки, которую иначе не исправить ничем, кроме второго
-- письма с извинениями: забытое вложение, не тот адресат, опечатка в первой
-- строке. Ровно поэтому она включена по умолчанию у всех, у кого её видели
-- (Gmail, Proton Mail, Яндекс).
--
-- Пять, а не десять и не тридцать: задержка настоящая — эти секунды письма
-- у получателя НЕТ. Ошибку замечают в первую секунду после нажатия, и
-- платить за отмену больше, чем она стоит, незачем.
--
-- Значение по умолчанию действует и на уже заведённые ящики (DEFAULT
-- проставляется существующим строкам при ALTER): возможность появляется
-- у всех сразу, а не только у тех, кто заведётся после обновления.
--
-- Разрешённые значения — 0, 5, 10 и 30 — проверяет API
-- (normalizeUndoSeconds). Ограничения в базе нет намеренно: непонятное
-- значение там всё равно приводится к «выключено», а CHECK превратил бы
-- будущее добавление ещё одного срока в ещё одну миграцию.
--
-- Миграция идемпотентна (IF NOT EXISTS): каталог миграций монтируется
-- в docker-entrypoint-initdb.d и на уже поднятой базе применяется руками.

ALTER TABLE mail_user_settings
    ADD COLUMN IF NOT EXISTS undo_send_seconds INTEGER NOT NULL DEFAULT 5;
