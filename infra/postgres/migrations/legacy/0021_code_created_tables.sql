-- Миграция 0021: таблицы, которые до сих пор заводил код на лету.
--
--   sender_logo_cache  — кэш логотипов отправителей (apps/api/src/logos/store.ts)
--   migrate_messages   — что уже перенесено при переезде с чужого сервера
--   migrate_cursors    — точка докачки по каждой папке источника
--                        (обе — packages/migrate/src/state.ts, PgStateStore.init)
--
-- ------------------------------------------------------------------
-- ЧТО БЫЛО НЕ ТАК
-- ------------------------------------------------------------------
-- Все три таблицы создавались кодом при первом обращении, через
-- CREATE TABLE IF NOT EXISTS. Работало это исправно, и именно поэтому
-- дефект был незаметен. Плохо здесь другое — таблица, которой нет в
-- каталоге миграций, НЕ СУЩЕСТВУЕТ для всего, что разбирает схему:
--
--   * install/selfcheck.sh берёт список ожидаемых таблиц из строк
--     `CREATE TABLE IF NOT EXISTS` в файлах миграций и сверяет со схемой
--     базы. Этих трёх в списке не было — то есть их пропажу (например,
--     после восстановления старой копии) проверка не заметила бы;
--   * при обновлении сервера план «что поменяется в базе» читается по
--     каталогу миграций. Изменение, спрятанное в коде, в план не попадает;
--   * добавить sender_logo_cache колонку было нечем: миграция правила бы
--     таблицу, которой в её мире нет, а код продолжал бы создавать старый
--     вариант на чистой установке — и схема разъезжалась бы в зависимости
--     от того, что случилось раньше.
--
-- В комментариях 0012 и 0013 отсутствие этих таблиц было записано как
-- осознанное решение («это кэш», «это заводит сам пакет»). Довод про кэш
-- верен по сути — терять его не жалко, и install/backup.sh намеренно
-- исключает его СОДЕРЖИМОЕ из выгрузки (--exclude-table-data). Но из
-- «данные не ценны» не следует «структуру не описываем»: место, где
-- объявлена таблица, и ценность её строк — разные вопросы.
--
-- ------------------------------------------------------------------
-- ЧТО С КОДОМ, КОТОРЫЙ ЭТИ ТАБЛИЦЫ СОЗДАВАЛ
-- ------------------------------------------------------------------
-- Разное, и по разной причине.
--
-- sender_logo_cache: DDL из apps/api/src/logos/store.ts УБРАН. Таблица
-- живёт только в нашей схеме, второго владельца у неё нет, и держать
-- два описания одной таблицы в двух местах — это ровно тот разъезд,
-- ради которого миграция и заводится.
--
-- migrate_messages / migrate_cursors: самосоздание в packages/migrate
-- ОСТАВЛЕНО. Это не наши внутренние таблицы, а переносимое хранилище
-- состояния: `pg:postgresql://…` в packages/migrate можно направить на
-- ЛЮБУЮ базу, в том числе не нашу (так это и описано в docs/migration.md),
-- и там наших миграций нет по определению. CREATE TABLE IF NOT EXISTS
-- в init() с этим описанием совпадает слово в слово, поэтому расходиться
-- нечему: кто бы ни создал таблицу первым, результат один.
--
-- Скрипт идемпотентен (IF NOT EXISTS везде), повторное применение безвредно.

BEGIN;

-- ------------------------------------------------------------------
-- 1. Кэш логотипов отправителей.
--
-- Заполняется поиском по BIMI-записи домена и по /favicon.ico. Строки
-- целиком восстановимы из сети, поэтому install/backup.sh выгружает
-- структуру без содержимого. Пустой кэш — это медленное первое открытие
-- папки, а не потеря данных.
-- ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS sender_logo_cache (
    domain      VARCHAR(255) PRIMARY KEY,
    -- Откуда взялась картинка: bimi | favicon | NULL (не нашли)
    source      VARCHAR(16),
    mime        VARCHAR(64),
    image       BYTEA,
    width       INTEGER,
    height      INTEGER,
    -- Отпечаток содержимого: попадает в адрес картинки и делает кэш
    -- браузера честным — сменилась картинка, сменился адрес.
    version     VARCHAR(32)  NOT NULL,
    fetched_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- Срок годности записи. Просроченную показываем и обновляем в фоне,
    -- чтобы открытие папки не ждало сети.
    expires_at  TIMESTAMPTZ  NOT NULL,
    last_used_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Уборка кэша идёт по давности последнего обращения (см. store.ts:
-- удаление самых давно не нужных при превышении размера).
CREATE INDEX IF NOT EXISTS sender_logo_cache_last_used
    ON sender_logo_cache (last_used_at);

-- ------------------------------------------------------------------
-- 2. Состояние переноса почты с чужого сервера.
--
-- Описание обязано слово в слово совпадать с PgStateStore.init()
-- в packages/migrate/src/state.ts — см. пояснение выше.
-- ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS migrate_messages (
    account     text NOT NULL,
    dest_folder text NOT NULL,
    dedup_key   text NOT NULL,
    -- Сколько копий письма с этим ключом уже перенесено. Ключ
    -- дедупликации не уникален (повторный Message-ID, письма без
    -- Message-ID с одинаковыми заголовками), поэтому храним число.
    copies      integer NOT NULL DEFAULT 1,
    migrated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (account, dest_folder, dedup_key)
);

-- Таблица могла быть создана старым кодом, где колонки copies ещё не было.
ALTER TABLE migrate_messages
    ADD COLUMN IF NOT EXISTS copies integer NOT NULL DEFAULT 1;

CREATE TABLE IF NOT EXISTS migrate_cursors (
    account       text NOT NULL,
    source_folder text NOT NULL,
    uid_validity  text NOT NULL,
    last_uid      bigint NOT NULL,
    updated_at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (account, source_folder)
);

COMMIT;
