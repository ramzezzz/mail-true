-- Миграция 0017: указатель переписки для подсказки адреса.
--
-- ------------------------------------------------------------------
-- ЗАЧЕМ ЭТО ВООБЩЕ ЕСТЬ
-- ------------------------------------------------------------------
-- Адрес получателя набирался руками целиком, каждый раз. Ни одна почта
-- так не работает: адрес подсказывается с первых введённых букв. Чтобы
-- подсказать, надо знать, с кем человек переписывался, — а знание это
-- лежит в письмах, то есть в IMAP.
--
-- Спрашивать IMAP на каждую нажатую букву нельзя. Проверено на живом
-- стенде: выборка конвертов тысячи писем занимает сотни миллисекунд —
-- то есть подсказка отставала бы от печати на несколько букв, и вместо
-- помощи получилась бы помеха. Значит, нужен свой указатель, который
-- наполняется один раз и отвечает по индексу за единицы миллисекунд.
--
-- Это ровно тот же довод, по которому заведена таблица истории доставки
-- (миграция 0007): разбор источника — операция дорогая и повторять её на
-- каждый запрос бессмысленно.
--
-- ------------------------------------------------------------------
-- ЧТО ЗДЕСЬ НЕ ХРАНИТСЯ
-- ------------------------------------------------------------------
-- Ни тем, ни текстов, ни идентификаторов писем. Только адрес, имя рядом с
-- ним, два счётчика и две даты. Указатель — это оглавление переписки, а не
-- её копия: потеря таблицы не теряет ничего, что нельзя восстановить
-- повторным проходом по ящику.
--
-- ------------------------------------------------------------------
-- ПРИВАТНОСТЬ
-- ------------------------------------------------------------------
-- Список тех, с кем человек переписывается, — сведения чувствительные:
-- по нему видно круг общения, работодателя, врача, банк. Поэтому:
--
--   1. Первым столбцом ключа стоит адрес ящика-владельца. Ни один запрос
--      в apps/api/src/contacts/db.ts не выполняется без него — не «по
--      договорённости», а потому что в самих запросах нет ветки, где его
--      можно опустить, а адрес берётся из сессии и не приходит от клиента.
--   2. При удалении ящика строки убираются вместе с настройками, подписями
--      и правилами фильтрации — см. AdminDb.purgeMailboxData. Пережить
--      своего владельца этот список не должен: воскресший ящик с тем же
--      адресом получил бы чужой круг общения в подсказках.
--
-- Миграция идемпотентна (IF NOT EXISTS): каталог монтируется
-- в docker-entrypoint-initdb.d, а на уже поднятой базе применяется руками.

-- ------------------------------------------------------------------
-- Сами контакты
-- ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mail_contacts (
    -- Владелец. Хранится приведённым к нижнему регистру — приводит API
    -- (нормализация одна на всех, см. contacts/tokens.ts), поэтому в
    -- запросах не нужен lower() и работает индекс первичного ключа.
    account_email VARCHAR(320) NOT NULL,
    -- Адрес корреспондента, тоже в нижнем регистре. Регистр локальной
    -- части по RFC значим, но на практике его не различает ни один
    -- почтовый сервер, а различение здесь дало бы две записи об одном
    -- человеке и два одинаковых пункта в подсказке.
    address       VARCHAR(320) NOT NULL,
    -- Имя из последнего письма. Именно последнего, а не первого: люди
    -- меняют фамилию и подпись, и подсказка обязана показывать то, как
    -- человек называет себя сейчас.
    display_name  TEXT,
    -- Строка поиска: слова имени, адрес целиком и его части, всё в нижнем
    -- регистре через пробел. Считается при записи, а не при поиске.
    --
    -- Почему отдельным столбцом, а не выражением в WHERE: поиск идёт по
    -- НАЧАЛУ слова («иван», «петров», «iva» — три разных способа вспомнить
    -- одного человека), и без готовой строки каждый запрос заново собирал
    -- бы её из имени и адреса для каждой строки таблицы.
    tokens        TEXT         NOT NULL,
    -- Сколько раз человек писал ЭТОМУ адресу сам.
    sent_count    INTEGER      NOT NULL DEFAULT 0,
    -- Сколько писем пришло С этого адреса.
    --
    -- Два счётчика, а не один, потому что вес у них разный: тому, кому
    -- писали сами, ошибиться адресом почти невозможно, а среди приходящей
    -- почты полно рассылок, роботов и «no-reply». Их складывает
    -- contacts/rank.ts с разными коэффициентами.
    recv_count    INTEGER      NOT NULL DEFAULT 0,
    first_seen_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- Дата последнего письма в любую сторону. Порядок подсказок не
    -- алфавитный: сверху те, с кем переписывались чаще и недавнее.
    last_seen_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- Убран из подсказок человеком.
    --
    -- ПОЧЕМУ ПРИЗНАК, А НЕ УДАЛЕНИЕ СТРОКИ. Указатель — производная от
    -- содержимого ящика: письмо, из которого адрес взят, никуда не делось,
    -- и следующий же проход сборщика вернул бы удалённую строку обратно.
    -- Человек, убравший опечатку «ivan@exmaple.com», увидел бы её снова
    -- через минуту и решил бы, что удаление не работает. Признак переживает
    -- повторный сбор: сборщик обновляет счётчики и имя, но hidden не трогает.
    hidden        BOOLEAN      NOT NULL DEFAULT false,
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (account_email, address)
);

-- Отбор всегда идёт по одному ящику и без скрытых. Частичный индекс —
-- потому что скрытых в выдаче не бывает никогда, и держать их в индексе
-- значит замедлять единственный запрос ради строк, которые он отбросит.
CREATE INDEX IF NOT EXISTS mail_contacts_suggest_idx
    ON mail_contacts (account_email, last_seen_at DESC)
    WHERE NOT hidden;

-- ------------------------------------------------------------------
-- Где сборщик остановился
-- ------------------------------------------------------------------
-- Ящик, заведённый вчера, и ящик с десятью тысячами писем должны вести
-- себя одинаково хорошо, а это разные задачи:
--
--   * во вчерашнем ящике всё содержимое разбирается за один заход;
--   * в ящике с десятью тысячами писем разбор «с начала времён» в один
--     заход — это минуты работы и мегабайты в памяти, то есть подсказка
--     не появилась бы вовсе до конца прохода.
--
-- Поэтому проход идёт С КОНЦА, от самых свежих писем к старым, порциями,
-- и после первой же порции подсказка уже работает — по последним письмам,
-- то есть по самым нужным. Отсюда два номера вместо одного:
--
--   top_uid    — докуда дошли ВВЕРХ (новая почта: всё, что больше, ещё не
--                разобрано);
--   bottom_uid — докуда дошли ВНИЗ (старая почта, добирается порциями в
--                фоне, пока backfill_done не станет true).
CREATE TABLE IF NOT EXISTS mail_contact_cursors (
    account_email VARCHAR(320) NOT NULL,
    -- 'inbox' — отправители полученных писем, 'sent' — получатели
    -- отправленных. Роль, а не путь папки: путь у «Отправленных» зависит
    -- от языка и настроек клиента, роль же вычисляется по флагу \Sent
    -- (см. mail/folders.ts) и не меняется от переименования папки.
    folder_role   VARCHAR(16)  NOT NULL,
    -- UIDVALIDITY папки. Смена значения по RFC 3501 означает «прежние
    -- номера ничего не значат»; тогда сбор начинается заново, иначе
    -- сборщик пропустил бы всю папку, приняв чужие номера за свои.
    uid_validity  BIGINT       NOT NULL DEFAULT 0,
    top_uid       BIGINT       NOT NULL DEFAULT 0,
    bottom_uid    BIGINT       NOT NULL DEFAULT 0,
    backfill_done BOOLEAN      NOT NULL DEFAULT false,
    -- Сколько писем разобрано всего. Нужно не для отчётности, а для
    -- честного ответа интерфейсу: пока указатель неполон, об этом можно
    -- сказать, а не делать вид, что подсказка знает всё.
    scanned       BIGINT       NOT NULL DEFAULT 0,
    started_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (account_email, folder_role)
);
