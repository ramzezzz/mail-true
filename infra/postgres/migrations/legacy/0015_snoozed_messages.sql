-- Миграция 0015: «отложить письмо до срока».
--
--   docker compose -f infra/docker-compose.yml exec -T postgres \
--     psql -v ON_ERROR_STOP=1 -U mailserver -d mailserver \
--     < infra/postgres/migrations/0015_snoozed_messages.sql
--
-- Скрипт идемпотентен (IF NOT EXISTS везде), повторное применение безвредно.
--
-- ------------------------------------------------------------------
-- ЧТО ЭТО И ПОЧЕМУ ТАБЛИЦА, А НЕ БРАУЗЕР
-- ------------------------------------------------------------------
-- Человек убирает письмо из «Входящих» и назначает час, в который оно
-- вернётся: завтра утром, в понедельник, через неделю. Письмо переезжает
-- в служебную папку «Отложенные», а СРОК И ИСХОДНАЯ ПАПКА ложатся сюда.
--
-- Требование к возможности ровно одно, и оно жёсткое: письмо обязано
-- вернуться, даже если человек не открывал почту неделю. Значит, ждать
-- нельзя ни в браузере (там таймер живёт до закрытия вкладки), ни в памяти
-- процесса (перезапуск контейнера — и срок пропал молча). Возврат делает
-- работник сервера, который входит в ящик служебным пользователем Dovecot
-- (`ящик*mtadmin`, тот же, которым в ящики входит панель и сборщик почты
-- с чужих ящиков), поэтому пароль владельца здесь не нужен и не хранится.
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ ПИСЬМО ОПОЗНАЁТСЯ ДВУМЯ СПОСОБАМИ СРАЗУ
-- ------------------------------------------------------------------
-- Основной ключ письма в IMAP — пара (UIDVALIDITY папки, UID письма).
-- Она короткая и точная, но живёт ровно до тех пор, пока папку не
-- пересоздали: смена UIDVALIDITY обнуляет все UID разом, и запись начнёт
-- указывать на чужое письмо или в пустоту.
--
-- Поэтому рядом лежит message_id — заголовок Message-ID письма. Он к папке
-- не привязан вовсе, и по нему письмо находится поиском даже после
-- пересоздания папки. Сверка идёт в таком порядке: сперва UID (дёшево),
-- при несовпадении UIDVALIDITY — поиск по Message-ID (дорого, но редко).
-- Если не нашлось ни так, ни так — письма в «Отложенных» больше нет
-- (человек утащил его мышью или удалил), и запись молча закрывается
-- состоянием 'gone'. Именно молча: падать из-за письма, которое человек
-- сам и убрал, — значит останавливать возврат всех остальных писем.
--
-- ------------------------------------------------------------------
-- ЧЕГО ЗДЕСЬ НЕТ
-- ------------------------------------------------------------------
-- Ни тела письма, ни его заголовков целиком, ни тем более пароля ящика.
-- Тема и отправитель лежат ТОЛЬКО ради строки списка «Отложенных» и
-- ради журнала: показать человеку, что именно он отложил, не открывая
-- каждое письмо по IMAP. Само письмо всё это время лежит в ящике —
-- там же, где лежало бы и без нас.
CREATE TABLE IF NOT EXISTS snoozed_messages (
    id                 BIGSERIAL    PRIMARY KEY,
    account_email      VARCHAR(320) NOT NULL,

    -- Где письмо лежит СЕЙЧАС: папка «Отложенные» этого ящика.
    -- Путь хранится явно, потому что имя служебной папки в IMAP может
    -- отличаться от нашего умолчания (ящик мог приехать с чужого сервера).
    snooze_path        TEXT         NOT NULL,
    snooze_uid         BIGINT       NOT NULL,
    -- UIDVALIDITY папки на момент переноса. Расходится с текущим —
    -- значит, UID выше уже ничего не значит, и письмо ищется по Message-ID.
    snooze_uidvalidity BIGINT       NOT NULL DEFAULT 0,

    -- Куда возвращать. Путь IMAP, а не наш идентификатор папки:
    -- идентификатор `f-<base64url(путь)>` — это форма показа, и завязывать
    -- на неё хранение значило бы, что переименование правил показа ломает
    -- возврат. Папки может уже не быть — тогда письмо вернётся во «Входящие».
    origin_path        TEXT         NOT NULL,

    -- Заголовок Message-ID без угловых скобок. Запасной ключ поиска,
    -- см. пояснение выше. Пусто — письмо пришло без Message-ID (бывает
    -- у писем, собранных кривыми отправителями): тогда остаётся только UID.
    message_id         TEXT,

    -- Только для строки списка «Отложенных» и журнала.
    subject            TEXT         NOT NULL DEFAULT '',
    from_address       TEXT         NOT NULL DEFAULT '',

    -- Когда вернуть. Момент времени, а не «дата и время»: «завтра утром» —
    -- это утро ЧЕЛОВЕКА, и превращение его в момент происходит один раз,
    -- при постановке срока, по поясу браузера (см. mail/snooze-schedule.ts).
    -- Хранить «08:00» без пояса означало бы «08:00 у сервера», то есть не то.
    wake_at            TIMESTAMPTZ  NOT NULL,
    -- Пояс, в котором срок назначали (IANA, «Europe/Moscow»). Нужен, чтобы
    -- показать срок теми же словами, какими его назначили.
    time_zone          VARCHAR(64),
    -- Каким сроком его назначили: 'tomorrow-morning' | 'monday' |
    -- 'next-week' | 'custom'. Проверяет API, а не база: новый готовый срок
    -- не должен требовать миграции.
    preset             VARCHAR(32)  NOT NULL DEFAULT 'custom',

    -- 'pending'   — ждёт срока (единственное живое состояние);
    -- 'returned'  — вернулось в папку;
    -- 'cancelled' — человек вернул его сам, не дожидаясь срока;
    -- 'gone'      — письма в «Отложенных» больше нет (унесли или удалили).
    state              VARCHAR(16)  NOT NULL DEFAULT 'pending',

    -- Сколько раз возврат срывался. НЕ повод сдаться: срыв возврата — это
    -- почти всегда недоступный Dovecot, а недоступность проходит сама.
    -- Число нужно журналу и разделу состояния: по нему видно, что письма
    -- копятся, ещё до того, как о них спросит человек.
    attempts           INT          NOT NULL DEFAULT 0,
    last_error         TEXT,
    last_attempt_at    TIMESTAMPTZ,

    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- Когда письмо вернулось (или когда запись закрылась иначе).
    closed_at          TIMESTAMPTZ
);

-- Главный запрос работника: «кому пора». Частичный индекс — по состоянию:
-- закрытых записей со временем станет на порядки больше живых, и полный
-- индекс по wake_at обслуживал бы в основном историю.
CREATE INDEX IF NOT EXISTS snoozed_messages_due_idx
    ON snoozed_messages (wake_at)
    WHERE state = 'pending';

-- Список «Отложенных» одного человека.
CREATE INDEX IF NOT EXISTS snoozed_messages_account_idx
    ON snoozed_messages (lower(account_email), wake_at)
    WHERE state = 'pending';

-- Одно письмо — одна живая запись.
--
-- Без этого двойное нажатие кнопки (или повтор запроса при обрыве связи)
-- заводило бы два срока на одно письмо: первый возврат унёс бы письмо из
-- «Отложенных», а второй потом искал бы его там же и не находил. Индекс
-- частичный: закрытые записи повторяться могут и должны — человек имеет
-- право отложить одно и то же письмо второй раз.
CREATE UNIQUE INDEX IF NOT EXISTS snoozed_messages_live_key
    ON snoozed_messages (lower(account_email), snooze_path, snooze_uidvalidity, snooze_uid)
    WHERE state = 'pending';
