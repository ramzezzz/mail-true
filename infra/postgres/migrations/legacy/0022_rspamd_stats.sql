-- Миграция 0022: снимки счётчиков антиспама (rspamd).
--
-- ------------------------------------------------------------------
-- ЗАЧЕМ ХРАНИТЬ ЭТО САМИМ
-- ------------------------------------------------------------------
-- Вопрос, ради которого администратор открывает раздел «Спам», звучит
-- «сколько писем ушло в спам за неделю и стало ли больше». Ответа на него
-- у rspamd нет ни в каком виде:
--
--   * GET /stat отдаёт счётчики, НАКОПЛЕННЫЕ С ЗАПУСКА ПРОЦЕССА. После
--     перезапуска контейнера (обновление, смена конфигурации) они
--     обнуляются, и «за неделю» превращается в «за два часа»;
--   * GET /history держит последние письма В ПАМЯТИ процесса — сотни
--     штук, и тоже до первого перезапуска;
--   * встроенных графиков (rrd) на этой сборке нет: /graph отвечает
--     «Invalid graph type».
--
-- Значит, разность между двумя моментами времени может посчитать только
-- тот, кто эти моменты записал. Записывает сервер приложения — раз в
-- MAIL_METRICS_INTERVAL_SECONDS, тем же расписанием, что и остальные
-- показатели (см. spam-collector.ts).
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ ХРАНЯТСЯ АБСОЛЮТНЫЕ ЗНАЧЕНИЯ, А НЕ ПРИРОСТ
-- ------------------------------------------------------------------
-- Прирост нельзя пересчитать обратно, а абсолютное значение позволяет
-- посчитать прирост за ЛЮБОЕ окно, в том числе за то, которое придумают
-- позже. Плюс абсолютные значения самоисправляются: пропущенный снимок
-- (сервер приложения перезапускали) не теряет события, он лишь укрупняет
-- одну ступеньку, тогда как в схеме с приростом эти события исчезли бы.
--
-- ------------------------------------------------------------------
-- ЗАЧЕМ КОЛОНКА uptime_seconds
-- ------------------------------------------------------------------
-- Это ЕДИНСТВЕННЫЙ способ отличить «за час ничего не приходило» от «час
-- назад rspamd перезапустили, и счётчики поехали с нуля». Без неё разность
-- соседних снимков после перезапуска уходит в минус, и любая честная
-- арифметика ломается. Разность считается по правилу: если время работы
-- уменьшилось — процесс перезапускали, и приростом считается всё
-- абсолютное значение нового снимка (оно и есть «сколько было с
-- перезапуска»).
--
-- Применение к работающей базе:
--   docker compose -f infra/docker-compose.yml exec -T postgres \
--     psql -v ON_ERROR_STOP=1 -U mailserver -d mailserver \
--     < infra/postgres/migrations/0022_rspamd_stats.sql
--
-- Скрипт идемпотентен, повторное применение безвредно.

BEGIN;

CREATE TABLE IF NOT EXISTS rspamd_stat_samples (
    id                  BIGSERIAL PRIMARY KEY,
    taken_at            TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- Сколько секунд работает процесс rspamd. См. пояснение выше:
    -- по уменьшению этого числа опознаётся перезапуск.
    uptime_seconds      BIGINT NOT NULL,

    -- Проверено писем всего. Знаменатель для доли спама.
    scanned             BIGINT NOT NULL DEFAULT 0,

    -- Разбивка по решениям. Имена — как их зовёт сам rspamd, только
    -- пробелы заменены подчёркиванием.
    act_reject          BIGINT NOT NULL DEFAULT 0,
    act_add_header      BIGINT NOT NULL DEFAULT 0,
    act_rewrite_subject BIGINT NOT NULL DEFAULT 0,
    act_greylist        BIGINT NOT NULL DEFAULT 0,
    act_soft_reject     BIGINT NOT NULL DEFAULT 0,
    act_no_action       BIGINT NOT NULL DEFAULT 0,

    -- Обучение байесова классификатора. Считает ВСЁ обучение, включая
    -- автоматическое (autolearn = true в local.d/classifier-bayes.conf).
    -- Ручное обучение из панели считается отдельно — по журналу аудита,
    -- потому что только там видно, кто и когда это сделал.
    learned             BIGINT NOT NULL DEFAULT 0,
    spam_count          BIGINT NOT NULL DEFAULT 0,
    ham_count           BIGINT NOT NULL DEFAULT 0
);

COMMIT;

-- ==================================================================
-- ИНДЕКС — ОТДЕЛЬНО ОТ ТРАНЗАКЦИИ И ТОЛЬКО CONCURRENTLY
-- ==================================================================
-- Причина та же, что у миграции 0011: обычный CREATE INDEX держит запись
-- таблицы заблокированной, а запускают миграцию на работающем сервере.
-- Незавершённое построение оставляет НЕДЕЙСТВИТЕЛЬНЫЙ индекс, который
-- `IF NOT EXISTS` потом молча пропустит, — поэтому сначала убираем такие
-- остатки. CONCURRENTLY нельзя внутри транзакции и внутри блока DO,
-- отсюда \gexec.

SELECT format('DROP INDEX CONCURRENTLY IF EXISTS %I', c.relname)
  FROM pg_index i
  JOIN pg_class c ON c.oid = i.indexrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
 WHERE n.nspname = 'public'
   AND NOT i.indisvalid
   AND c.relname IN ('idx_rspamd_stat_time')
\gexec

-- Единственный способ читать эту таблицу — окно времени назад от «сейчас»,
-- по возрастанию (разность соседних снимков считается оконной функцией).
SELECT 'CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_rspamd_stat_time
            ON rspamd_stat_samples (taken_at)'
 WHERE to_regclass('public.rspamd_stat_samples') IS NOT NULL
\gexec
