-- Миграция 0036: адреса, с которых к почтовым службам подключается сам
-- сервер приложения. Нужна разделу «Вход и действия».
--
--   docker compose -f infra/docker-compose.yml exec -T postgres \
--     psql -v ON_ERROR_STOP=1 -U mailserver -d mailserver \
--     < infra/postgres/migrations/0036_api_service_addresses.sql
--
-- Скрипт идемпотентен (IF NOT EXISTS везде), повторное применение безвредно.
--
-- ------------------------------------------------------------------
-- ЧТО БЫЛО НЕ ТАК
-- ------------------------------------------------------------------
-- Веб-интерфейс работает с почтой настоящим IMAP-логином, поэтому в
-- журнале Dovecot на один вход человека приходятся десятки строк с
-- адресом НАШЕГО контейнера. Раздел «Вход и действия» помечал их
-- служебными, сравнивая адрес из журнала с адресами сетевых интерфейсов
-- своего же процесса (`os.networkInterfaces()`).
--
-- Сравнение верное ровно до первой пересборки контейнера. Docker выдаёт
-- новому контейнеру следующий свободный адрес в подсети стека, и после
-- `docker compose up -d --build api` процесс видит своим, скажем,
-- 172.28.0.7, а все вчерашние строки журнала написаны про 172.28.0.2.
-- Вчерашние служебные подключения после этого показываются человеку как
-- ОБЫЧНЫЕ ВХОДЫ ПО IMAP ИЗ ЛОКАЛЬНОЙ СЕТИ — то есть раздел, заведённый
-- ради ответа на вопрос «не заходил ли кто-то чужой», сам же и отвечает
-- на него ложной тревогой. Ровно это видно на стенде: в dovecot.log
-- соседствуют rip=172.28.0.2 и rip=172.28.0.7, и оба — мы.
--
-- ------------------------------------------------------------------
-- ЗАЧЕМ ТАБЛИЦА, А НЕ СПИСОК В НАСТРОЙКАХ
-- ------------------------------------------------------------------
-- Адрес контейнера никто не выбирает: его выдаёт Docker при создании.
-- Просить администратора вписать его руками — значит требовать правки
-- настройки после каждого обновления образа; забудет он об этом ровно
-- один раз, и дальше раздел снова врёт. Поэтому адрес не настраивается,
-- а ЗАПОМИНАЕТСЯ: процесс при запуске записывает сюда свои собственные
-- адреса, и запись переживает и перезапуск, и пересборку контейнера —
-- она лежит в базе, а не в контейнере.
--
-- Подсеть целиком в качестве признака не годится по той же причине, по
-- которой её отверг код: подсеть стека может совпасть с подсетью офиса,
-- и тогда служебными станут настоящие входы сотрудников.
--
-- Строки стареют вместе с историей, которую они объясняют: уборщик
-- истории входов (MAILBOX_ACCESS_LOG_DAYS) убирает и их — адрес, не
-- встречавшийся дольше срока хранения, объяснять больше нечего, а
-- держать его вечно значило бы однажды принять за себя чужую машину,
-- которой Docker отдал тот же адрес.
CREATE TABLE IF NOT EXISTS api_service_addresses (
    -- Адрес в том же виде, в каком он попадает в журнал Dovecot (`rip=`):
    -- IPv4 точками, IPv6 без обёртки `::ffff:`.
    ip          VARCHAR(64)  PRIMARY KEY,

    -- Когда этот адрес впервые оказался нашим. Показывать пока негде,
    -- но без него нельзя ответить на вопрос «с каких пор это мы».
    first_seen  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    -- Когда процесс в последний раз видел адрес своим. По нему и стареет
    -- строка: пересобранный контейнер перестаёт обновлять старый адрес.
    last_seen   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Единственный вопрос к таблице помимо выборки целиком — «что пора убрать».
CREATE INDEX IF NOT EXISTS api_service_addresses_last_seen_idx
    ON api_service_addresses (last_seen);

COMMENT ON TABLE api_service_addresses IS
    'Адреса самого сервера приложения: по ним раздел «Вход и действия» отличает '
    'служебные подключения веб-интерфейса от входов человека. Заполняет процесс сам.';
