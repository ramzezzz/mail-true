-- Миграция 0010: снимки показателей сервера для дашборда.
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ ИСТОРИЮ ПРИХОДИТСЯ ХРАНИТЬ САМИМ
-- ------------------------------------------------------------------
-- «Занято 80 %» без истории не отвечает на единственный вопрос, ради
-- которого администратор открывает панель: РАСТЁТ ЛИ. Восемьдесят
-- процентов, которые держатся месяц, и восемьдесят, которые вчера были
-- сорока, — это разные ситуации, и по одному числу их не различить.
--
-- Источники показателей истории не ведут вовсе:
--   * /proc/stat и /proc/meminfo — мгновенное состояние; загрузка CPU
--     вычисляется только РАЗНОСТЬЮ двух замеров, то есть без хранения
--     предыдущего замера её нельзя посчитать даже один раз;
--   * statfs — мгновенное состояние тома;
--   * `postqueue -j` — очередь прямо сейчас.
-- Внешнего сборщика (Prometheus и подобных) в стеке нет и по условиям
-- задачи не появится. Значит, снимки складывает сюда сам сервер
-- приложения — раз в MAIL_METRICS_INTERVAL_SECONDS.
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ ОДИН ШАГ, А НЕ ТРИ ТАБЛИЦЫ РАЗНОЙ ЗЕРНИСТОСТИ
-- ------------------------------------------------------------------
-- Соблазн сделать «минутные, часовые, суточные» таблицы велик, но здесь
-- он не окупается. При шаге в минуту и хранении семь суток это 10 080
-- строк — меньше, чем в одной секунде почтового журнала на нагруженном
-- сервере. Прореживание при ЧТЕНИИ (усреднение по корзинам) даёт тот же
-- результат на графике и не заводит трёх мест, которые могут разъехаться.
--
-- ------------------------------------------------------------------
-- ЧТО ОЗНАЧАЕТ NULL В КОЛОНКЕ
-- ------------------------------------------------------------------
-- Ровно «снять не удалось», а не «ноль». Разница принципиальная: ноль в
-- очереди — это пустая очередь (хорошо), а недоступная очередь — это
-- неизвестность (плохо), и рисовать их одной линией нельзя. Поэтому все
-- измеряемые колонки допускают NULL, а панель показывает разрыв линии,
-- а не проседание до нуля.
--
-- Применение к работающей базе:
--   docker compose -f infra/docker-compose.yml exec -T postgres \
--     psql -v ON_ERROR_STOP=1 -U mailserver -d mailserver \
--     < infra/postgres/migrations/0010_metrics.sql
--
-- Скрипт идемпотентен (IF NOT EXISTS везде), повторное применение безвредно.

BEGIN;

-- ------------------------------------------------------------------
-- 1. Снимок показателей: одна строка — один момент времени.
-- ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS server_metric_samples (
    id                  BIGSERIAL PRIMARY KEY,
    taken_at            TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- Загрузка процессора ВСЕГО УЗЛА, проценты (0..100). Считается
    -- разностью счётчиков /proc/stat между этим снимком и предыдущим —
    -- отсюда и NULL в самом первом снимке после запуска: разности ещё нет.
    cpu_node_percent    NUMERIC(5, 2),
    -- Загрузка процессора КОНТЕЙНЕРОМ api, проценты одного ядра
    -- (/sys/fs/cgroup/cpu.stat, usage_usec). На восьми ядрах законно
    -- бывает больше 100, поэтому разрядность с запасом.
    cpu_api_percent     NUMERIC(7, 2),
    -- Средняя длина очереди готовых к исполнению за минуту (/proc/loadavg).
    -- Не проценты: показывает перегрузку там, где CPU уже упёрся в 100 %
    -- и по нему разницы между «впритык» и «вдвое больше, чем тянем» нет.
    load1               NUMERIC(7, 2),

    mem_node_total      BIGINT,
    -- Занято = total - available. Именно available, а не free: страницы
    -- под кэшем считаются свободными, и по free сервер с исправным кэшем
    -- выглядит как сервер на грани нехватки памяти.
    mem_node_used       BIGINT,
    -- Память контейнера api (/sys/fs/cgroup/memory.current).
    mem_api_bytes       BIGINT,

    -- Том, на котором лежат письма: размер и свободное место (statfs).
    disk_total          BIGINT,
    disk_free           BIGINT,

    -- Разрез занятого места по тому, что важно почтовику. Общее «занято
    -- 60 ГБ» бесполезно, когда надо понять, ЧТО именно съело диск.
    vmail_bytes         BIGINT,
    mailindex_bytes     BIGINT,
    logs_bytes          BIGINT,
    db_bytes            BIGINT,
    db_index_bytes      BIGINT,

    -- Очередь Postfix — через посредника в его контейнере (сокет Docker
    -- не подключаем, см. queue-agent.ts). NULL — посредник не ответил.
    queue_total         INTEGER,
    queue_deferred      INTEGER,
    -- Возраст самого старого письма очереди, секунды. Именно возраст, а не
    -- «сколько лежит»: очередь из тысячи писем возрастом в минуту — это
    -- всплеск, а одно письмо возрастом в сутки — это сломанный адресат.
    queue_oldest_seconds INTEGER
);

COMMIT;

-- ==================================================================
-- ИНДЕКСЫ — ОТДЕЛЬНО ОТ ТРАНЗАКЦИИ И ТОЛЬКО CONCURRENTLY
-- ==================================================================
-- Обычный CREATE INDEX берёт на таблицу блокировку SHARE: чтение
-- продолжается, а любая ЗАПИСЬ ждёт окончания построения. Для
-- mail_flow_events это прямой отказ в обслуживании на живом сервере:
-- в неё непрерывно пишет сборщик журнала Postfix, и на потолке в
-- 500 000 строк (MAIL_FLOW_MAX_ROWS) построение индекса с INCLUDE из
-- пяти колонок занимает секунды — всё это время история доставки не
-- пишется. А запускают это обновлением работающего сервера.
--
-- CONCURRENTLY строит индекс в два прохода, не блокируя запись. Платим
-- за это тем, что команда не может выполняться внутри транзакции —
-- отсюда COMMIT выше и отсутствие BEGIN ниже. По той же причине
-- CONCURRENTLY нельзя вызвать из блока DO: тело DO выполняется как
-- транзакция. Поэтому условие «таблица существует» проверяется не в
-- PL/pgSQL, а запросом, который ПОРОЖДАЕТ команду, и psql выполняет
-- порождённое (\gexec). Команда не строится вовсе, если строить нечего.
--
-- Незавершённое построение CONCURRENTLY оставляет НЕДЕЙСТВИТЕЛЬНЫЙ
-- индекс: планировщик им не пользуется, а `IF NOT EXISTS` считает имя
-- занятым и молча пропускает повтор — то есть один сбой отключал бы
-- индекс навсегда. Поэтому сначала убираем такие остатки.
-- ==================================================================

SELECT format('DROP INDEX CONCURRENTLY IF EXISTS %I', c.relname)
  FROM pg_index i
  JOIN pg_class c ON c.oid = i.indexrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
 WHERE n.nspname = 'public'
   AND NOT i.indisvalid
   AND c.relname IN ('idx_metric_samples_time', 'idx_mail_flow_agg')
\gexec

-- Единственный способ читать таблицу снимков — окно времени назад
-- от «сейчас».
SELECT 'CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_metric_samples_time
            ON server_metric_samples (taken_at DESC)'
 WHERE to_regclass('public.server_metric_samples') IS NOT NULL
\gexec

-- ------------------------------------------------------------------
-- 2. Индекс под агрегаты почтового потока.
--
-- Дашборд считает по mail_flow_events пять разных сводок (поток по
-- корзинам времени, доли состояний, размеры, топ отправителей, топ
-- получателей) — и все по ОДНОМУ окну времени. Индекс idx_mail_flow_time
-- из миграции 0007 сужает окно, но за каждой строкой всё равно приходится
-- идти в таблицу: нужны direction, status, sender, recipient, size_bytes.
--
-- INCLUDE кладёт эти столбцы в сам индекс. Тогда агрегат считается
-- ИСКЛЮЧИТЕЛЬНО по индексу (Index Only Scan), не трогая кучу вовсе.
--
-- ЗАМЕРЕНО на стенде, 300 000 строк, окно шесть часов (75 000 строк):
--   с индексом     17–19 мс, Index Only Scan, Heap Fetches: 0
--   без индекса    34–48 мс, Bitmap Heap Scan по idx_mail_flow_time
-- Цена — 34 МБ на 300 000 строк. При потолке в 500 000 строк
-- (MAIL_FLOW_MAX_ROWS) это около 57 МБ: приемлемо за двукратное ускорение
-- каждого открытия дашборда.
--
-- ВАЖНО про Index Only Scan: он возможен только по страницам, помеченным
-- «все видимы», а помечает их VACUUM. Сразу после массовой вставки (или
-- после первого разбора большого журнала) планировщик знает, что кучу
-- всё равно придётся читать, и индекс не выберет. Это не поломка: как
-- только автовакуум пройдёт по таблице, запросы ускорятся сами.
--
-- Почему INCLUDE, а не составной ключ: по этим столбцам не ищут и не
-- сортируют, они нужны только чтобы не ходить в таблицу. В ключе они
-- раздували бы каждый уровень дерева без всякой пользы.
--
-- Индекс создаётся только если таблица есть: миграция 0007 могла быть не
-- применена (тогда раздел «Почтовый поток» и так не работает), и падать
-- из-за этого целиком нельзя — снимки показателей от истории не зависят.
--
-- Проверка сделана порождающим запросом, а не блоком DO: тело DO —
-- это транзакция, а CONCURRENTLY в транзакции запрещён (см. пояснение
-- выше). Пустой результат SELECT означает «выполнять нечего».
SELECT 'CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_mail_flow_agg
            ON mail_flow_events (occurred_at)
            INCLUDE (direction, status, sender, recipient, size_bytes)'
 WHERE to_regclass('public.mail_flow_events') IS NOT NULL
\gexec
