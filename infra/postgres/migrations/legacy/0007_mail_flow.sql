-- Миграция 0007: история обработанных писем для раздела «Почтовый поток».
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ ЭТА ТАБЛИЦА ВООБЩЕ ЕСТЬ
-- ------------------------------------------------------------------
-- Postfix НЕ ХРАНИТ историю доставки. Письмо лежит в очереди ровно до тех
-- пор, пока не доставлено (или не отбито), после чего файл очереди
-- удаляется. Единственный след обработанного письма — строка в журнале:
--
--   ... postfix/lmtp[42]: 4c2wKp1Vt2z: to=<a@mail.local>,
--       relay=172.28.0.54[172.28.0.54]:24, delay=0.08,
--       dsn=2.0.0, status=sent (250 2.0.0 <a@mail.local> saved)
--
-- Другого источника не существует: ни базы, ни API у Postfix для этого нет.
-- Поэтому админка разбирает журнал и складывает разобранное сюда.
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ В БАЗУ, А НЕ «ЧИТАТЬ ЖУРНАЛ ПРИ КАЖДОМ ЗАПРОСЕ»
-- ------------------------------------------------------------------
-- Читать журнал на каждый запрос — значит перечитывать десятки мегабайт
-- ради одной страницы и получить отбор по адресу линейным поиском по
-- файлу. На боевом сервере счёт записей идёт на сотни тысяч, а страницы
-- листают и фильтруют — без индексов это не работает.
-- Здесь же строки живут в постоянном виде и переживают проворот журнала:
-- журнал проворачивается по размеру, а история — по сроку.
--
-- ------------------------------------------------------------------
-- СКОЛЬКО ХРАНИТЬ И ПОЧЕМУ ИМЕННО ТАК
-- ------------------------------------------------------------------
-- Два предела сразу, вытесняет тот, что сработал первым:
--   * по сроку — MAIL_FLOW_RETENTION_DAYS (по умолчанию 14 суток);
--   * по числу строк — MAIL_FLOW_MAX_ROWS (по умолчанию 500 000).
--
-- Один только срок не годится: рассылка на сто тысяч адресов за ночь
-- заняла бы диск, нужный письмам. Одно только число строк не годится:
-- на тихом сервере оно означало бы «история за три года», в которой
-- давно нет ни одного письма из журнала, — и человек искал бы в ней
-- то, чего там быть не может.
--
-- ВАЖНО: история начинается с момента установки этой миграции. Показывать
-- «за год», когда журналу час от роду, — это рисовать то, чего нет.
-- Раздел админки честно показывает, с какого момента у него есть данные.
--
--   docker compose -f infra/docker-compose.yml exec -T postgres \
--     psql -v ON_ERROR_STOP=1 -U mailserver -d mailserver \
--     < infra/postgres/migrations/0007_mail_flow.sql
--
-- Скрипт идемпотентен (IF NOT EXISTS везде), повторное применение безвредно.

BEGIN;

-- ------------------------------------------------------------------
-- 1. Разобранные события доставки.
--
-- Одна строка — одна ПОПЫТКА доставки одному адресату, а не одно письмо.
-- Так и надо: письмо, отложенное пять раз и доставленное на шестой, даёт
-- шесть строк, и по ним видно, почему оно шло два часа. Свести их в одно
-- письмо всегда можно по queue_id, обратно развернуть — уже нет.
-- ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mail_flow_events (
    id            BIGSERIAL PRIMARY KEY,
    -- Время из строки журнала, а не время вставки: разбор может отстать
    -- от журнала на секунды, а при первом запуске — на часы.
    occurred_at   TIMESTAMPTZ NOT NULL,
    -- Идентификатор в очереди. NULL у отказов на приёме: письму, отбитому
    -- на команде RCPT, очередь не заводится вовсе (в журнале — NOQUEUE).
    queue_id      TEXT,
    -- 'in'  — доставка в наши ящики (транспорт lmtp в Dovecot);
    -- 'out' — отправка наружу (транспорт smtp);
    -- 'unknown' — определить не удалось, лучше сказать честно.
    direction     TEXT NOT NULL DEFAULT 'unknown',
    -- sent | deferred | bounced | expired | rejected | held
    status        TEXT NOT NULL,
    sender        TEXT,
    recipient     TEXT,
    relay         TEXT,
    -- Задержка от приёма до этой попытки, секунды (из delay= в журнале).
    delay_seconds NUMERIC(12, 2),
    size_bytes    BIGINT,
    -- Код DSN (2.0.0, 4.4.1, 5.1.1) — по нему видно, временный отказ
    -- или постоянный, без разбора текста.
    dsn           TEXT,
    -- Текст причины: то, что ответила принимающая сторона. Именно его
    -- ищет человек, когда спрашивает «почему письмо не дошло».
    reason        TEXT,
    -- Какой процесс Postfix это сказал (smtp, lmtp, smtpd, bounce, qmgr).
    component     TEXT
);

-- Листание всегда идёт по времени вниз: это же и порядок вытеснения.
CREATE INDEX IF NOT EXISTS idx_mail_flow_time ON mail_flow_events (occurred_at DESC, id DESC);
-- Отбор по состоянию в пределах окна времени («покажи только отбитые»).
CREATE INDEX IF NOT EXISTS idx_mail_flow_status ON mail_flow_events (status, occurred_at DESC);
-- Все попытки одного письма — по нему связывается очередь с историей.
CREATE INDEX IF NOT EXISTS idx_mail_flow_queue ON mail_flow_events (queue_id) WHERE queue_id IS NOT NULL;

-- Поиск по адресу.
--
-- Ищут почти всегда подстрокой: «покажи всё по ivanov» или «по домену
-- example.com». Обычный btree такому запросу не помогает вовсе — он умеет
-- только начало строки. Триграммный индекс умеет и середину.
--
-- Расширение pg_trgm входит в contrib и есть в образе postgres:16-alpine,
-- но установка требует прав суперпользователя. Если их нет, поиск всё
-- равно работает — просто перебором в пределах окна времени, — поэтому
-- отсутствие расширения не должно ронять миграцию целиком.
DO $$
BEGIN
    CREATE EXTENSION IF NOT EXISTS pg_trgm;
EXCEPTION WHEN OTHERS THEN
    RAISE NOTICE 'pg_trgm недоступно (%): поиск по адресу пойдёт перебором', SQLERRM;
END
$$;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_trgm') THEN
        CREATE INDEX IF NOT EXISTS idx_mail_flow_recipient_trgm
            ON mail_flow_events USING gin (lower(recipient) gin_trgm_ops);
        CREATE INDEX IF NOT EXISTS idx_mail_flow_sender_trgm
            ON mail_flow_events USING gin (lower(sender) gin_trgm_ops);
    END IF;
END
$$;

-- ------------------------------------------------------------------
-- 2. Где остановился разбор журнала.
--
-- Без этой строки после перезапуска сервер приложения либо перечитал бы
-- журнал сначала (дубли в истории), либо начал бы с конца (дыра за время
-- простоя). Файл опознаётся по устройству и номеру inode: после проворота
-- журнала они меняются, и это законный повод читать новый файл с нуля,
-- а не признак сбоя.
-- ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mail_flow_cursor (
    source      TEXT PRIMARY KEY,
    file_id     TEXT NOT NULL,
    byte_offset BIGINT NOT NULL DEFAULT 0,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Когда разбор увидел первую строку. Ровно это показывается в админке
    -- как «история ведётся с …»: обещать больше, чем есть, нельзя.
    started_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMIT;
