-- Миграция 0026: «шаблоны писем».
--
--   docker compose -f infra/docker-compose.yml exec -T postgres \
--     psql -v ON_ERROR_STOP=1 -U mailserver -d mailserver \
--     < infra/postgres/migrations/0026_mail_templates.sql
--
-- Скрипт идемпотентен (IF NOT EXISTS везде), повторное применение безвредно.
--
-- ------------------------------------------------------------------
-- ЗАЧЕМ ЭТО
-- ------------------------------------------------------------------
-- Человек, отвечающий типовым текстом по десять раз в день, до этой
-- таблицы шёл в «Отправленные», искал похожее письмо, копировал текст и
-- правил имя. Шаблон — это тот же текст, сохранённый один раз и названный
-- по-человечески.
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ ТАБЛИЦА, А НЕ ПОДПАПКА «ЧЕРНОВИКОВ»
-- ------------------------------------------------------------------
-- Яндекс держит шаблоны письмами в «Черновики → Шаблоны», и это избавляет
-- от отдельного хранилища. Нам оно не подошло по трём причинам, и все три
-- про поведение, а не про удобство кода:
--
--   1. Шаблон в подпапке черновиков ВИДЕН как черновик — в списке писем,
--      в поиске, в счётчике папки. Двадцать заготовок превращают «Черновики»
--      в свалку, из которой настоящий недописанный черновик уже не найти.
--   2. Порядок шаблонов в меню задаёт человек. У писем в папке порядок
--      задаёт дата, и держать свой пришлось бы всё равно — отдельной
--      таблицей, то есть ровно этой.
--   3. Случайное «удалить всё из Черновиков» уносило бы заготовки вместе
--      с мусором, причём в Корзину и молча.
--
-- Следствие, о котором продукт говорит прямо: шаблоны видны только в нашем
-- интерфейсе. Сторонняя почтовая программа по IMAP их не покажет — их там
-- нет. Это цена за то, что они не мешаются в «Черновиках».
CREATE TABLE IF NOT EXISTS mail_templates (
    id            BIGSERIAL    PRIMARY KEY,
    account_email VARCHAR(320) NOT NULL,

    -- Название — то, что человек видит в меню «Шаблоны». Обязательно:
    -- шаблон без имени в списке из пятнадцати штук не найти.
    name          VARCHAR(120) NOT NULL,

    -- Тема письма. Пустая допустима: бывает шаблон одного лишь текста
    -- («реквизиты»), который вставляют в уже начатое письмо.
    subject       VARCHAR(512) NOT NULL DEFAULT '',

    -- Тело письма разметкой — ровно тем, что лежит в окне написания.
    -- Приходит уже вычищенной (см. apps/api/src/templates/sanitize.ts):
    -- в базе не должно оказаться ничего, что нельзя вставить в письмо.
    body_html     TEXT         NOT NULL DEFAULT '',

    -- Порядок в меню и в настройках. Задаёт человек, а не дата создания:
    -- три ходовых шаблона обязаны стоять сверху, даже если заведены давно.
    position      INT          NOT NULL DEFAULT 0,

    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Одно имя на ящик. Два шаблона «Ответ клиенту» в меню неразличимы, и
-- человек будет вставлять их наугад.
CREATE UNIQUE INDEX IF NOT EXISTS mail_templates_name_idx
    ON mail_templates (lower(account_email), lower(name));

-- Список шаблонов одного ящика в порядке показа.
CREATE INDEX IF NOT EXISTS mail_templates_account_idx
    ON mail_templates (lower(account_email), position, id);

-- ------------------------------------------------------------------
-- ВЛОЖЕНИЯ ШАБЛОНА: ПОЧЕМУ БАЙТЫ, А НЕ ССЫЛКА НА ЗАГРУЗКУ
-- ------------------------------------------------------------------
-- Вложение попадает в письмо через временное хранилище загрузок
-- (apps/api/src/uploads.ts: <id>.bin + <id>.json в UPLOAD_DIR). Хранилище
-- временное НЕ на словах: `UploadStore.sweep()` удаляет всё старше суток,
-- и это правильно — иначе диск забился бы отменёнными черновиками.
--
-- Поэтому запомнить в шаблоне идентификатор загрузки нельзя. Шаблон,
-- сохранённый в понедельник, во вторник вставлял бы письмо без прайса —
-- молча, потому что файла на диске уже нет. Это ровно тот случай, когда
-- возможность лучше не делать вовсе, чем сделать так.
--
-- Значит, байты. Они копируются в эту таблицу в момент сохранения шаблона
-- и живут ровно столько же, сколько сам шаблон. При вставке шаблона в
-- письмо сервер кладёт их обратно во временное хранилище новой загрузкой —
-- и дальше письмо отправляется тем же кодом, что и всегда, ничего не зная
-- ни про какие шаблоны.
--
-- Предел размера (см. MAX_TEMPLATE_BYTES в apps/api/src/templates/types.ts)
-- намеренно меньше предела вложения письма: шаблон читается из базы целиком
-- при каждой вставке, и держать в строке двадцать мегабайт незачем.
CREATE TABLE IF NOT EXISTS mail_template_attachments (
    id           BIGSERIAL    PRIMARY KEY,

    -- Вложение без шаблона не существует: ON DELETE CASCADE, а не уборка
    -- кодом. Уборка кодом означала бы, что оборванное удаление оставляет
    -- в базе байты, на которые никто уже не сошлётся, — и найти их нечем.
    template_id  BIGINT       NOT NULL
                 REFERENCES mail_templates (id) ON DELETE CASCADE,

    filename     VARCHAR(255) NOT NULL,
    mime_type    VARCHAR(160) NOT NULL DEFAULT 'application/octet-stream',

    -- Размер хранится отдельно от содержимого нарочно: список шаблонов
    -- показывает «прайс.pdf, 240 КБ», и тянуть ради этого сами байты из
    -- базы (а их могут быть мегабайты на каждый шаблон) незачем.
    size         INT          NOT NULL DEFAULT 0,

    content      BYTEA        NOT NULL,
    position     INT          NOT NULL DEFAULT 0,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS mail_template_attachments_template_idx
    ON mail_template_attachments (template_id, position, id);
