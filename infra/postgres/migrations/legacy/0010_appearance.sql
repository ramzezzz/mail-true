-- Миграция 0009: оформление ящика хранится за пользователем.
--
-- ------------------------------------------------------------------
-- ЧТО БЫЛО НЕ ТАК
-- ------------------------------------------------------------------
-- Требование заказчика дословно: «тема оформления должна запоминаться
-- для каждого юзера». Выполнено не было: выбор темы лежал в localStorage
-- браузера (ключ `mt-theme`), выбор фоновой картинки — там же
-- (`mt-wallpaper`). Привязка получалась не к человеку, а к БРАУЗЕРУ,
-- и это давало два неприятных случая сразу:
--
--   * человек садится за другой компьютер — тема сбрасывается на
--     системную, будто он её и не выбирал;
--   * два человека за одним браузером делят одну тему, и вошедший вторым
--     видит оформление первого.
--
-- ------------------------------------------------------------------
-- РЕШЕНИЕ
-- ------------------------------------------------------------------
-- Две колонки в уже существующей таблице настроек ящика, а не отдельная
-- таблица: оформление — такая же настройка ящика, как имя отправителя
-- или поведение после удаления письма, и живёт ровно столько же. Своя
-- таблица дала бы второй источник истины и второй набор запросов на
-- ровном месте.
--
-- Значения по умолчанию подобраны так, чтобы у ящиков, которые ничего
-- не выбирали, поведение не изменилось: 'system' — следовать теме
-- операционной системы (ровно это делал пустой localStorage), пустая
-- строка в wallpaper — «фон не выбирали», интерфейс покажет первый
-- готовый.
--
-- Байты пользовательской картинки СЮДА НЕ КЛАДУТСЯ. Здесь только
-- КОРОТКИЙ выбор: 'preset:<id>' или 'custom'. Сама картинка может весить
-- мегабайты, хранится в IndexedDB браузера, и маршрута для её загрузки
-- на сервер нет (см. apps/web/src/appearance/wallpapers.ts). Выбор
-- 'custom' на другом устройстве честно откатывается на первый готовый
-- фон — тема при этом остаётся «обойной», то есть выглядит как выбор
-- пользователя, а не как поломка.
--
-- Миграция идемпотентна (IF NOT EXISTS): каталог миграций монтируется
-- в docker-entrypoint-initdb.d и на уже поднятой базе применяется руками.

ALTER TABLE mail_user_settings
    -- Выбор темы: 'system' | идентификатор темы из реестра
    -- (packages/shared/src/appearance.ts). Список тем проверяет API,
    -- а не база: новая тема не должна требовать миграции.
    ADD COLUMN IF NOT EXISTS theme      VARCHAR(16) NOT NULL DEFAULT 'system',

    -- Выбор фона «обойной» темы: 'preset:<id>' | 'custom' | '' (не выбирали).
    ADD COLUMN IF NOT EXISTS wallpaper  VARCHAR(64) NOT NULL DEFAULT '';
