-- Миграция 0018: «свои метки».
--
--   docker compose -f infra/docker-compose.yml exec -T postgres \
--     psql -v ON_ERROR_STOP=1 -U mailserver -d mailserver \
--     < infra/postgres/migrations/0018_mail_labels.sql
--
-- Скрипт идемпотентен (IF NOT EXISTS везде), повторное применение безвредно.
--
-- ------------------------------------------------------------------
-- ЧТО ЗДЕСЬ ЛЕЖИТ, А ЧТО — НЕТ
-- ------------------------------------------------------------------
-- Здесь лежит СПРАВОЧНИК меток: как метка называется по-человечески и
-- каким цветом её рисовать. Сама пометка письма здесь НЕ хранится и не
-- может: она живёт в ящике ключевым словом IMAP (`STORE +FLAGS mt-oplatit`),
-- ровно там же, где живут прочитанность и флажок.
--
-- Разделение не техническое удобство, а требование к поведению. Пометка
-- обязана быть видна во всех вкладках, в телефоне и после переустановки
-- браузера — значит, ей место в письме. А имя «Оплатить» и цвет в письмо
-- не положить: ключевое слово IMAP — это атом, в нём нет ни пробелов, ни
-- кириллицы, и переживает он не всякий перенос между серверами. Поэтому
-- в письме лежит короткий ключ, а всё остальное — в этой таблице.
--
-- Следствие, о котором продукт говорит человеку прямо в настройках:
-- если таблицу потерять, метки НЕ пропадут — они останутся в письмах
-- ключевыми словами, — но станут безымянными и бесцветными.
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ КЛЮЧ ХРАНИТСЯ ОТДЕЛЬНО ОТ ИМЕНИ
-- ------------------------------------------------------------------
-- Имя метки человек меняет когда захочет, а ключ в письме менять нельзя:
-- переименование «Оплатить» → «Счета» не должно ходить по всему ящику и
-- переставлять ключевые слова на тысячах писем. Поэтому ключ выдаётся один
-- раз при создании (`mt-` + транслитерация имени, см. mail/labels.ts) и
-- дальше не меняется никогда — меняются только имя и цвет.
CREATE TABLE IF NOT EXISTS mail_labels (
    id            BIGSERIAL    PRIMARY KEY,
    account_email VARCHAR(320) NOT NULL,

    -- Ключевое слово IMAP, лежащее в письмах. Всегда с приставкой `mt-`:
    -- она отделяет метки человека от служебных слов продукта, которые
    -- продукт может завести ЗАВТРА (см. RESERVED_KEYWORDS в mail/labels.ts).
    label_key     VARCHAR(64)  NOT NULL,

    -- Имя для человека: кириллица, пробелы, что угодно.
    name          VARCHAR(64)  NOT NULL,

    -- Идентификатор цвета из закрытого набора ('red', 'blue', …), а НЕ
    -- строка вида '#ff0000': цвет попадает в разметку интерфейса, и
    -- произвольное значение из базы означало бы, что туда доезжает ввод
    -- пользователя. Набор проверяет API, а не база: новый цвет не должен
    -- требовать миграции.
    color         VARCHAR(16)  NOT NULL DEFAULT 'blue',

    -- Порядок в справочнике и в пилюлях на письме.
    position      INT          NOT NULL DEFAULT 0,

    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Один ключ на ящик. Без этого повтор запроса при обрыве связи заводил бы
-- вторую метку с тем же ключевым словом — и в справочнике появились бы две
-- строки, снимающие друг у друга пометку с одних и тех же писем.
CREATE UNIQUE INDEX IF NOT EXISTS mail_labels_key_idx
    ON mail_labels (lower(account_email), label_key);

-- Список меток одного ящика в порядке показа.
CREATE INDEX IF NOT EXISTS mail_labels_account_idx
    ON mail_labels (lower(account_email), position, id);
