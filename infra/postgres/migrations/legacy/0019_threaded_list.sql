-- Миграция 0019: группировка писем в переписки в списке.
--
-- ------------------------------------------------------------------
-- ЧТО ДОБАВЛЯЕТСЯ
-- ------------------------------------------------------------------
-- Одна колонка в настройках ящика: показывать список разговорами или
-- письмами. Отдельной таблицы нет намеренно — это такая же настройка
-- ящика, как тема оформления или поведение после удаления письма, и
-- живёт она ровно столько же.
--
-- Сами переписки в базе НЕ хранятся и храниться не будут. Их собирает
-- почтовый сервер командой THREAD прямо по своему индексу
-- (apps/api/src/mail/threads.ts): наша копия этой связи неизбежно
-- разошлась бы с ящиком при первом же письме, доставленном мимо нас —
-- из телефона, из Thunderbird, правилом Sieve.
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ ВКЛЮЧЕНО ПО УМОЛЧАНИЮ
-- ------------------------------------------------------------------
-- У mail.ru, который мы повторяем, группировка по переписке включена
-- по умолчанию, и в этом заметная часть привычности интерфейса: человек
-- ждёт, что ответ на письмо окажется в той же строке, а не заведёт вторую
-- строку с той же темой. Выключенная по умолчанию возможность, которую
-- надо сперва найти в настройках, эту привычность не воспроизводит.
--
-- Выключить можно — переключатель есть в общих настройках почты, и выбор
-- запоминается за ящиком на сервере, а не за браузером: человек с двумя
-- компьютерами должен видеть свою почту одинаково.
--
-- Значение по умолчанию действует и на уже заведённые ящики (DEFAULT
-- проставляется существующим строкам при ALTER).
--
-- Миграция идемпотентна (IF NOT EXISTS): каталог миграций монтируется
-- в docker-entrypoint-initdb.d и на уже поднятой базе применяется руками.

ALTER TABLE mail_user_settings
    ADD COLUMN IF NOT EXISTS threaded_list BOOLEAN NOT NULL DEFAULT true;
