-- Миграция 0031: отметка «этот сервер уже установлен».
--
-- ------------------------------------------------------------------
-- ЗАЧЕМ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ СТРОКА В .env
-- ------------------------------------------------------------------
-- Отметка нужна веб-установщику (apps/installer): он поднимается с
-- сокетом Docker, то есть с правом пересоздавать контейнеры, и потому
-- обязан отказаться работать на уже настроенном сервере. Одного признака
-- мало — каждый по отдельности лжёт:
--
--   * INSTALL_COMPLETED_AT в infra/.env лежит рядом с установщиком и
--     стирается вместе с файлом. Достаточно потерять .env (или развернуть
--     стек в новый каталог поверх СТАРЫХ томов), и отметка исчезает, а
--     почта, ящики и пароли остаются. Установщик увидел бы чистое поле и
--     переписал бы пароль Postgres, разойдясь с уже созданным томом;
--
--   * запись в базе живёт в том же томе, что и сами данные, — то есть
--     ровно там, где живёт то, что установщик может испортить. Её
--     невозможно потерять, не потеряв заодно и повод для осторожности.
--
-- Поэтому отметок две, и обе ставятся вместе (install/install.sh, шаг
-- «Установка завершена»). Установщик считает сервер установленным, если
-- нашёл ЛЮБУЮ из них: пропустить установку на живом сервере не страшно,
-- а переустановить поверх — страшно.
--
-- Снимается отметка одной осознанной командой на сервере:
--     sudo bash install/allow-reinstall.sh
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ ОДНА СТРОКА
-- ------------------------------------------------------------------
-- Это не журнал установок, а состояние сервера: «установлен» или нет.
-- Ключ id с проверкой CHECK (id) допускает единственное значение true —
-- вторая строка в таблицу физически не поместится, и «какая из двух
-- записей главная» спрашивать не придётся. Повторная установка обновляет
-- ту же строку (ON CONFLICT DO UPDATE).
--
-- Скрипт идемпотентен, повторное применение безвредно.

BEGIN;

CREATE TABLE IF NOT EXISTS install_state (
    -- Единственная допустимая строка таблицы.
    id            boolean     PRIMARY KEY DEFAULT true CHECK (id),

    -- Когда установка завершилась успешно. Именно завершилась: строка
    -- пишется последним шагом, после того как стек поднялся, схема
    -- применилась, а ящик и учётная запись администратора созданы.
    completed_at  timestamptz NOT NULL DEFAULT now(),

    -- Чем ставили: install.sh (консоль) или installer (браузер).
    -- Пригождается в одном разговоре — «как этот сервер вообще ставили».
    installed_by  text        NOT NULL DEFAULT 'install.sh',

    -- Что именно установлено. Веб-установщик показывает это на экране
    -- отказа: человеку нужно понять, что за сервер он чуть не переписал.
    mail_domain   text        NOT NULL DEFAULT '',
    mail_hostname text        NOT NULL DEFAULT '',
    admin_login   text        NOT NULL DEFAULT ''
);

COMMENT ON TABLE install_state IS
    'Отметка «сервер установлен». Ставит install/install.sh, читает apps/installer; снимает install/allow-reinstall.sh.';

COMMIT;
