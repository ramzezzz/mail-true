-- Миграция 0020: ящик-приёмник задания переноса связывается с базой.
--
-- ------------------------------------------------------------------
-- ЧТО БЫЛО НЕ ТАК
-- ------------------------------------------------------------------
-- В mail_migration_items адрес приёмника хранился одной строкой
-- (dest_user VARCHAR(320)) и ни с чем не был связан. Ничто не мешало
-- завести задание на ящик, которого нет: опечатка в столбце «куда»
-- выгрузки Kerio принималась молча, задание вставало в очередь, и
-- узнавал о ней человек только в середине ночного переноса — когда
-- работник доходил до этой строки и получал от нашего же Dovecot отказ
-- входа. Отказ этот выглядел как «сервер не принял логин или пароль»,
-- то есть звал проверять пароли там, где не было самого ящика.
--
-- ------------------------------------------------------------------
-- ЧТО ДОБАВЛЯЕТСЯ
-- ------------------------------------------------------------------
-- Столбец dest_user_id — ссылка на virtual_users(id). Он НЕ заменяет
-- dest_user, и это осознанно:
--
--   * dest_user остаётся текстом, потому что задание переноса — ещё и
--     отчёт. Ящик могут удалить через месяц после переезда, и строка
--     «куда ехало» обязана пережить удаление, иначе отчёт о ночном
--     переносе превратится в список пустых клеток;
--   * dest_user_id даёт настоящую проверку существования на уровне базы:
--     сослаться на несуществующую строку нельзя, и ошибиться адресом
--     мимо приложения (руками в psql, чужим скриптом) уже не выйдет.
--
-- ON DELETE SET NULL по той же причине: удаление ящика не должно ни
-- удалять историю переноса, ни блокироваться ею. NULL в этом столбце
-- у завершённого задания читается как «ящик с тех пор удалён», а у
-- идущего — как повод остановить его строку с внятным объяснением
-- (см. apps/api/src/admin/migrate-runner.ts).
--
-- Существующие строки остаются с NULL намеренно: задания, заведённые до
-- этой миграции, — уже история, и достраивать им связь задним числом
-- значило бы приписать им проверку, которой при их создании не было.
--
-- Миграция идемпотентна (IF NOT EXISTS + проверка наличия связи):
-- каталог монтируется в docker-entrypoint-initdb.d, а на уже поднятой
-- базе применяется руками.

ALTER TABLE mail_migration_items
    ADD COLUMN IF NOT EXISTS dest_user_id INTEGER;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
         WHERE conname = 'mail_migration_items_dest_user_fkey'
           AND conrelid = 'mail_migration_items'::regclass
    ) THEN
        ALTER TABLE mail_migration_items
            ADD CONSTRAINT mail_migration_items_dest_user_fkey
            FOREIGN KEY (dest_user_id) REFERENCES virtual_users(id) ON DELETE SET NULL;
    END IF;
END
$$;

-- Индекс нужен не поиску по нему, а самому ON DELETE SET NULL: без него
-- удаление ящика заставляет Postgres просматривать всю таблицу строк
-- переноса, а она растёт на строку с каждого ящика каждого задания.
CREATE INDEX IF NOT EXISTS idx_migration_items_dest_user
    ON mail_migration_items (dest_user_id);
