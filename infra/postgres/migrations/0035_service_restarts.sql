-- Миграция 0035: журнал перезапусков служб (кнопки «Применить» в панели).
--
--   docker compose -f infra/docker-compose.yml exec -T postgres \
--     psql -v ON_ERROR_STOP=1 -U mailserver -d mailserver \
--     < infra/postgres/migrations/0035_service_restarts.sql
--
-- Скрипт идемпотентен (IF NOT EXISTS везде), повторное применение безвредно.
--
-- ------------------------------------------------------------------
-- ЗАЧЕМ ОТДЕЛЬНАЯ ТАБЛИЦА, ЕСЛИ ЕСТЬ ЖУРНАЛ АУДИТА
-- ------------------------------------------------------------------
-- Журнал аудита отвечает на вопрос «кто это сделал» и не удаляется
-- никогда. Здесь же лежит РАБОЧЕЕ состояние, которое нужно продукту
-- прямо во время работы, а не человеку через полгода:
--
--   1. «Настройка сохранена, но ещё не применена». Для настроек ЧУЖИХ
--      контейнеров это нельзя вычислить сравнением с окружением своего
--      процесса: значение читает autoconfig или unbound, а не сервер
--      приложения. Единственный честный признак — время последнего
--      удачного применения этой службы против времени правки настройки.
--      Оба времени лежат здесь и в server_settings.
--
--   2. «Служба поднялась или нет и почему». Ответ приходит через
--      несколько секунд после нажатия — то есть уже другому запросу,
--      а после перезапуска сервера приложения и вовсе другому процессу.
--      Держать его в памяти негде.
--
--   3. Защита от петли. Сервер приложения умеет перезапускать сам себя,
--      и настройка, из-за которой он падает на старте, превращала бы
--      кнопку в бесконечный круг: поднялся, упал, поднялся. Записи о
--      КАЖДОМ старте процесса (action='boot') позволяют ему сосчитать,
--      сколько раз он перезапускался за последние минуты, и отказаться
--      делать это снова, объяснив причину.
--
-- Записи здесь ЧИСТЯТСЯ по возрасту (в отличие от аудита): это рабочее
-- состояние, а не доказательство. Доказательство пишется в аудит теми же
-- маршрутами и остаётся навсегда.
--
-- ------------------------------------------------------------------
-- ЧЕГО ЗДЕСЬ НЕТ
-- ------------------------------------------------------------------
-- Ни имени контейнера, ни команды. Хранится ИМЯ СЛУЖБЫ из закрытого
-- списка в коде (apps/api/src/admin/restart-targets.ts). Строка с чужим
-- именем не даёт ничего: посредник, который единственный имеет доступ к
-- Docker, сверяет имя со своим собственным списком и произвольных команд
-- не принимает вовсе.
CREATE TABLE IF NOT EXISTS service_restarts (
    id           BIGSERIAL    PRIMARY KEY,

    -- Имя службы из закрытого списка (api, postfix, dovecot, nginx,
    -- rspamd, unbound, autoconfig). Не имя контейнера: оно зависит от
    -- имени проекта Docker Compose и на разных стендах разное.
    service      VARCHAR(64)  NOT NULL,

    -- Что делали:
    --   restart   — перезапуск процесса в том же контейнере;
    --   recreate  — пересоздание контейнера (нужно, когда служба читает
    --               настройку из окружения: окружение задаётся при
    --               СОЗДАНИИ контейнера, и перезапуск его не меняет);
    --   boot      — отметка «процесс сервера приложения запустился».
    --               Её ставит сам процесс при старте, администратора у
    --               неё нет. Нужна для защиты от петли перезапусков.
    action       VARCHAR(16)  NOT NULL,

    -- Логин администратора. NULL у отметок boot: их никто не заказывал.
    requested_by VARCHAR(128),

    requested_at TIMESTAMPTZ  NOT NULL DEFAULT now(),

    -- Когда стало известно, чем кончилось. NULL, пока идёт.
    finished_at  TIMESTAMPTZ,

    -- pending — идёт (или процесс умер, не успев дописать);
    -- ok      — служба поднялась;
    -- failed  — не поднялась, причина в detail.
    status       VARCHAR(16)  NOT NULL DEFAULT 'pending',

    -- Что ответила служба или посредник. Показывается человеку как есть,
    -- поэтому здесь текст, а не код: «код 137» не объясняет ничего.
    detail       TEXT
);

-- Основной вопрос к таблице: «когда эту службу удачно применяли в
-- последний раз». Отсюда и порядок столбцов в индексе.
CREATE INDEX IF NOT EXISTS service_restarts_service_time_idx
    ON service_restarts (service, requested_at DESC);

-- Второй вопрос — «что происходило за последние минуты» (защита от петли
-- и лента последних действий в панели).
CREATE INDEX IF NOT EXISTS service_restarts_time_idx
    ON service_restarts (requested_at DESC);

COMMENT ON TABLE service_restarts IS
    'Рабочее состояние перезапусков служб из панели: что применяли, чем кончилось, '
    'когда служба применялась в последний раз. След «кто это сделал» — в admin_audit_log.';
