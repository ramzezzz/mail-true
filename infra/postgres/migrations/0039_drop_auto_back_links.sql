-- Миграция 0039: снять связи ящиков, заведённые сервером «в обратную сторону».
--
-- ------------------------------------------------------------------
-- ЧТО БЫЛО НЕ ТАК
-- ------------------------------------------------------------------
-- Связывание второго ящика («мои ящики» в почте) заводило запись В ОБЕ
-- СТОРОНЫ. Человек доказывал пароль ящика B — и сервер молча записывал
-- ещё и строку «владелец B, связанный A» с зашифрованным паролем A.
-- Обоснование было бытовым: чтобы вернуться назад тоже без пароля.
--
-- Цена несоразмерна. Проверка при связывании доказывает ровно одно:
-- вызывающий знает пароль B. Права B ходить в A из этого не следует, а
-- записывалось именно оно: владелец B видел ящик A в списке связанных и
-- входил туда одним нажатием, ничего не подтверждая.
--
-- Живой сценарий: администратор сам выдал сотруднику пароль, связал его
-- ящик со своим, чтобы разобрать жалобу, — и подарил сотруднику вход в
-- свою почту.
--
-- В коде это уже исправлено: связь заводится в одну сторону, а право
-- вернуться живёт в сессии того, кто переключился. Но у серверов, где
-- ящики связывали раньше, обратные записи ОСТАЛИСЬ — вместе с чужими
-- паролями и правом входа. Обновление кода их не убирает; убирает эта
-- миграция.
--
-- ------------------------------------------------------------------
-- КАК ОТЛИЧИТЬ АВТОМАТИЧЕСКУЮ ЗАПИСЬ ОТ ЗАКОННОЙ
-- ------------------------------------------------------------------
-- Законная связь B → A тоже возможна: владелец B мог сам добавить ящик A,
-- введя его пароль. Отличаем по трём признакам сразу:
--
--   1. существует парная связь A → B (её заводили в той же операции);
--   2. обе записи созданы почти одновременно — в пределах пяти секунд:
--      это был один запрос, два соседних INSERT;
--   3. удаляемая запись создана ПОЗЖЕ парной (id больше). Прямую связь
--      прежний код заводил первой, автоматическую обратную — следом.
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ ЗДЕСЬ ВАЖЕН ТРЕТИЙ ПРИЗНАК
-- ------------------------------------------------------------------
-- Без него условие СИММЕТРИЧНО: для пары A → B и B → A каждая строка
-- подходит под «есть парная и создана рядом», а EXISTS в DELETE считается
-- по снимку до начала оператора — то есть удалялись ОБЕ. Проверено на
-- живой базе: две вставленные строки, `DELETE 2`, пусто.
--
-- Цена ошибки высокая: у каждого, кто связал свой второй ящик, он исчезал
-- из переключателя вместе с сохранённым паролем — без единого слова, и
-- вернуть его можно было только вводом пароля заново.
--
-- Прежний четвёртый признак — «у автоматической записи нет названия, а
-- человек обычно даёт связи имя» — убран: названия связи в продукте дать
-- НЕГДЕ. Веб-интерфейс зовёт связывание двумя полями (адрес и пароль), и
-- label у любой связи всегда NULL. Признак, который верен для всех строк,
-- ничего не отличает.
DELETE FROM linked_accounts back
 WHERE EXISTS (
         SELECT 1
           FROM linked_accounts forward
          WHERE lower(forward.owner_email)  = lower(back.linked_email)
            AND lower(forward.linked_email) = lower(back.owner_email)
            -- Асимметрия: уходит только та, что заведена ВТОРОЙ.
            AND forward.id < back.id
            AND abs(extract(epoch FROM (forward.created_at - back.created_at))) <= 5
       );

COMMENT ON TABLE linked_accounts IS
    'Свои дополнительные ящики: переключение без ввода пароля. Связь ОДНОСТОРОННЯЯ — '
    'её заводит тот, кто доказал пароль второго ящика. Обратный переход разрешает '
    'сессия (SessionData.returnTo), а не запись в этой таблице.';
