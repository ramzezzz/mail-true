-- Миграция 0000: журнал применённых миграций.
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ НОМЕР 0000, А НЕ СЛЕДУЮЩИЙ СВОБОДНЫЙ
-- ------------------------------------------------------------------
-- Порядок применения задаётся именем файла: и Postgres при первичной
-- инициализации тома (каталог смонтирован в /docker-entrypoint-initdb.d),
-- и установщик перебирают каталог по алфавиту. Реестр обязан существовать
-- ДО того, как в него что-то запишут, поэтому он первый по имени.
-- Номер 0000 свободен и занят намеренно; следующая содержательная
-- миграция берёт очередной номер после последнего существующего.
--
-- ------------------------------------------------------------------
-- ЧТО БЫЛО НЕ ТАК
-- ------------------------------------------------------------------
-- Журнала не было вовсе. Установщик применял ВЕСЬ каталог целиком при
-- каждом запуске, полагаясь на идемпотентность файлов. Это работает ровно
-- до тех пор, пока каждая миграция состоит из CREATE ... IF NOT EXISTS,
-- и разваливается сразу, как только появляется содержательное действие
-- над данными: 0008 переписывала историю доставки UPDATE-ом по всей
-- таблице и делала это ЗАНОВО при каждой установке и каждом обновлении.
--
-- Хуже другое: ответить на вопрос «какие миграции на этом сервере
-- применены» было нечем. Ответ добывался косвенно — «посмотрим, есть ли
-- такая таблица». Отсюда и вся диагностика в install/selfcheck.sh,
-- которая сравнивает список CREATE TABLE в файлах со списком таблиц
-- в базе: это была единственная доступная замена журналу.
--
-- ------------------------------------------------------------------
-- ЗАЧЕМ ХРАНИТЬ КОНТРОЛЬНУЮ СУММУ
-- ------------------------------------------------------------------
-- Чтобы отличить «миграция применена» от «применена ДРУГАЯ миграция
-- с этим же именем». Файл могли поправить после выпуска — например,
-- дописать в него забытую колонку. Без контрольной суммы такой файл
-- навсегда остался бы неприменённым: имя в журнале есть, значит пропустим.
-- С контрольной суммой установщик видит расхождение и применяет файл
-- заново (все они идемпотентны), обновляя запись.
--
-- ------------------------------------------------------------------
-- КАК ЖУРНАЛ ПРИНИМАЕТ УЖЕ РАБОТАЮЩИЙ СЕРВЕР
-- ------------------------------------------------------------------
-- Никак не «принимает» — и это осознанное решение, а не упущение.
--
-- На стенде, который стоит давно, журнал пуст, а схема уже накатана.
-- Соблазн отметить все файлы применёнными «задним числом» велик и
-- НЕВЕРЕН: сервер может стоять на версии 0015, а в каталоге лежать 0021,
-- и такая отметка тихо пропустила бы шесть настоящих миграций — то есть
-- ровно тот отказ, ради предотвращения которого журнал и заводится.
-- Узнать версию неоткуда: её негде было хранить, журнала-то не было.
--
-- Поэтому первый запуск с журналом ведёт себя ровно как все запуски до
-- него: применяет весь каталог (файлы идемпотентны, это безопасно) и
-- записывает результат. Один лишний проход — цена honest-перехода.
-- Начиная со ВТОРОГО запуска применяется только новое.
--
-- Скрипт идемпотентен, повторное применение безвредно.

BEGIN;

CREATE TABLE IF NOT EXISTS schema_migrations (
    -- Имя файла целиком — оно и есть естественный ключ каталога.
    -- Не номер: номера в этом проекте уже дважды сталкивались между
    -- собой, и ключ по номеру превратил бы столкновение имён в тихую
    -- пропажу одной из двух миграций.
    filename    text        PRIMARY KEY,

    -- Номер и имя отдельно — чтобы по журналу можно было отвечать
    -- на вопрос «до какой версии докатан этот сервер» без разбора
    -- строки в запросе.
    version     text        NOT NULL,
    name        text        NOT NULL,

    -- sha256 содержимого файла на момент применения.
    checksum    text        NOT NULL,

    applied_at  timestamptz NOT NULL DEFAULT now(),

    -- Кто применил: install.sh, restore.sh или initdb (первичная
    -- инициализация тома силами самого Postgres). Пригождается ровно
    -- в одном разговоре — «откуда на сервере взялась эта миграция».
    applied_by  text        NOT NULL DEFAULT ''
);

COMMENT ON TABLE schema_migrations IS
    'Журнал применённых миграций схемы. Ведут install/install.sh и install/restore.sh.';

-- Отчёт «что и когда накатывали» читается по времени.
CREATE INDEX IF NOT EXISTS idx_schema_migrations_applied
    ON schema_migrations (applied_at DESC);

COMMIT;
