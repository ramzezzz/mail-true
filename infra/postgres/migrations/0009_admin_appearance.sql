-- Миграция 0009: тема оформления панели — за учётной записью администратора.
--
-- До неё выбор темы жил в localStorage браузера. Это привязка к КОМПЬЮТЕРУ,
-- а не к человеку: сел за другую машину — тема сбросилась; два администратора
-- за одной машиной делили одну тему. Заказчик просил «запоминать для каждого
-- юзера», то есть за учётной записью.
--
-- Применение к уже работающей базе:
--
--   docker compose -f infra/docker-compose.yml exec -T postgres \
--     psql -v ON_ERROR_STOP=1 -U mailserver -d mailserver \
--     < infra/postgres/migrations/0009_admin_appearance.sql
--
-- Скрипт идемпотентен (IF NOT EXISTS), повторное применение безвредно.

BEGIN;

-- ------------------------------------------------------------------
-- Оформление панели у администратора.
--
-- Колонка в admin_users, а не отдельная таблица настроек: значение ровно
-- одно на учётную запись, живёт столько же, сколько сама учётная запись,
-- и читается тем же запросом, что и всё остальное о ней. Отдельная таблица
-- дала бы соединение и строку-сироту на каждый вход — ради одного поля.
--
-- NULL значит «администратор темы не выбирал»: панель показывает свою
-- тему по умолчанию (Графит). Отличать «не выбирал» от «выбрал графит»
-- незачем — поведение одинаковое, но NULL честнее пустой строки.
--
-- Проверки на список тем ЗДЕСЬ НЕТ намеренно. Названия тем — понятие
-- интерфейса (apps/admin/src/appearance/adminThemes.ts), и CHECK означал бы
-- миграцию базы на каждую новую расцветку. База хранит опознавательный
-- знак, а разбирает его панель: незнакомое имя она молча заменяет темой
-- по умолчанию (см. isAdminThemeName). Форму значения стережёт сервер
-- (apps/api/src/admin/routes/auth.ts) и длина колонки.
-- ------------------------------------------------------------------
ALTER TABLE admin_users
    ADD COLUMN IF NOT EXISTS theme VARCHAR(32);

COMMENT ON COLUMN admin_users.theme IS
    'Тема оформления панели у этого администратора; NULL — тема по умолчанию';

COMMIT;
