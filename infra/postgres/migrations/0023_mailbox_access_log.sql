-- Миграция 0023: «история входов и действий» владельца ящика.
--
--   docker compose -f infra/docker-compose.yml exec -T postgres \
--     psql -v ON_ERROR_STOP=1 -U mailserver -d mailserver \
--     < infra/postgres/migrations/0023_mailbox_access_log.sql
--
-- Скрипт идемпотентен (IF NOT EXISTS везде), повторное применение безвредно.
--
-- ------------------------------------------------------------------
-- ЗАЧЕМ ЭТО ЕСТЬ
-- ------------------------------------------------------------------
-- У администратора журнал аудита есть с миграции 0003 (admin_audit_log),
-- у владельца ящика — не было. То есть человек, у которого угнали пароль,
-- не мог узнать даже того, заходил ли кто-то ещё. У mail.ru на это есть
-- «Лог действий», и вопрос он закрывает ровно один: «это был я?».
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ ТАБЛИЦА, ЕСЛИ ЕСТЬ ЖУРНАЛЫ DOVECOT
-- ------------------------------------------------------------------
-- Половина ответа действительно лежит в журналах: Dovecot пишет каждый
-- вход по IMAP и POP3, Postfix — каждую отправку с проверкой пароля.
-- Читать их мы умеем (apps/api/src/admin/log-files.ts), и раздел их
-- читает — это второй источник, и он остаётся источником.
--
-- Но журналов НЕ ХВАТАЕТ, и по трём причинам сразу:
--
--   1. Веб-входа в них нет вовсе. Веб-интерфейс проверяет пароль
--      IMAP-логином из своего контейнера, поэтому в журнале Dovecot он
--      выглядит как подключение сервера приложения к самому себе — без
--      адреса того человека, который на самом деле вошёл. Настоящий адрес
--      знает только сервер приложения, и записать его может только он.
--   2. Журналы проворачиваются. Через неделю (а на нагруженном сервере
--      через сутки) вчерашняя история уезжает в dovecot.log.1.gz, и
--      «заходил ли кто-то в отпуске» ответа уже не имеет.
--   3. Действий над ящиком в журналах нет: смена настроек, правка правил,
--      очистка корзины, заказ выгрузки. Это не входы, но именно их человек
--      и ищет, когда подозревает чужого.
--
-- Поэтому здесь лежит то, что знает ТОЛЬКО сервер приложения, а журналы
-- Dovecot и Postfix подмешиваются к этому при показе.
--
-- ------------------------------------------------------------------
-- ЧЕГО ЗДЕСЬ НЕТ
-- ------------------------------------------------------------------
-- Пароля — ни в каком виде, даже неудачная попытка входа не сохраняет
-- того, что человек ввёл. Ни темы письма, ни адресатов: это журнал
-- ДОСТУПА, а не переписки. `detail` — короткая строка по-русски, которую
-- пишет сам код («Изменены общие настройки»), а не данные пользователя.
CREATE TABLE IF NOT EXISTS mailbox_access_log (
    id            BIGSERIAL    PRIMARY KEY,

    -- Чей ящик. Ключ отбора и единственная защита от чужих глаз: маршрут
    -- берёт адрес из сессии, передать чужой негде.
    account_email VARCHAR(320) NOT NULL,

    at            TIMESTAMPTZ  NOT NULL DEFAULT now(),

    -- Что произошло: 'login' | 'login.failed' | 'logout' | 'settings' |
    -- 'filters' | 'folders' | 'trash' | 'export'. Набор проверяет API,
    -- а не база: новое действие не должно требовать миграции.
    kind          VARCHAR(32)  NOT NULL,

    -- Каким способом. Здесь всегда 'web': всё остальное ('imap', 'pop3',
    -- 'smtp') приходит из журналов Dovecot и Postfix и в базе не оседает.
    -- Колонка всё равно нужна: без неё показ не отличит свою запись от
    -- журнальной, а строки в таблице на экране стоят вперемешку.
    channel       VARCHAR(16)  NOT NULL DEFAULT 'web',

    -- Удачно или нет. Неудачные входы — половина смысла раздела: три
    -- отказа подряд из чужой страны человек обязан увидеть.
    success       BOOLEAN      NOT NULL DEFAULT TRUE,

    -- Адрес того, кто это сделал. Настоящий адрес человека, а не адрес
    -- контейнера: он берётся из X-Forwarded-For, которому Fastify верит
    -- только от своего обратного прокси (TRUSTED_PROXIES, см. app.ts).
    ip            VARCHAR(64),

    -- Строка браузера или почтовой программы. Обрезается до 512 в коде.
    user_agent    VARCHAR(512),

    -- Короткое пояснение по-русски: «Изменены общие настройки»,
    -- «Очищена папка Корзина (14 писем)». Пишет код, не пользователь.
    detail        TEXT
);

-- Главный и единственный запрос показа: последние события одного ящика.
CREATE INDEX IF NOT EXISTS mailbox_access_log_account_idx
    ON mailbox_access_log (lower(account_email), at DESC, id DESC);

-- Запрос уборщика: «что старше срока». Отдельный индекс по времени, без
-- ящика: уборщик ходит по всей таблице разом, и индекс по (ящик, время)
-- ему не годится — начинать пришлось бы с перебора ящиков.
CREATE INDEX IF NOT EXISTS mailbox_access_log_at_idx
    ON mailbox_access_log (at);
