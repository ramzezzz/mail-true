-- Миграция 0030: «напомнить, если не ответили».
--
--   docker compose -f infra/docker-compose.yml exec -T postgres \
--     psql -v ON_ERROR_STOP=1 -U mailserver -d mailserver \
--     < infra/postgres/migrations/0030_awaiting_replies.sql
--
-- Скрипт идемпотентен (IF NOT EXISTS везде), повторное применение безвредно.
--
-- ------------------------------------------------------------------
-- ЧТО ЭТО
-- ------------------------------------------------------------------
-- Отправив письмо, человек назначает срок ожидания. Ответили вовремя —
-- он ничего не замечает, и это главное свойство: напоминание, которое
-- срабатывает всегда, — это просто ещё одно письмо в почте. Не ответили —
-- письмо возвращается ему на глаза, во «Входящие», непрочитанным и
-- закреплённым наверху.
--
-- Сейчас этот список человек ведёт в голове: кому я писал, кто не ответил,
-- пора ли напоминать. И перечитывает «Отправленные», сверяя их с
-- «Входящими», — ровно та ручная работа, которая здесь исчезает.
--
-- ------------------------------------------------------------------
-- КАК УЗНАЁТСЯ, ЧТО ОТВЕТ ПРИШЁЛ (главный вопрос этой возможности)
-- ------------------------------------------------------------------
-- Проверок ДВЕ, и они устроены по-разному не случайно.
--
-- 1. ОСНОВНАЯ — по ссылкам. В ответе стоит In-Reply-To (и, как правило,
--    References) с Message-ID нашего письма. Это и есть определение ответа
--    по RFC 5322; по этим же заголовкам собирает переписки сам почтовый
--    сервер (mail/threads.ts). Ложное срабатывание здесь практически
--    невозможно: Message-ID уникален.
--
-- 2. ЗАПАСНАЯ — тот же собеседник и та же тема. Часть почтовых программ
--    In-Reply-To не ставит вовсе, и по одной первой проверке такой ответ
--    остался бы незамеченным. Поэтому дополнительно считается ответом
--    письмо, пришедшее ПОСЛЕ нашего от кого-то из адресатов поля «Кому»
--    с той же темой (с точностью до «Re:», «Ответ:», регистра и пробелов).
--
-- Обе ошибки здесь несимметричны, и выбор сделан осознанно:
--   - НЕ заметить ответ = не напомнить. Человек остаётся ровно там, где
--     был бы без возможности вовсе, — сам заметит и сам напишет.
--   - Напомнить ЗРЯ = сказать неправду. Человек открывает письмо, видит
--     ответ, который пришёл три дня назад, и больше механизму не верит.
-- Поэтому вторая проверка нарочно широкая: она ошибается в сторону
-- «ответ был». Ровно про это и предупреждает разбор (docs/gaps.md, п. 4):
-- «Лучше не заметить ответ реже, чем напомнить впустую».
--
-- Что НЕ считается ответом: наше же письмо (человек написал вдогонку сам),
-- автоответ об отпуске (у него есть Auto-Submitted, см. mail/await-reply.ts)
-- и отчёт о недоставке. Иначе достаточно было бы уехать в отпуск обоим.
--
-- ------------------------------------------------------------------
-- ЧЕГО ЗДЕСЬ НЕТ
-- ------------------------------------------------------------------
-- Ни тела письма, ни пароля ящика. Тема и адресат лежат ради строки
-- подборки «Ждут ответа» и ради запасной проверки — и ничего кроме.
CREATE TABLE IF NOT EXISTS awaiting_replies (
    id                 BIGSERIAL    PRIMARY KEY,
    account_email      VARCHAR(320) NOT NULL,

    -- Где лежит отправленное письмо. Путь IMAP, а не наш идентификатор
    -- папки: идентификатор `f-<base64url(путь)>` — это форма показа, и
    -- завязывать на неё хранение значило бы, что правила показа ломают
    -- напоминание.
    sent_path          TEXT         NOT NULL,
    sent_uid           BIGINT       NOT NULL,
    -- UIDVALIDITY папки на момент постановки срока. Разошёлся — номер выше
    -- ничего не значит, и письмо ищется по Message-ID.
    sent_uidvalidity   BIGINT       NOT NULL DEFAULT 0,

    -- Message-ID отправленного письма БЕЗ угловых скобок. Обязателен:
    -- без него ждать ответа не по чему (см. пояснение выше), поэтому
    -- маршрут отказывает сразу и внятно, а не заводит запись, которая
    -- потом напомнит впустую.
    message_id         TEXT         NOT NULL,

    -- Для строки подборки «Ждут ответа» и для запасной проверки.
    subject            TEXT         NOT NULL DEFAULT '',
    -- Адреса из поля «Кому», через запятую. Именно «Кому», а не «Копия»:
    -- ответа ждут от того, кому написали, а не от тех, кто читает.
    to_addresses       TEXT         NOT NULL DEFAULT '',
    -- Когда письмо было отправлено: запасная проверка смотрит только на
    -- письма, пришедшие ПОСЛЕ этого момента.
    sent_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),

    -- Когда напоминать, если ответа не будет. Момент времени, а не «дата
    -- и время»: «через три дня» — это три дня ЧЕЛОВЕКА, и превращение
    -- в момент происходит один раз, по поясу браузера.
    due_at             TIMESTAMPTZ  NOT NULL,
    time_zone          VARCHAR(64),
    preset             VARCHAR(32)  NOT NULL DEFAULT 'custom',

    -- 'waiting'   — ждём ответа (единственное живое состояние);
    -- 'answered'  — ответ пришёл, напоминать не о чем;
    -- 'reminded'  — срок вышел, ответа нет, письмо поднято на глаза;
    -- 'cancelled' — человек нажал «больше не ждать»;
    -- 'gone'      — отправленного письма в ящике больше нет.
    state              VARCHAR(16)  NOT NULL DEFAULT 'waiting',
    -- Чем именно опознан ответ: 'references' | 'subject'. Пусто — ответа
    -- не было. Хранится ради разбора жалоб «оно напомнило зря»: по этому
    -- полю видно, какая из двух проверок сработала.
    answer_kind        VARCHAR(16),
    answered_at        TIMESTAMPTZ,
    reminded_at        TIMESTAMPTZ,

    -- Сколько раз проверка срывалась. НЕ повод сдаться: срыв — это почти
    -- всегда недоступный Dovecot, а недоступность проходит сама.
    attempts           INT          NOT NULL DEFAULT 0,
    last_error         TEXT,
    last_attempt_at    TIMESTAMPTZ,

    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    closed_at          TIMESTAMPTZ
);

-- Главный запрос работника: «кому пора». Частичный индекс по состоянию —
-- закрытых записей со временем станет на порядки больше живых.
CREATE INDEX IF NOT EXISTS awaiting_replies_due_idx
    ON awaiting_replies (due_at)
    WHERE state = 'waiting';

-- Подборка «Ждут ответа» одного человека.
CREATE INDEX IF NOT EXISTS awaiting_replies_account_idx
    ON awaiting_replies (lower(account_email), due_at)
    WHERE state = 'waiting';

-- Одно письмо — один срок. Без этого двойное нажатие кнопки (или повтор
-- запроса при обрыве связи) заводило бы два срока на одно письмо, и
-- человек получил бы два одинаковых напоминания. Индекс частичный:
-- закрытые записи повторяться могут и должны — ждать ответа на то же
-- письмо второй раз человек вправе.
CREATE UNIQUE INDEX IF NOT EXISTS awaiting_replies_live_key
    ON awaiting_replies (lower(account_email), message_id)
    WHERE state = 'waiting';
