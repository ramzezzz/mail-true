-- Миграция 0008: направление у повторных попыток доставки.
--
-- ------------------------------------------------------------------
-- ЧТО БЫЛО НЕ ТАК
-- ------------------------------------------------------------------
-- Направление письма определяется ТРАНСПОРТОМ, а не адресом: адрес врёт
-- (алиас, пересылка, ящик на чужом домене), транспорт — нет. Но повторные
-- попытки Postfix пишет псевдотранспортом `error`:
--
--   postfix/error[9300]: 1D816432FF: to=<kuda@example.org>, relay=none,
--       delay=420, dsn=4.4.1, status=deferred
--       (delivery temporarily suspended: connect refused)
--
-- Транспорта доставки в такой строке нет вовсе, и в разделе «Почтовый
-- поток» эти записи показывались как «неизвестно» — при том что первая
-- попытка ТОГО ЖЕ письма честно назвала его исходящим. На сервере, где
-- принимающая сторона недоступна, таких строк набирается больше всего:
-- одно письмо даёт десятки повторов.
--
-- Сборщик теперь наследует направление от того же письма в очереди.
-- Эта миграция чинит то, что уже накоплено: переписывать историю задним
-- числом можно только там, где ответ известен ТОЧНО, а не угадан.
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ ИМЕННО ПО queue_id, А НЕ ПО ДОМЕНУ АДРЕСАТА
-- ------------------------------------------------------------------
-- По домену получилось бы правдоподобно и неверно: письмо на адрес нашего
-- домена может уходить наружу (пересылка), а письмо на чужой адрес —
-- приходить к нам (алиас на внешний ящик). Идентификатор очереди — это
-- одно письмо, и направление у него одно. Где такого «брата» нет, запись
-- остаётся неизвестной: честное «неизвестно» лучше уверенной ошибки.

UPDATE mail_flow_events AS u
   SET direction = k.direction
  FROM (
        SELECT DISTINCT ON (queue_id) queue_id, direction
          FROM mail_flow_events
         WHERE direction <> 'unknown' AND queue_id IS NOT NULL
         ORDER BY queue_id, occurred_at
       ) AS k
 WHERE u.direction = 'unknown'
   AND u.queue_id IS NOT NULL
   AND u.queue_id = k.queue_id;
