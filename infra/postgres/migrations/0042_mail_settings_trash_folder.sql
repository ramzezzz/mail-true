-- Путь корзины ящика — для правил «удалить в корзину».
--
-- ------------------------------------------------------------------
-- ЗАЧЕМ
-- ------------------------------------------------------------------
-- Действие правила «удалить в корзину» уезжает в Sieve командой
-- `fileinto :create "<корзина>"`. Имя корзины — свойство ЯЩИКА, а не
-- сервера: у наших она называется Trash, у перенесённого извне может
-- быть «Корзина» или «Deleted Messages» (роль назначается по имени, см.
-- apps/api/src/mail/folders.ts).
--
-- Генератор скрипта параметр для этого имел с самого начала, но никто
-- его не заполнял: единственный боевой вызов buildSieveScript передавал
-- только адрес ящика и общие настройки, и в файл всегда уходило
-- умолчание "Trash". У ящика с корзиной «Корзина» это заводило
-- ПАПКУ-ПРИЗРАК: письма, удалённые правилом, ложились в новую папку
-- Trash рядом с настоящей корзиной, а сам человек видел её в списке как
-- обычную папку и не понимал, откуда она взялась. Та же операция,
-- выполненная разом по существующим письмам (settings/apply.ts), при
-- этом искала корзину ПО РОЛИ и попадала правильно — то есть «применить
-- правило к старым письмам» и «правило для новых» раскладывали письма
-- в разные места.
--
-- Спрашивать IMAP в момент сборки скрипта нельзя: скрипт пересобирается
-- и без пароля владельца — из панели администратора, при заглушении
-- цепочки, после восстановления резервной копии. Поэтому путь корзины
-- запоминается тогда, когда список папок и так перед глазами (любое
-- обращение владельца к своим папкам), и берётся отсюда при каждой
-- пересборке — кем бы она ни была вызвана.
--
-- Пустая строка — «не видели»; тогда действует прежнее умолчание.
ALTER TABLE mail_user_settings
    ADD COLUMN IF NOT EXISTS trash_folder VARCHAR(512) NOT NULL DEFAULT '';

COMMENT ON COLUMN mail_user_settings.trash_folder IS
    'Полный путь IMAP к корзине ящика, замеченный при последнем обращении к списку папок. '
    'Используется правилами «удалить в корзину» при сборке личного файла Sieve. '
    'Пустая строка — не видели, действует умолчание Trash.';

/*
 * Самозапись в журнал миграций.
 *
 * Каталог миграций примонтирован в /docker-entrypoint-initdb.d, поэтому на
 * ПУСТОЙ базе этот файл выполняет сам Postgres при первичной инициализации.
 * Без этой записи установщик применил бы миграцию второй раз (разбор — в
 * 0000_schema_migrations.sql). Контрольная сумма ставится 'initdb':
 * настоящую внутри SQL не вычислить, установщик такую строку узнаёт и
 * заменяет сумму на настоящую.
 */
DO $mt_journal$
BEGIN
    IF to_regclass('public.schema_migrations') IS NOT NULL THEN
        INSERT INTO schema_migrations (filename, version, name, checksum, applied_by)
        VALUES ('0042_mail_settings_trash_folder.sql', '0042', 'mail_settings_trash_folder', 'initdb', 'initdb')
        ON CONFLICT (filename) DO NOTHING;
    END IF;
END
$mt_journal$;
