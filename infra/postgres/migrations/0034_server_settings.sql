-- Миграция 0034: настройки сервера в базе (раздел «Настройки сервера» в панели).
--
--   docker compose -f infra/docker-compose.yml exec -T postgres \
--     psql -v ON_ERROR_STOP=1 -U mailserver -d mailserver \
--     < infra/postgres/migrations/0034_server_settings.sql
--
-- Скрипт идемпотентен (IF NOT EXISTS везде), повторное применение безвредно.
--
-- ------------------------------------------------------------------
-- ЗАЧЕМ
-- ------------------------------------------------------------------
-- До этой таблицы почти сотня настроек сервера жила только в infra/.env:
-- поменять срок хранения истории доставки или квоту нового ящика мог
-- только тот, у кого есть доступ по SSH к боевой машине, и стоило это
-- перезапуска всего стека. Администратор с полным доступом в панели —
-- человек, который отвечает за сервер, — не мог изменить ни одного
-- значения, хотя отвечает именно за них.
--
-- Теперь значение живёт здесь, а окружение остаётся УМОЛЧАНИЕМ. Порядок
-- разрешения ровно такой:
--
--   строка в этой таблице  >  переменная окружения  >  значение в коде
--
-- Направление выбрано не произвольно. Обратное («окружение важнее»)
-- означало бы, что уже настроенный сервер после обновления образа
-- откатывает всё, что администратор задал в панели, — то есть настройка
-- в вебе работала бы ровно до следующего `docker compose up -d`.
-- А выбранное направление даёт то, что нужно: сервер, где никто ничего
-- не менял в панели, ведёт себя в точности как раньше (таблица пуста —
-- читается окружение), а изменённая настройка переживает и перезапуск,
-- и пересборку, и перенос стека на другую машину вместе с базой.
--
-- ------------------------------------------------------------------
-- ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ
-- ------------------------------------------------------------------
-- Ни паролей, ни ключей. Пароль базы, пароль Redis, пароль контроллера
-- rspamd, секреты сессий, ключи шифрования и общий секрет посредника
-- очереди сюда не кладутся ни при каких условиях: писать секрет в ту же
-- базу, доступ к которой этим секретом и защищён, — это хранить ключ от
-- сейфа внутри сейфа. Список того, что разрешено менять, задан в коде
-- (apps/api/src/admin/server-settings-registry.ts), и строка с неизвестным
-- ключом не действует ни на что — её просто никто не читает.
--
-- Имя ключа НЕ проверяется на уровне схемы намеренно: список разрешённого
-- меняется вместе с кодом, а CHECK по списку означал бы миграцию на
-- каждую новую настройку. Проверку делает единственный, кто может делать
-- её осмысленно, — код, который эту настройку и читает.
CREATE TABLE IF NOT EXISTS server_settings (
    -- Имя переменной окружения — то же, что в infra/.env.example.
    -- Второго имени у настройки нет намеренно: два имени для одного
    -- значения это прямая дорога к «настроил, а не работает».
    key         VARCHAR(128) PRIMARY KEY,

    -- Значение ВСЕГДА строкой, как в окружении. Не JSON и не типизованные
    -- столбцы: разбирает его та же схема, что разбирает переменную
    -- окружения, и другого разбора у настройки быть не должно — иначе
    -- значение из панели и значение из файла проходят разные проверки
    -- и однажды разойдутся.
    value       TEXT         NOT NULL,

    -- Кто и когда поменял. Полный след — в admin_audit_log (там же старое
    -- значение); здесь ровно столько, чтобы панель могла показать
    -- «изменено 5 августа, snimki» рядом с самим полем, не поднимая журнал.
    updated_by  VARCHAR(128),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON TABLE server_settings IS
    'Настройки сервера, заданные из панели. Побеждают переменные окружения; '
    'пустая таблица = поведение целиком по infra/.env.';
