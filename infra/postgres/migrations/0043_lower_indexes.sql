-- ------------------------------------------------------------------
-- Указатели под сравнение адресов БЕЗ УЧЁТА РЕГИСТРА.
--
-- Почтовый адрес нечувствителен к регистру, поэтому весь код сравнивает
-- его через lower(...). А указателей под такое сравнение не было ни
-- одного: обычный индекс по столбцу базе для lower(столбец) не годится,
-- и она честно читает таблицу целиком.
--
-- Во что это обходилось:
--
--  * список ящиков в панели считает число адресов на КАЖДУЮ строку
--    отдельным подзапросом. Страница в пятьдесят строк — пятьдесят
--    полных проходов по virtual_aliases;
--  * проверка связности при импорте разматывает цепочку перенаправлений
--    по одному адресу за раз: на пяти тысячах строк это пять тысяч
--    проходов;
--  * поиск ящика по адресу шёл мимо UNIQUE-индекса на email — ровно
--    потому, что искал по lower(email), а индекс построен по email.
--
-- На пустом сервере разницы не видно, на трёх тысячах ящиков панель
-- открывается секундами. Стоимость самих указателей — доли процента от
-- размера таблиц.
--
-- CONCURRENTLY здесь НЕ используется намеренно: миграции идут в одной
-- транзакции, а этот способ в транзакции запрещён. Таблицы небольшие
-- (адреса и ящики, не письма), блокировка на время построения — доли
-- секунды даже на крупной установке.
-- ------------------------------------------------------------------

CREATE INDEX IF NOT EXISTS virtual_aliases_destination_lower_idx
    ON virtual_aliases (lower(destination));

CREATE INDEX IF NOT EXISTS virtual_aliases_source_lower_idx
    ON virtual_aliases (lower(source));

CREATE INDEX IF NOT EXISTS virtual_users_email_lower_idx
    ON virtual_users (lower(email));

/*
 * Запись о себе в журнал миграций. Без неё установщик применил бы файл
 * второй раз: на новом сервере его выполняет сам Postgres при
 * инициализации каталога. Сумма ставится условная — настоящую внутри SQL
 * не вычислить, установщик такую строку узнаёт и заменяет её.
 */
DO $mt_journal$
BEGIN
    IF to_regclass('public.schema_migrations') IS NOT NULL THEN
        INSERT INTO schema_migrations (filename, version, name, checksum, applied_by)
        VALUES ('0043_lower_indexes.sql', '0043', 'lower_indexes', 'initdb', 'initdb')
        ON CONFLICT (filename) DO NOTHING;
    END IF;
END
$mt_journal$;
