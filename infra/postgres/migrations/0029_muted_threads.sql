-- Миграция 0029: «заглушить цепочку».
--
--   docker compose -f infra/docker-compose.yml exec -T postgres \
--     psql -v ON_ERROR_STOP=1 -U mailserver -d mailserver \
--     < infra/postgres/migrations/0029_muted_threads.sql
--
-- Скрипт идемпотентен (IF NOT EXISTS везде), повторное применение безвредно.
--
-- ------------------------------------------------------------------
-- ЧТО ЭТО И ПОЧЕМУ ТАБЛИЦА, А НЕ ПРИЗНАК В ПИСЬМЕ
-- ------------------------------------------------------------------
-- Человек попал в переписку на двадцать участников, которая его не
-- касается. Он не может из неё выйти — писем ему всё равно шлют, — и
-- каждое новое письмо удаляет руками, неделю подряд. «Заглушить» означает:
-- продолжение этой переписки больше не попадает во «Входящие», не поднимает
-- счётчик непрочитанных и не приезжает уведомлением. Но и не пропадает:
-- всё пришедшее лежит в папке «Заглушённые» и читается, когда захочется.
--
-- Хранить это признаком на письме нельзя по простой причине: признак
-- ставится письму, КОТОРОЕ УЖЕ ПРИШЛО, а заглушить надо то, что придёт
-- завтра. Решение принимается в момент доставки, до всякого письма, —
-- значит, нужен список, который читает Dovecot. Он его и читает: список
-- превращается во включаемый файл Sieve (apps/api/src/settings/sieve-muted.ts),
-- а источник истины — эта таблица.
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ ЦЕПОЧКА ОПОЗНАЁТСЯ СПИСКОМ MESSAGE-ID, А НЕ ОДНИМ КЛЮЧОМ
-- ------------------------------------------------------------------
-- Устойчивого идентификатора у переписки не существует: IMAP собирает её
-- командой THREAD по ссылкам между письмами (mail/threads.ts), и результат
-- зависит от того, какие письма лежат в папке прямо сейчас. Поэтому цепочка
-- здесь — это набор заголовков Message-ID её писем на момент заглушения.
--
-- Новое письмо считается её продолжением, если в его References или
-- In-Reply-To встретился ХОТЯ БЫ ОДИН из них. Это и есть определение
-- ответа по RFC 5322, и ровно по этим же заголовкам собирает переписку
-- сам почтовый сервер. Совпадение по теме для этого не годится: на живом
-- ящике оно склеивает в одну «переписку» сорок несвязанных писем «Ваш
-- заказ» (замер в шапке mail/threads.ts). Заглушить по теме значило бы
-- заглушить заодно и чужое письмо — то есть потерять почту молча.
--
-- Оговорка, которую честнее записать здесь, чем обнаружить потом. Ответ,
-- присланный почтовой программой БЕЗ References (такие есть), попадёт
-- во «Входящие», если он ссылается только на письмо, пришедшее уже после
-- заглушения. Тогда человек увидит письмо и заглушит переписку ещё раз —
-- заметно и поправимо. Обратная ошибка (заглушить лишнее) заметна не была
-- бы вовсе, и именно поэтому выбор сделан в эту сторону.
CREATE TABLE IF NOT EXISTS muted_threads (
    id                 BIGSERIAL    PRIMARY KEY,
    account_email      VARCHAR(320) NOT NULL,

    -- Ключ переписки для показа и снятия: Message-ID самого раннего письма
    -- из тех, что были видны в момент заглушения (без угловых скобок).
    -- Это НЕ «корень» цепочки в строгом смысле — корень мог быть удалён
    -- или вовсе не приходить, — а устойчивое имя записи, по которому
    -- человек снимает заглушку.
    thread_key         TEXT         NOT NULL,

    -- Message-ID писем переписки (без угловых скобок). Именно этот список
    -- превращается в условие Sieve.
    message_ids        TEXT[]       NOT NULL DEFAULT '{}',

    -- Только для строки подборки «Заглушённые»: показать человеку, что
    -- именно он заглушил, не открывая переписку.
    subject            TEXT         NOT NULL DEFAULT '',
    -- Кто писал последним на момент заглушения.
    from_address       TEXT         NOT NULL DEFAULT '',

    -- 'muted'  — заглушено (единственное живое состояние);
    -- 'lifted' — человек вернул переписку во «Входящие».
    -- Снятые записи не удаляются: по ним видно, что заглушку снимали,
    -- и повторное заглушение той же переписки не заводит дубль.
    state              VARCHAR(16)  NOT NULL DEFAULT 'muted',

    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    lifted_at          TIMESTAMPTZ
);

-- Главный запрос: собрать файл правил ящика. Частичный индекс по состоянию —
-- снятых записей со временем станет больше живых.
CREATE INDEX IF NOT EXISTS muted_threads_account_idx
    ON muted_threads (lower(account_email), created_at DESC)
    WHERE state = 'muted';

-- Одна переписка — одна запись. Без этого двойное нажатие кнопки заводило
-- бы две записи, и снятие заглушки убирало бы только одну из них: человек
-- нажал «вернуть», а письма продолжают уходить в «Заглушённые».
CREATE UNIQUE INDEX IF NOT EXISTS muted_threads_key
    ON muted_threads (lower(account_email), thread_key);
