-- Миграция 0024: «выгрузка ящика целиком».
--
--   docker compose -f infra/docker-compose.yml exec -T postgres \
--     psql -v ON_ERROR_STOP=1 -U mailserver -d mailserver \
--     < infra/postgres/migrations/0024_mailbox_exports.sql
--
-- Скрипт идемпотентен (IF NOT EXISTS везде), повторное применение безвредно.
--
-- ------------------------------------------------------------------
-- ЗАЧЕМ ТАБЛИЦА, ЕСЛИ «ЭТО ПРОСТО СКАЧАТЬ АРХИВ»
-- ------------------------------------------------------------------
-- Потому что ящик бывает на гигабайты, а «нажал и жди ответа» на таком
-- объёме — это оборванное соединение через минуту и ноль результата.
-- Выгрузка обязана пережить закрытую вкладку, перезапуск контейнера и
-- разрыв связи, а человек — видеть, сколько сделано. Значит, это задание
-- с состоянием, а состояние живёт в базе, а не в памяти процесса.
--
-- Ровно так же устроен перенос почты с чужого сервера (0013) и импорт
-- ящиков (0006): третьего механизма для того же самого здесь не заводится,
-- но и общей таблицы у них нет — у переноса свои поля, у выгрузки свои.
--
-- ------------------------------------------------------------------
-- ПОЧЕМУ ZIP С .EML, А НЕ MBOX
-- ------------------------------------------------------------------
-- Оба формата стандартные, и выбор здесь не «что современнее», а «что
-- человек сможет открыть, когда откроет».
--
--   * ZIP открывается двойным щелчком в Windows, macOS и любом Linux
--     без единой установленной программы. Внутри — папки ящика как папки
--     на диске и по файлу .eml на письмо; двойной щелчок по .eml открывает
--     письмо в любой почтовой программе. Mbox не открывает НИЧЕГО из
--     коробки: это один слипшийся файл на сотни мегабайт, и чтобы
--     достать из него письмо, нужен Thunderbird с расширением.
--   * Mbox меняет байты письма. Формат разделяет письма строкой «From »
--     в начале строки, поэтому каждую такую строку внутри тела приходится
--     портить («>From »). Мы отдаём человеку ЕГО почту — она обязана
--     совпадать с оригиналом до байта, чтобы подпись DKIM на выгруженном
--     письме продолжала проверяться.
--   * Структура папок в mbox не выражается вовсе: либо всё в один файл
--     (папки потеряны), либо файл на папку (то есть уже архив, только
--     без архива).
--   * ZIP сжимает. Письма — это текст и base64, они жмутся вдвое-втрое;
--     mbox отдаётся как есть.
--
-- Единственное, что теряется при .eml, — флаги (прочитано, флажок) и
-- пометки папок IMAP. Их не переносит и mbox; кому нужен полный перенос
-- с флагами, тому нужен IMAP-в-IMAP, и он у нас есть (раздел «Перенос
-- почты» в панели). Раздел говорит об этом прямо, а не умалчивает.
CREATE TABLE IF NOT EXISTS mailbox_export_jobs (
    id              BIGSERIAL    PRIMARY KEY,
    account_email   VARCHAR(320) NOT NULL,

    -- 'queued'   — стоит в очереди, работник до неё ещё не дошёл;
    -- 'running'  — идёт прямо сейчас;
    -- 'ready'    — файл готов и лежит на диске;
    -- 'failed'   — сорвалось, причина в last_error;
    -- 'cancelled'— человек отменил;
    -- 'expired'  — срок хранения файла вышел, файл удалён.
    -- Набор проверяет API, а не база: новое состояние не должно требовать
    -- миграции.
    state           VARCHAR(16)  NOT NULL DEFAULT 'queued',

    -- Что берём. Спам и корзину человек включает отдельно и осознанно:
    -- в спаме бывает половина объёма ящика, а в корзине — то, что человек
    -- уже решил выбросить.
    include_spam    BOOLEAN      NOT NULL DEFAULT FALSE,
    include_trash   BOOLEAN      NOT NULL DEFAULT FALSE,

    -- Ход работы. Всего писем становится известно после обхода папок —
    -- до этого 0, и интерфейс честно показывает «считаем письма», а не
    -- полоску на нуле процентов.
    total_messages  INT          NOT NULL DEFAULT 0,
    done_messages   INT          NOT NULL DEFAULT 0,
    total_bytes     BIGINT       NOT NULL DEFAULT 0,
    done_bytes      BIGINT       NOT NULL DEFAULT 0,
    -- Письма, которых не удалось прочитать (битое письмо в ящике —
    -- редкость, но встречается). Выгрузку они не останавливают: потерять
    -- весь архив из-за одного письма было бы хуже, чем отдать архив без
    -- него. Число показывается человеку.
    skipped         INT          NOT NULL DEFAULT 0,

    -- Где лежит готовый файл и сколько он весит. Путь внутри контейнера
    -- (том api-uploads); наружу он не отдаётся никогда, скачивание идёт
    -- отдельным маршрутом с проверкой сессии.
    file_path       TEXT,
    file_bytes      BIGINT       NOT NULL DEFAULT 0,

    last_error      TEXT,
    -- Отметка живости работника. Нужна ровно из-за перезапуска: состояние
    -- 'running' переживает падение процесса, и без срока давности задание
    -- залипало бы навсегда — так же, как залипал бы сбор почты с чужих
    -- ящиков без COLLECTOR_STALE_MINUTES.
    heartbeat_at    TIMESTAMPTZ,

    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    started_at      TIMESTAMPTZ,
    finished_at     TIMESTAMPTZ,
    -- Когда файл будет удалён. Хранить архив с чужой перепиской вечно
    -- нельзя: это копия всего ящика в открытом виде на диске сервера.
    expires_at      TIMESTAMPTZ
);

-- Очередь работника: «кого брать следующим». Частичный индекс — живые
-- задания всегда единицы, а готовых и просроченных со временем тысячи.
CREATE INDEX IF NOT EXISTS mailbox_export_jobs_queue_idx
    ON mailbox_export_jobs (created_at, id)
    WHERE state IN ('queued', 'running');

-- Список заданий одного человека.
CREATE INDEX IF NOT EXISTS mailbox_export_jobs_account_idx
    ON mailbox_export_jobs (lower(account_email), created_at DESC);

-- Одно живое задание на ящик.
--
-- Без этого двойное нажатие кнопки (или повтор запроса при обрыве связи)
-- заводило бы вторую выгрузку того же ящика: два обхода одного и того же
-- по IMAP, два архива на диске и вдвое больше работы на сервере — ради
-- ничего. Индекс частичный: закончившиеся задания повторяться могут и
-- должны, человек вправе выгрузить ящик второй раз.
CREATE UNIQUE INDEX IF NOT EXISTS mailbox_export_jobs_live_key
    ON mailbox_export_jobs (lower(account_email))
    WHERE state IN ('queued', 'running');

-- Запрос уборщика: «у кого вышел срок». По времени, без ящика — уборщик
-- ходит по всей таблице разом.
CREATE INDEX IF NOT EXISTS mailbox_export_jobs_expiry_idx
    ON mailbox_export_jobs (expires_at)
    WHERE state = 'ready';
