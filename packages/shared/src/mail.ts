/**
 * Доменная модель почты. Общий контракт между API и веб-интерфейсом.
 */

/** Служебное назначение папки. IMAP-имя папки может быть любым. */
export type FolderRole =
  | 'inbox'
  | 'sent'
  | 'drafts'
  | 'spam'
  | 'trash'
  | 'archive'
  /**
   * «Отложенные» — служебная папка, в которой письмо ждёт своего часа
   * (см. apps/api/src/mail/snooze-service.ts). Роль, а не обычная папка,
   * по двум причинам: её содержимое трогает сервер (в срок он вынимает
   * оттуда письмо сам), и её нельзя переименовывать или удалять, пока
   * в ней что-то лежит, — иначе отложенные письма перестанут находиться.
   * У SPECIAL-USE (RFC 6154) такой роли нет, поэтому она узнаётся по имени.
   */
  | 'snoozed'
  | 'custom';

export interface Folder {
  /** Стабильный идентификатор для URL: 'inbox', 'sent', 'custom-1'. */
  id: string;
  /** Полное IMAP-имя, например 'INBOX' или 'Личное/Счета'. */
  path: string;
  /** Отображаемое имя последнего сегмента пути. */
  name: string;
  role: FolderRole;
  /** Идентификатор родительской папки для вложенных папок. */
  parentId: string | null;
  /** Глубина вложенности: 0 для папок верхнего уровня. */
  depth: number;
  unreadCount: number;
  totalCount: number;
  /** Папка не может быть переименована или удалена (системная). */
  system: boolean;
  /** Значение IMAP UIDVALIDITY — при изменении локальный кэш недействителен. */
  uidValidity: number;
}

export interface MailAddress {
  /** Отображаемое имя из заголовка, если оно есть. */
  name: string | null;
  address: string;
}

export interface AttachmentInfo {
  /** IMAP-номер части тела, например '2' или '1.2'. */
  partId: string;
  filename: string;
  mimeType: string;
  size: number;
  /** Встроенное изображение (Content-Disposition: inline) с этим Content-ID. */
  contentId: string | null;
  inline: boolean;
}

export interface MessageFlags {
  seen: boolean;
  /** Флаг «важное» — в интерфейсе это восклицательный знак. */
  flagged: boolean;
  answered: boolean;
  forwarded: boolean;
  draft: boolean;
  deleted: boolean;
  /**
   * Уведомление о прочтении по этому письму уже отправлено ИЛИ человек
   * от него отказался — стандартное ключевое слово IMAP `$MDNSent`
   * (RFC 3503). Именно одно поле на оба исхода: спрашивать второй раз
   * нельзя ни после «отправить», ни после «не отправлять», иначе отказ
   * ничего не значил бы и плашка возвращалась бы при каждом открытии.
   *
   * Необязательное, потому что письмо в такой же форме собирают заглушки
   * интерфейса, где никаких ключевых слов нет.
   */
  mdnSent?: boolean;
}

/** Строка в списке писем. Тело не загружается. */
export interface MessageSummary {
  /** Составной идентификатор `${folderId}:${uid}` — уникален в пределах аккаунта. */
  id: string;
  folderId: string;
  uid: number;
  /** Идентификатор цепочки: письма одной переписки имеют общее значение. */
  threadId: string;
  from: MailAddress;
  to: MailAddress[];
  cc: MailAddress[];
  subject: string;
  /** Первые ~200 символов текста для серой подписи в строке списка. */
  snippet: string;
  /** Дата в формате ISO 8601 (UTC). */
  date: string;
  flags: MessageFlags;
  hasAttachments: boolean;
  /** Названия вложений для показа плашками прямо в списке. */
  attachmentNames: string[];
  /** Пользовательские метки (IMAP keywords), кроме системных флагов. */
  labels: string[];
  /** Письмо закреплено вверху списка. */
  pinned: boolean;
  /**
   * Письмо вернулось из «Отложенных» и его ещё не открывали.
   *
   * Ставится сервером ключевым словом `$Snoozed` в момент возврата и
   * снимается, как только письмо прочитано. Нужно ровно для одного:
   * вернувшееся письмо обязано быть ЗАМЕТНЫМ. Оно приходит на своё старое
   * место по дате — то есть в середину списка, — и без пометки человек его
   * попросту не найдёт: он же и убирал его с глаз неделю назад. Список
   * поднимает такие письма наверх и рисует значок времени (так делает
   * Яндекс).
   *
   * Необязательное, потому что письмо в такой же форме собирают заглушки
   * интерфейса, где никаких ключевых слов нет.
   */
  returnedFromSnooze?: boolean;
  sizeBytes: number;
  /**
   * Домен, логотип которого можно показать в кружке вместо буквы.
   *
   * null (или поле отсутствует) — показывается прежняя буква. Значение
   * ставит СЕРВЕР и только для писем, чью подлинность подтвердила проверка
   * DMARC/DKIM: логотип рядом с письмом читается как знак подлинности, и
   * у поддельного отправителя его быть не должно ни при каких условиях
   * (apps/api/src/mail/sender-auth.ts).
   *
   * Необязательное, потому что письмо в такой же форме собирают заглушки
   * интерфейса, где никаких заголовков проверки нет.
   */
  senderLogoDomain?: string | null;
}

/** Полное письмо с телом. */
export interface Message extends MessageSummary {
  /** Значение заголовка Message-ID. */
  messageId: string | null;
  inReplyTo: string | null;
  references: string[];
  replyTo: MailAddress[];
  bcc: MailAddress[];
  /** Продезинфицированный HTML; ссылки на встроенные картинки уже переписаны. */
  bodyHtml: string | null;
  bodyText: string | null;
  attachments: AttachmentInfo[];
  /** Заголовки, которые могут понадобиться интерфейсу (Return-Path, List-Unsubscribe и т. п.). */
  headers: Record<string, string>;
  /** Результаты проверки подлинности отправителя. */
  authentication: {
    spf: AuthResult;
    dkim: AuthResult;
    dmarc: AuthResult;
  };
  /**
   * Сколько внешних картинок сервер заблокировал в теле письма.
   *
   * `GET /api/messages/:id` возвращает это поле всегда — по нему интерфейс
   * рисует плашку «Показать картинки». Поле необязательное только потому,
   * что письмо в таком же виде собирают заглушки интерфейса, где блокировать
   * нечего; сам сервер его не пропускает никогда.
   */
  blockedRemote?: number;
  /**
   * Разбор письма не дал ни одной текстовой части, и текст взят из исходника
   * как есть.
   *
   * Нужно, чтобы интерфейс отличал «в письме нет текста» от «текст есть, но
   * разобрать его не вышло». Раньше на проводе оба случая выглядели
   * одинаково — пустое тело, — и человек, получив письмо с испорченным
   * разделителем частей, видел совершенно пустую страницу и не мог узнать,
   * что письмо на самом деле не пустое.
   *
   * Такие письма встречаются: разделитель портят самописные рассылки и
   * пересылка через старые шлюзы. Почтовые программы в этом случае
   * показывают письмо как есть — так же поступаем и мы.
   */
  bodyRecovered?: boolean;
}

export type AuthResult = 'pass' | 'fail' | 'softfail' | 'neutral' | 'none' | 'temperror' | 'permerror';

/** Цепочка писем в режиме группировки по переписке. */
export interface Thread {
  id: string;
  messageIds: string[];
  /** Сводка последнего письма в цепочке — она рисуется в списке. */
  latest: MessageSummary;
  messageCount: number;
  unreadCount: number;
  hasAttachments: boolean;
  /** Уникальные участники переписки в порядке появления. */
  participants: MailAddress[];
}

export interface MessageListQuery {
  folderId: string;
  /** Смещение от начала списка (новые письма первыми). */
  offset: number;
  limit: number;
  /** Группировать письма в цепочки. */
  threaded: boolean;
  filter: MessageFilter;
  search?: string;
  /**
   * Загружать ли сниппеты писем. Они дороже остального списка на порядок
   * (каждый — отдельная докачка куска текстовой части), поэтому список
   * умеет обходиться без них. По умолчанию — загружать.
   * В строке запроса передаётся как `snippets=0|1`.
   */
  snippets?: boolean;
}

export type MessageFilter = 'all' | 'unread' | 'flagged' | 'with-attachments';

export interface MessageListPage {
  items: MessageSummary[];
  /** Общее число писем, подходящих под запрос. */
  total: number;
  offset: number;
  limit: number;
}

/** Черновик письма, отправляемый на сервер. */
export interface DraftPayload {
  /** UID существующего черновика; отсутствует для нового письма. */
  draftUid?: number;
  /**
   * Идентификатор окна написания, постоянный на всё время его жизни.
   *
   * Нужен автосохранению: пока у черновика ещё нет UID, только по этому
   * ключу сервер и может понять, что несколько одновременных сохранений
   * относятся к одному письму. Без него таймер автосохранения вместе с
   * явным «сохранить» плодят копии черновика.
   */
  draftKey?: string;
  to: MailAddress[];
  cc: MailAddress[];
  bcc: MailAddress[];
  subject: string;
  bodyHtml: string;
  /** Идентификаторы загруженных вложений, полученные от POST /api/uploads. */
  attachmentIds: string[];
  /**
   * Письма, которые нужно вложить целиком (`message/rfc822`) — «Переслать
   * как вложение». Это составные идентификаторы `${folderId}:${uid}`, а не
   * загрузки: исходник письма и так лежит в ящике, гонять его через браузер
   * туда и обратно незачем.
   */
  attachMessageIds?: string[];
  /** Message-ID письма, на которое отвечаем. */
  inReplyTo?: string;
  references?: string[];
  /**
   * Попросить получателя уведомить о прочтении: в письмо уйдёт заголовок
   * `Disposition-Notification-To` с адресом отправителя (RFC 8098).
   */
  requestReadReceipt?: boolean;
  /** Отложенная отправка: ISO-дата, когда письмо должно уйти. */
  sendAt?: string;
}

/**
 * Сохранённый черновик, прочитанный ОБРАТНО в окно написания
 * (`GET /api/drafts/:uid`).
 *
 * Отдельный тип, а не `DraftPayload`, потому что направление другое и данные
 * другие. На сервер уходят идентификаторы загрузок, а в ящике лежит уже
 * собранное письмо — вложения в нём части MIME, а не загрузки. Поэтому сервер
 * при чтении черновика заново кладёт их во временное хранилище и отдаёт сюда
 * готовые `attachments` с новыми идентификаторами: только так дописанный
 * черновик можно сохранить или отправить, не потеряв приложенные файлы.
 */
export interface DraftContent {
  /** UID черновика в папке «Черновики» — с ним же его и перезапишут. */
  draftUid: number;
  to: MailAddress[];
  cc: MailAddress[];
  bcc: MailAddress[];
  subject: string;
  /** Тело письма ровно таким, каким его сохранили: с подписью и цитатой. */
  bodyHtml: string;
  /** Вложения черновика, заново положенные во временное хранилище. */
  attachments: Array<{ id: string; filename: string; size: number }>;
  /** Message-ID письма, на которое отвечает черновик (если отвечает). */
  inReplyTo: string | null;
  references: string[];
  /** В черновике стоит просьба уведомить о прочтении. */
  requestReadReceipt: boolean;
  /**
   * Почему это письмо не ушло.
   *
   * Не null у черновика, который вернулся из очереди отправки: письмо
   * пробовали отправить, почтовый сервер отказал, и попытки кончились.
   * Человек такой черновик не создавал и знать о нём не знает — поэтому
   * окно написания обязано сказать ему, откуда взялось это письмо и что
   * с ним не так, а не молча его открыть.
   */
  sendFailure?: {
    reason: string;
    rejected: Array<{ address: string; message: string }>;
    attempts: number;
    lastAttemptAt: string;
    envelopeTo: string[];
  } | null;
}

export interface Account {
  id: string;
  email: string;
  displayName: string;
  /** Инициалы или URL аватара для кружка в шапке. */
  avatarUrl: string | null;
  quotaUsedBytes: number;
  quotaLimitBytes: number;
  signature: string;
  /**
   * Дата заведения ящика (ISO). `null`, когда узнать её неоткуда —
   * база почтового стека API не обязательна. Раньше в этом случае
   * подставлялась «01.01.1970», и профиль показывал заведомую неправду.
   */
  createdAt: string | null;
}
