/**
 * Доменная модель почты. Общий контракт между API и веб-интерфейсом.
 */

/** Служебное назначение папки. IMAP-имя папки может быть любым. */
export type FolderRole =
  | 'inbox'
  | 'sent'
  | 'drafts'
  | 'spam'
  | 'trash'
  | 'archive'
  /**
   * «Отложенные» — служебная папка, в которой письмо ждёт своего часа
   * (см. apps/api/src/mail/snooze-service.ts). Роль, а не обычная папка,
   * по двум причинам: её содержимое трогает сервер (в срок он вынимает
   * оттуда письмо сам), и её нельзя переименовывать или удалять, пока
   * в ней что-то лежит, — иначе отложенные письма перестанут находиться.
   * У SPECIAL-USE (RFC 6154) такой роли нет, поэтому она узнаётся по имени.
   */
  | 'snoozed'
  /**
   * «Заглушённые» — служебная папка, в которую Dovecot складывает
   * продолжение переписок, помеченных человеком как «меня не касается»
   * (см. apps/api/src/mail/mute-service.ts). Роль, а не обычная папка,
   * по той же причине, что и «Отложенные»: её наполняет сервер при
   * доставке, и переименование или удаление её человеком означало бы,
   * что письма заглушённых цепочек начнут падать неизвестно куда.
   * SPECIAL-USE (RFC 6154) для неё нет — узнаётся по имени.
   */
  | 'muted'
  | 'custom';

export interface Folder {
  /** Стабильный идентификатор для URL: 'inbox', 'sent', 'custom-1'. */
  id: string;
  /** Полное IMAP-имя, например 'INBOX' или 'Личное/Счета'. */
  path: string;
  /** Отображаемое имя последнего сегмента пути. */
  name: string;
  role: FolderRole;
  /** Идентификатор родительской папки для вложенных папок. */
  parentId: string | null;
  /** Глубина вложенности: 0 для папок верхнего уровня. */
  depth: number;
  unreadCount: number;
  totalCount: number;
  /**
   * Счётчики выше — догадка, а не ответ сервера: STATUS по этой папке не
   * прошёл, и `totalCount` равен нулю просто потому, что взять его негде.
   *
   * Различать это обязательно. «Пусто» и «не смогли прочитать» — разные
   * вещи, и там, где на счётчике принимается РЕШЕНИЕ, они расходятся
   * дорого: выгрузка ящика пропускала пустые папки и вместе с ними
   * молча теряла те, чей счётчик не ответил, — человек забирал «всю
   * почту», а папки в архиве не было (см. settings/export-runner.ts).
   */
  countUnknown?: boolean;
  /** Папка не может быть переименована или удалена (системная). */
  system: boolean;
  /** Значение IMAP UIDVALIDITY — при изменении локальный кэш недействителен. */
  uidValidity: number;
}

export interface MailAddress {
  /** Отображаемое имя из заголовка, если оно есть. */
  name: string | null;
  address: string;
}

export interface AttachmentInfo {
  /** IMAP-номер части тела, например '2' или '1.2'. */
  partId: string;
  filename: string;
  mimeType: string;
  size: number;
  /** Встроенное изображение (Content-Disposition: inline) с этим Content-ID. */
  contentId: string | null;
  inline: boolean;
}

export interface MessageFlags {
  seen: boolean;
  /** Флаг «важное» — в интерфейсе это восклицательный знак. */
  flagged: boolean;
  answered: boolean;
  forwarded: boolean;
  draft: boolean;
  deleted: boolean;
  /**
   * Уведомление о прочтении по этому письму уже отправлено ИЛИ человек
   * от него отказался — стандартное ключевое слово IMAP `$MDNSent`
   * (RFC 3503). Именно одно поле на оба исхода: спрашивать второй раз
   * нельзя ни после «отправить», ни после «не отправлять», иначе отказ
   * ничего не значил бы и плашка возвращалась бы при каждом открытии.
   *
   * Необязательное, потому что письмо в такой же форме собирают заглушки
   * интерфейса, где никаких ключевых слов нет.
   */
  mdnSent?: boolean;
}

/** Строка в списке писем. Тело не загружается. */
export interface MessageSummary {
  /** Составной идентификатор `${folderId}:${uid}` — уникален в пределах аккаунта. */
  id: string;
  folderId: string;
  uid: number;
  /** Идентификатор цепочки: письма одной переписки имеют общее значение. */
  threadId: string;
  from: MailAddress;
  to: MailAddress[];
  cc: MailAddress[];
  subject: string;
  /** Первые ~200 символов текста для серой подписи в строке списка. */
  snippet: string;
  /** Дата в формате ISO 8601 (UTC). */
  date: string;
  flags: MessageFlags;
  hasAttachments: boolean;
  /** Названия вложений для показа плашками прямо в списке. */
  attachmentNames: string[];
  /** Пользовательские метки (IMAP keywords), кроме системных флагов. */
  labels: string[];
  /** Письмо закреплено вверху списка. */
  pinned: boolean;
  /**
   * Письмо вернулось из «Отложенных» и его ещё не открывали.
   *
   * Ставится сервером ключевым словом `$Snoozed` в момент возврата и
   * снимается, как только письмо прочитано. Нужно ровно для одного:
   * вернувшееся письмо обязано быть ЗАМЕТНЫМ. Оно приходит на своё старое
   * место по дате — то есть в середину списка, — и без пометки человек его
   * попросту не найдёт: он же и убирал его с глаз неделю назад. Список
   * поднимает такие письма наверх и рисует значок времени (так делает
   * Яндекс).
   *
   * Необязательное, потому что письмо в такой же форме собирают заглушки
   * интерфейса, где никаких ключевых слов нет.
   */
  returnedFromSnooze?: boolean;
  /**
   * Письмо участвует в ожидании ответа.
   *
   *   'waiting' — это отправленное письмо, на которое человек попросил
   *     напомнить, если не ответят. Пометка нужна в «Отправленных»:
   *     иначе увидеть, на какие письма поставлено ожидание, можно только
   *     в подборке — а про подборку легко забыть.
   *   'overdue' — срок вышел, ответа не было, и сервер поднял копию
   *     письма во «Входящие». Ради этой пометки всё и делалось: без неё
   *     человек видит во «Входящих» собственное письмо и не понимает,
   *     откуда оно там взялось.
   *
   * Ставится сервером по ключевым словам `$AwaitReply` и `$NoReplyYet`
   * (apps/api/src/mail/await-reply-service.ts). Необязательное, потому что
   * письмо в такой же форме собирают заглушки интерфейса.
   */
  awaitReply?: 'waiting' | 'overdue' | undefined;
  sizeBytes: number;
  /**
   * Домен, логотип которого можно показать в кружке вместо буквы.
   *
   * null (или поле отсутствует) — показывается прежняя буква. Значение
   * ставит СЕРВЕР и только для писем, чью подлинность подтвердила проверка
   * DMARC/DKIM: логотип рядом с письмом читается как знак подлинности, и
   * у поддельного отправителя его быть не должно ни при каких условиях
   * (apps/api/src/mail/sender-auth.ts).
   *
   * Необязательное, потому что письмо в такой же форме собирают заглушки
   * интерфейса, где никаких заголовков проверки нет.
   */
  senderLogoDomain?: string | null;
  /**
   * Переписка, которую представляет эта строка.
   *
   * Поля нет — строка представляет одно письмо, ровно как раньше. Список
   * без группировки, папка, где группировка не нужна, и заглушки интерфейса
   * ведут себя одинаково и не обязаны ничего знать о цепочках.
   */
  thread?: ThreadSummary;
}

/** Полное письмо с телом. */
export interface Message extends MessageSummary {
  /** Значение заголовка Message-ID. */
  messageId: string | null;
  inReplyTo: string | null;
  references: string[];
  replyTo: MailAddress[];
  bcc: MailAddress[];
  /** Продезинфицированный HTML; ссылки на встроенные картинки уже переписаны. */
  bodyHtml: string | null;
  bodyText: string | null;
  attachments: AttachmentInfo[];
  /** Заголовки, которые могут понадобиться интерфейсу (Return-Path, List-Unsubscribe и т. п.). */
  headers: Record<string, string>;
  /** Результаты проверки подлинности отправителя. */
  authentication: {
    spf: AuthResult;
    dkim: AuthResult;
    dmarc: AuthResult;
  };
  /**
   * Сколько внешних картинок сервер заблокировал в теле письма.
   *
   * `GET /api/messages/:id` возвращает это поле всегда — по нему интерфейс
   * рисует плашку «Показать картинки». Поле необязательное только потому,
   * что письмо в таком же виде собирают заглушки интерфейса, где блокировать
   * нечего; сам сервер его не пропускает никогда.
   */
  blockedRemote?: number;
  /**
   * Разбор письма не дал ни одной текстовой части, и текст взят из исходника
   * как есть.
   *
   * Нужно, чтобы интерфейс отличал «в письме нет текста» от «текст есть, но
   * разобрать его не вышло». Раньше на проводе оба случая выглядели
   * одинаково — пустое тело, — и человек, получив письмо с испорченным
   * разделителем частей, видел совершенно пустую страницу и не мог узнать,
   * что письмо на самом деле не пустое.
   *
   * Такие письма встречаются: разделитель портят самописные рассылки и
   * пересылка через старые шлюзы. Почтовые программы в этом случае
   * показывают письмо как есть — так же поступаем и мы.
   */
  bodyRecovered?: boolean;
}

export type AuthResult =
  'pass' | 'fail' | 'softfail' | 'neutral' | 'none' | 'temperror' | 'permerror';

/**
 * Сводка переписки, приложенная к строке списка.
 *
 * Приходит только когда список запрошен с группировкой (`threaded=true`) И
 * группировка в этой папке разрешена (см. `threadingAllowed` в API). В
 * остальных случаях поля нет вовсе, и строка — это по-прежнему одно письмо.
 *
 * Почему сводка ВЛОЖЕНА в письмо, а не заменяет его отдельным типом строки:
 * рисуется в списке всё равно последнее письмо переписки — его тема, его
 * дата, его сниппет. Отдельный тип строки заставил бы каждого потребителя
 * списка (виртуализация, выделение, горячие клавиши, контекстное меню)
 * разбирать два вида строк там, где разница всего в нескольких полях.
 */
export interface ThreadSummary {
  /**
   * Составные идентификаторы ВСЕХ писем переписки, попавших в выборку —
   * включая то, что показано строкой.
   *
   * Это самое важное поле: по нему действие над строкой (удалить, в архив,
   * прочитано, флажок) применяется ко всей переписке. Без него получался бы
   * ровно тот дефект, ради которого поле и заведено: «удалил цепочку, а два
   * письма остались».
   *
   * «Попавших в выборку» — не оговорка. Под отбором «непрочитанные» строка
   * представляет непрочитанные письма переписки, и действие тоже относится
   * к ним: показали одно, а сделали с тремя — это не то, чего ждут.
   */
  messageIds: string[];
  /** Сколько писем в переписке — число в пилюле перед темой. */
  count: number;
  /** Сколько из них не прочитано. Цепочка непрочитана, если хоть одно. */
  unreadCount: number;
  /** Хоть одно письмо переписки помечено флажком. */
  flagged: boolean;
  /** Хоть при одном письме переписки есть вложение. */
  hasAttachments: boolean;
  /**
   * Свои метки переписки — ключевые слова, стоящие хоть на одном её письме.
   *
   * Правило то же, что у `flagged` и `hasAttachments` рядом, и оно здесь не
   * ради единообразия. Строку рисует ПОСЛЕДНЕЕ письмо разговора, а ответ
   * собеседника ключевого слова не несёт: считай строка метки по последнему
   * письму — пометка «оплатить» пропадала бы из списка ровно тогда, когда
   * разговор ожил.
   *
   * Поле сводки, а не отдельный запрос: метки лежат в тех же ключевых
   * словах, которые список и так забирает вместе с флагами (FETCH FLAGS),
   * то есть объединение считается по уже полученным данным и не стоит
   * почтовому серверу ни одного лишнего оборота.
   *
   * Служебные слова продукта (`$Snoozed`, чипы категорий, `reliable`) сюда
   * не попадают — их отсекает `labelsFromSet` на сервере, ровно как и
   * в `MessageSummary.labels`.
   */
  labels: string[];
  /**
   * Участники переписки — отправители писем в порядке появления, без
   * повторов. Их показывает колонка отправителя: «Иван, Пётр».
   */
  participants: MailAddress[];
}

export interface MessageListQuery {
  folderId: string;
  /** Смещение от начала списка (новые письма первыми). */
  offset: number;
  limit: number;
  /** Группировать письма в цепочки. */
  threaded: boolean;
  filter: MessageFilter;
  search?: string;
  /**
   * Отбор по своей метке — ключевое слово IMAP (`mt-oplatit`).
   *
   * Отдельно от `filter`, потому что это не одно из готовых значений, а
   * ключ из справочника ящика, и складывается он с фильтром: «непрочитанные
   * с меткой «Оплатить»» — законный запрос.
   *
   * Отбор делает СЕРВЕР (`KEYWORD` в поиске IMAP), а не список в браузере.
   * Разница видна ровно там, где возможность и нужна: у человека с сотней
   * помеченных писем в папке на двадцать тысяч отбор по загруженной
   * странице показывал бы горстку и молчал об остальных.
   *
   * В строке запроса передаётся как `label=mt-oplatit`. Служебное слово
   * продукта сюда не проходит — сервер отвечает отказом (см. buildSearchQuery).
   */
  label?: string;
  /**
   * Загружать ли сниппеты писем. Они дороже остального списка на порядок
   * (каждый — отдельная докачка куска текстовой части), поэтому список
   * умеет обходиться без них. По умолчанию — загружать.
   * В строке запроса передаётся как `snippets=0|1`.
   */
  snippets?: boolean;
}

