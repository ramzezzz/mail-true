/**
 * Описание мастера: шаги, поля и объяснения к ним.
 *
 * Тексты живут ЗДЕСЬ, а не в разметке страницы, по двум причинам. Первая:
 * их источник — infra/.env.example, где всё уже написано человеческим
 * языком, и держать два расходящихся набора объяснений одной и той же
 * настройки хуже, чем не иметь их вовсе. Вторая: у каждого поля должно
 * быть сказано не только «что это», но и «чем грозит ошибка» — а такое
 * предложение легко потерять при вёрстке, и никто не заметит.
 *
 * Правило для каждого поля: `help` отвечает «что это», `risk` — «что
 * будет, если ошибиться». Если на второй вопрос ответить нечем, поле,
 * скорее всего, не нужно спрашивать вовсе.
 */
import { DEFAULT_PORTS, PORT_FIELDS } from './validate.js';

export interface WizardField {
  readonly name: string;
  readonly label: string;
  readonly type: 'text' | 'email' | 'password' | 'select' | 'toggle' | 'bytes' | 'port' | 'pem';
  readonly help: string;
  readonly risk?: string;
  readonly placeholder?: string;
  readonly options?: ReadonlyArray<{ value: string; label: string; note: string }>;
  /** Поле спрашивается только при этом значении другого поля. */
  readonly showWhen?: { field: string; equals: string };
  /** Поле спрятано под «Дополнительно»: обычной установке оно не нужно. */
  readonly advanced?: boolean;
  readonly units?: 'MiB' | 'GiB';
}

export interface WizardStep {
  readonly id: string;
  readonly title: string;
  readonly intro: string;
  readonly fields: readonly WizardField[];
}

