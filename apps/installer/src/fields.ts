export interface WizardDefaults {
  readonly [key: string]: string | number | boolean;
}

/** Значения по умолчанию — те же, что в infra/.env.example. */
export function defaultAnswers(): Record<string, string | number | boolean> {
  const values: Record<string, string | number | boolean> = {
    domain: '',
    hostname: '',
    adminEmail: '',
    adminLogin: '',
    adminPassword: '',
    adminPasswordRepeat: '',
    tls: 'letsencrypt',
    leEmail: '',
    customCert: '',
    customChain: '',
    customKey: '',
    bindAddress: '0.0.0.0',
    clamav: false,
    aiEnabled: true,
    subnet: '172.28.0.0/16',
    resolverIp: '172.28.0.53',
    dovecotIp: '172.28.0.54',
    messageMaxBytes: 26214400,
    uploadMaxBytes: 26214400,
    composeBodyMaxBytes: 12582912,
    defaultQuotaBytes: 1073741824,
  };
  for (const [key, port] of Object.entries(DEFAULT_PORTS)) {
    values[`port.${key}`] = port;
  }
  return values;
}
