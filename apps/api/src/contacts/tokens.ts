/**
 * Экранирует спецсимволы LIKE.
 *
 * Не «на всякий случай»: подчёркивание и процент — обычные символы в
 * адресах, а в LIKE они значат «любой символ» и «что угодно». Без
 * экранирования запрос «no_reply» находил бы «noXreply», а запрос «%» —
 * весь указатель разом.
 */
export function escapeLike(value: string): string {
  return value.replace(/([\\%_])/g, '\\$1');
}
