/**
 * Порядок подсказок.
 *
 * ------------------------------------------------------------------
 * ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ORDER BY В ЗАПРОСЕ
 * ------------------------------------------------------------------
 * Порядок — единственное, что отличает полезную подсказку от раздражающей.
 * Алфавитный список из тридцати адресов не помогает никому: нужный
 * человек в нём на двадцатом месте, и его быстрее набрать руками.
 * Значит, правило порядка придётся подкручивать, и подкручивать по живым
 * данным.
 *
 * Выражением в ORDER BY такое правило не проверишь: чтобы убедиться, что
 * «тот, кому писали сами, стоит выше рассылки, пришедшей вчера», нужна
 * поднятая база с подготовленными строками. Здесь же это обычная функция,
 * и каждое правило проверено в обе стороны (см. rank.test.ts).
 *
 * База отдаёт кандидатов (отбор по началу слова — это её работа, там
 * индекс), а порядок среди них считается здесь. Кандидатов немного:
 * отбор ограничен сверху, см. CANDIDATE_LIMIT в db.ts.
 *
 * ------------------------------------------------------------------
 * ИЗ ЧЕГО СКЛАДЫВАЕТСЯ ОЦЕНКА
 * ------------------------------------------------------------------
 *   вес × свежесть × совпадение с начала
 *
 * Произведение, а не сумма, и это не вкусовщина. При сумме давняя рассылка
 * с сотней писем перебивала бы человека, которому написали вчера, — просто
 * потому что слагаемое «сто» больше любого разумного бонуса за свежесть.
 * Произведение же гасит старое целиком: «сто писем, но три года назад»
 * даёт почти ноль, а именно так и должно быть — это мёртвый адрес.
 */

/** Строка указателя в том виде, в каком её отдаёт база. */
export interface ContactRow {
  address: string;
  name: string | null;
  /** Сколько раз человек писал ЭТОМУ адресу сам. */
  sentCount: number;
  /** Сколько писем пришло С этого адреса. */
  recvCount: number;
  /** Дата последнего письма в любую сторону. */
  lastSeenAt: Date;
  /** Строка поиска (слова имени и адреса) — нужна для оценки совпадения. */
  tokens: string;
}

/**
 * Вес письма, которое человек отправил САМ.
 *
 * Втрое против полученного, потому что это разные свидетельства. Отправка
 * означает, что адрес осознанно выбран и, скорее всего, проверен: письмо
 * дошло, ответ пришёл. Полученное письмо не означает ничего — половина
 * входящих это рассылки, роботы и «no-reply», которым не пишут никогда.
 *
 * Ровно об этом предупреждает разбор (docs/gaps.md, «Риск»): «сначала те,
 * кому писали сами и чаще, потом те, от кого получали».
 */
export const SENT_WEIGHT = 3;

/** Вес полученного письма. */
export const RECEIVED_WEIGHT = 1;

/**
 * Надбавка за сам факт «человек писал по этому адресу своими руками».
 *
 * Это не то же самое, что SENT_WEIGHT, и потому считается отдельно.
 * SENT_WEIGHT — про ЧАСТОТУ: чем больше писем, тем выше. Здесь — про
 * КАЧЕСТВО сведений: адрес, который человек однажды набрал сам и по
 * которому письмо ушло, проверен доставкой. Адрес из входящих не проверен
 * ничем: половина входящих — рассылки, роботы и «no-reply», которым не
 * пишут никогда, и по числу писем они легко перебивают живого человека.
 *
 * Разбор говорит об этом прямо: «сначала те, кому писали сами и чаще,
 * потом те, от кого получали» (docs/gaps.md, раздел 5, «Риск»). Вчетверо
 * — столько, чтобы рассылка с тридцатью письмами не обошла человека, с
 * которым переписывались четырежды, и при этом недостаточно, чтобы
 * поднять наверх адрес, которым не пользовались три года: давность гасит
 * и надбавку тоже.
 */
export const SENT_BONUS = 4;

/**
 * Через сколько суток вес переписки падает вдвое.
 *
 * Четыре месяца — не круглое число ради красоты. Более короткий период
 * (месяц) выбрасывает наверх случайного собеседника прошлой недели поверх
 * постоянного корреспондента, с которым просто не было повода списаться
 * в отпуске. Более длинный (год) не отличает живую переписку от прошлогодней.
 */
export const HALF_LIFE_DAYS = 120;

/**
 * Надбавка за совпадение с САМОГО начала записи.
 *
 * Человек, набравший «ив», чаще всего ищет Ивана, а не Петра Иванченко и
 * не «support@ivanovo.ru». Совпадение с начала имени или адреса — более
 * сильное свидетельство, чем совпадение с начала любого слова внутри,
 * и полутора крат хватает, чтобы при прочих равных оно вышло вперёд,
 * но не хватает, чтобы перебить давнюю и частую переписку.
 */
export const HEAD_MATCH_BONUS = 1.5;

/** Сколько подсказок показываем. Больше десяти человек не читает — он печатает. */
export const SUGGEST_LIMIT = 8;

/** Вес самой переписки, без учёта давности. */
export function correspondenceWeight(row: Pick<ContactRow, 'sentCount' | 'recvCount'>): number {
  return SENT_WEIGHT * Math.max(0, row.sentCount) + RECEIVED_WEIGHT * Math.max(0, row.recvCount);
}

/** Множитель свежести: 1 сегодня, 0.5 через HALF_LIFE_DAYS суток. */
export function recencyFactor(lastSeenAt: Date, now: Date): number {
  const days = (now.getTime() - lastSeenAt.getTime()) / 86_400_000;
  // Письмо «из будущего» (кривая дата в заголовке) не должно давать
  // множитель больше единицы и вылезать наверх вперёд живой переписки.
  if (!Number.isFinite(days) || days <= 0) return 1;
  return Math.pow(2, -days / HALF_LIFE_DAYS);
}

/**
 * Оценка строки для конкретного запроса. Чем больше, тем выше в списке.
 * Запрос уже приведён к нижнему регистру (см. tokens.normalizeQuery).
 */
export function contactScore(row: ContactRow, query: string, now: Date): number {
  const head = row.tokens.startsWith(query) ? HEAD_MATCH_BONUS : 1;
  const own = row.sentCount > 0 ? SENT_BONUS : 1;
  // Единица в основании веса нужна, чтобы вообще не потерять контакт,
  // о котором известно только «однажды переписывались»: счётчики могли
  // не проставиться при частичном сборе, а показать его всё равно надо.
  return (1 + correspondenceWeight(row)) * recencyFactor(row.lastSeenAt, now) * head * own;
}

/**
 * Упорядочивает кандидатов и отрезает лишних.
 *
 * Совпадение оценок разрешается по адресу — не «как получится», а чтобы
 * список не переставлялся сам по себе между двумя одинаковыми запросами.
 * Прыгающая подсказка опаснее бесполезной: человек целится в строку, а
 * она уезжает.
 */
export function rankContacts(
  rows: readonly ContactRow[],
  query: string,
  now: Date,
  limit: number = SUGGEST_LIMIT,
): ContactRow[] {
  return rows
    .map((row) => ({ row, score: contactScore(row, query, now) }))
    .sort((a, b) => b.score - a.score || a.row.address.localeCompare(b.row.address))
    .slice(0, Math.max(0, limit))
    .map((entry) => entry.row);
}
