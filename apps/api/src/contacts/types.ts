/**
 * Контракт подсказки адреса между сервером и интерфейсом.
 *
 * Отдаётся ровно то, что нужно нарисовать строку подсказки и объяснить её
 * место в списке. Счётчики писем и даты наружу НЕ уходят: показывать
 * «вы писали ему 47 раз» незачем, а вот утечь эти числа могут — подсказка
 * живёт в браузере, её видно в средствах разработчика и в кэше.
 */

/** Одна строка подсказки. */
export interface ContactSuggestion {
  address: string;
  name: string | null;
  /**
   * Человек писал по этому адресу сам.
   *
   * Интерфейсу это нужно не для украшения: адрес, которым человек уже
   * пользовался, надёжнее адреса, просто попавшегося во входящих, и
   * пометка объясняет, почему он стоит выше.
   */
  own: boolean;
}

/** Ответ маршрута подсказки. */
export interface ContactSuggestResponse {
  items: ContactSuggestion[];
  /**
   * Указатель разобран целиком.
   *
   * Нужно, чтобы интерфейс мог не врать в редком, но неприятном случае:
   * у ящика с десятью тысячами писем первые секунды после входа подсказка
   * знает только последние письма. «Ничего не найдено» в этот момент —
   * неправда, правда — «пока ищем».
   */
  complete: boolean;
}
