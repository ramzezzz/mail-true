/**
 * Предел времени обязан ОТМЕНЯТЬ сбор, а не бросать его висеть.
 *
 * ------------------------------------------------------------------
 * ЧТО БЫЛО
 * ------------------------------------------------------------------
 * Ограничитель времени просто отклонял обещание, а сама работа
 * продолжалась в фоне — это было прямо записано в коде: «оборвать её
 * снаружи нечем». Стоило это людям дублей в ящике:
 *
 *   1. предел сработал, подключение помечено ошибкой, пометка «идёт»
 *      снята;
 *   2. настоящий перенос жив: держит оба соединения и продолжает по
 *      одному складывать письма в папку человека;
 *   3. человек видит ошибку и жмёт «Забрать почту сейчас» — или через
 *      пятнадцать минут приходит планировщик (брошенным подключение
 *      считается только через тридцать);
 *   4. второй проход строит набор для сверки ОДИН раз, в начале. Всё,
 *      что первый — ещё живой — проход допишет после этого снимка, во
 *      втором числится отсутствующим и кладётся ЗАНОВО.
 *
 * Пакет переноса умеет прерываться (MigrateMailboxOptions.signal) — им и
 * пользуемся.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = readFileSync(
  fileURLToPath(new URL('./collector.ts', import.meta.url).href.replace('/dist/', '/src/')),
  'utf8',
);

/** Код без комментариев: разбор рядом не должен изображать правку. */
const CODE = SOURCE.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');

test('по пределу времени работа отменяется, а не бросается', () => {
  const limiter = CODE.slice(
    CODE.indexOf('async function withTimeout'),
    CODE.indexOf('export interface CollectResult'),
  );
  assert.match(
    limiter,
    /cancel\?\.abort\(\)/,
    'без отмены висящий перенос продолжает класть письма',
  );
  // Отказ по-прежнему доходит до вызывающего: подключение должно
  // пометиться ошибкой, а не молча «успеть».
  assert.match(limiter, /reject\(new CollectTimeoutError\(ms\)\)/);
});

test('сигнал отмены уходит в сам перенос', () => {
  assert.match(CODE, /signal: cancel\.signal/, 'иначе отменять нечего: пакет о пределе не знает');
  assert.match(CODE, /deadline\(\),\s*\n?\s*cancel,/, 'ограничителю нужен тот же сигнал');
});

test('хранилище состояния закрывается не раньше, чем работа успела остановиться', () => {
  /*
   * Перенос прерывается на ближайшей проверке сигнала, а закрытие идёт
   * сразу. Раньше pool.end() выдёргивал хранилище на ходу: запись об
   * уже положенном письме падала, попадала в поштучный перехват — и
   * письмо помечалось неудачным. Отчёт врал во вторую сторону.
   */
  const tail = CODE.slice(CODE.lastIndexOf('} finally {'));
  assert.match(tail, /if \(cancelled\)/, 'после отмены нужна пауза перед закрытием');
  assert.match(tail, /state\.close\(\)/);
});
