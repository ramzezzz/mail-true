/**
 * Пароль от чужого ящика не уходит открытым текстом.
 *
 * ------------------------------------------------------------------
 * ЧТО БЫЛО
 * ------------------------------------------------------------------
 * В настройках соединения стояло `requireTLS: true` — под комментарием
 * «ШИФРОВАНИЕ ОБЯЗАТЕЛЬНО». Такой опции у ImapFlow нет вовсе: это опция
 * nodemailer (и там она применена верно). У ImapFlow требование STARTTLS
 * называется `doSTARTTLS`, и только при нём соединение рвётся вместо
 * молчаливого продолжения открытым текстом. Проверка типов лишнее
 * свойство не поймала — оно приходило через распаковку условного
 * объекта.
 *
 * То есть защита не работала ни разу: снятый флажок «SSL/TLS» на порту
 * 143 означал, что каждые пятнадцать минут, вечно, пароль и все письма
 * идут по сети открытым текстом, если сервер-источник STARTTLS не
 * объявил или его вырезал посредник. Мастер при этом говорил «работает».
 *
 * Проверка идёт по исходному тексту: настройки уходят прямо в
 * конструктор ImapFlow, и подставить туда сам клиент, не подняв
 * настоящий сервер, негде. Зато опечатка в имени опции — ровно тот
 * случай, который здесь и произошёл, — ловится именно так.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const source = readFileSync(
  join(dirname(fileURLToPath(import.meta.url)).replace(/dist([\\/])/u, 'src$1'), 'direct.ts'),
  'utf8',
);

/**
 * Тот же текст без комментариев.
 *
 * Разбор «что было» рядом с правкой называет старую опцию по имени, и
 * проверка «её здесь нет» иначе спотыкалась бы о собственное объяснение.
 */
const code = source
  .replace(/\/\*[\s\S]*?\*\//gu, '')
  .split(/\r?\n/u)
  .filter((line) => !line.trim().startsWith('//'))
  .join('\n');

/**
 * Только настройки IMAP.
 *
 * У SMTP-половины файла `requireTLS` — законная и верная опция: там
 * nodemailer, и у него она есть. Спутать эти два места легко, а цена
 * путаницы — ровно тот дефект, который здесь и был.
 */
const imapOptions = /new ImapFlow\(\{[\s\S]*?\n {4}\}\)/u.exec(code)?.[0] ?? '';

test('соединение без TLS требует STARTTLS опцией, которая у ImapFlow есть', () => {
  assert.match(
    imapOptions,
    /doSTARTTLS:\s*true/u,
    'требование STARTTLS исчезло: пароль пойдёт открытым текстом',
  );
});

test('несуществующей опции requireTLS в настройках IMAP нет', () => {
  // Она из nodemailer. Здесь её присутствие означает ровно то, что и
  // означало: защита выглядит сделанной и не работает.
  assert.notEqual(imapOptions, '', 'не нашлись настройки ImapFlow — проверка ослепла');
  assert.doesNotMatch(
    imapOptions,
    /requireTLS/u,
    'вернулась опция, которой у ImapFlow не существует',
  );
});

test('требование ставится только когда соединение начинается без TLS', () => {
  /*
   * ImapFlow считает ошибкой настройки `doSTARTTLS: true` вместе с
   * `secure: true` и отказывается соединяться вовсе. Поэтому условие
   * обязано остаться: при `secure` шифрование и так с первого байта.
   */
  assert.match(
    code,
    /account\.imap\.secure \|\| account\.allowInsecureTls \? \{\} : \{ doSTARTTLS: true \}/u,
    'условие постановки требования изменилось — проверьте оба случая',
  );
});

test('поблажка остаётся только для явного согласия человека', () => {
  // «Разрешить недоверенный сертификат» человек ставит сам и осознанно.
  assert.match(code, /allowInsecureTls/u);
});
