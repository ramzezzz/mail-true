/**
 * Связывание ящика не имеет права давать чужому вход в наш.
 *
 * ------------------------------------------------------------------
 * ЧТО БЫЛО
 * ------------------------------------------------------------------
 * Связь заводилась В ОБЕ СТОРОНЫ: доказал пароль ящика B — и сервер молча
 * записывал ещё и строку «владелец B, связанный A» с зашифрованным
 * паролем A. Обоснование было бытовым и звучало разумно: «чтобы
 * переключиться назад тоже без пароля».
 *
 * Цена оказалась несоразмерной. Проверка при связывании доказывает ровно
 * одно: вызывающий знает пароль B. Из этого никак не следует право B
 * ходить в A — а записывалось именно оно.
 *
 * Живой сценарий: администратор сам выдал сотруднику пароль, связал его
 * ящик со своим, чтобы разобрать жалобу, — и подарил сотруднику вход в
 * СВОЮ почту. Тот видел ящик администратора в списке связанных и входил
 * одним нажатием, ничего не подтверждая и ничего не зная.
 *
 * ------------------------------------------------------------------
 * ЧТО ВМЕСТО
 * ------------------------------------------------------------------
 * Связь только в одну сторону. Право вернуться живёт в СЕССИИ (returnTo):
 * оно принадлежит человеку за этим сеансом, а не учётной записи вообще.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Тест выполняется из dist/, а читать надо исходники: заменяем каталог.
const source = (name: string): string =>
  readFileSync(
    fileURLToPath(new URL(name, import.meta.url).href.replace('/dist/', '/src/')),
    'utf8',
  );

/** Код без комментариев: объяснение рядом не должно изображать правку. */
function code(text: string): string {
  return text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
}

const ROUTES = code(source('./routes.ts'));

test('связывание не заводит обратную связь с нашим паролем', () => {
  /*
   * Границы блока ищем по самим путям, а не по строке `app.post('/link'`.
   *
   * У маршрута появились настройки (предел частоты запросов), объявление
   * переехало на несколько строк — и поиск по слитному написанию перестал
   * находить хоть что-нибудь. Тест при этом не покраснел от настоящей
   * поломки: он просто резал пустоту и считал в ней ноль вызовов.
   */
  const linkBlock = ROUTES.slice(ROUTES.indexOf("'/link'"), ROUTES.indexOf("'/link/:email'"));
  assert.ok(
    linkBlock.length > 0,
    'блок маршрута связывания не найден — проверка ничего не проверяет',
  );

  const links = linkBlock.match(/db\.linkAccount\(/g) ?? [];
  assert.equal(
    links.length,
    1,
    'вторая запись — это связь «владелец чужого ящика → наш» с нашим паролем',
  );
  assert.ok(
    !/box\.encrypt\(session\.password\)/.test(linkBlock),
    'пароль текущего ящика не имеет права попасть в таблицу связей',
  );
  // Свой пароль по-прежнему доказывается настоящим входом.
  assert.match(linkBlock, /pool\.verify\(email, password\)/);
});

test('вернуться назад можно, и это право живёт в сессии', () => {
  const switchBlock = ROUTES.slice(ROUTES.indexOf("app.post('/switch'"));

  // Возврат разрешён по отметке сеанса…
  assert.match(switchBlock, /session\.returnTo/);
  assert.match(switchBlock, /back\.email === email/);
  // …а новая сессия помнит, чем вернуться.
  assert.match(switchBlock, /returnTo: \{ email: session\.email/);
});

test('отметка возврата описана в данных сессии, а не додумана на месте', () => {
  const session = source('../session.ts');
  assert.match(session, /returnTo\?: \{ email: string; passwordEnc: string \}/);
  // Разбор «почему в сессии, а не в таблице» обязан остаться рядом:
  // без него следующий читатель вернёт обратную связь как «удобную».
  assert.match(session, /в обе стороны/i);
});

test('удаление связи по-прежнему чистит обе стороны', () => {
  /*
   * Записи «владелец B → A» больше не заводятся, но у старых установок
   * они остались: там связывали до этой правки. Снимать их надо, иначе
   * дыра переживёт обновление.
   */
  const unlink = ROUTES.slice(
    ROUTES.indexOf("app.delete('/link"),
    ROUTES.indexOf("app.post('/switch'"),
  );
  assert.match(unlink, /unlinkAccount\(session\.email, email\)/);
  assert.match(unlink, /unlinkAccount\(email, session\.email\)/);
});
