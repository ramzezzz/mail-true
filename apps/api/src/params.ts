/**
 * Разбор числового номера из адреса запроса.
 *
 * ПОЧЕМУ ОТДЕЛЬНОЙ ФУНКЦИЕЙ, А НЕ `Number(request.params.id)`. Голое
 * приведение отдаёт NaN на всём, что не число, — и NaN спокойно доезжает
 * до базы. Postgres на `WHERE id = $1` со значением NaN отвечает
 * «invalid input syntax for type integer», а человек снаружи получает
 * 500 «Внутренняя ошибка сервера» и запись в журнале с трассировкой.
 *
 * Так вело себя девятнадцать маршрутов панели. Достаточно опечатки в
 * адресе (`/users/cleanup` вместо `/users/12`), чтобы получить отказ,
 * неотличимый от настоящей поломки сервера: и в ответе, и в журнале.
 * За настоящими бедами такой шум не разглядеть.
 *
 * Что здесь считается верным номером: только десятичные цифры, возможно
 * со знаком минус. Не «1e999», не «0x10», не «12abc», не пустая строка —
 * `Number` принимает их все, а `parseInt` вдобавок молча обрезает хвост,
 * превращая `12abc` в двенадцать.
 *
 * Ноль и отрицательные ПРОПУСКАЕМ дальше: таких строк в базе нет, и
 * маршрут ответит своим «не найдено» — так и должно быть, это разговор
 * про существование записи, а не про испорченный адрес.
 */
import { BadRequestError } from './errors.js';

/**
 * Предел signed int4 — тип всех наших первичных ключей. Номер больше него
 * не просто отсутствует в таблице: Postgres откажется его сравнивать
 * («integer out of range») с той же 500-й ошибкой, что и NaN.
 */
const INT4_MAX = 2_147_483_647;

/** Только цифры со знаком; длина ограничена, чтобы не считать простыню. */
const DIGITS = /^-?\d{1,10}$/u;

/** Показываем полученное, но коротко и без управляющих знаков. */
function quote(raw: string): string {
  // eslint-disable-next-line no-control-regex
  const clean = raw.replace(/[\u0000-\u001f\u007f]/gu, ' ').trim();
  return clean.length > 40 ? `${clean.slice(0, 40)}…` : clean;
}

/**
 * @param raw   значение из адреса, как его отдал маршрутизатор
 * @param what  что нумеруется — попадёт в объяснение отказа
 */
export function pathId(raw: string, what = 'записи'): number {
  const trimmed = raw.trim();
  if (!DIGITS.test(trimmed)) {
    throw new BadRequestError(
      `В адресе запроса ожидался номер ${what}, а получено «${quote(raw)}».`,
    );
  }
  const value = Number(trimmed);
  if (Math.abs(value) > INT4_MAX) {
    throw new BadRequestError(`Номер ${what} «${quote(raw)}» выходит за допустимые пределы.`);
  }
  return value;
}
