/**
 * Что показывать во всплывающем окне. Порядок — от самого закрытого
 * к самому подробному; на этом порядке держится `levelAtMost`.
 */
export const NOTIFICATION_LEVELS = ['minimal', 'sender-subject', 'preview', 'ai-summary'] as const;

export type NotificationLevel = (typeof NOTIFICATION_LEVELS)[number];

export function isNotificationLevel(value: unknown): value is NotificationLevel {
  return typeof value === 'string' && (NOTIFICATION_LEVELS as readonly string[]).includes(value);
}

/** Понижает уровень до допустимого: используется, когда ИИ недоступен. */
export function levelAtMost(
  level: NotificationLevel,
  ceiling: NotificationLevel,
): NotificationLevel {
  const a = NOTIFICATION_LEVELS.indexOf(level);
  const b = NOTIFICATION_LEVELS.indexOf(ceiling);
  return a <= b ? level : ceiling;
}

