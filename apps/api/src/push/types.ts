/** Кнопка в уведомлении. Поддерживается не всеми браузерами — см. sw.js. */
export interface NotificationAction {
  action: 'open' | 'read' | 'archive';
  title: string;
}

/**
 * Всё, что нужно браузеру, чтобы показать окно. Одна и та же форма
 * приходит и в Service Worker, и на открытую вкладку: правила показа
 * должны быть одни, а не «почти одни».
 */
export interface NotificationView {
  title: string;
  body: string;
  /**
   * Ярлык окна. Одинаковый ярлык — одно окно: десять писем подряд
   * заменяют друг друга, а не выкладываются стопкой.
   */
  tag: string;
  icon: string;
  badge: string;
  actions: NotificationAction[];
  /** Куда вести по щелчку: адрес КОНКРЕТНОГО письма, а не почты вообще. */
  url: string;
  /** Идентификаторы писем, которые это окно представляет. */
  ids: string[];
  /**
   * Почему уровень оказался ниже выбранного (исчерпан предел ИИ,
   * письмо не читается). Показывается в настройках, не в уведомлении.
   */
  degraded: string | null;
}
