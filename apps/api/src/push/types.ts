/* Подписка браузера                                                    */
/* ------------------------------------------------------------------ */

export interface PushSubscriptionRecord {
  id: number;
  accountEmail: string;
  /** Адрес службы доставки. Он же секрет: кто его знает, тот может слать. */
  endpoint: string;
  p256dh: string;
  auth: string;
  /**
   * Отпечаток браузера, в котором живёт подписка. Тот же самый браузер
   * присылает его при подключении к /ws — благодаря этому push не уходит
   * туда, где вкладка сейчас открыта и уведомление покажется само.
   */
  clientId: string;
  /** Для списка «где включены уведомления» в настройках. */
  userAgent: string | null;
  createdAt: string;
  lastSeenAt: string;
  /** Когда служба доставки в последний раз отказала (для диагностики). */
  lastErrorAt: string | null;
  lastError: string | null;
}

