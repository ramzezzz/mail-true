/** «Тихие часы»: границы в минутах от полуночи по поясу человека. */
export interface QuietHours {
  enabled: boolean;
  /** Начало, минуты от полуночи (23:00 → 1380). */
  fromMinutes: number;
  /** Конец, минуты от полуночи (7:00 → 420). Меньше начала — через полночь. */
  toMinutes: number;
}

export interface NotificationPrefs {
  /**
   * Показывать уведомления вообще. Живёт здесь, а не в общих настройках
   * ящика: у общих настроек уже есть свой флажок `notifyBrowser`, и он
   * остаётся главным выключателем — см. db.ts, где эти два значения
   * сводятся в одно.
   */
  enabled: boolean;
  level: NotificationLevel;
  /**
   * Доставлять уведомления при закрытой вкладке (Web Push).
   * Выключено — уведомления показываются только пока почта открыта,
   * и наружу не уходит ничего вовсе, даже отпечатка.
   */
  push: boolean;
  /** Класть содержимое в тело push. По умолчанию НЕТ — см. заголовок файла. */
  pushPayload: boolean;
  /**
   * Не уведомлять о письмах, которые фильтр разложил по папкам.
   * Мы наблюдаем только «Входящие», поэтому разложенные письма и так не
   * дадут события; настройка нужна для писем, которые фильтр пометил
   * прочитанными, оставив на месте.
   */
  skipFiltered: boolean;
  quietHours: QuietHours;
  /**
   * Часовой пояс человека (IANA, например «Europe/Moscow»). Приходит от
   * браузера при подписке: «тихие часы» задаются по местному времени, а
   * сервер может стоять где угодно.
   */
  timeZone: string | null;
  updatedAt: string | null;
}

export function defaultNotificationPrefs(): NotificationPrefs {
  return {
    enabled: false,
    // Отправитель и тема — то, чего ждут от почты по умолчанию: понять,
    // стоит ли отрываться от дела. Первые фразы письма уже показывают
    // содержимое случайному взгляду на экран, поэтому не по умолчанию.
    level: 'sender-subject',
    push: false,
    pushPayload: false,
    skipFiltered: true,
    quietHours: { enabled: false, fromMinutes: 23 * 60, toMinutes: 7 * 60 },
    timeZone: null,
    updatedAt: null,
  };
}

