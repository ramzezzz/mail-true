/**
 * Типы уведомлений о новой почте: настройки человека, подписка браузера
 * и готовое описание всплывающего окна.
 *
 * Здесь же — главное решение всего раздела, и его стоит прочитать целиком,
 * прежде чем что-то менять.
 *
 * ------------------------------------------------------------------
 * ЧТО УХОДИТ В PUSH И ПОЧЕМУ ТАК МАЛО
 * ------------------------------------------------------------------
 * Уведомление при ЗАКРЫТОЙ вкладке доставляется не нами. Оно идёт через
 * службу доставки браузера: Google (Chrome), Mozilla (Firefox), Apple
 * (Safari). Наш сервер обращается к ним, они будят браузер на устройстве.
 *
 * Тело такого сообщения зашифровано (RFC 8291), и служба доставки прочитать
 * его не может — это правда, и притворяться иначе нечестно. Но правда и
 * другое:
 *
 *   * шифротекст ОСТАЁТСЯ у постороннего. Что он с ним делает и сколько
 *     хранит, мы не знаем и проверить не можем;
 *   * ему в любом случае видно, КОМУ, КОГДА и КАК ЧАСТО приходит почта.
 *     Этого не скрывает никакое шифрование;
 *   * почтовый сервер ставят как раз затем, чтобы переписка не уходила
 *     на сторону. Класть в чужую трубу тему письма — значит отдавать
 *     ровно то, ради чего сервер и поднимали.
 *
 * Поэтому по умолчанию в push уходит МИНИМУМ: номер уведомления и адрес
 * ящика в виде отпечатка. Ни темы, ни отправителя, ни текста. Содержимое
 * Service Worker забирает с НАШЕГО сервера в момент показа
 * (GET /api/push/notifications) — по той же сессии, что и вкладка.
 *
 * У такого решения есть и чисто инженерные достоинства, не только
 * охранительные:
 *
 *   1. Содержимое в push — это снимок прошлого. Письмо могли уже прочитать
 *      или удалить с другого устройства, а уведомление всё равно всплывёт
 *      и покажет то, чего уже нет. Забирая содержимое при показе, мы
 *      показываем то, что есть сейчас, — или не показываем ничего.
 *   2. Тело push ограничено четырьмя килобайтами. Сводка от ИИ, тема и
 *      имя отправителя туда влезут не всегда, и обрезать их пришлось бы
 *      вслепую.
 *   3. Сводку от ИИ считать в момент ОТПРАВКИ push — значит ждать ответа
 *      внешнего сервиса, держа очередь доставки. При показе она считается
 *      только для тех устройств, которые действительно проснулись.
 *
 * Человек может решить иначе — настройка `pushPayload`. Она честно
 * объясняет, что содержимое будет уходить через чужой сервер в
 * зашифрованном виде, и зачем это может понадобиться: если наш сервер
 * недоступен с устройства в момент показа (телефон вне сети предприятия),
 * без содержимого в теле уведомление останется безымянным «Новое письмо».
 */

