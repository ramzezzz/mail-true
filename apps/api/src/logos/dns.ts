/**
 * Запрос TXT-записи через СВОЙ резольвер.
 *
 * ------------------------------------------------------------------
 * Почему не публичные резольверы, как в проверке DNS у админки
 * ------------------------------------------------------------------
 * Проверка домена в админке (admin/dns.ts) намеренно спрашивает 8.8.8.8 и
 * его товарищей: она отвечает на вопрос «а видит ли МИР мои записи», и
 * спрашивать при этом собственный сервер бессмысленно.
 *
 * Здесь вопрос ровно обратный, и цена ошибки другая. Мы спрашиваем про
 * домены, С КОТОРЫХ ПРИШЛИ ПИСЬМА КОНКРЕТНОМУ ЧЕЛОВЕКУ. Поток таких запросов
 * на публичный резольвер — это готовый рассказ Google о том, с кем наши
 * пользователи переписываются: клиника, юрист, кадровое агентство,
 * знакомства. Ровно от такой утечки задача и защищается тем, что логотипы
 * ходит забирать сервер, а не браузер, — глупо было бы отдать то же самое
 * на шаг ниже.
 *
 * Поэтому здесь берётся резольвер, заданный системе (в нашем стеке это
 * unbound, см. infra/docker-compose.yml): он ходит к корневым серверам сам
 * и никому не отчитывается.
 */
import { Resolver } from 'node:dns/promises';

export interface TxtLookup {
  /** Найденные записи, склеенные из кусков по 255 символов. */
  records: string[];
  /**
   * Ответ получен по существу: записи есть или их точно нет.
   * false — спросить не удалось (резольвер молчит, сбой) — а это НЕ то же
   * самое, что «логотипа нет»: такой ответ нельзя запоминать надолго.
   */
  answered: boolean;
}

/** «Записи нет» — это ответ по существу, а не отказ (как в admin/dns.ts). */
function isDefiniteAbsence(err: unknown): boolean {
  const code = (err as { code?: string } | null)?.code;
  return code === 'ENOTFOUND' || code === 'ENODATA' || code === 'NXDOMAIN';
}

/**
 * Спрашивает TXT у системного резольвера.
 * Сервера не задаются намеренно: их берёт сам Node из /etc/resolv.conf.
 */
export async function lookupTxt(name: string, timeoutMs: number): Promise<TxtLookup> {
  const resolver = new Resolver({ timeout: timeoutMs, tries: 1 });
  try {
    const txt = await resolver.resolveTxt(name);
    // Длинное значение DNS отдаёт кусками по 255 символов — склеиваем без
    // разделителя, ровно как это делает получатель письма.
    return { records: txt.map((chunks) => chunks.join('')), answered: true };
  } catch (err) {
    if (isDefiniteAbsence(err)) return { records: [], answered: true };
    return { records: [], answered: false };
  }
}
