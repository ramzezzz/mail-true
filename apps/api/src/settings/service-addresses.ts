/**
 * Память о собственных адресах сервера приложения.
 *
 * ------------------------------------------------------------------
 * ЗАЧЕМ ЭТО ЕСТЬ
 * ------------------------------------------------------------------
 * Веб-интерфейс разговаривает с почтой настоящим IMAP-логином, поэтому в
 * журнале Dovecot на один вход человека приходятся десятки строк с
 * адресом нашего же контейнера. Раздел «Вход и действия» помечает их
 * служебными и по умолчанию сворачивает — иначе настоящие входы в них
 * утонут.
 *
 * Сравнение шло с адресами сетевых интерфейсов СВОЕГО ЖЕ ПРОЦЕССА, и
 * верным оно было ровно до первой пересборки контейнера: Docker выдаёт
 * новому контейнеру следующий свободный адрес, процесс считает своим
 * 172.28.0.7, а вчерашние строки журнала написаны про 172.28.0.2. После
 * пересборки вчерашние служебные подключения показывались человеку как
 * обычные входы по IMAP из локальной сети — то есть раздел, заведённый
 * ради вопроса «не заходил ли кто-то чужой», сам отвечал ложной тревогой.
 * На стенде это видно прямо в dovecot.log: соседние строки с rip=172.28.0.2
 * и rip=172.28.0.7, и оба адреса — мы.
 *
 * ------------------------------------------------------------------
 * ЧЕМ ЗАМЕНЕНО
 * ------------------------------------------------------------------
 * Адрес не угадывается по подсети и не настраивается руками — он
 * ЗАПОМИНАЕТСЯ. Процесс при запуске (и дальше на каждом проходе уборщика)
 * записывает свои текущие адреса в таблицу `api_service_addresses`, а
 * сравнение идёт со всем, что там накопилось. Запись лежит в базе, а не в
 * контейнере, поэтому переживает и перезапуск, и пересборку, и переезд
 * стека на другую машину вместе с базой.
 *
 * Почему не подсеть стека: её отвергает тот же довод, что и раньше, —
 * подсеть Docker по умолчанию 172.х, и офисная сеть вполне может оказаться
 * такой же; тогда служебными стали бы настоящие входы сотрудников.
 *
 * Почему не спрашиваем администратора: адрес контейнера никто не выбирает,
 * его выдаёт Docker при создании. Настройка, которую надо править после
 * каждого обновления образа, — это настройка, о которой забудут один раз,
 * и дальше раздел снова врёт.
 *
 * ------------------------------------------------------------------
 * ГРАНИЦЫ
 * ------------------------------------------------------------------
 * Строки стареют вместе с историей, которую объясняют: их убирает тот же
 * уборщик и по тому же сроку, что и записи истории входов. Адрес, не
 * встречавшийся дольше срока хранения, объяснять больше нечего, а держать
 * его вечно значило бы однажды принять за себя чужую машину, которой
 * Docker отдал тот же адрес.
 *
 * Нет таблицы (миграция не применена) — поведение ровно прежнее: сравнение
 * с текущими адресами процесса. Хуже, чем было, не становится нигде.
 */
import type { Logger } from 'pino';
import { normalizeIp, ownAddresses } from './access-log.js';

/** Часть хранилища, которая нужна памяти адресов. */
export interface ServiceAddressStore {
  serviceAddressesReady(): Promise<boolean>;
  rememberServiceAddresses(ips: readonly string[]): Promise<void>;
  listServiceAddresses(): Promise<string[]>;
  purgeServiceAddresses(olderThan: Date): Promise<number>;
}

export class ServiceAddressBook {
  /** Всё, что когда-либо было нашим, плюс сегодняшнее. */
  #known: Set<string> = new Set(ownAddresses());
  #store: ServiceAddressStore | null = null;
  readonly #logger: Logger | undefined;

  constructor(logger?: Logger) {
    this.#logger = logger;
  }

  /** Адреса для сравнения. Всегда непустые: свои интерфейсы известны сразу. */
  get known(): ReadonlySet<string> {
    return this.#known;
  }

  /** Есть ли за спиной база. Ложь — работаем на одних текущих адресах. */
  get persistent(): boolean {
    return this.#store !== null;
  }

  /**
   * Подключить хранилище и слить память с текущими адресами.
   *
   * Отказ базы здесь НЕ авария: раздел продолжает работать на текущих
   * адресах, то есть ровно так, как работал раньше.
   */
  async attach(store: ServiceAddressStore): Promise<boolean> {
    if (!(await store.serviceAddressesReady())) return false;
    this.#store = store;
    await this.sync();
    return true;
  }

  /**
   * Отметить текущие адреса своими и перечитать накопленное.
   *
   * Зовётся не только при запуске: адрес контейнера может смениться и без
   * перезапуска процесса (пересоздание сети), а проход уборщика всё равно
   * ходит в базу.
   */
  async sync(): Promise<void> {
    const store = this.#store;
    if (!store) return;
    const current = [...ownAddresses()].filter((ip) => ip !== '');
    try {
      await store.rememberServiceAddresses(current);
      const saved = await store.listServiceAddresses();
      const next = new Set(current);
      for (const ip of saved) {
        const value = normalizeIp(ip);
        if (value !== '') next.add(value);
      }
      this.#known = next;
    } catch (err) {
      // Память не обновилась — сравниваем с тем, что уже знали.
      this.#logger?.warn({ err }, 'Не удалось обновить список собственных адресов сервера');
    }
  }

  /** Убрать адреса, которых не видели дольше срока хранения истории. */
  async purge(olderThan: Date): Promise<void> {
    const store = this.#store;
    if (!store) return;
    try {
      await store.purgeServiceAddresses(olderThan);
    } catch (err) {
      this.#logger?.warn({ err }, 'Уборка списка собственных адресов сервера не удалась');
    }
  }
}
