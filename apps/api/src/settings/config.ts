/**
 * Конфигурация раздела настроек и правил фильтрации.
 *
 * Отдельная схема, как у админки и помощника ИИ: почтовый API обязан
 * работать и без базы — просто без настроек и фильтров. В окружении
 * лежит только то, чему в базе места нет: подключение к самой базе и
 * способ добраться до почтового хранилища Dovecot.
 */
import { z } from 'zod';
import type { SieveTransport } from './store.js';

const intVar = (def: number, min = 0, max = Number.MAX_SAFE_INTEGER) =>
  z.coerce.number().int().min(min).max(max).default(def);

export const settingsEnvSchema = z.object({
  /** Подключение к базе почтового стека. Без него настройки недоступны. */
  SETTINGS_DATABASE_URL: z.string().optional(),
  ADMIN_DATABASE_URL: z.string().optional(),
  DATABASE_URL: z.string().optional(),

  /**
   * Как API добирается до почтового хранилища, чтобы положить туда
   * личный файл правил:
   *   local  — каталог хранилища виден процессу API (боевой Ubuntu);
   *   docker — хранилище внутри контейнера Dovecot (dev-стек);
   *   off    — не класть никуда (правила остаются только в базе).
   */
  SIEVE_TRANSPORT: z.enum(['local', 'docker', 'off']).default('docker'),
  /** Корень почтового хранилища (%d/%n внутри него). */
  SIEVE_ROOT: z.string().default('/var/mail/vhosts'),
  /**
   * Имя контейнера Dovecot для транспорта docker.
   *
   * Значение по умолчанию именно такое, потому что имя контейнера теперь
   * складывается из имени проекта: `<проект>-dovecot-1`. Жёсткие
   * `container_name: mail-dovecot` из infra/docker-compose.yml убраны —
   * с ними на одной машине не поднимался второй стенд, — и прежний
   * умолчательный `mail-dovecot` больше не существует ни в одной установке.
   *
   * В самом стеке это значение не используется: там SIEVE_TRANSPORT=local
   * (каталог хранилища примонтирован в контейнер API, сокет Docker внутрь
   * не пробрасывается и не должен). Транспорт docker — только для запуска
   * API вне контейнера, и там имя всё равно задаётся явно.
   */
  SIEVE_DOCKER_CONTAINER: z.string().default('mailtrue-dovecot-1'),
  /** Имя файла скрипта в каталоге sieve/ (без расширения). */
  SIEVE_SCRIPT_NAME: z.string().default('mailtrue'),
  /** Владелец файлов в хранилище: под этим пользователем работает LMTP. */
  SIEVE_OWNER: z.string().default('vmail:vmail'),

  /** Сколько писем максимум перебирать при применении правила к старой почте. */
  FILTER_APPLY_MAX_MESSAGES: intVar(5000, 1, 100_000),

  /* ------------------------------------------------------------------ */
  /* История входов в ящик (раздел «Вход и действия»)                     */
  /* ------------------------------------------------------------------ */

  /**
   * Где лежат журналы Dovecot и Postfix. Тот же том, что читает раздел
   * «Журналы» в панели (MAIL_LOG_DIR в admin/config.ts), и та же
   * переменная: два имени для одного каталога — прямая дорога к
   * «настроил, а не работает».
   */
  MAIL_LOG_DIR: z.string().default('/var/log/mail'),
  /**
   * Сколько дней хранить СВОИ записи о входах.
   *
   * Не «навсегда»: это журнал доступа с адресами, и бессрочное хранение
   * адресов — то, за что отвечают уже не мы. Девяносто дней покрывают
   * любой разумный вопрос («не заходил ли кто-то, пока я был в отпуске»)
   * и остаются объяснимым сроком.
   */
  MAILBOX_ACCESS_LOG_DAYS: intVar(90, 1, 3650),

  /* ------------------------------------------------------------------ */
  /* Выгрузка ящика целиком                                               */
  /* ------------------------------------------------------------------ */

  /** Общий выключатель раздела: на закрытом контуре выгрузку запрещают. */
  MAILBOX_EXPORT_ENABLED: z
    .enum(['true', 'false'])
    .default('true')
    .transform((v) => v === 'true'),
  /**
   * Куда класть готовые архивы. Том api-uploads, но ОТДЕЛЬНЫМ каталогом
   * от временных вложений: те чистит уборщик по возрасту файлов, и архив
   * однажды исчез бы сам собой посреди скачивания.
   */
  MAILBOX_EXPORT_DIR: z.string().default('/srv/data/exports'),
  /**
   * Сколько часов живёт готовый файл.
   *
   * Двое суток — это «заказал вечером, скачал на следующий день», то есть
   * покрывает и медленный канал, и выходной. Больше держать нельзя: это
   * копия всей переписки в открытом виде на диске сервера, и каждый
   * лишний день — лишний день, когда её может забрать не тот.
   */
  MAILBOX_EXPORT_TTL_HOURS: intVar(48, 1, 720),
  /**
   * Сколько выгрузок идёт одновременно НА ВЕСЬ СЕРВЕР.
   *
   * Одна. Выгрузка — это последовательное вычитывание всего ящика по IMAP
   * плюс сжатие: она грузит и Dovecot, и диск, и процессор. Две таких
   * рядом не ускоряют ни одну, а вот почту остальных замедляют обе.
   * Ждущие стоят в очереди и видят своё место в ней.
   */
  MAILBOX_EXPORT_CONCURRENCY: intVar(1, 1, 8),
  /** Как часто работник заглядывает в очередь. */
  MAILBOX_EXPORT_TICK_MS: intVar(5_000, 1_000, 600_000),
  /**
   * Потолок размера архива.
   *
   * Не про жадность, а про диск: том с архивами общий, и один ящик на
   * терабайт заполнил бы его целиком, после чего перестала бы работать
   * загрузка вложений у всех. Дойдя до потолка, задание честно
   * останавливается с понятной причиной, а не оставляет обрезанный архив.
   */
  MAILBOX_EXPORT_MAX_BYTES: intVar(20 * 1024 * 1024 * 1024, 1024 * 1024),

  /* ------------------------------------------------------------------ */
  /* Восстановление после очистки корзины                                 */
  /* ------------------------------------------------------------------ */

  /**
   * Потолок срока хранения очищенного, в днях. Сам срок выбирает человек
   * (это его место в ящике), сервер задаёт только верхнюю границу.
   */
  TRASH_RECOVERY_MAX_DAYS: intVar(30, 0, 365),
  /** Как часто работник проверяет, чему пора удаляться по-настоящему. */
  TRASH_RECOVERY_TICK_MS: intVar(60_000, 1_000, 3_600_000),
});

export type SettingsEnv = z.infer<typeof settingsEnvSchema>;

export interface SettingsConfig extends SettingsEnv {
  /** Итоговая строка подключения (SETTINGS_DATABASE_URL важнее остальных). */
  databaseUrl: string | null;
  transport: SieveTransport;
}

export function loadSettingsConfig(env: NodeJS.ProcessEnv = process.env): SettingsConfig {
  const parsed = settingsEnvSchema.safeParse(env);
  if (!parsed.success) {
    const details = parsed.error.issues.map((i) => `${i.path.join('.')}: ${i.message}`).join('; ');
    throw new Error(`Некорректная конфигурация настроек ящика: ${details}`);
  }
  const data = parsed.data;
  return {
    ...data,
    databaseUrl:
      data.SETTINGS_DATABASE_URL || data.ADMIN_DATABASE_URL || data.DATABASE_URL || null,
    transport: data.SIEVE_TRANSPORT,
  };
}
