/**
 * Включаемый файл Sieve с заглушёнными цепочками.
 *
 * ==================================================================
 * ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ЧАСТЬ ЛИЧНОГО СКРИПТА
 * ==================================================================
 * Заглушка обязана работать ПРИ ДОСТАВКЕ. Половинчатый вариант — прятать
 * заглушённую переписку в списке писем — не работает вовсе: пока вкладка
 * закрыта, новое письмо всё равно ложится во «Входящие», поднимает счётчик
 * непрочитанных и приезжает уведомлением на телефон. То есть человек, ради
 * которого возможность и делается, получает ровно то, от чего он спрятался.
 * Значит, решение принимает Dovecot в момент доставки, а не браузер.
 *
 * Единственное место, где Dovecot принимает такие решения, — Sieve. Но
 * личный файл правил (settings/sieve.ts) пересобирается ЦЕЛИКОМ из базы
 * при каждом сохранении настроек: держать в нём список заглушённых цепочек
 * значило бы перекомпилировать все правила человека каждый раз, когда он
 * заглушает переписку, — и рисковать его правилами ради нашей возможности.
 *
 * Поэтому список живёт своим файлом, а личный скрипт подключает его строкой
 *
 *     include :optional :personal "mt-muted";
 *
 * `:optional` здесь — главное слово. Файла может не быть вовсе (никто ничего
 * не заглушал), и тогда Pigeonhole молча пропускает строку: уже написанные
 * правила пользователя от появления возможности не ломаются ни на байт.
 * Проверено компилятором на живом стенде — скрипт с отсутствующим
 * `:optional`-включением собирается без единого предупреждения.
 *
 * ==================================================================
 * ПОЧЕМУ ССЫЛКИ, А НЕ ТЕМА
 * ==================================================================
 * Переписка узнаётся по заголовкам `References` и `In-Reply-To`: они и
 * ЕСТЬ определение ответа по RFC 5322, и ими же собирает цепочки сам IMAP
 * (mail/threads.ts, алгоритм REFS). Совпадение темы для этого не годится
 * принципиально — на живом ящике оно склеивает в одну «переписку» сорок
 * несвязанных писем «Ваш заказ» (замер в шапке mail/threads.ts). Заглушить
 * по теме значило бы заглушить заодно и чужие письма, а это уже потеря
 * почты, о которой человек не узнает.
 *
 * ==================================================================
 * ЧТО ДЕЛАЕТ ПРАВИЛО
 * ==================================================================
 * Кладёт письмо в папку «Заглушённые» и помечает прочитанным. Оба действия
 * нужны, и второе не менее первого: непрочитанное письмо в любой папке
 * поднимает общий счётчик непрочитанных — то есть заглушённая переписка
 * продолжала бы дёргать человека, просто из другого места.
 *
 * Письмо при этом НЕ удаляется и не помечается спамом. «Заглушить» — это
 * «мне это больше не нужно читать», а не «этого не было: подборка
 * «Заглушённые» показывает всё пришедшее, и вернуть переписку обратно можно
 * в любой момент.
 */
import { MUTED_INCLUDE_NAME, quoteSieveString } from './sieve.js';

/** IMAP-имя папки, в которую уходит продолжение заглушённой переписки. */
export const MUTED_FOLDER_PATH = 'Muted';

/** Идентификатор роли этой папки (см. DEFAULT_ROLE_PATHS в imap/service.ts). */
export const MUTED_FOLDER_ID = 'muted';

/**
 * Сколько идентификаторов писем попадает в файл максимум.
 *
 * Ограничение не про место на диске, а про время доставки: тест
 * `header :contains` перебирает список для КАЖДОГО входящего письма, и файл
 * на десятки тысяч строк оплачивался бы задержкой всей почты ящика. Тысяча
 * идентификаторов — это порядка сотни заглушённых переписок средней длины;
 * дальше в дело вступает отбор: старые записи вытесняются новыми
 * (см. mail/mute-db.ts, listActiveIds — сортировка по времени заглушения).
 */
export const MUTED_MAX_IDS = 1000;

/**
 * Годится ли Message-ID для помещения в файл правил.
 *
 * Здесь намеренно строго: в файл попадает только то, что заведомо не
 * потребует ни экранирования, ни перевода в `:regex`. Message-ID по
 * RFC 5322 — это ASCII без пробелов и угловых скобок, и всё, что на него
 * не похоже, безопаснее пропустить, чем внести в файл, от которого зависит
 * доставка ВСЕЙ почты ящика.
 *
 * Отдельно про кириллицу. У нас условие правила с не-ASCII переводится в
 * `:regex` с перечислением регистров (см. sieve.ts). Здесь этого не будет
 * никогда: идентификатор с кириллицей — это либо ошибка отправителя, либо
 * попытка что-то нам подсунуть, и в обоих случаях правильный ответ —
 * не заглушать такую переписку, а не изобретать ей сравнение.
 */
export function usableMutedId(raw: string | null | undefined): string | null {
  const value = (raw ?? '').trim().replace(/^<|>$/g, '').trim();
  if (value === '' || value.length > 250) return null;
  // Только печатный ASCII, без пробелов, кавычек, угловых скобок и обратной
  // косой черты — то есть ровно то, что можно поставить в строку Sieve как есть.
  if (!/^[\x21-\x7E]+$/.test(value)) return null;
  if (/[<>"\\]/.test(value)) return null;
  return value;
}

export interface MutedScriptOptions {
  /** Адрес ящика — попадает в шапку файла для опознания. */
  accountEmail?: string | undefined;
  /** Куда складывать заглушённое. По умолчанию — MUTED_FOLDER_PATH. */
  folder?: string | undefined;
}

/**
 * Собирает включаемый файл по списку идентификаторов писем.
 *
 * Пустой список даёт пустую строку — и это не «нечего писать», а команда
 * УБРАТЬ файл (см. mail/mute-service.ts). Файл с условием без единого
 * значения Pigeonhole не примет, а файл с условием, которое никогда не
 * срабатывает, стоил бы проверки на каждом письме впустую.
 */
export function buildMutedSieveScript(
  messageIds: readonly string[],
  options: MutedScriptOptions = {},
): string {
  const ids: string[] = [];
  const seen = new Set<string>();
  for (const raw of messageIds) {
    const id = usableMutedId(raw);
    if (!id || seen.has(id.toLowerCase())) continue;
    seen.add(id.toLowerCase());
    ids.push(id);
    if (ids.length >= MUTED_MAX_IDS) break;
  }
  if (ids.length === 0) return '';

  const folder = options.folder?.trim() ? options.folder.trim() : MUTED_FOLDER_PATH;
  const lines: string[] = [
    '# Файл сформирован Mail.True автоматически: заглушённые цепочки.',
    ...(options.accountEmail ? [`# Ящик: ${options.accountEmail}`] : []),
    '# Не редактируйте вручную: файл переписывается целиком при каждом',
    '# изменении списка. Источник истины — база (muted_threads).',
    '#',
    '# Подключается из личного файла правил строкой',
    `#   include :optional :personal "${MUTED_INCLUDE_NAME}";`,
    '# и выполняется ДО правил пользователя: «эта переписка меня не касается»',
    '# — решение человека о переписке целиком, и оно сильнее любого правила',
    '# про отдельное письмо.',
    '',
    // imap4flags — ради addflag "\Seen": заглушённое письмо не должно
    // поднимать счётчик непрочитанных ни в одной папке.
    'require ["fileinto", "mailbox", "imap4flags"];',
    '',
    `# Идентификаторов писем в списке: ${String(ids.length)}.`,
    'if header :contains ["References", "In-Reply-To"] [',
  ];
  ids.forEach((id, index) => {
    // Угловые скобки — часть значения заголовка, и без них идентификатор
    // «abc@x» совпал бы и с чужим «xyzabc@x». Совпадение подстрокой здесь
    // единственно возможное: References содержит СПИСОК идентификаторов.
    const value = quoteSieveString(`<${id}>`);
    lines.push(`\t${value}${index === ids.length - 1 ? '' : ','}`);
  });
  lines.push(
    '] {',
    // addflag, а не setflag: setflag стёр бы остальные флаги письма.
    '\taddflag "\\\\Seen";',
    `\tfileinto :create ${quoteSieveString(folder)};`,
    // stop прекращает выполнение и ВКЛЮЧАЮЩЕГО скрипта (RFC 6609) — правила
    // пользователя и раскладка спама к заглушённому письму не применяются.
    '\tstop;',
    '}',
    '',
  );
  return lines.join('\n');
}
