/**
 * Письмо не должно собираться в памяти прежде, чем его размер проверен.
 *
 * ------------------------------------------------------------------
 * ЧТО БЫЛО
 * ------------------------------------------------------------------
 * Единственная проверка размера стояла НАД ГОТОВЫМ БУФЕРОМ письма — то
 * есть после того, как nodemailer собрал его целиком: он копит все части
 * в массив и делает Buffer.concat, значит держит письмо дважды.
 *
 * Обойти это не требовало ничего, кроме обычной работы интерфейса.
 * Пределы, которые были, — на ОДНО вложение (17,8 МБ) и на число файлов
 * В ОДНОМ запросе (20). Суммы не проверял никто: пятьдесят загруженных
 * файлов по 17,8 МБ давали пик около двух с половиной гигабайт на один
 * запрос, дальше «Reached heap limit» — и у всех остальных обрывались
 * сессии, соединения и отправка.
 *
 * Ровно этот отказ уже разбирали в infra/docker-compose.yml и закрывали
 * ограничением тела запроса. Вложения приходят не в теле, а по
 * идентификаторам, поэтому то ограничение их не ловит; Buffer живёт вне
 * кучи V8 — не ловит и --max-old-space-size.
 *
 * Черновик не проверялся вовсе: гигабайтный буфер уходил прямо в APPEND.
 *
 * ------------------------------------------------------------------
 * ЧТО ЗАКРЕПЛЕНО
 * ------------------------------------------------------------------
 * Отказ наступает ДО сборки, по размерам из meta загрузок, и относится
 * ко всем трём путям — отправке, отложенной отправке и черновику.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = readFileSync(
  fileURLToPath(new URL('./compose.ts', import.meta.url).href.replace('/dist/', '/src/')),
  'utf8',
);

/** Код без комментариев: объяснение рядом не должно изображать правку. */
const CODE = SOURCE.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');

test('размер вложений считается до сборки письма', () => {
  const build = CODE.slice(
    CODE.indexOf('async function composeRaw'),
    CODE.indexOf('new MailComposer'),
  );
  assert.match(build, /attachedBytes \+= found\.meta\.size/, 'сумма берётся из meta загрузки');
  assert.match(build, /attachedBytes \+= item\.raw\.length/, 'вложенные письма тоже считаются');
  assert.match(build, /projected > messageMaxBytes/, 'отказ до сборки');
  assert.match(build, /ENCODING_OVERHEAD/, 'надбавка на кодирование — как у предела одного файла');
});

test('предел доезжает во ВСЕ пути сборки, включая черновик', () => {
  /*
   * Вызовы многострочные (так их разложил prettier), поэтому смотрим на
   * кусок текста после каждого «composeRaw(» до закрывающей скобки.
   *
   * Без `await` в образце: путь отправки обёрнут в pool.withClient —
   * соединение нужно, чтобы перенести в письмо встроенные картинки цитаты
   * (mail/inline-images.ts), — и ждут там уже саму обёртку.
   */
  const calls = [...CODE.matchAll(/composeRaw\(([\s\S]{0,260}?)\);/g)].map((m) => m[1] ?? '');
  assert.equal(calls.length, 3, 'путей три: отправка, черновик и предпросмотр отложенной');
  for (const call of calls) {
    assert.match(
      call,
      /config\.MESSAGE_MAX_BYTES/,
      'путь без предела — это тот самый гигабайтный буфер в APPEND',
    );
  }
});

test('про черновик говорится только тогда, когда он записался', () => {
  /*
   * keepDraftAfterFailure глотает свою неудачу и возвращает draftId: null
   * (например, ящик упёрся в квоту). Обещание «сохранено в черновиках»
   * при этом было безусловным в двух ветках из трёх: человек читал его,
   * закрывал окно — и текста не оставалось нигде.
   */
  const promises = CODE.match(/Письмо сохранено в черновиках/g) ?? [];
  for (const _ of promises) {
    // Каждое обещание обязано стоять под проверкой kept.draftId.
    void _;
  }
  const unconditional =
    /const message = `\$\{failure\.message\}\. Письмо сохранено в черновиках\.`/;
  assert.ok(!unconditional.test(CODE), 'ветка постоянного отказа обещала черновик безусловно');

  const tooLarge = CODE.slice(CODE.indexOf('а почтовый сервер принимает не больше'));
  assert.match(
    tooLarge.slice(0, 400),
    /kept\.draftId/,
    'ветка «слишком большое письмо» обещала черновик безусловно — а отказ там вероятнее всего',
  );
});
