/**
 * Длина пути папки и достижимость писем в ней.
 *
 * Папка с длинным названием была ловушкой: список писем открывался, а само
 * письмо нельзя было ни прочитать, ни пометить, ни ВЫНЕСТИ ОБРАТНО — все
 * обращения по идентификатору отвергал маршрутизатор. Папку тоже нельзя было
 * ни переименовать, ни удалить. Письмо, попавшее туда правилом фильтрации,
 * оставалось недостижимым ничем, кроме прямого доступа к серверу.
 *
 * Причина: идентификатор папки несёт в себе путь (`f-<base64url(путь)>`),
 * кодирование удлиняет его примерно в 1,34 раза, а кириллическая буква
 * занимает два байта. Порог наступал уже на 37 русских буквах, тогда как
 * форма создания разрешала 255 символов.
 *
 * Проверка считает пороги от тех же констант, что использует продукт, —
 * не повторяя их числами, иначе она проверяла бы саму себя.
 */
import assert from 'node:assert/strict';
import test from 'node:test';
import {
  encodePathId,
  folderPathBytes,
  MAX_ENTITY_ID_LENGTH,
  MAX_FOLDER_PATH_BYTES,
} from './folders.js';

test('идентификатор самого длинного допустимого пути умещается в предел', () => {
  // Худший случай: путь целиком из двухбайтовых букв, ровно по пределу.
  const path = 'я'.repeat(Math.floor(MAX_FOLDER_PATH_BYTES / 2));
  assert.ok(folderPathBytes(path) <= MAX_FOLDER_PATH_BYTES);

  const folderId = encodePathId(path);
  // Идентификатор письма длиннее идентификатора папки: плюс двоеточие и номер.
  const messageId = `${folderId}:4294967295`;
  assert.ok(
    messageId.length <= MAX_ENTITY_ID_LENGTH,
    `идентификатор письма ${messageId.length} символов при пределе ${MAX_ENTITY_ID_LENGTH}`,
  );
});

test('прежний порог в сто символов давно пройден кириллицей', () => {
  // Именно этот случай был ловушкой: 37 русских букв — обычное название папки.
  const id = encodePathId('я'.repeat(37));
  assert.ok(id.length > 100, 'кириллическое название из 37 букв даёт id длиннее ста символов');
  assert.ok(id.length <= MAX_ENTITY_ID_LENGTH, 'и при этом умещается в действующий предел');
});

test('вложенность считается по всему пути, а не по имени папки', () => {
  const path = 'Работа/Проекты/Договоры с подрядчиками';
  assert.equal(folderPathBytes(path), Buffer.byteLength(path, 'utf8'));
  // Длина пути больше длины имени — на этом и строится проверка при создании.
  assert.ok(folderPathBytes(path) > folderPathBytes('Договоры с подрядчиками'));
});

test('кодирование обратимо на границе предела', () => {
  const path = 'я'.repeat(Math.floor(MAX_FOLDER_PATH_BYTES / 2));
  const id = encodePathId(path);
  assert.equal(Buffer.from(id.slice(2), 'base64url').toString('utf8'), path);
});
