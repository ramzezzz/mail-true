/**
 * Как отдавать письмо и его части браузеру: показывать или скачивать,
 * с каким типом и под каким именем.
 *
 * Решение вынесено сюда, а не оставлено в обработчике маршрута, потому что
 * это правило безопасности, а правила безопасности должны быть закреплены
 * тестом. Ошибка здесь стоит дорого: часть письма отдаётся с источника API,
 * и всё, что браузер согласится исполнить, получит доступ к сессионной куке
 * владельца ящика — то есть сможет читать и отправлять его почту.
 */
import { safeEntryName } from '../settings/zip.js';

/**
 * Типы, которые допустимо показывать прямо в браузере.
 *
 * Список разрешительный, а не запретительный, и это принципиально. Раньше
 * правило было обратным — «всё, что image/*, показываем; text/html
 * обезвреживаем», — и в эту щель проходил `image/svg+xml`: он считается
 * картинкой, объявляется честно (поэтому заголовок nosniff не мешает),
 * а браузер открывает его как документ и выполняет скрипт внутри.
 *
 * Здесь только растровые картинки — ровно то, что нужно для изображений,
 * встроенных в тело письма. Вложения интерфейс скачивает и без этого.
 * Каждая новая строка в списке — новая поверхность атаки.
 */
const INLINE_SAFE_TYPES = new Set([
  'image/png',
  'image/jpeg',
  'image/gif',
  'image/webp',
  'image/bmp',
  'image/avif',
]);

export interface PartDelivery {
  /** Значение заголовка Content-Type. */
  contentType: string;
  /** Показывать в браузере (inline) или скачивать (attachment). */
  inline: boolean;
}

/**
 * @param declaredType тип, заявленный в самом письме — доверять ему нельзя
 */
export function decidePartDelivery(declaredType: string | undefined | null): PartDelivery {
  const baseType = (declaredType ?? '').split(';')[0]?.trim().toLowerCase() ?? '';
  if (INLINE_SAFE_TYPES.has(baseType)) {
    return { contentType: baseType, inline: true };
  }
  // Всё остальное — поток байтов: браузер не должен даже пытаться его разобрать,
  // что бы ни было написано в письме.
  return { contentType: 'application/octet-stream', inline: false };
}

/* ------------------------------------------------------------------ */
/* Имя файла для письма, сохранённого как .eml                          */
/* ------------------------------------------------------------------ */

/**
 * Сколько букв темы попадает в имя файла.
 *
 * Столько же берёт выгрузка ящика (settings/export-runner.ts): темы в сотни
 * символов существуют, а имя файла длиннее 255 байт файловая система не
 * примет — и кириллица в UTF-8 расходует по два байта на букву.
 */
const SUBJECT_LIMIT = 80;

/**
 * Как назвать скачиваемое письмо.
 *
 * Раньше имя собиралось из идентификатора письма — `inbox_209.eml`. Такой
 * файл, сохранённый в «Загрузки», через день не отличить ни от какого
 * другого: ни темы, ни даты. Поэтому имя — «тема пробел дата».
 *
 * Чистка темы НЕ пишется здесь заново: та же `safeEntryName`, что чистит
 * имена внутри выгрузки ящика. Тема — это данные от кого угодно, в ней
 * бывает и `/`, и `..`, и управляющие символы; правило, как из неё
 * получается имя файла, должно быть в продукте одно, иначе второе
 * разойдётся с первым при первой же правке.
 *
 * @param subject тема письма (уже раскодированная), может быть пустой
 * @param date дата письма — объектом или строкой, как её отдаёт IMAP; при
 *             отсутствии или порче имя остаётся без даты: выдумывать
 *             сегодняшнее число письму трёхлетней давности хуже, чем не
 *             написать даты вовсе
 */
export function emlFileName(
  subject: string | null | undefined,
  date: Date | string | null | undefined,
): string {
  const cleaned = safeEntryName(subject ?? '')
    .slice(0, SUBJECT_LIMIT)
    .trim();
  // safeEntryName на пустой строке возвращает «без имени» — здесь у этого
  // случая своё, более точное название: файл-то не безымянный, это письмо.
  const head = cleaned === '' || cleaned === 'без имени' ? 'Письмо без темы' : cleaned;
  const at = date == null ? null : date instanceof Date ? date : new Date(date);
  const day = at && Number.isFinite(at.getTime()) ? at.toISOString().slice(0, 10) : null;
  return `${day ? `${head} ${day}` : head}.eml`;
}
