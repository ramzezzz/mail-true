/**
 * Сборка переписок для списка писем.
 *
 * ------------------------------------------------------------------
 * ПОЧЕМУ ЦЕПОЧКИ СОБИРАЕТ ПОЧТОВЫЙ СЕРВЕР, А НЕ МЫ
 * ------------------------------------------------------------------
 * Собрать переписки самим — значит прочитать заголовки References и
 * In-Reply-To у ВСЕХ писем папки: не у страницы в двадцать пять строк,
 * а у всех, иначе нельзя узнать, сколько писем в цепочке и какое из них
 * последнее. На папке в двадцать тысяч писем это двадцать тысяч заголовков
 * на каждое открытие папки — ровно тот риск, который записан в разборе
 * (docs/gaps.md, п. 11): «ответ за 0,4 с не должен превратиться в пять».
 *
 * У IMAP для этого есть отдельная команда — THREAD (RFC 5256), и Dovecot
 * её умеет: в списке возможностей нашего сервера есть THREAD=REFS,
 * THREAD=REFERENCES и THREAD=ORDEREDSUBJECT. Считает он её по своему
 * индексу, то есть по тем же данным, по которым отвечает на поиск.
 * Замер на живом стенде: папка «Входящие», 478 писем — 9 мс.
 *
 * ------------------------------------------------------------------
 * ПОЧЕМУ ИМЕННО REFS, А НЕ REFERENCES
 * ------------------------------------------------------------------
 * Разница между ними одна, и она решающая. REFERENCES (и тем более
 * ORDEREDSUBJECT) после сборки по ссылкам ДОПОЛНИТЕЛЬНО склеивает письма
 * с одинаковой темой — так велит сам RFC 5256. REFS этого шага не делает
 * и связывает письма только по настоящим ссылкам.
 *
 * Замерено на живом ящике (478 писем во «Входящих»):
 *
 *   REFS        478 писем -> 478 строк, склеек нет
 *   REFERENCES  478 писем -> 384 строки, 14 склеек, самая большая — 40 писем
 *
 * Эти сорок писем — не переписка. Это рассылки с одинаковой темой
 * («Ваш заказ», «Уведомление»), которые REFERENCES свалил в одну строку.
 * Сорок писем, спрятанных за счётчиком, из списка не достать: строка
 * показывает последнее, а остальные тридцать девять видны только внутри.
 * То есть группировка, которая должна помогать читать, начинает ПРЯТАТЬ
 * почту — и именно в тех папках, где её больше всего.
 *
 * Поэтому REFS. В разборе так и написано: «Собирать цепочки по References
 * и In-Reply-To».
 */
import type { FolderRole } from '@mail-true/shared';

/** Алгоритм сборки цепочек и возможность IMAP, которая его объявляет. */
export const THREAD_ALGORITHM = 'REFS';
export const THREAD_CAPABILITY = `THREAD=${THREAD_ALGORITHM}`;

/**
 * Можно ли группировать письма в этой папке.
 *
 * Правило одно: группируем там, где письма ЧИТАЮТ, и не группируем там,
 * куда приходят за ОДНИМ конкретным письмом. Строка-переписка прячет письма
 * за счётчиком — это выгодный обмен, когда читаешь разговор, и прямой вред,
 * когда ищешь потерянное.
 *
 *   «Входящие», «Архив», свои папки — читают. Группируем.
 *
 *   «Отправленные» — читают («я ему вообще отвечал?»). Три своих письма
 *      одной переписки — это одна строка со счётчиком «3», а не три
 *      одинаковых строки. Группируем.
 *
 *   «Черновики» — НЕ группируем, и это запрет, а не предпочтение. Черновик
 *      открывается на дописывание, а не на чтение: щелчок по строке ведёт
 *      в окно написания ОДНОГО письма. Два черновика ответа на одно и то же
 *      письмо связаны общим References и склеились бы в одну строку —
 *      и второй черновик стал бы недостижим вовсе. Это потеря работы
 *      человека, а не неудобство.
 *
 *   «Корзина» — НЕ группируем. В корзину приходят ровно за одним: вернуть
 *      письмо, удалённое по ошибке. Удаляют письма поштучно, поэтому
 *      переписка в корзине — это её обрывок, и счётчик «3» рядом с ним
 *      сообщал бы неправду о размере переписки. А главное — искомое письмо
 *      оказалось бы спрятано за строкой, показывающей другое.
 *
 *   «Спам» — НЕ группируем, по той же причине, что и корзину: туда заходят
 *      найти письмо, попавшее туда по ошибке.
 *
 *   «Отложенные» — НЕ группируем: в строке показан срок возврата, а он
 *      у каждого письма свой. У группы писем с разными сроками единого
 *      срока не существует, и показать в строке было бы нечего.
 *
 * Решение принимает СЕРВЕР, а не интерфейс, и это не мелочь: так папка
 * черновиков не станет группироваться ни от чужого клиента, ни от
 * сохранившейся в браузере настройки, ни от ошибки в новом экране.
 */
export function threadingAllowed(role: FolderRole): boolean {
  switch (role) {
    case 'drafts':
    case 'trash':
    case 'spam':
    case 'snoozed':
      return false;
    default:
      return true;
  }
}

/**
 * Узел ответа THREAD в разборе imapflow: либо атом с числом, либо список.
 * Вложенность произвольная — RFC 5256 отдаёт дерево ответов.
 */
type ThreadNode = { value?: unknown } | readonly ThreadNode[];

/**
 * Разбирает нетегированный ответ `* THREAD (1)(2 3 (4)(5))` в плоские группы.
 *
 * Дерево ответов внутри цепочки нам не нужно: в списке строка одна на всю
 * переписку, а порядок писем внутри неё задаёт время, а не глубина ответа.
 * Поэтому каждая ветвь верхнего уровня сплющивается в набор номеров.
 */
export function parseThreadGroups(attributes: unknown): number[][] {
  if (!Array.isArray(attributes)) return [];
  const groups: number[][] = [];
  for (const branch of attributes as ThreadNode[]) {
    const uids: number[] = [];
    collectUids(branch, uids);
    if (uids.length > 0) groups.push(uids);
  }
  return groups;
}

function collectUids(node: ThreadNode | undefined, out: number[]): void {
  if (node === undefined || node === null) return;
  if (Array.isArray(node)) {
    for (const child of node) collectUids(child, out);
    return;
  }
  const raw = (node as { value?: unknown }).value;
  if (typeof raw !== 'string') return;
  const uid = Number(raw);
  // «0» в ответе THREAD означает недостающее письмо-корень (RFC 5256):
  // цепочка есть, а самого письма в папке нет. Номера у него тоже нет.
  if (Number.isInteger(uid) && uid > 0) out.push(uid);
}

/**
 * Сводит найденные поиском письма в строки-переписки.
 *
 * ------------------------------------------------------------------
 * ГЛАВНОЕ СВОЙСТВО, РАДИ КОТОРОГО ЭТА ФУНКЦИЯ ОТДЕЛЬНАЯ И ПРОВЕРЯЕМАЯ
 * ------------------------------------------------------------------
 * Объединение всех строк равно ровно тому набору писем, который вернул бы
 * список БЕЗ группировки при тех же папке, отборе и поиске. Ни одного
 * письма не пропало и ни одного не появилось дважды.
 *
 * Это не украшение проверки, а то самое место, где заводится дефект
 * «удалил цепочку, а два письма остались»: действие над строкой применяется
 * к её письмам, и если строка знает о переписке не всё — часть писем
 * останется нетронутой.
 *
 * Отсюда же и ответ на вопрос, что считать «перепиской» под отбором
 * «непрочитанные»: только непрочитанные письма. Строка представляет то,
 * что нашлось, а не то, что где-то есть.
 *
 * @param groups — ветви ответа THREAD по ВСЕЙ папке.
 * @param matched — номера писем, которые прошли поиск и отбор.
 * @returns группы номеров: внутри — по возрастанию (то есть по времени),
 *   сами группы — новые первыми, как и плоский список.
 */
export function buildThreadRows(
  groups: readonly (readonly number[])[],
  matched: readonly number[],
): number[][] {
  const wanted = new Set(matched);
  const rows: number[][] = [];

  for (const group of groups) {
    const kept: number[] = [];
    for (const uid of group) {
      // delete, а не has: письмо, уже разложенное в строку, второй раз
      // попасть никуда не должно. Ответ THREAD теоретически может назвать
      // один номер дважды, и тогда действие над строкой ушло бы дважды
      // на одно письмо.
      if (wanted.delete(uid)) kept.push(uid);
    }
    if (kept.length > 0) rows.push(kept.sort((a, b) => a - b));
  }

  /*
   * Письма, которых нет ни в одной ветви ответа.
   *
   * Так быть не должно, но «не должно» — не основание терять письмо из
   * списка. Пропущенное здесь письмо исчезло бы из папки совсем: его нет
   * ни отдельной строкой, ни внутри чьей-то переписки. Поэтому каждое
   * такое письмо становится своей строкой.
   */
  for (const uid of wanted) rows.push([uid]);

  // Порядок строк — по самому свежему письму переписки. Номер письма растёт
  // со временем, поэтому это то же самое правило, что и у плоского списка.
  rows.sort((a, b) => (b[b.length - 1] ?? 0) - (a[a.length - 1] ?? 0));
  return rows;
}
