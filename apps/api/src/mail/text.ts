/** Утилиты работы с текстом писем: сниппеты, декодирование, HTML -> текст. */

const ENTITIES: Record<string, string> = {
  '&nbsp;': ' ',
  '&amp;': '&',
  '&lt;': '<',
  '&gt;': '>',
  '&quot;': '"',
  '&#39;': "'",
  '&laquo;': '«',
  '&raquo;': '»',
  '&mdash;': '—',
  '&ndash;': '–',
};

/**
 * Снимает теги — проходом по строке, а не выражением.
 *
 * ------------------------------------------------------------------
 * ПОЧЕМУ НЕ РЕГУЛЯРНЫМ ВЫРАЖЕНИЕМ
 * ------------------------------------------------------------------
 * Здесь стояло `/<[^>]+>/g`. На теле, где после `<` нет закрывающей
 * скобки, разбор просматривает ВЕСЬ остаток для каждого `<` — то есть
 * квадрат от длины письма. Замерено на этой функции: тело в два
 * мегабайта с сорока тысячами «<img » считалось 137 СЕКУНД, и всё это
 * время сервер (он однопоточный) не отвечал никому: живая проверка на
 * стенде получила 504 и на сохранение черновика, и на запрос папок.
 *
 * Первой починкой был потолок длины (`{1,8192}`), и он оказался хуже
 * болезни: тег длиннее потолка не совпадал и ОСТАВАЛСЯ В ТЕКСТЕ
 * ЦЕЛИКОМ. А самый длинный тег в письме — это как раз `<img>` со
 * вшитым снимком экрана: в текстовую часть уходящего письма уезжали
 * двести килобайт base64, и они же показывались вместо начала письма
 * в списке «Отправленных».
 *
 * Проход по строке через indexOf линеен от длины и потолка не требует
 * вовсе: каждый знак просматривается один раз. Незакрытый `<` в конце
 * остаётся текстом — как и было с прежним выражением: в письмах
 * попадается «5 < 3», и съедать такой хвост нельзя.
 */
function stripTags(text: string): string {
  if (!text.includes('<')) return text;
  let out = '';
  let from = 0;
  for (;;) {
    const open = text.indexOf('<', from);
    if (open < 0) {
      out += text.slice(from);
      break;
    }
    const close = text.indexOf('>', open + 1);
    if (close < 0) {
      out += text.slice(from);
      break;
    }
    out += `${text.slice(from, open)} `;
    from = close + 1;
  }
  return out;
}

/**
 * Убирает НЕЗАКРЫТЫЙ блок и весь хвост письма после него.
 *
 * Зачем это вообще: сюда приходит и обрезанный HTML — сниппет для списка
 * писем качает первые 4 КБ тела (imap/service.ts), и блок стилей рассылки
 * в них почти никогда не помещается. Без этого `<style …>` без закрывающего
 * тега снимался как обычный тег, а его содержимое уезжало в список писем и
 * в уведомление: вместо начала письма человек читал
 * `body{margin:0;padding:0} .wrapper{width:100%…`.
 *
 * Раньше это делалось выражением с проверкой «а нет ли дальше закрывающего
 * тега» — она просматривает весь остаток письма для каждого вхождения, то
 * есть считается квадратом от длины. Поиск одного вхождения такого не
 * делает: парные блоки к этому моменту уже убраны, значит найденный
 * открывающий тег и есть незакрытый.
 */
function dropUnclosedTail(text: string, tag: string): string {
  // `\\b` — граница слова. Одинарный `\b` внутри шаблонной строки означает
  // символ забоя, и выражение переставало совпадать вовсе: проверка тут же
  // показала стили рассылки в тексте письма.
  const open = new RegExp(`<${tag}\\b[^>]{0,4096}>`, 'i');
  const found = open.exec(text);
  return found ? `${text.slice(0, found.index)} ` : text;
}

/** Грубое преобразование HTML в текст (для сниппетов и text-версии писем). */
export function htmlToText(html: string): string {
  // Сперва ПАРНЫЕ блоки целиком, потом незакрытые (dropUnclosedTail):
  // порядок обратный прежнему и оттого проще — после удаления парных
  // любой оставшийся открывающий тег заведомо не закрыт, и проверять
  // это отдельным просмотром всего письма больше не нужно.
  let text = html
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<head[\s\S]*?<\/head>/gi, ' ');

  // Парные блоки убраны выше; всё, что осталось от них, — незакрытое,
  // и текстом не является ни оно, ни хвост письма после него.
  text = dropUnclosedTail(dropUnclosedTail(dropUnclosedTail(text, 'style'), 'script'), 'head');

  text = text.replace(/<br\s*\/?>/gi, '\n').replace(/<\/(p|div|tr|li|h[1-6])>/gi, '\n');
  text = stripTags(text);
  for (const [entity, char] of Object.entries(ENTITIES)) {
    text = text.split(entity).join(char);
  }
  text = text.replace(/&#(\d+);/g, (_m, code: string) => {
    const num = Number(code);
    return Number.isFinite(num) && num > 0 && num < 0x110000 ? String.fromCodePoint(num) : '';
  });
  return text
    .replace(/[\t ]+/g, ' ')
    .replace(/\s*\n\s*/g, '\n')
    .trim();
}

/** Сниппет — первые max символов текста без переносов и лишних пробелов. */
export function makeSnippet(text: string, max = 200): string {
  const collapsed = text.replace(/\s+/g, ' ').trim();
  return collapsed.length <= max ? collapsed : collapsed.slice(0, max - 1).trimEnd() + '…';
}

/** Декодирует Buffer с учётом charset (насколько поддерживает TextDecoder). */
export function decodeBuffer(buf: Buffer, charset: string | undefined): string {
  if (charset) {
    try {
      return new TextDecoder(charset).decode(buf);
    } catch {
      /* неизвестная кодировка — используем utf-8 */
    }
  }
  return buf.toString('utf8');
}
