/**
 * Сохранённый поисковый запрос: правила имени и строки.
 *
 * Отдельно от хранилища и от маршрутов, потому что эти правила нужны всем
 * троим: маршрут проверяет присланное, хранилище в памяти повторяет
 * поведение настоящего, а проверки сверяют их между собой.
 */

/** Предел длины имени — тот же, что у метки: это подпись в левой колонке. */
export const MAX_SAVED_SEARCH_NAME_LENGTH = 64;

/**
 * Предел длины запроса — тот же, что у параметра `search` в маршруте списка
 * писем. Сохранить нельзя то, что нельзя выполнить.
 */
export const MAX_SAVED_SEARCH_QUERY_LENGTH = 500;

/** Сколько запросов может завести один ящик. */
export const MAX_SAVED_SEARCHES = 50;

export interface SavedSearch {
  /** Идентификатор строки в базе, строкой — он попадает в адрес маршрута. */
  id: string;
  name: string;
  /** Строка поиска со всеми операторами, как её набрал человек. */
  query: string;
  /** Искать ли в Спаме и Корзине. */
  includeJunk: boolean;
  position: number;
}

/**
 * Приводит имя к виду для хранения: схлопывает пробелы и обрезает края.
 *
 * Ровно то же делает нормализация имени метки, и по той же причине: имя
 * «Счета  » и «Счета» человек считает одним и тем же, а список с обоими
 * выглядел бы как ошибка продукта.
 */
export function normalizeSavedSearchName(raw: string): string {
  return raw.replace(/\s+/gu, ' ').trim().slice(0, MAX_SAVED_SEARCH_NAME_LENGTH);
}

/**
 * Приводит строку запроса к виду для хранения.
 *
 * Переводы строк схлопываются в пробел: запрос попадает в адресную строку
 * и в параметр `search`, а перевод строки там не живёт. Вставка из письма
 * или из заметки не должна ломать сохранённый запрос.
 */
export function normalizeSavedSearchQuery(raw: string): string {
  return raw.replace(/\s+/gu, ' ').trim().slice(0, MAX_SAVED_SEARCH_QUERY_LENGTH);
}
