/**
 * Преобразование HTML письма в текст — то, из чего собирается сниппет для
 * списка писем и текстовая часть отправляемого письма.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { htmlToText } from './text.js';

test('обрезанный HTML не выдаёт CSS за начало письма', () => {
  /*
   * Сниппет для списка качает первые 4 КБ тела (imap/service.ts,
   * fetchSnippet), и блок стилей рассылки в них почти никогда не
   * помещается: закрывающего тега в куске нет. Парная замена его не
   * находила, тег снимался как обычный — и в списке писем, а заодно во
   * всплывающем уведомлении о новой почте, человек читал
   * `body{margin:0;padding:0}…` вместо первых слов письма.
   */
  const cut = '<html><head><style type="text/css">body{margin:0;padding:0}.wrap{width:100%}';
  assert.equal(htmlToText(cut).trim(), '');
});

test('целый документ разбирается как и прежде', () => {
  assert.equal(
    htmlToText('<html><head><style>body{margin:0}</style></head><body><p>Привет</p></body>').trim(),
    'Привет',
  );
});

test('закрытый блок стилей не съедает письмо целиком', () => {
  // Важен порядок замен: если бы незакрытые вырезались первыми без учёта
  // парных, первый же <style> унёс бы с собой весь текст письма.
  assert.equal(
    htmlToText('<style>a{color:red}</style><p>Текст</p><style>b{color:blue}').trim(),
    'Текст',
  );
});

test('переводы строк и сущности сохраняются', () => {
  assert.equal(htmlToText('<p>Первая</p><p>Вторая</p>').trim(), 'Первая\nВторая');
  assert.equal(htmlToText('Пять &lt; шесть &amp; семь').trim(), 'Пять < шесть & семь');
});

test('длинный тег снимается целиком, а не остаётся текстом', () => {
  /*
   * ЭТА ПРОВЕРКА СТОИТ ЗДЕСЬ ИЗ-ЗА ПОЧИНКИ, КОТОРАЯ СЛОМАЛА ДРУГОЕ.
   *
   * Квадрат в разборе (см. проверку ниже) сначала закрыли потолком
   * длины тега — `/<[^>]{1,8192}>/g`. Тег длиннее потолка перестал
   * совпадать и ОСТАВАЛСЯ В ТЕКСТЕ ЦЕЛИКОМ. А самый длинный тег в
   * письме — это `<img>` со вшитым снимком экрана: в текстовую часть
   * уходящего письма уезжали двести килобайт base64, и они же шли в
   * список «Отправленных» вместо начала письма.
   */
  const huge = `<p>Смотрите снимок:</p><img src="data:image/png;base64,${'A'.repeat(200_000)}">`;
  const out = htmlToText(huge);

  assert.doesNotMatch(out, /base64/u, 'вшитая картинка утекла в текст письма');
  assert.doesNotMatch(out, /AAAA/u, 'байты картинки утекли в текст письма');
  assert.match(out, /Смотрите снимок/u, 'сам текст письма при этом обязан остаться');
  assert.ok(out.length < 200, `текст раздулся до ${String(out.length)} знаков`);
});

test('одинокая угловая скобка остаётся текстом, а не съедает остаток', () => {
  // В письмах пишут «5 < 3» и «цена < 1000». Прежнее выражение такой
  // хвост не трогало, и проход по строке обязан вести себя так же.
  assert.equal(htmlToText('<p>цена &lt; 1000</p>'), 'цена < 1000');
  assert.match(htmlToText('<p>если a < b, то</p>'), /если a < b, то/u);
});

test('разбор большого письма в текст линеен, а не квадратичен', () => {
  /*
   * ЭТА ПРОВЕРКА СТОИТ ЗДЕСЬ ИЗ-ЗА НАСТОЯЩЕЙ ОСТАНОВКИ СЕРВЕРА.
   *
   * Выражение `<[^>]+>` на теле, где после `<` нет закрывающей скобки,
   * просматривает весь остаток письма для каждого `<`. Замерено на этой
   * функции: два мегабайта с сорока тысячами «<img » считались 137
   * СЕКУНД. Node однопоточный — всё это время сервер не отвечал никому.
   * Живая проверка на стенде получила 504 и на сохранение черновика, и
   * на параллельный запрос папок.
   *
   * Порог щедрый: проверка ловит возврат квадрата, а не колебания машины.
   */
  const evil = '<p>привет</p>' + '<img '.repeat(40000) + 'x'.repeat(2 * 1024 * 1024);
  const started = Date.now();
  htmlToText(evil);
  const spent = Date.now() - started;
  assert.ok(
    spent < 5000,
    `разбор двух мегабайт занял ${String(spent)} мс — похоже на возврат квадрата`,
  );
});

test('незакрытый блок стилей по-прежнему не течёт в текст', () => {
  // Ради этого поведения выражения и писались: сниппет качает первые 4 КБ
  // тела, и блок стилей рассылки в них почти никогда не закрывается.
  assert.equal(htmlToText('<p>Привет</p><style>body{margin:0}').trim(), 'Привет');
  assert.equal(htmlToText('<p>Привет</p><script>var a=1;').trim(), 'Привет');
  assert.equal(htmlToText('<p>А</p><style>x{}</style><p>Б</p>').replace(/\s+/g, ' ').trim(), 'А Б');
});
