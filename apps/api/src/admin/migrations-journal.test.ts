/**
 * Каждая миграция обязана записать себя в журнал.
 *
 * ------------------------------------------------------------------
 * ЧТО БЫЛО
 * ------------------------------------------------------------------
 * Каталог infra/postgres/migrations примонтирован в контейнер Postgres как
 * /docker-entrypoint-initdb.d (infra/docker-compose.yml). Это значит, что на
 * ПУСТОЙ базе весь каталог выполняет сам Postgres при первичной
 * инициализации — до того, как установщик вообще запустится.
 *
 * Строку о себе в journal писала только базовая схема. Установщик, читая
 * `schema_migrations`, видел там 0000 и 0001 — и применял все остальные
 * миграции ВТОРОЙ раз, на каждом новом сервере.
 *
 * Пока миграции идемпотентны, это сходит с рук. Но 0039 — уже
 * `DELETE … WHERE EXISTS` по связям ящиков, а следующая такая миграция
 * отработает дважды и молча. Ровно этот случай и описан в шапке
 * 0000_schema_migrations.sql как причина завести журнал: миграция 0008
 * когда-то повторяла свой UPDATE при каждой установке.
 *
 * ------------------------------------------------------------------
 * ПОЧЕМУ ПРОВЕРЯЕТСЯ ТЕКСТ ФАЙЛОВ
 * ------------------------------------------------------------------
 * Забыть эту строку в новой миграции ничего не стоит: файл применится,
 * сервер поднимется, всё будет выглядеть исправным. Цена выяснится на
 * первой же установке с данными.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { readdirSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const DIR = fileURLToPath(new URL('../../../../infra/postgres/migrations/', import.meta.url));

/** Только верхний уровень: legacy/ — архив, оттуда файлы не применяются. */
const FILES = readdirSync(DIR)
  .filter((name) => name.endsWith('.sql'))
  .sort();

test('в каталоге вообще есть миграции — иначе проверка бессмысленна', () => {
  assert.ok(FILES.length > 1, `в ${DIR} не нашлось миграций`);
});

test('каждая миграция, кроме заводящей журнал, пишет о себе строку', () => {
  for (const name of FILES) {
    // 0000 создаёт саму таблицу журнала: писать в неё ей нечем и незачем.
    if (name.startsWith('0000')) continue;
    const text = readFileSync(DIR + name, 'utf8');
    assert.match(
      text,
      /INSERT INTO schema_migrations/i,
      `миграция ${name} не записывает себя в журнал — на новом сервере ` +
        'её выполнит Postgres при инициализации, а установщик применит второй раз',
    );
    // Имя в записи — своё, а не скопированное у соседней миграции.
    assert.ok(
      text.includes(`'${name}'`),
      `в записи журнала миграции ${name} стоит чужое имя файла`,
    );
  }
});

test('запись не затирает уже проставленную установщиком контрольную сумму', () => {
  for (const name of FILES) {
    if (name.startsWith('0000')) continue;
    const text = readFileSync(DIR + name, 'utf8');
    assert.match(
      text,
      /ON CONFLICT \(filename\) DO NOTHING/i,
      `миграция ${name} перезапишет строку журнала: настоящая сумма файла ` +
        'сменится на «initdb», и установщик применит миграцию заново',
    );
  }
});
