/**
 * Справочник по серверу для админского разговора с ИИ.
 *
 * ------------------------------------------------------------------
 * ЧТО ЗДЕСЬ ЗАКРЫВАЕТСЯ
 * ------------------------------------------------------------------
 * 1. Утечка значений. Справочник уезжает во ВНЕШНИЙ сервис ИИ. Попади в
 *    него значения настроек — и разговор стал бы способом вытащить
 *    содержимое infra/.env вопросом «а что у меня сейчас стоит».
 *    Отдаются только имена, разделы и назначение.
 * 2. Расхождение с продуктом. Список настроек берётся из того же
 *    реестра, по которому работает раздел «Настройки сервера»: справочник,
 *    переписанный руками, разошёлся бы через месяц — и отвечал бы
 *    уверенно и мимо, что хуже отсутствия справочника.
 * 3. Прямой запрет на выдумывание паролей: модель, которую попросили
 *    «напомни пароль», обязана отказаться, а не сочинить.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { serverKnowledge } from './ai-knowledge.js';
import { SETTING_SPECS } from './server-settings-registry.js';

void test('в справочнике перечислены настройки из реестра, а не свой список', () => {
  const text = serverKnowledge();
  for (const spec of SETTING_SPECS) {
    assert.ok(text.includes(spec.key), `настройки ${spec.key} нет в справочнике`);
  }
});

void test('значений настроек в справочнике нет — даже умолчаний', () => {
  /*
   * Умолчание модель пересказала бы как «сейчас стоит столько», а это
   * неправда: значение могли изменить. Проверяем на приметных
   * умолчаниях — таких, которые в описаниях случайно не встречаются.
   */
  const text = serverKnowledge();
  const notable = SETTING_SPECS.filter(
    (spec) => spec.def.length >= 6 && /^\d+$/u.test(spec.def),
  ).slice(0, 20);
  assert.ok(notable.length > 0, 'не нашлось приметных умолчаний для проверки');
  for (const spec of notable) {
    assert.ok(
      !text.includes(`${spec.key} — ${spec.def}`) && !text.includes(`= ${spec.def}`),
      `похоже, в справочник попало значение ${spec.key}`,
    );
  }
});

void test('секретные настройки названы, но их значения не берутся ниоткуда', () => {
  // Секретные настройки в списке быть должны — администратор спрашивает и
  // про них («где задаётся SESSION_SECRET»). Нельзя лишь значений, а их
  // справочник не читает вовсе: он работает с описаниями реестра.
  const secrets = SETTING_SPECS.filter((spec) => spec.secret === true);
  assert.ok(secrets.length > 0, 'в реестре не осталось секретных настроек — проверка бессмысленна');
  const text = serverKnowledge();
  for (const spec of secrets) assert.ok(text.includes(spec.key));
});

void test('модели прямо сказано, что доступа к серверу у неё нет', () => {
  // Без этого на вопрос «покажи мои настройки» модель отвечает выдуманным
  // списком — не по злому умыслу, а потому что её не предупредили.
  assert.match(serverKnowledge(), /НЕТ доступа/u);
});

void test('запрет называть пароли и секреты записан явно', () => {
  assert.match(serverKnowledge(), /паролей/u);
});

void test('разделы панели перечислены с назначением', () => {
  const text = serverKnowledge();
  for (const section of ['Ящики', 'Домены', 'Спам', 'Обновления', 'Аудит', 'Сертификат']) {
    assert.ok(text.includes(section), `раздела «${section}» нет в справочнике`);
  }
});

void test('описания настроек — в одну строку', () => {
  /*
   * В реестре описания бывают многострочными. Перенос строки внутри
   * пункта разорвал бы список: модель приняла бы продолжение описания за
   * новую настройку и назвала бы администратору несуществующее имя.
   */
  const lines = serverKnowledge().split('\n');
  const settingLines = lines.filter((line) => /^[A-Z][A-Z0-9_]+ \(/u.test(line));
  assert.ok(settingLines.length >= SETTING_SPECS.length);
  for (const line of settingLines) assert.ok(!line.includes('\n'));
});

void test('справочник не разрастается: он уходит поставщику при каждом вопросе', () => {
  /*
   * Полные описания настроек давали тридцать килобайт на КАЖДУЮ реплику
   * разговора — заметную часть дневного предела домена за один вопрос
   * «где DKIM». Оставлено первое предложение каждого описания.
   *
   * Предел здесь с запасом: он ловит не лишний абзац, а возврат к
   * полным описаниям или новый раздел, вставленный целиком.
   */
  assert.ok(
    serverKnowledge().length < 24_000,
    `справочник вырос до ${String(serverKnowledge().length)} символов — он уходит с каждым вопросом`,
  );
});

void test('назначение настройки обрывается по предложению, а не по букве', () => {
  // Описание, обрезанное на полуслове, читается моделью как другое
  // правило: «...применяется только при» — и дальше она додумывает сама.
  const lines = serverKnowledge()
    .split('\n')
    .filter((line) => /^[A-Z][A-Z0-9_]+ \(/u.test(line));
  for (const line of lines) {
    const tail = line.slice(-1);
    assert.ok(
      ['.', '!', '?', '…', ')'].includes(tail),
      `строка обрывается на полуслове: ${line.slice(-60)}`,
    );
  }
});
