/**
 * «Наблюдение» не имеет права показывать зелёное там, где не смотрели.
 *
 * ------------------------------------------------------------------
 * ТРИ СПОСОБА СОВРАТЬ МОЛЧАНИЕМ — И ВСЕ ТРИ ЗДЕСЬ БЫЛИ
 * ------------------------------------------------------------------
 * 1. Непришедшее поле считалось нулём. `audit.env.sameAsExample ?? 0`
 *    означало: посредник постарше или сбойный разбор не прислали данных
 *    — панель показывает «файл настроек в порядке». Проверка, которая
 *    ничего не проверила, отчитывалась успешной.
 *
 * 2. Проверка ИСЧЕЗАЛА из списка. При несмонтированном каталоге миграций
 *    строка про схему просто не добавлялась, и раздел выглядел так,
 *    будто со схемой всё хорошо. Ответ на этот случай в самой проверке
 *    был написан с самого начала — до него не доходило управление.
 *
 * 3. Подсказка чинила одно и ломала другое: «sed -i» для концов строк
 *    заменяет файл новым, и посредник остаётся с прежним — настройки из
 *    панели перестают доходить до служб (см. env-file-mount.test.ts).
 *
 * Пропавшая или ложно-зелёная проверка хуже красной: красную видно.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { gradeMigrations } from './deploy-checks.js';

const FILE = fileURLToPath(
  new URL('./routes/monitoring.ts', import.meta.url).href.replace('/dist/', '/src/'),
);
const RAW = readFileSync(FILE, 'utf8');

/**
 * Исходник без комментариев.
 *
 * Без этого проверки ловили бы сами объяснения: в комментариях рядом с
 * исправленным местом прямо называется то, что было раньше («здесь
 * стояло if (files.length > 0)», «не через sed -i»). Разбор кода обязан
 * смотреть на код.
 */
const SOURCE = RAW.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');

test('состояние схемы показывается даже тогда, когда файлов не видно', () => {
  const check = gradeMigrations({ files: [], applied: new Set() });
  assert.equal(check.state, 'unknown', 'не «ок»: мы ничего не проверили');
  assert.match(check.detail, /не виден/, 'причина обязана быть названа');
  assert.ok(check.hint, 'человеку нужно сказать, что чинить');
});

test('маршрут зовёт проверку схемы без условия на число файлов', () => {
  /*
   * Ровно то место, где строка пропадала. Проверяется исходником,
   * потому что условие было снаружи вызова: сама проверка вела себя
   * правильно и в тесте выглядела бы исправной.
   */
  assert.ok(
    !/if\s*\(files\.length\s*>\s*0\)/.test(SOURCE),
    'условие вокруг вызова возвращает пропажу строки при несмонтированном каталоге',
  );
  assert.match(SOURCE, /checks\.push\(gradeMigrations\(/, 'проверка обязана попадать в список');
});

test('непришедшие данные о файле настроек не считаются нулём нарушений', () => {
  assert.ok(
    !/sameAsExample\s*\?\?\s*0/.test(SOURCE),
    '«?? 0» превращает «не проверяли» в «нарушений нет»',
  );
  assert.ok(!/crlfLines\s*\?\?\s*0/.test(SOURCE), '«?? 0» превращает «не проверяли» в «ноль»');
  assert.match(SOURCE, /не проверено/, 'непроверенное обязано быть названо вслух');
});

test('подсказка про концы строк не заменяет файл настроек', () => {
  /*
   * infra/.env примонтирован в посредник отдельным файлом: «sed -i»
   * оставит его с призраком, и настройки из панели молча перестанут
   * доходить до служб.
   */
  const hint = SOURCE.slice(SOURCE.indexOf('виндовыми концами строк'));
  const nearby = hint.slice(0, 600);
  assert.ok(!/sed\s+-i/.test(nearby), 'этот совет ломает связь посредника с infra/.env');
  assert.match(nearby, /tr -d/, 'починка обязана переписывать файл поверх, а не заменять его');
});
