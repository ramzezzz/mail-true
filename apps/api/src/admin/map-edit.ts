/**
 * Правка карт антиспама по одной за раз.
 *
 * ------------------------------------------------------------------
 * ЧТО БЫЛО
 * ------------------------------------------------------------------
 * Добавление записи в список — это «прочитать карту целиком, дописать
 * строку, записать карту целиком». Копии в базе нет намеренно: источник
 * истины — файл, который переписывает сам rspamd.
 *
 * Между чтением и записью нет ничего, что мешало бы второй такой же
 * правке пройти насквозь. Два администратора, разбирающие одно обращение
 * в четыре руки (а именно так этот раздел и используют — про «четыре
 * руки» написано в самом коде списков), добавляют по адресу почти
 * одновременно:
 *
 *   А читает карту   [x]
 *   Б читает карту   [x]
 *   А пишет карту    [x, a]
 *   Б пишет карту    [x, b]   ← адреса «a» больше нет
 *
 * И это молчаливая потеря: панель отвечает «готово», в ответе показывает
 * список СО СВОЕЙ строкой (он строится из своей же версии текста), в
 * журнале аудита стоит запись о добавлении. Всё говорит, что адрес
 * заблокирован, а письма от него продолжают приходить.
 *
 * ------------------------------------------------------------------
 * ПОЧЕМУ ОЧЕРЕДЬ, А НЕ ТРАНЗАКЦИЯ
 * ------------------------------------------------------------------
 * Транзакции здесь нет и быть не может: правим не базу, а файл через
 * чужой HTTP-интерфейс, у которого нет ни версий, ни условной записи.
 * Единственное, что доступно, — не делать двух правок одной карты
 * одновременно. Сервер приложения один на установку, поэтому очередь в
 * его памяти закрывает случай целиком.
 *
 * Очередь ПОИМЁННАЯ: правки разных карт (чёрный список и белый) идут
 * параллельно, ждать друг друга им незачем.
 */

/** Незавершённая правка по каждой карте: к ней пристраивается следующая. */
const chains = new Map<string, Promise<unknown>>();

/**
 * Выполнить правку карты, дождавшись предыдущей.
 *
 * Отказ одной правки не должен ронять следующие: цепочка продолжается
 * в любом случае, а ошибка достаётся тому, кто эту правку заказал.
 */
export async function withMapLock<T>(file: string, run: () => Promise<T>): Promise<T> {
  const previous = chains.get(file) ?? Promise.resolve();
  const current = previous.then(run, run);

  /*
   * В цепочку кладём заведомо успешный хвост: иначе отказ одной правки
   * пометил бы промис отклонённым, и следующая получила бы
   * «unhandled rejection» вместо своей очереди.
   */
  const tail = current.then(
    () => undefined,
    () => undefined,
  );
  chains.set(file, tail);

  try {
    return await current;
  } finally {
    /*
     * Уборка: без неё карта, которую правили один раз, держала бы ссылку
     * на промис навсегда. Сверяем именно с тем объектом, который клали, —
     * иначе условие не совпадёт никогда и уборки не будет. Убираем
     * только если после нас никто не встал в очередь.
     */
    if (chains.get(file) === tail) chains.delete(file);
  }
}
