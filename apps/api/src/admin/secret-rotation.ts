const BY_KEY = new Map(ROTATABLE_SECRETS.map((item) => [item.key, item]));

export function findRotatable(key: string): RotatableSecret | undefined {
  return BY_KEY.get(key);
}

/**
 * Новое значение секрета.
 *
 * base64url, а не hex и не «буквы с цифрами»: значение попадает в
 * infra/.env, где строка вида KEY=value разбирается построчно, и в
 * командные строки контейнеров. Кавычки, пробелы, знаки доллара и
 * обратные слэши в таком месте — источник поломок, которые проявляются
 * не сразу и выглядят как что угодно, кроме опечатки в секрете.
 *
 * Длина берётся у каждого своя, но нижняя граница общая: 32 байта. Меньше
 * не бывает ни у одного, потому что SESSION_SECRET проверяется схемой на
 * минимум 32 СИМВОЛА, и секрет, не проходящий собственную проверку, уронил
 * бы сервер приложения при следующем запуске.
 */
export function generateSecret(bytes: number): string {
  const size = Math.max(32, bytes);
  return randomBytes(size).toString('base64url');
}
