/**
 * Перевыпуск секретов из панели.
 *
 * ------------------------------------------------------------------
 * ПОЧЕМУ ПЕРЕВЫПУСК, А НЕ ПОЛЕ ВВОДА
 * ------------------------------------------------------------------
 * Секреты стоят в группе locked с честной причиной: наружу они не
 * отдаются, в базу не кладутся. Поле ввода эту причину нарушает — оно
 * означает, что значение проходит через браузер, историю запросов и
 * журнал прокси. Заодно оно приглашает вписать «qwerty123»: секрет,
 * который человек придумывает руками, почти всегда хуже случайного.
 *
 * Поэтому не «поменять на что скажу», а «выпустить новый»: значение
 * рождается на сервере, уходит прямо в infra/.env через посредника и
 * никому не показывается — даже тому, кто нажал кнопку. Показывать его
 * незачем: он нужен только службам, а они читают его из файла.
 *
 * ------------------------------------------------------------------
 * ЧТО ЛОМАЕТСЯ ПРИ ПЕРЕВЫПУСКЕ
 * ------------------------------------------------------------------
 * Каждый секрет что-то скрепляет, и разрыв скрепы имеет цену — разную.
 * Она названа словами у каждого, потому что это единственное, что нужно
 * знать перед нажатием: подписи cookie перестают сходиться и люди
 * оказываются на странице входа; общий секрет двух служб перестаёт
 * совпадать до тех пор, пока обе не пересозданы.
 *
 * Секреты, разрыв которых стоит ДАННЫХ, сюда не попали, и это не
 * недоделка. Ключами шифрования (AI_ENCRYPTION_KEY,
 * EXTERNAL_ACCOUNTS_KEY, ключ заданий переноса) зашифрованы лежащие в
 * базе значения: новый ключ не «меняет замок», а делает уже записанное
 * нечитаемым навсегда. Такой перевыпуск обязан идти вместе с
 * перешифровкой всего, что им закрыто, — это отдельная работа с
 * отдельной ценой ошибки, а не кнопка рядом с остальными.
 */
import { randomBytes } from 'node:crypto';
import type { RestartAction } from './restart-targets.js';

/*
 * Общий хвост ко всем описаниям.
 *
 * Все четыре секрета так или иначе читает сервер приложения, а окружение
 * контейнер получает при СОЗДАНИИ — значит его придётся пересоздать, и
 * запрос, которым перевыпуск запущен, оборвётся вместе с процессом,
 * который его обрабатывал. Поймано живьём: в ответ приходит
 * «Сервер приложения не отвечает», хотя всё сработало.
 *
 * Умолчать об этом нельзя: ошибка на экране после необратимого действия
 * читается как «не получилось», и второе нажатие выпустит ещё один
 * секрет — уже поверх работающего.
 */
const RESTART_TAIL =
  ' Панель на несколько секунд перестанет отвечать: чтобы новое значение подействовало, ' +
  'контейнер сервера приложения пересоздаётся, а вместе с ним обрывается и этот запрос. ' +
  'Сообщение об ошибке в ответ — ожидаемо и НЕ означает, что перевыпуск не удался. ' +
  'Повторять не нужно: просто обновите страницу через несколько секунд.';

export interface RotatableSecret {
  key: string;
  title: string;
  /** Что произойдёт сразу после перевыпуска — до нажатия, а не после. */
  impact: string;
  /** Кого пересоздать, в порядке выполнения. */
  applies: ReadonlyArray<{ target: string; action: RestartAction }>;
  /** Длина в байтах до кодирования. */
  bytes: number;
  /**
   * Дополнительная проверка перед перевыпуском: строка с причиной отказа
   * или null, если можно.
   *
   * Нужна там, где безопасность перевыпуска зависит от НАСТРОЙКИ сервера,
   * а не от самого секрета. Разбор — у SESSION_SECRET ниже.
   */
  guard?: (env: NodeJS.ProcessEnv) => string | null;
}

