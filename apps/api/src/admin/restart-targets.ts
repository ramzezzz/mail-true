const BY_ID = new Map<string, RestartTarget>(RESTART_TARGETS.map((t) => [t.id, t]));

/** Описание цели или undefined, если такого имени в перечне нет. */
export function findTarget(id: string): RestartTarget | undefined {
  return BY_ID.get(id);
}

/**
 * Проверка «цель и действие разрешены». Единственная точка, через которую
 * имя службы попадает из запроса в код: всё остальное работает уже с
 * описанием из перечня, а не со строкой от клиента.
 */
export function resolveTarget(
  id: unknown,
  action: unknown,
): RestartTarget & { action: RestartAction } {
  if (typeof id !== 'string' || typeof action !== 'string') {
    throw new Error('Не указаны служба и действие.');
  }
  const target = BY_ID.get(id);
  if (!target) {
    throw new Error(
      `Служба «${id}» не перезапускается из панели. Из панели перезапускаются только: ` +
        `${RESTART_TARGETS.map((t) => t.id).join(', ')}.`,
    );
  }
  if (!(target.actions as readonly string[]).includes(action)) {
    throw new Error(
      `Для службы «${target.id}» действие «${action}» не предусмотрено. Доступно: ` +
        `${target.actions.join(', ')}.`,
    );
  }
  return { ...target, action: action as RestartAction };
}

/**
 * Команда для консоли — на случай, когда посредника нет.
 *
 * Отдаётся панели вместе с отказом: кнопка, которая молча ничего не делает,
 * хуже отсутствующей кнопки, а «обратитесь к администратору» — это не ответ,
 * когда администратор и есть тот, кто смотрит на экран.
 */
export function consoleCommand(target: RestartTarget, action: RestartAction): string {
  const base = 'docker compose -f infra/docker-compose.yml';
  return action === 'recreate'
    ? `${base} up -d --no-deps ${target.id}`
    : `${base} restart ${target.id}`;
}

/** Человекочитаемое название действия — панели и журналу аудита. */
export function actionTitle(action: RestartAction): string {
  return action === 'recreate' ? 'пересоздание контейнера' : 'перезапуск';
}
