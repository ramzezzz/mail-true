/**
 * Закрытый список того, что панель вообще умеет перезапускать, и честное
 * описание последствий каждого перезапуска.
 *
 * ------------------------------------------------------------------
 * ПОЧЕМУ СПИСОК, А НЕ ИМЯ СЛУЖБЫ ИЗ ЗАПРОСА
 * ------------------------------------------------------------------
 * Перезапуск делает посредник, у которого есть сокет Docker, — то есть
 * права root на всей машине (см. infra/service-agent/agent.pl). Единственное,
 * что отделяет «перезапустить rspamd» от «запустить что угодно от root», —
 * это то, что имя службы НЕ передаётся снаружи как значение, а выбирается
 * из перечня, заданного в коде. Пришедшее по сети имя лишь ищется в этом
 * перечне; не нашлось — отказ, и до посредника запрос не доходит вовсе.
 *
 * Тот же перечень продублирован в самом посреднике. Дублирование
 * намеренное, ровно как у идентификатора письма в очереди: здесь проверка
 * даёт человеку внятный отказ и не пускает мусор в сеть, а там — последний
 * рубеж, потому что именно там запускается программа.
 *
 * ------------------------------------------------------------------
 * ДВА РАЗНЫХ ДЕЙСТВИЯ, И ПУТАТЬ ИХ НЕЛЬЗЯ
 * ------------------------------------------------------------------
 *   restart   — перезапуск ПРОЦЕССА в том же контейнере. Годится, когда
 *               служба читает настройку из файла или из базы при старте.
 *   recreate  — пересоздание КОНТЕЙНЕРА. Нужно, когда служба читает
 *               настройку из переменной окружения: окружение задаётся при
 *               создании контейнера и живёт столько же, сколько он сам.
 *               Перезапуск процесса в таком случае бесполезен — он поднимет
 *               его с тем же старым окружением, и человек будет смотреть
 *               на сохранённую настройку, которая не работает.
 *
 * Это различие — не тонкость реализации, а то, что панель обязана
 * показывать словами: «перезапустить Rspamd» и «пересоздать контейнер
 * автонастройки» — разные кнопки с разной ценой.
 *
 * ------------------------------------------------------------------
 * ПОЧЕМУ ПОСЛЕДСТВИЯ ОПИСАНЫ У КАЖДОЙ СЛУЖБЫ СВОИ
 * ------------------------------------------------------------------
 * Общего текста «служба будет недоступна несколько секунд» здесь нет и не
 * будет. Остановка Postfix означает, что чужие серверы получают временный
 * отказ; остановка Dovecot — что у всех обрываются почтовые программы;
 * остановка nginx — что не войти в веб вообще, включая эту самую панель.
 * Это три разных решения, и человек принимает их по-разному.
 */

/** Что делаем со службой. */
export type RestartAction = 'restart' | 'recreate';

export interface RestartTarget {
  /** Он же имя сервиса в docker-compose.yml. Второго имени нет намеренно. */
  id: string;
  /** Как называется в панели. */
  title: string;
  /** Разрешённые действия. Порядок — порядок предпочтения. */
  actions: readonly RestartAction[];
  /**
   * Сервер приложения перезапускает сам себя и посредник ему не нужен:
   * у всех служб в compose стоит `restart: unless-stopped`, поэтому
   * достаточно корректно завершить процесс.
   */
  self: boolean;
  /**
   * Что именно перестанет работать. Пишется от лица последствий для людей,
   * а не для служб: «обрываются сессии почтовых программ», а не «служба
   * IMAP недоступна».
   */
  impact: string;
  /** Насколько. Отдельно от impact: это первое, что ищут глазами. */
  downtime: string;
  /**
   * Что НЕ пострадает. Не украшение: половина страха перед кнопкой — это
   * незнание границ. «Почтовые программы не заметят» снимает его сразу.
   */
  safe: string;
}

