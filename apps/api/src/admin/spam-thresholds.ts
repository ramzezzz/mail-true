/**
 * Пороги антиспама: что означает каждый, чем оборачивается его сдвиг и
 * почему в этой сборке их нельзя записать из панели.
 *
 * ------------------------------------------------------------------
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ ТРИ ЧИСЛА В ОТВЕТЕ
 * ------------------------------------------------------------------
 * Раньше раздел отдавал ровно то, что вернул контроллер rspamd: словарь
 * вида {"add header": 6, "reject": 15, "greylist": null}. На экране это
 * выглядело как четыре плитки с числами и подписями в три слова —
 * настройка, про которую нельзя понять ни что она делает, ни в какую
 * сторону её двигать. Замечание заказчика было именно об этом: «не понял
 * про пороги, там практически ничего нельзя настроить».
 *
 * Число само по себе бесполезно: «6» не отвечает ни на один вопрос, с
 * которым к порогам приходят. Приходят с двумя:
 *   • «письма партнёра уезжают в спам — что покрутить?»
 *   • «нас заваливают — можно ли отбивать жёстче и чем я рискую?»
 * Поэтому каждый порог отдаётся вместе с тем, ЧТО происходит с письмом на
 * этом рубеже, кто это увидит, и что будет, если поднять или опустить.
 *
 * ------------------------------------------------------------------
 * ЧТО ЗДЕСЬ ФАКТ, А ЧТО МНЕНИЕ
 * ------------------------------------------------------------------
 * Значения порогов — факт: их отдаёт живой rspamd (GET /actions и разбор
 * пробного письма). Описания последствий — свойства ЭТОЙ сборки, а не
 * общие слова про антиспам: заголовок X-Spam ставит milter_headers.conf,
 * по нему письмо раскладывает sieve Dovecot, отказ на приёме отдаёт
 * Postfix. Рекомендуемые коридоры — мнение, и они так и подписаны.
 *
 * ------------------------------------------------------------------
 * ПОЧЕМУ ЗАПИСИ НЕТ
 * ------------------------------------------------------------------
 * Не из осторожности, а потому что писать некуда:
 *
 *   1. Контроллер rspamd (POST /saveactions) сохраняет пороги только при
 *      настроенном dynamic_conf, которого в сборке нет. Без него запрос
 *      отвечает отказом — проверено живьём на rspamd 4.1.4.
 *   2. Даже с dynamic_conf пороги легли бы в отдельный файл ПОВЕРХ
 *      infra/rspamd/local.d/actions.conf. Тогда правка actions.conf
 *      молча перестала бы действовать — два источника истины у одного
 *      числа, и разбираться в этом пришлось бы при первом же инциденте.
 *   3. Сам файл actions.conf серверу приложения недоступен: каталог
 *      local.d примонтирован в контейнер rspamd, причём только на чтение
 *      (infra/docker-compose.yml). Списки в maps.d правятся потому, что
 *      их пишет сам rspamd по запросу /savemap; у порогов такого
 *      механизма нет вовсе.
 *
 * Отсюда честный вывод: пороги показываются, объясняются и проверяются на
 * противоречия, но не записываются — и раздел говорит это прямо, вместе с
 * точной командой и путём. Ложная кнопка «Сохранить», которая молча ничего
 * не меняет, хуже её отсутствия.
 *
 * Что нужно, чтобы запись появилась (работа за пределами этого модуля):
 * entrypoint контейнера rspamd должен собирать override.d/actions.conf из
 * переменных окружения — ровно так он уже делает для DKIM, Redis и
 * антивируса, — эти переменные нужно разрешить посреднику служб
 * (infra/service-agent/agent.pl) и завести в реестре настроек сервера.
 */

