export function findSpamAction(id: string): SpamActionSpec | undefined {
  return SPAM_ACTIONS.find((action) => action.id === id);
}

/** Один порог в том виде, в каком его читает панель. */
export interface SpamThresholdItem {
  id: string;
  title: string;
  /** Балл, с которого действие срабатывает; null — действие выключено. */
  value: number | null;
  effect: string;
  visible: string;
  higher: string;
  lower: string;
  off: string;
  /** Рекомендуемый коридор, [от, до]; null — рекомендации нет. */
  advice: readonly [number, number] | null;
  /** Значение вне рекомендуемого коридора — повод перепроверить, не ошибка. */
  unusual: boolean;
}

/**
 * Свести значения от rspamd с описаниями.
 *
 * Порядок берётся из SPAM_ACTION_ORDER, а НЕ из ответа контроллера: письмо
 * проходит рубежи по возрастанию оценки, и читать их надо в том же
 * порядке. Ответ контроллера приходит в своём, и раньше выключенные
 * действия оказывались вперемешку с настроенными.
 *
 * «no action» отбрасывается: это название исхода «ничего не делать», порога
 * у него не бывает по устройству rspamd. На экране оно выглядело как
 * выключенная настройка, то есть предлагало включить несуществующее.
 *
 * Незнакомые действия не выбрасываются: если в новой версии rspamd
 * появится своё, лучше показать его без описания, чем спрятать порог,
 * который на письма действует.
 */
export function describeThresholds(
  values: Readonly<Record<string, number | null>>,
): SpamThresholdItem[] {
  const known = new Set<string>(SPAM_ACTION_ORDER);
  const names = [
    ...SPAM_ACTION_ORDER.filter((id) => id in values),
    ...Object.keys(values).filter((id) => !known.has(id) && id !== 'no action'),
  ];
  return names.map((id) => {
    const spec = findSpamAction(id);
    const value = values[id] ?? null;
    const advice = spec?.advice ?? null;
    return {
      id,
      title: spec?.title ?? id,
      value,
      effect: spec?.effect ?? 'Это действие появилось в rspamd после выпуска панели.',
      visible: spec?.visible ?? '—',
      higher: spec?.higher ?? '—',
      lower: spec?.lower ?? '—',
      off: spec?.off ?? 'Действие выключено.',
      advice,
      unusual: value !== null && advice !== null && (value < advice[0] || value > advice[1]),
    };
  });
}

/**
 * Противоречия в наборе порогов.
 *
 * Это главное, ради чего пороги вообще стоит показывать вместе. По
 * отдельности каждое число выглядит осмысленным, а вместе они складываются
 * в поведение, которого никто не хотел: например, при пороге пометки не
 * ниже порога отказа папка «Спам» не наполняется НИКОГДА — письмо либо
 * проходит, либо отбивается. Заметить это по трём плиткам с числами нельзя,
 * а последствие — молча пропавшая почта.
 *
 * Каждая строка говорит, что именно сломано и чем это кончится, а не
 * «проверьте настройки».
 */
export function thresholdWarnings(values: Readonly<Record<string, number | null>>): string[] {
  const out: string[] = [];
  const addHeader = values['add header'] ?? null;
  const reject = values.reject ?? null;
  const greylist = values.greylist ?? null;
  const rewrite = values['rewrite subject'] ?? null;

  if (addHeader === null) {
    out.push(
      'Пометка спама выключена: письма не получают заголовок X-Spam и не раскладываются в ' +
        'папку «Спам». Пользователи увидят рекламу во «Входящих».',
    );
  }
  if (reject === null) {
    out.push(
      'Отказ в приёме выключен: сервер принимает всё, включая заведомый спам. Это не ошибка, ' +
        'но нагрузка на ящики и хранилище будет выше.',
    );
  }
  if (addHeader !== null && reject !== null && addHeader >= reject) {
    out.push(
      `Порог пометки (${String(addHeader)}) не ниже порога отказа (${String(reject)}): папка ` +
        '«Спам» не наполнится никогда — письмо либо проходит, либо отбивается на приёме.',
    );
  }
  if (greylist !== null && addHeader !== null && greylist >= addHeader) {
    out.push(
      `Порог серого списка (${String(greylist)}) не ниже порога пометки (${String(addHeader)}): ` +
        'задержка не сработает — письмо раньше будет помечено как спам.',
    );
  }
  if (rewrite !== null && addHeader !== null && rewrite >= addHeader) {
    out.push(
      `Пометка в теме (${String(rewrite)}) не ниже порога пометки спама (${String(addHeader)}): ` +
        'тема правиться не будет — письмо раньше уедет в папку «Спам».',
    );
  }
  for (const item of describeThresholds(values)) {
    if (!item.unusual || item.advice === null || item.value === null) continue;
    out.push(
      `Порог «${item.title}» равен ${String(item.value)} — это вне обычного коридора ` +
        `${String(item.advice[0])}–${String(item.advice[1])}. ${
          item.value < item.advice[0] ? item.lower : item.higher
        }`,
    );
  }
  return out;
}

/**
 * Служебное письмо для измерения порогов профиля «свой отправитель».
 *
 * Иначе эти пороги не увидеть вовсе. Своим аутентифицированным
 * отправителям infra/rspamd/local.d/settings.conf назначает СВОИ, более
 * мягкие пороги, а контроллер про профили настроек не рассказывает
 * (GET /actions отдаёт только общие). Единственный способ узнать
 * действующие числа — прогнать письмо и посмотреть, какие пороги rspamd
 * применил к нему сам.
 *
 * Письмо намеренно скучное и без ссылок: измеряются пороги, а не оценка,
 * и лишние сработавшие правила тут только мешали бы.
 */
export function thresholdProbeMessage(domain: string): string {
  const from = `postmaster@${domain}`;
  return [
    `From: ${from}`,
    `To: ${from}`,
    'Subject: Mail.True: измерение действующих порогов',
    `Message-ID: <thresholds-probe@${domain}>`,
    'MIME-Version: 1.0',
    'Content-Type: text/plain; charset=utf-8',
    '',
    'Служебное письмо панели администратора. Оно никуда не доставляется и',
    'ничему не обучает: по нему определяются пороги, действующие для писем',
    'собственных аутентифицированных отправителей.',
    '',
  ].join('\r\n');
}
