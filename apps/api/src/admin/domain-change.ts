/** Домен: только буквы, цифры, дефисы, минимум две метки. */
const DOMAIN_RE = /^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/u;

export function isDomainName(value: string): boolean {
  return DOMAIN_RE.test(value) && value.length <= 255;
}

/** Приводит домен к сравнимому виду: нижний регистр, без точки на конце. */
export function normalizeDomain(value: string): string {
  return value.trim().toLowerCase().replace(/\.$/u, '');
}

/**
 * Имя почтового сервера для нового домена.
 *
 * Правило «как было, так и будет»: если старое имя сервера получалось из
 * старого домена приставкой (mail.старый), новое получается той же
 * приставкой (mail.новый). Если же имя сервера к домену отношения не
 * имело — например, сервер зовётся mx1.хостер.рф, а обслуживает домен
 * заказчика, — то менять его при смене домена НЕЛЬЗЯ: на это имя выписан
 * сертификат, оно стоит в MX чужих зон и в настройках почтовых программ
 * у людей. Тогда возвращаем прежнее.
 */
export function hostnameForDomain(
  oldDomain: string,
  oldHostname: string,
  newDomain: string,
): string {
  const od = normalizeDomain(oldDomain);
  const oh = normalizeDomain(oldHostname);
  const nd = normalizeDomain(newDomain);
  if (oh === od) return nd;
  if (oh.endsWith(`.${od}`)) return `${oh.slice(0, oh.length - od.length - 1)}.${nd}`;
  return oh;
}

/** Заканчивается ли адрес на «@домен». */
export function addressInDomain(address: string, domain: string): boolean {
  const at = address.lastIndexOf('@');
  return at > 0 && address.slice(at + 1).toLowerCase() === normalizeDomain(domain);
}

/** Тот же адрес в другом домене. Локальная часть не трогается вовсе. */
export function moveAddress(address: string, newDomain: string): string {
  const at = address.lastIndexOf('@');
  if (at <= 0) return address;
  return `${address.slice(0, at + 1)}${normalizeDomain(newDomain)}`;
}

