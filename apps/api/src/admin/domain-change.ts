/**
 * Смена основного домена сервера: типы, реестр адресных колонок и разбор
 * имён. Чистый модуль — ни базы, ни файловой системы, ни сети, чтобы всё
 * это можно было проверить без стенда.
 *
 * ==================================================================
 * ЧТО ВООБЩЕ ЗНАЧИТ «СМЕНИТЬ ДОМЕН»
 * ==================================================================
 * Домен вплетён в установку в четырёх разных местах, и живут они по
 * разным законам:
 *
 *   1. АДРЕСА В БАЗЕ. `virtual_users.email`, `virtual_aliases.source`
 *      и ещё два десятка таблиц, где ящик опознаётся строкой адреса.
 *      Внешних ключей на адрес нет НИ ОДНОГО (проверено по всем
 *      миграциям), поэтому `UPDATE virtual_users SET email = …` не тянет
 *      за собой ничего: каждую таблицу надо переписать явно. Пропустить
 *      хоть одну — значит оставить человека без подписи, без фильтров или
 *      без меток, причём молча.
 *
 *   2. ПИСЬМА НА ДИСКЕ. Лежат в /var/mail/vhosts/<домен>/<логин>, индексы
 *      в /var/mail/index/<домен>/<логин>. Домен здесь — имя каталога, и
 *      «перенос» писем это переименование ОДНОГО каталога: обе стороны
 *      внутри одного тома, значит rename(2), значит мгновенно и без
 *      единого лишнего байта на диске. Копировать сотни гигабайт ради
 *      смены имени каталога незачем.
 *
 *   3. КЛЮЧ DKIM И ЗАПИСИ DNS. Ключ выпущен на домен, запись живёт в
 *      чужой зоне. Ни то, ни другое панель поменять не может — она может
 *      только выпустить новый ключ и показать, что опубликовать.
 *
 *   4. ИМЕНА В КОНФИГУРАЦИИ СТЕКА: сертификаты на mail./admin./autoconfig.,
 *      server_name в nginx, MAIL_DOMAIN у автонастройки и rspamd. Это файлы
 *      ВНУТРИ чужих контейнеров, а сокета Docker у панели нет и не будет
 *      (он равен правам root на машине). Поэтому четвёртую часть делает
 *      скрипт на сервере — infra/scripts/change-domain.sh, — а панель
 *      честно пишет об этом в плане, вместо того чтобы делать вид, что
 *      всё случилось само.
 *
 * ==================================================================
 * СТАРЫЙ ДОМЕН ОСТАЁТСЯ ПРИНИМАЮЩИМ. ВСЕГДА
 * ==================================================================
 * Это не настройка, а свойство операции. Смена домена, после которой на
 * прежние адреса перестаёт приходить почта, — это не смена домена, а
 * потеря почты: визитки, подписи в договорах, формы восстановления
 * доступа, рассылки, чужие адресные книги ссылаются на старый адрес
 * годами.
 *
 * Выражено это так: строка старого домена в `virtual_domains` НЕ
 * удаляется (Postfix продолжает принимать для него почту — карта
 * `virtual_mailbox_domains` читается прямо из этой таблицы), а на каждый
 * переехавший ящик заводится алиас `логин@старый → логин@новый`.
 *
 * Почему алиасы, а не второй адрес у того же ящика: у Dovecot ящик
 * опознаётся ровно одной строкой (`password_query` по `email`), второго
 * имени у него не бывает. Алиас же — штатный механизм Postfix, он
 * раскрывается рекурсивно, попадает в `smtpd_sender_login_maps` (то есть
 * человек может и ОТПРАВЛЯТЬ со старого адреса), виден и правится в
 * разделе «Алиасы» и удаляется по одному, когда старый домен решат
 * отпустить. Ничего для этого писать не пришлось — механизм уже есть,
 * его надо было только применить.
 */

