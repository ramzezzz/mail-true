/**
 * Оценка простоя.
 *
 * Считается не «от балды»: переезд писем — это одно переименование
 * каталога, то есть доли секунды при любом объёме. Время уходит на
 * транзакцию в базе (пропорционально числу строк) и на то, чтобы
 * почтовые службы заметили изменения в своих картах — Postfix кэширует
 * ответы pgsql-карт, Dovecot держит открытые сеансы.
 *
 * Верхняя граница намеренно с запасом: человек, которому пообещали
 * «двадцать секунд», а вышло полторы минуты, считает, что всё сломалось.
 */
export function estimateDowntime(counts: DomainChangeCounts): { min: number; max: number } {
  const rows = counts.rows + counts.mailboxes + counts.aliases;
  const dbSeconds = Math.ceil(rows / 2000);
  return { min: 5 + dbSeconds, max: 30 + dbSeconds * 4 };
}

