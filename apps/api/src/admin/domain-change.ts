export interface AddressColumn {
  table: string;
  column: string;
  /** Что именно там лежит — одной строкой для плана. */
  what: string;
  /**
   * Что делать с этой строкой, когда ящик УДАЛЯЮТ.
   *
   * Поле появилось не для смены домена, а из-за находки при ней: список
   * таблиц в уборке после удаления ящика был написан руками и отстал от
   * продукта на четырнадцать разделов. Метки, шаблоны, сохранённые
   * запросы, подписки на уведомления, история входов и одноразовые адреса
   * переживали своего владельца — а ящик, заведённый заново с тем же
   * адресом, доставался новому человеку вместе с ними.
   *
   * Теперь список один на две работы: что переезжает при смене домена, то
   * и убирается при удалении. Новый раздел, добавленный сюда ради смены
   * домена, автоматически попадает в уборку — и наоборот. Забыть можно
   * только оба сразу, а этого не пропустит проверка.
   *
   *   'delete' — строку убрать вместе с ящиком (по умолчанию);
   *   'keep'   — оставить, и тогда обязательно сказать почему.
   */
  onDelete?: 'delete' | 'keep';
  /** Почему строка переживает удаление ящика. Обязательно при 'keep'. */
  keepReason?: string;
}

