/**
 * Закрытие доступа к ящику прямо сейчас — для всех путей, что меняют
 * пароль или признак «включён».
 *
 * ------------------------------------------------------------------
 * ПОЧЕМУ ЭТО ОБЩИЙ МОДУЛЬ, А НЕ ФУНКЦИЯ ВНУТРИ МАРШРУТА ЯЩИКОВ
 * ------------------------------------------------------------------
 * Потому что путей, меняющих пароль и активность, больше одного, а замок
 * был ровно в одном. Смена пароля и блокировка из раздела «Ящики» звали
 * его, а ВОССТАНОВЛЕНИЕ КОПИИ — нет, хотя переписывает те же два столбца
 * сразу у всех ящиков из файла. Получалось худшее: уволенный сотрудник,
 * ящик которого копия отключила, продолжал читать и отправлять почту и
 * заказывать выгрузку всего ящика, а панель показывала его отключённым.
 *
 * ------------------------------------------------------------------
 * ЧТО ИМЕННО ЗАКРЫВАЕТСЯ И ПОЧЕМУ ЭТОГО ТРИ
 * ------------------------------------------------------------------
 * Ни пароль, ни `active` сами по себе не выгоняют никого: Dovecot
 * отсеивает и тех, и других ТОЛЬКО при проверке пароля, а у вошедшего
 * проверять нечего.
 *
 *   1. Сессии. Хранят пароль таким, каким он был при входе, и продлеваются
 *      на каждом запросе — то есть живут сколько угодно долго сами.
 *   2. Соединения пула. Переиспользуются по одному адресу без повторной
 *      сверки пароля (imap/pool.ts), и уже открытое переживает смену.
 *   3. Наблюдатель. Держит собственное соединение с паролем и живёт до
 *      суток даже без единой открытой вкладки — ради уведомлений о новых
 *      письмах (ws.ts).
 *
 * Ни один шаг не считается критичным: отказ любого из них не имеет права
 * отменить действие, ради которого доступ и закрывали (смену пароля,
 * блокировку, восстановление копии). Поэтому здесь ничего не бросается, а
 * сделанное уходит строкой в журнал сервера.
 */
import type { FastifyInstance } from 'fastify';

/**
 * Выкидывает ящик из веб-почты немедленно: сессии, соединения, наблюдатель.
 *
 * @param why — зачем закрыли; попадает в журнал сервера рядом с адресом,
 *   и по нему потом отличают смену пароля от восстановления копии.
 */
export async function dropMailboxAccess(
  app: FastifyInstance,
  email: string,
  why: string,
): Promise<void> {
  const deps = app.deps;
  const closed = await deps.sessions.revokeByEmail(email).catch(() => 0);
  await deps.pool.closeUser(email).catch(() => undefined);
  const watcher = app.mailNotifier?.dropWatcher(email) ?? false;
  app.log.info({ email, sessions: closed, watcher, why }, 'Доступ к ящику закрыт');
}
