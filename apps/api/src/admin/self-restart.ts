/**
 * Перезапуск сервера приложения САМИМ СОБОЙ.
 *
 * ------------------------------------------------------------------
 * ПОЧЕМУ ЕМУ НЕ НУЖЕН ПОСРЕДНИК
 * ------------------------------------------------------------------
 * У всех служб стека стоит `restart: unless-stopped`. Это значит, что
 * демон Docker поднимает контейнер заново всякий раз, когда его главный
 * процесс завершился, — по любой причине и с любым кодом возврата.
 * Значит серверу приложения, чтобы перезапуститься, достаточно корректно
 * закончиться. Ни сокета Docker, ни посредника, ни прав на машине.
 *
 * Это важно не только экономией: перезапуск сервера приложения — самая
 * частая из всех кнопок (59 настроек из 133 ждут именно его), и делать её
 * зависимой от отдельной службы значило бы, что стек без посредника
 * теряет главное.
 *
 * ------------------------------------------------------------------
 * ЧТО ЗНАЧИТ «КОРРЕКТНО ЗАКОНЧИТЬСЯ»
 * ------------------------------------------------------------------
 * Ничего нового изобретать не нужно: у процесса уже есть обработчик
 * SIGTERM (apps/api/src/server.ts), и он делает ровно то, что требуется, —
 * дожидается текущих запросов (app.close), закрывает соединения с IMAP,
 * отпускает задания переноса и смены домена, закрывает базу и Redis.
 * Поэтому останавливаемся мы СВОИМ ЖЕ СИГНАЛОМ, а не отдельным путём
 * выхода: два способа остановки разошлись бы при первой же правке одного
 * из них, и второй тихо перестал бы закрывать что-нибудь важное.
 *
 * ------------------------------------------------------------------
 * ЗАЩИТА ОТ ПЕТЛИ
 * ------------------------------------------------------------------
 * Настройка группы restart читается при старте. Значит настройка с
 * негодным значением может уронить процесс НА СТАРТЕ — и тогда демон
 * поднимет его снова, он снова упадёт, и так до бесконечности. Сама по
 * себе эта петля не наша: её крутит демон, и он же её тормозит своей
 * задержкой. Наша забота в другом — не подливать в неё.
 *
 * Поэтому каждый старт процесса оставляет отметку в journal перезапусков,
 * и перед тем как остановиться по кнопке, сервер считает эти отметки за
 * последние минуты. Слишком много — отказ с объяснением: «за последние
 * N минут сервер уже стартовал M раз, похоже, он падает после запуска;
 * посмотрите журнал, прежде чем перезапускать снова». Это ровно тот
 * случай, когда правильный ответ продукта — не выполнить действие.
 */
import { existsSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import type { Logger } from 'pino';
import type { RestartStore } from './restart-store.js';

export interface SelfRestartOptions {
  logger: Logger;
  /** Журнал перезапусков. null — миграция не применена, работаем без него. */
  store: RestartStore | null;
  /**
   * Чем останавливаться. По умолчанию — свой же SIGTERM: он попадает в
   * тот обработчик, который и так закрывает всё по-человечески.
   */
  stop?: () => void;
  /**
   * Есть ли кому поднять процесс обратно. Подменяется в проверках; в
   * жизни определяется по признаку контейнера.
   */
  supervised?: boolean;
  /**
   * Пауза перед остановкой. Ответ «принято» обязан уйти в браузер ДО
   * того, как сервер начнёт закрываться, иначе панель увидит обрыв
   * соединения вместо подтверждения и не будет знать, началось ли что-то
   * вообще.
   */
  graceMs?: number;
  /** Окно и потолок защиты от петли. */
  loopWindowMinutes?: number;
  loopMaxBoots?: number;
}

export interface SelfRestartRefusal {
  allowed: false;
  reason: string;
}
export interface SelfRestartPermission {
  allowed: true;
}
export type SelfRestartDecision = SelfRestartPermission | SelfRestartRefusal;

/**
 * Признак «процесс живёт в контейнере», то есть его есть кому поднять.
 *
 * Проверка грубая намеренно. Точный ответ («какая у контейнера политика
 * перезапуска») знает только демон Docker, а спрашивать его — значит
 * требовать тот самый сокет, ради отсутствия которого всё и затевалось.
 * Зато грубая проверка закрывает единственный случай, в котором кнопка
 * действительно опасна: запуск из исходников на машине разработчика, где
 * после остановки не поднимется ничто и сервер просто исчезнет.
 */
export function detectSupervised(): boolean {
  return existsSync('/.dockerenv');
}

const NOT_SUPERVISED =
  'Перезапуск из панели недоступен: сервер приложения запущен не в контейнере, ' +
  'и поднять его обратно после остановки будет некому. Перезапустите процесс тем ' +
  'же способом, каким запускали.';

export class SelfRestart {
  /**
   * Метка ЭТОГО процесса. Ради неё всё и сделано: панель запоминает
   * метку до нажатия и опрашивает сервер, пока не увидит другую. Именно
   * так она узнаёт, что перед ней уже новый процесс, а не тот же самый,
   * который просто задумался.
   */
  readonly bootId = randomUUID();
  readonly startedAt = new Date();

  readonly #logger: Logger;
  readonly #store: RestartStore | null;
  readonly #stop: () => void;
  readonly #supervised: boolean;
  readonly #graceMs: number;
  readonly #windowMinutes: number;
  readonly #maxBoots: number;
  /** Остановка уже назначена: второе нажатие не должно её ускорять. */
  #scheduled = false;

  constructor(opts: SelfRestartOptions) {
    this.#logger = opts.logger;
    this.#store = opts.store;
    this.#stop = opts.stop ?? (() => process.kill(process.pid, 'SIGTERM'));
    this.#supervised = opts.supervised ?? detectSupervised();
    this.#graceMs = opts.graceMs ?? 700;
    this.#windowMinutes = opts.loopWindowMinutes ?? 10;
    this.#maxBoots = opts.loopMaxBoots ?? 5;
  }

  get supervised(): boolean {
    return this.#supervised;
  }

  get pending(): boolean {
    return this.#scheduled;
  }

  /** Можно ли перезапускаться прямо сейчас. */
  async decide(): Promise<SelfRestartDecision> {
    if (!this.#supervised) return { allowed: false, reason: NOT_SUPERVISED };
    if (this.#scheduled) {
      return {
        allowed: false,
        reason: 'Перезапуск уже начат — сервер закрывает текущие запросы и остановится.',
      };
    }
    if (this.#store === null) return { allowed: true };

    let boots: number;
    try {
      boots = await this.#store.bootsSince(this.#windowMinutes);
    } catch (err) {
      // Отказ журнала не должен запрещать перезапуск: это защита от
      // петли, а не разрешение на работу. Скажем в лог и пропустим.
      this.#logger.warn({ err }, 'Не удалось сосчитать старты сервера, защита от петли пропущена');
      return { allowed: true };
    }
    if (boots > this.#maxBoots) {
      return {
        allowed: false,
        reason:
          `Перезапуск отклонён: за последние ${String(this.#windowMinutes)} минут сервер ` +
          `приложения стартовал ${String(boots)} раз. Похоже, он падает сразу после ` +
          'запуска — скорее всего, из-за настройки, которая читается при старте. ' +
          'Посмотрите журнал сервера приложения (раздел «Журналы» или ' +
          'docker compose logs --tail 100 api) и верните настройку к прежнему значению. ' +
          'Ещё один перезапуск сейчас только продлит этот круг.',
      };
    }
    return { allowed: true };
  }

  /**
   * Назначает остановку. Возвращает управление немедленно: ответ панели
   * обязан уйти раньше, чем сервер начнёт закрываться.
   */
  schedule(reason: string): void {
    if (this.#scheduled) return;
    this.#scheduled = true;
    this.#logger.warn(
      { bootId: this.bootId, graceMs: this.#graceMs },
      `Перезапуск сервера приложения по запросу из панели: ${reason}`,
    );
    const timer = setTimeout(() => {
      this.#stop();
    }, this.#graceMs);
    // Не держим цикл событий: если сервер и так закрывается, ждать нас
    // ему незачем.
    timer.unref?.();
  }

  /**
   * Отметка о старте и закрытие заявки, которую этот старт и выполнил.
   * Заодно — громкое предупреждение, если процесс перезапускается
   * подозрительно часто: человек должен увидеть это в журнале, даже если
   * в панель он не заходит.
   */
  async announceBoot(): Promise<void> {
    if (this.#store === null) return;
    try {
      const closed = await this.#store.markBoot();
      if (closed) {
        this.#logger.info(
          { restartId: closed.id, requestedBy: closed.requestedBy },
          'Сервер приложения поднялся после перезапуска из панели',
        );
      }
      const boots = await this.#store.bootsSince(this.#windowMinutes);
      if (boots > this.#maxBoots) {
        this.#logger.error(
          { boots, minutes: this.#windowMinutes },
          'Сервер приложения перезапускался слишком часто: похоже на падение сразу после ' +
            'старта. Перезапуск из панели будет отклоняться, пока это не прекратится.',
        );
      }
      await this.#store.trim();
    } catch (err) {
      // Ни одна беда журнала не должна мешать серверу подняться.
      this.#logger.warn({ err }, 'Не удалось отметить старт в журнале перезапусков');
    }
  }
}
