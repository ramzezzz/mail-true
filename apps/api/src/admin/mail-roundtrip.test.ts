/**
 * Сквозная проверка доставки: то, что можно проверить без живого сервера.
 *
 * Сам прогон требует Postfix и Dovecot и проверяется живьём. Здесь
 * закреплено свойство, из-за которого проверка молча испортила бы чужие
 * данные: метка письма обязана быть разной у двух одновременных запусков,
 * иначе одна проверка удалит письмо другой — и обе соврут, каждая
 * по-своему.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { makeToken, subjectFor } from './mail-roundtrip.js';

test('метки двух запусков не совпадают', () => {
  const seen = new Set<string>();
  for (let i = 0; i < 500; i += 1) seen.add(makeToken());
  assert.equal(seen.size, 500);
});

test('метка не зависит от времени: две проверки в одну секунду различимы', () => {
  // Время здесь было бы худшим выбором из возможных: раздел открывают
  // вкладками, и два нажатия в одну секунду — обычное дело.
  let call = 0;
  const random = (): number => (call++ === 0 ? 0.25 : 0.75);
  assert.notEqual(makeToken(random), makeToken(random));
});

test('метка годится для поиска по теме: только цифры и латиница', () => {
  // По теме письмо ищется через IMAP. Пробел, кавычка или кириллица в
  // метке превратили бы поиск в лотерею с чужой кодировкой.
  for (let i = 0; i < 50; i += 1) assert.match(makeToken(), /^[0-9a-f]{16}$/);
});

test('тема письма содержит метку — по ней письмо и удаляется', () => {
  const token = makeToken();
  const subject = subjectFor(token);
  assert.ok(subject.includes(token));
  // И называет себя: человек, увидевший письмо в ящике (например, если
  // уборка не удалась), должен сразу понять, откуда оно.
  assert.match(subject, /Mail\.True/);
});
