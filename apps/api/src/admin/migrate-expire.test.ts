/**
 * Живой перенос почты нельзя убивать по возрасту.
 *
 * ------------------------------------------------------------------
 * ЧТО БЫЛО
 * ------------------------------------------------------------------
 * Уборка «брошенных» заданий смотрела ТОЛЬКО на время создания: всё, что
 * старше срока, помечалось неудавшимся, а свёрток паролей исходных ящиков
 * стирался. При этом перенос организации — сотни ящиков и, как прямо
 * сказано в шапке работника, сутки работы.
 *
 * Выходило так: на исходе срока очередной обход (раз в десять секунд)
 * находил ИДУЩЕЕ задание и ставил ему state = 'failed', secret_enc = NULL,
 * runner = NULL. Последствия:
 *
 *   * в панели идущий перенос показан отказавшим — с ложной причиной
 *     «работник не выходил на связь», хотя биение шло секунду назад и
 *     счётчики продолжали расти;
 *   * touchMigrationJob перестаёт что-либо обновлять (ищет по runner, а
 *     тот уже NULL);
 *   * задание больше не подхватывается: берутся только queued и running.
 *
 * То есть перезапуск контейнера в этот момент — уже не «продолжится после
 * запуска», как обещает вся конструкция работника, а безвозвратная
 * потеря: пароли сотен чужих ящиков надо собирать заново.
 *
 * ------------------------------------------------------------------
 * ЧТО ЗАКРЕПЛЕНО
 * ------------------------------------------------------------------
 * Брошенность определяется молчанием (heartbeat_at), а возраст остаётся
 * запасным случаем для заданий, которые не начинали вести ни разу.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = readFileSync(
  fileURLToPath(new URL('./db.ts', import.meta.url).href.replace('/dist/', '/src/')),
  'utf8',
);

/** Тело запроса без комментариев: разбор рядом не должен изображать правку. */
function expireQuery(): string {
  const start = SOURCE.indexOf('async expireStaleMigrationJobs');
  const end = SOURCE.indexOf('return rows.length;', start);
  return SOURCE.slice(start, end)
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/^\s*\/\/.*$/gm, '');
}

test('брошенность определяется молчанием работника, а не возрастом задания', () => {
  const query = expireQuery();
  assert.match(
    query,
    /heartbeat_at < now\(\) - make_interval/,
    'без этого условия убивается идущий перенос',
  );
});

test('задание, которое не начинали вести, всё же истекает по возрасту', () => {
  /*
   * Иначе очередь копила бы вечные записи со свёртками паролей: работник
   * не запускался ни разу (раздел выключили, сервер перевели в другой
   * режим), heartbeat_at пуст — и по нему такое задание не истечёт
   * никогда.
   */
  const query = expireQuery();
  assert.match(query, /heartbeat_at IS NULL/);
  assert.match(query, /created_at < now\(\) - make_interval/);
});

test('пароли стираются только вместе с признанием задания неудавшимся', () => {
  const query = expireQuery();
  assert.match(query, /secret_enc = NULL/);
  assert.match(query, /state = 'failed'/);
  // Живые состояния — единственные, которые вообще рассматриваются.
  assert.match(query, /state IN \('queued', 'running'\)/);
});
