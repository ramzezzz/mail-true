/**
 * Смена пароля администратора — вместе с отзывом его открытых сессий.
 *
 * ------------------------------------------------------------------
 * ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ ДВЕ СТРОКИ В КОНСОЛЬНОЙ УТИЛИТЕ
 * ------------------------------------------------------------------
 * Потому что «сменить пароль» и «выгнать тех, кто вошёл по старому» —
 * это ОДНО действие, и разъединять их нельзя. Раньше здесь стоял голый
 * `UPDATE admin_users SET password_hash = …` в cli.ts, и он не закрывал
 * ничего: пароль в проверке админской сессии не участвует нигде
 * (`loadAdminSession` перечитывает из базы только роль и активность), а
 * срок жизни сессии скользящий — каждый запрос продлевает её сам.
 *
 * Цена ровно та, ради которой пароль и меняют. Скрипт
 * install/reset-admin-password.sh называется «вернуть контроль» и зовёт
 * именно эту команду; человек, уведший cookie владельца, после её
 * выполнения по-прежнему правил настройки сервера, перезапускал службы,
 * заказывал резервную копию с хэшами паролей ВСЕХ ящиков и входил в чужую
 * почту. Контроль не возвращался — возвращалась только уверенность в этом.
 *
 * Отсюда же смена пароля станет доступной панели, если её однажды туда
 * добавят: SQL и отзыв сессий живут в одном месте, и забыть второе,
 * повторив первое, уже не получится.
 */
import type { AdminDb } from './db.js';
import { hashAdminPassword } from './passwords.js';
import type { AdminSessionStore } from './session.js';

export interface AdminPasswordDeps {
  db: AdminDb;
  /**
   * Хранилище админских сессий. `null` означает «дотянуться до сессий
   * неоткуда» — так бывает у консольной утилиты при SESSION_STORE=memory,
   * когда сессии живут в памяти ЧУЖОГО процесса. Это не повод не менять
   * пароль, но повод сказать человеку правду: см. `sessionsReachable`.
   */
  sessions: AdminSessionStore | null;
}

export interface AdminPasswordResult {
  adminId: number;
  login: string;
  /** Сколько открытых сессий закрыто. Null — закрыть их не вышло. */
  closedSessions: number | null;
  /**
   * Почему сессии не закрыты — словами. Null означает «закрыты» (в том
   * числе «закрывать было нечего»).
   *
   * Отдельным полем, а не исключением: пароль к этому моменту УЖЕ
   * изменён, и уронить команду значило бы сказать человеку «сменить не
   * удалось» про пароль, который на самом деле сменился. Он повторил бы
   * попытку с другим паролем и запутался бы окончательно.
   */
  sessionsProblem: string | null;
}

/**
 * Меняет пароль администратора и закрывает все его сессии.
 *
 * Возвращает null, если такого логина нет. Счётчик неудачных попыток и
 * блокировка снимаются здесь же: пароль меняют как раз тогда, когда по
 * учётной записи только что стучались, и оставить её запертой значило бы
 * не пустить и настоящего владельца.
 */
export async function changeAdminPassword(
  deps: AdminPasswordDeps,
  login: string,
  password: string,
): Promise<AdminPasswordResult | null> {
  const row = await deps.db.findAdminByLogin(login);
  if (!row) return null;

  await deps.db.query(
    `UPDATE admin_users SET password_hash = $2, failed_attempts = 0,
            locked_until = NULL, updated_at = now() WHERE id = $1`,
    [row.id, hashAdminPassword(password)],
  );

  /*
   * ПОАДРЕСНЫЕ ЗАМКИ СНИМАЮТСЯ ТОЖЕ.
   *
   * Строка выше чистит только admin_users, а ОСНОВНОЙ замок с миграции
   * 0037 живёт в admin_login_failures: пять промахов против тридцати у
   * учётной записи. И проверяется он РАНЬШЕ пароля — значит новый,
   * правильный пароль не помогал вовсе.
   *
   * Ломалось это ровно в том сценарии, ради которого смена пароля и
   * написана: человек забыл пароль, промахнулся пять раз со своего
   * адреса, пошёл на сервер сбрасывать. Скрипт печатал «счётчик
   * неудачных попыток обнулён, блокировка снята», форма отвечала «вход
   * заблокирован ещё на 15 мин», а в панели у этой учётной записи стояло
   * «не заперт»: список показывает lockedUntil только из admin_users.
   */
  await deps.db.clearAdminLoginFailures(row.login).catch(() => 0);

  /*
   * Сессии закрываются ПОСЛЕ записи пароля, а не до.
   *
   * Порядок важен: между двумя шагами есть мгновение, и в нём лучше
   * оказаться с новым паролем и старой сессией (её закроет следующая
   * строка), чем со старым паролем и закрытыми сессиями — тогда тот, у
   * кого cookie, просто вошёл бы заново по всё ещё действующему паролю.
   */
  let closedSessions: number | null = null;
  let sessionsProblem: string | null = null;
  if (!deps.sessions) {
    sessionsProblem = 'хранилище сессий этому процессу не видно';
  } else {
    try {
      closedSessions = await deps.sessions.revokeByAdminId(row.id);
    } catch (err) {
      sessionsProblem = err instanceof Error ? err.message : String(err);
    }
  }

  return { adminId: row.id, login: row.login, closedSessions, sessionsProblem };
}
