/**
 * Миграция, снимающая обратные связи ящиков, не должна снимать прямые.
 *
 * ------------------------------------------------------------------
 * ЧТО БЫЛО
 * ------------------------------------------------------------------
 * Прежний код связывания заводил запись В ОБЕ СТОРОНЫ: человек доказывал
 * пароль ящика B, а сервер молча записывал ещё и «владелец B, связанный
 * A» с паролем A. Это дыра, и миграция 0039 убирает такие записи на
 * серверах, где ящики связывали раньше.
 *
 * Условие в ней было СИММЕТРИЧНЫМ: «есть парная связь и создана рядом по
 * времени». Для пары A → B и B → A под него подходят ОБЕ строки, а
 * `EXISTS` в `DELETE` считается по снимку до начала оператора — то есть
 * удалялись обе. У каждого, кто связал свой второй ящик, он исчезал из
 * переключателя вместе с сохранённым паролем: ни сообщения, ни следа,
 * вернуть можно только вводом пароля заново.
 *
 * Четвёртый признак, на который опиралась прежняя версия («у
 * автоматической записи нет названия, а человек обычно даёт связи имя»),
 * не отличал ничего: названия связи в продукте дать негде — веб зовёт
 * связывание двумя полями, и `label` всегда NULL.
 *
 * ------------------------------------------------------------------
 * ПОЧЕМУ ПРОВЕРЯЕТСЯ ТЕКСТ МИГРАЦИИ
 * ------------------------------------------------------------------
 * Настоящей базы в этих проверках нет, а ошибка — ровно в условии
 * запроса. Проверяем то единственное, что делает удаление асимметричным:
 * сравнение идентификаторов. Прямую связь прежний код заводил первой,
 * автоматическую обратную — следом, поэтому уходить должна строка с
 * бо́льшим `id`.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SQL = readFileSync(
  fileURLToPath(
    new URL('../../../../infra/postgres/migrations/0039_drop_auto_back_links.sql', import.meta.url),
  ),
  'utf8',
);

/** Текст без комментариев: в них как раз объясняется прежнее поведение. */
const CODE = SQL.split('\n')
  .filter((line) => !line.trimStart().startsWith('--'))
  .join('\n');

test('удаление обратных связей асимметрично: уходит только заведённая второй', () => {
  assert.match(
    CODE,
    /forward\.id\s*<\s*back\.id/,
    'в условии нет сравнения идентификаторов — под него подпадут обе строки пары',
  );
});

test('признак «нет названия» больше не участвует: названия дать негде', () => {
  assert.doesNotMatch(
    CODE,
    /back\.label\s+IS\s+NULL/i,
    'условие снова опирается на label, который у всех связей одинаково пуст',
  );
});

test('парность и близость по времени остались — без них удалялось бы лишнее', () => {
  assert.match(CODE, /lower\(forward\.owner_email\)\s*=\s*lower\(back\.linked_email\)/);
  assert.match(CODE, /<=\s*5/, 'исчезло условие «созданы в пределах пяти секунд»');
});
