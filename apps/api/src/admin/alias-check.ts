/**
 * Проверка связности алиасов.
 *
 * Алиас — это перенаправление: письмо, пришедшее на один адрес, уходит на
 * другой. Пока проверялась ровно одна вещь — что адрес не указывает сам на
 * себя. Всё остальное принималось молча, и три случая из этого «остального»
 * тихо ломают почту.
 *
 * Самый тяжёлый — алиас, чей ИСХОДНЫЙ адрес совпадает с существующим ящиком.
 * В настройках Postfix карта алиасов разбирается раньше карты ящиков
 * (`virtual_alias_maps` до `virtual_mailbox_maps` в main.cf), поэтому такой
 * алиас уводит ВСЮ входящую почту живого ящика в сторону. Ящик при этом
 * выглядит целым: он есть в списке, в него можно войти, в нём лежит старая
 * почта — просто новая перестаёт приходить. Найти причину, не зная про
 * порядок карт, почти невозможно.
 *
 * Остальные два тише, но тоже реальны: цепочка алиасов (алиас на алиас)
 * работает не так, как ожидает человек, а кольцо из алиасов заставляет
 * почтовый сервер отбивать письмо с ошибкой «слишком много перенаправлений».
 */

/** Что известно о заданном адресе. */
export interface AliasWorld {
  /** Есть ли ящик с таким адресом. */
  mailboxExists(email: string): Promise<boolean>;
  /** Куда ведёт алиас с таким исходным адресом (null — алиаса нет). */
  aliasTarget(source: string): Promise<string | null>;
}

export interface AliasProblem {
  /** Что показать человеку. */
  message: string;
  /** Можно ли создать вопреки предупреждению (иначе — прямой отказ). */
  blocking: boolean;
}

/** Глубина, дальше которой цепочку не разматываем: кольцо ищется быстро. */
const MAX_CHAIN = 10;

/**
 * Проверяет пару «откуда → куда» и возвращает беду, если она есть.
 *
 * Возвращает null, когда всё в порядке.
 */
export async function checkAlias(
  source: string,
  destination: string,
  world: AliasWorld,
): Promise<AliasProblem | null> {
  if (source === destination) {
    return { message: 'Алиас не может указывать сам на себя', blocking: true };
  }

  /*
   * Исходный адрес занят живым ящиком. Отказываем наглухо: это не
   * «необычная настройка», а гарантированная потеря входящей почты, и
   * человек, который так делает, почти наверняка имел в виду другое.
   */
  if (await world.mailboxExists(source)) {
    return {
      message:
        `Адрес «${source}» — это существующий ящик. Алиас с таким же адресом ` +
        'уведёт всю его входящую почту в сторону: перенаправления разбираются ' +
        'раньше ящиков. Если нужно пересылать почту этого ящика, сделайте это ' +
        'правилом в самом ящике.',
      blocking: true,
    };
  }

  // Разматываем цепочку от адресата: ищем кольцо и конец пути.
  const seen = new Set<string>([source]);
  let current = destination;

  for (let step = 0; step < MAX_CHAIN; step += 1) {
    if (seen.has(current)) {
      return {
        message:
          `Получится кольцо перенаправлений: «${source}» → … → «${current}» → и обратно. ` +
          'Почтовый сервер такое письмо не доставит, а отобьёт отправителю.',
        blocking: true,
      };
    }
    seen.add(current);

    const next = await world.aliasTarget(current);
    if (next === null) break;
    current = next;
  }

  /*
   * Путь кончился на адресе, которого нет. Не отказываем: ящик могут
   * завести следующим действием, а пересылка на внешний адрес — обычное
   * дело. Но предупреждаем: письмо на несуществующий внутренний адрес
   * отобьётся, и человек об этом узнает не сразу.
   */
  const endsAtMailbox = await world.mailboxExists(current);
  if (!endsAtMailbox) {
    const chained = current !== destination;
    return {
      message: chained
        ? `Цепочка ведёт на «${current}», а такого ящика нет. Письма будут отбиваться.`
        : `Ящика «${current}» нет. Если он внутренний — заведите его, иначе письма будут отбиваться.`,
      blocking: false,
    };
  }

  return null;
}
