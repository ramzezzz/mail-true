/**
 * Проверка исправности сервера — то же, что делает install/selfcheck.sh,
 * но из панели.
 *
 * ------------------------------------------------------------------
 * ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ ДАШБОРДА
 * ------------------------------------------------------------------
 * Дашборд отвечает на вопрос «сколько»: загрузка, потоки, объёмы. Он
 * рисует то, что меняется каждую минуту, и по нему планируют.
 *
 * Здесь отвечают на другой вопрос — «что сломано и что вот-вот сломается».
 * Загрузка процессора в 3 % не говорит ничего о том, что сертификат
 * истекает через неделю, а свободные 40 % диска — о том, что резольвер
 * молчит и внешние списки антиспама перестали работать. Такие поломки
 * НЕ ВИДНЫ ни в одном графике: они не меняют ни одного числа, пока не
 * станет поздно.
 *
 * ------------------------------------------------------------------
 * ЧЕГО ПАНЕЛЬ НЕ МОЖЕТ И ПОЧЕМУ
 * ------------------------------------------------------------------
 * Скрипт selfcheck.sh работает НА ХОСТЕ и имеет доступ к docker, к файлам
 * репозитория и к внешней сети. Сервер приложения живёт в контейнере без
 * сокета Docker (он равносилен правам root на машине) и без каталога
 * установки. Поэтому часть проверок скрипта здесь принципиально
 * невозможна, и раздел обязан назвать их поимённо, а не молчать о них:
 * иначе зелёный экран панели прочитается как «проверено всё».
 *
 * Список того, что доступно только скрипту, лежит в SHELL_ONLY_CHECKS
 * и показывается в разделе отдельным блоком.
 */

/** Состояние проверки. Те же три ступени, что в сводке и в скрипте. */
export type CheckState = 'ok' | 'warn' | 'fail' | 'unknown';

export interface HealthCheck {
  id: string;
  /** К какой группе относится: службы, сертификаты, DNS, место, очередь. */
  group: string;
  title: string;
  state: CheckState;
  /** Что именно проверено или что именно сломано. */
  detail: string;
  /** Что делать — показывается только когда есть что делать. */
  hint?: string;
}

/*
 * Порог тревоги по сроку сертификата здесь НЕ заводится: он один на всю
 * панель и лежит в metrics-tls.ts (TLS_WARN_DAYS). Своё число означало бы,
 * что два экрана одной панели по-разному отвечают на вопрос «пора ли
 * продлевать» — а именно из-за такого расхождения сертификаты и истекают.
 * От двадцати суток в install/selfcheck.sh значение отличается на день;
 * скрипт запускают руками, панель открывают ежедневно.
 */

/** Порог, с которого место на диске становится проблемой. */
export const DISK_WARN_PERCENT = 80;
export const DISK_FAIL_PERCENT = 90;

/**
 * Возраст самого старого письма очереди, после которого это уже не всплеск.
 *
 * Четыре часа: обычная отсрочка Postfix при недоступном адресате —
 * минуты, а письмо, лежащее полсмены, означает, что что-то не чинится
 * само. Сутки (после которых письмо вернётся отправителем) ждать нельзя:
 * к этому моменту чинить уже поздно.
 */
export const QUEUE_OLD_SECONDS = 4 * 3600;

/** Сколько писем в очереди считаем затором. */
export const QUEUE_BIG = 500;

/* ------------------------------------------------------------------ */
/* Оценки — чистые функции, чтобы проверять их без живого сервера       */
/* ------------------------------------------------------------------ */

/** Оценка занятости тома. Совпадает со ступенями check_disk в selfcheck.sh. */
export function gradeDisk(usedPercent: number): CheckState {
  if (usedPercent >= DISK_FAIL_PERCENT) return 'fail';
  if (usedPercent >= DISK_WARN_PERCENT) return 'warn';
  return 'ok';
}

/**
 * Оценка срока сертификата.
 *
 * Истёк — отказ: почтовые программы перестают подключаться, панель
 * закрывается браузером, чужие серверы отказываются принимать почту по
 * STARTTLS. Истекает скоро — предупреждение: чинится за минуты, если знать.
 */
export function gradeCertificate(daysLeft: number | null, warnDays: number): CheckState {
  if (daysLeft === null) return 'unknown';
  if (daysLeft <= 0) return 'fail';
  if (daysLeft <= warnDays) return 'warn';
  return 'ok';
}

/** Оценка очереди: важен не только размер, но и возраст самого старого. */
export function gradeQueue(total: number | null, oldestSeconds: number | null): CheckState {
  if (total === null) return 'unknown';
  if (oldestSeconds !== null && oldestSeconds >= QUEUE_OLD_SECONDS) return 'fail';
  if (total >= QUEUE_BIG) return 'warn';
  return 'ok';
}

/** Худшее из состояний — итог по разделу. */
export function worstState(states: readonly CheckState[]): CheckState {
  if (states.includes('fail')) return 'fail';
  if (states.includes('warn')) return 'warn';
  if (states.includes('unknown')) return 'unknown';
  return 'ok';
}

/** Сводка «сколько чего» для заголовка раздела. */
export function summarize(checks: readonly HealthCheck[]): {
  state: CheckState;
  ok: number;
  warn: number;
  fail: number;
  unknown: number;
} {
  const count = (state: CheckState): number => checks.filter((c) => c.state === state).length;
  return {
    state: worstState(checks.map((c) => c.state)),
    ok: count('ok'),
    warn: count('warn'),
    fail: count('fail'),
    unknown: count('unknown'),
  };
}

