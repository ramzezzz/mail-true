/**
 * Выпуск ключа DKIM для нового домена.
 *
 * ------------------------------------------------------------------
 * ПОЧЕМУ КЛЮЧ ВЫПУСКАЕТ ПАНЕЛЬ, А НЕ RSPAMD
 * ------------------------------------------------------------------
 * Обычно ключ генерирует сам rspamd при первом запуске (см.
 * infra/rspamd/entrypoint.sh, `rspamadm dkim_keygen`) и кладёт в свой том.
 * Для смены домена этот порядок не годится по времени: запись DKIM надо
 * опубликовать в DNS ЗАРАНЕЕ — она расходится по интернету часами, а
 * подписывать письма новым ключом сервер начнёт сразу. Ждать, пока
 * rspamd перезапустится с новым MAIL_DOMAIN и что-нибудь себе выпустит,
 * значит выпустить ключ ПОСЛЕ переезда — то есть гарантированно отправить
 * первые письма с нового домена без действующей подписи.
 *
 * Поэтому пара ключей выпускается на шаге плана, публичная часть сразу
 * показывается человеку готовой строкой для панели регистратора, а
 * приватная ложится в базу шифротекстом и ждёт скрипт на сервере.
 *
 * Ключ — обычный RSA 2048, ровно как у rspamadm: DKIM не знает, кто
 * породил пару, он знает только «p=» в TXT-записи и приватный ключ в
 * файле. Openssl прочитает PKCS#8 PEM без единой оговорки.
 *
 * 2048 бит, а не 1024: 1024 уже отвергают часть крупных служб. И не 4096:
 * такая запись не помещается в одну строку TXT (255 символов), её
 * приходится резать на куски, и половина панелей регистраторов режет её
 * неправильно — то есть ключ длиннее оборачивается не большей стойкостью,
 * а неработающей подписью.
 */
import { generateKeyPairSync } from 'node:crypto';

export interface DkimKeyPair {
  /** Приватный ключ в PEM (PKCS#8) — то, что кладётся в том rspamd. */
  privatePem: string;
  /** Публичный ключ в base64 (DER SPKI) — то, что идёт в «p=» TXT-записи. */
  publicKey: string;
}

/** Выпускает пару ключей DKIM. Занимает доли секунды. */
export function generateDkimKeyPair(): DkimKeyPair {
  const { privateKey, publicKey } = generateKeyPairSync('rsa', {
    modulusLength: 2048,
    publicKeyEncoding: { type: 'spki', format: 'der' },
    privateKeyEncoding: { type: 'pkcs8', format: 'pem' },
  });
  return {
    privatePem: privateKey,
    publicKey: Buffer.from(publicKey).toString('base64'),
  };
}

/** Имя TXT-записи ключа: <селектор>._domainkey.<домен> */
export function dkimRecordName(selector: string, domain: string): string {
  return `${selector}._domainkey.${domain}`;
}
