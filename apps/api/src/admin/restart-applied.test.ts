/**
 * «Ждёт применения» не имеет права гаснуть само по себе.
 *
 * ------------------------------------------------------------------
 * ЧТО БЫЛО
 * ------------------------------------------------------------------
 * Для настройки ЧУЖОГО контейнера «применена или нет» нельзя вычислить
 * сравнением с окружением своего процесса: значение читает autoconfig,
 * unbound или dovecot. Единственный честный признак — время: настройку
 * правили позже, чем службу последний раз удачно применяли.
 *
 * Время «последнего удачного применения» бралось из таблицы перезапусков
 * без разбора действия — вместе с отметками о старте (action = 'boot').
 * А их пишет сам процесс при КАЖДОМ запуске: после обновления, после
 * падения, после `docker compose up`, после чего угодно.
 *
 * Получалось так: человек сохранил настройку, панель честно показала
 * «ждёт применения» — и следующий же запуск api погасил этот признак.
 * Ничего при этом не применялось: окружение контейнера задаётся при его
 * СОЗДАНИИ, перезапуск процесса его не меняет.
 *
 * Итог хуже неверной надписи: человек видел «применено», уходил — и
 * работал со старым значением, будучи уверенным в обратном.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { RestartStore } from './restart-store.js';
import type { AdminDb } from './db.js';

interface Recorded {
  text: string;
  values: unknown[];
}

/** База, которая запоминает запросы и отвечает пустотой. */
function spyDb(): { db: Pick<AdminDb, 'query'>; seen: Recorded[] } {
  const seen: Recorded[] = [];
  return {
    seen,
    db: {
      query: async <T>(text: string, values: unknown[] = []): Promise<T[]> => {
        seen.push({ text, values });
        return [] as T[];
      },
    } as Pick<AdminDb, 'query'>,
  };
}

test('отметки о старте не считаются применением настроек', async () => {
  const { db, seen } = spyDb();
  await new RestartStore(db).lastApplied();

  const query = seen[0]?.text ?? '';
  assert.match(query, /status = 'ok'/, 'считаются только удачные');
  assert.match(
    query,
    /action <> 'boot'/,
    'без этого любой запуск процесса гасит «ждёт применения», ничего не применив',
  );
});

test('лента событий по-прежнему без отметок о старте', async () => {
  /*
   * Соседний запрос уже фильтровал их — и правильно: человеку в ленте
   * «что происходило» нужны его действия, а не строчка на каждый подъём
   * контейнера. Здесь это закреплено, чтобы фильтр не сняли заодно.
   */
  const { db, seen } = spyDb();
  await new RestartStore(db).recent(5);
  assert.match(seen[0]?.text ?? '', /action <> 'boot'/);
});

test('счётчик петли считает ИМЕННО отметки о старте', async () => {
  /*
   * Обратная сторона: защита от петли перезапусков живёт ровно на этих
   * отметках. Убрать их из таблицы «чтобы не мешали» значило бы снять и
   * её — поэтому фильтр стоит в запросах, а не в записи.
   */
  const { db, seen } = spyDb();
  await new RestartStore(db).bootsSince(10);
  assert.match(seen[0]?.text ?? '', /action = 'boot'/);
});
