/**
 * Чистка разметки шаблона перед укладкой в базу.
 *
 * ------------------------------------------------------------------
 * ПОЧЕМУ НЕ mail/sanitize.ts
 * ------------------------------------------------------------------
 * Тот санитайзер написан для ЧУЖОГО письма, которое мы показываем: он
 * переписывает `src` картинок на заглушку и прячет настоящий адрес в
 * `data-mt-src` (чтобы отправитель не узнал о прочтении), выносит `cid:`
 * на маршрут частей письма и вешает на ссылки `target="_blank"`.
 *
 * Здесь всё это — порча. Шаблон человек написал сам, в собственном окне
 * написания, и из шаблона он собирается ОТПРАВИТЬ письмо. Прогони мы тело
 * через чтение писем — в письмо уехал бы прозрачный пиксель вместо
 * картинки и ссылки с `target`, которого в письме быть не должно.
 *
 * ------------------------------------------------------------------
 * ЗАЧЕМ ВООБЩЕ ЧИСТИТЬ СВОЁ
 * ------------------------------------------------------------------
 * Затем, что «своё» — это разметка, приехавшая из браузера строкой, и
 * попадает она обратно в браузер: тело шаблона вставляется в редактор
 * через `insertHTML` и показывается в настройках. Между «сохранил» и
 * «вставил» лежит база — то есть хранимая разметка. Скрипт, положенный
 * туда один раз (своими руками через средства разработчика, чужой
 * вкладкой, кривым переносом с другого сервера), исполнялся бы у себя же
 * в почте при каждой вставке.
 *
 * Набор запрещённого тот же, что и у писем, а вот переписывания ссылок и
 * картинок здесь нет вовсе: тело обязано вернуться в письмо ровно таким,
 * каким его набрали.
 */
import createDOMPurify from 'dompurify';
import { JSDOM } from 'jsdom';

const jsdomInstance = new JSDOM('<!doctype html><html><body></body></html>');
const purifier = createDOMPurify(jsdomInstance.window as unknown as Window & typeof globalThis);

/**
 * Чего в теле письма не бывает.
 *
 * `style` и `link` — не «на всякий случай»: правило из чужого шаблона
 * действует на весь документ, в который его вставили, то есть на окно
 * написания целиком. Формы и поля — потому что письмо ничего никуда не
 * отправляет; кнопка «Оплатить» внутри тела письма всегда обман.
 */
const FORBID_TAGS = [
  'script',
  'iframe',
  'frame',
  'frameset',
  'object',
  'embed',
  'applet',
  'form',
  'input',
  'button',
  'select',
  'textarea',
  'base',
  'meta',
  'link',
  'style',
  'noscript',
  'template',
  'audio',
  'video',
  'source',
  'track',
  'svg',
  'math',
];

const FORBID_ATTR = ['srcset', 'ping', 'formaction', 'action', 'xlink:href', 'poster'];

/**
 * Схемы, которые разрешено оставить в атрибутах.
 *
 * `cid:` здесь НЕТ намеренно, в отличие от чтения писем: у шаблона нет
 * частей письма, на которые такая ссылка могла бы указывать, и оставленная
 * она превратилась бы в битую картинку в каждом отправленном письме.
 */
const ALLOWED_URI =
  /^(?:(?:https?|mailto|tel|callto):|data:image\/(?:png|gif|jpe?g|webp|bmp);)/i;

/** Вычищенная разметка тела шаблона. */
export function sanitizeTemplateHtml(html: string): string {
  return purifier.sanitize(html, {
    FORBID_TAGS,
    FORBID_ATTR,
    ALLOWED_URI_REGEXP: ALLOWED_URI,
    ALLOW_DATA_ATTR: false,
    WHOLE_DOCUMENT: false,
    USE_PROFILES: { html: true },
  });
}

/**
 * Есть ли в теле хоть что-нибудь, кроме разметки.
 *
 * Нужно ровно для одного вопроса: пустой ли шаблон. По разметке этого не
 * узнать — у пустого редактора `innerHTML` не пуст, там живут `<br>` и
 * неразрывные пробелы, и по строке любой только что открытый редактор
 * выглядел бы непустым.
 */
export function templateHasText(html: string): boolean {
  const text = html
    .replace(/<[^>]*>/g, ' ')
    .replace(/&nbsp;/gi, ' ')
    // Неразрывный пробел записан кодом, а не самим символом: живой U+00A0
    // в исходнике неотличим от обычного пробела, и следующая правка этой
    // строки убила бы его, ничего не заметив.
    .replace(/\u00A0/g, ' ');
  return text.trim() !== '';
}
