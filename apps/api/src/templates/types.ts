/**
 * Контракт шаблонов писем между сервером и интерфейсом.
 *
 * Здесь же — пределы. Они лежат в типах, а не в маршрутах, потому что их
 * читают трое: маршрут (проверяет), хранилище (складывает) и интерфейс
 * (показывает человеку, сколько ещё можно). Разъехавшись, они дали бы
 * худший из возможных исходов — отказ уже ПОСЛЕ того, как человек выбрал
 * файл и подождал загрузку.
 */

/** Вложение шаблона — без содержимого: наружу байты не отдаются. */
export interface TemplateAttachment {
  id: number;
  filename: string;
  mimeType: string;
  size: number;
}

/** Шаблон целиком — ровно то, что нужно, чтобы собрать письмо. */
export interface MailTemplate {
  id: number;
  name: string;
  subject: string;
  bodyHtml: string;
  /**
   * Тело в СПИСКЕ обрезано — за полным надо сходить отдельно
   * (GET /api/templates/:id).
   *
   * Список шаблонов запрашивается при открытии окна написания и на
   * каждой странице настроек, а тело шаблона допускается до 512 КБ на
   * штуку при сотне штук на ящик. Отдавать всё это ради меню, где видно
   * первые полсотни символов, — половина мегабайта на нажатие «Написать
   * письмо» в обычном случае и полсотни мегабайт в предельном.
   *
   * Поле есть только в списке. Одиночный шаблон приходит целиком, и там
   * признак всегда false.
   */
  bodyTruncated?: boolean;
  position: number;
  attachments: TemplateAttachment[];
}

/** Что приходит от интерфейса при заведении и правке шаблона. */
export interface TemplateDraft {
  name: string;
  subject: string;
  bodyHtml: string;
  /**
   * Вложения задаются идентификаторами ВРЕМЕННЫХ загрузок — тех же, что
   * уходят в письмо (`POST /api/uploads`). Байты по ним сервер копирует
   * себе; см. шапку миграции 0026 о том, почему нельзя запомнить сам
   * идентификатор.
   *
   * Отсутствие поля и пустой список — разные вещи. Пусто значит «убрать
   * все вложения», отсутствие — «не трогать те, что есть»: правка одного
   * лишь названия не должна стирать приложенный прайс.
   */
  attachmentIds?: string[] | undefined;
}

/**
 * Состояние возможности целиком — то же, что у меток и отложенных писем.
 *
 * `available: false` значит, что хранилища нет (не настроена база или не
 * применена миграция 0026). Тогда интерфейс убирает и кнопку «Шаблоны» в
 * окне написания, и раздел настроек — кнопка появляется вместе с
 * поведением, а не показывается и потом отказывает.
 */
export interface TemplatesState {
  available: boolean;
  reason: string | null;
  items: MailTemplate[];
}

/** Предел длины названия. Оно целиком видно в строке меню. */
export const MAX_TEMPLATE_NAME_LENGTH = 120;

/** Предел темы — тот же, что у темы письма в базе. */
export const MAX_TEMPLATE_SUBJECT_LENGTH = 512;

/**
 * Предел тела. Полмегабайта разметки — это уже не заготовка ответа, а
 * пересланная переписка; такие вставляют из письма, а не из шаблона.
 */
export const MAX_TEMPLATE_BODY_LENGTH = 512 * 1024;

/**
 * Сколько тела отдаётся В СПИСКЕ шаблонов.
 *
 * Меню показывает выжимку в несколько десятков символов, страница
 * настроек — имя и тему; целое тело в списке нужно ровно одному
 * действию — вставке в письмо, и она умеет дочитать шаблон по номеру.
 *
 * Две тысячи знаков выбраны так, чтобы обычный шаблон («реквизиты»,
 * «график работы», «шаблон ответа») уезжал целиком и дочитывать ничего
 * не приходилось, а редкая простыня на полмегабайта не тянулась в
 * браузер при каждом открытии окна написания.
 */
export const TEMPLATE_LIST_BODY_CHARS = 2000;

/**
 * Сколько вложений может нести один шаблон.
 *
 * Меньше, чем у письма (20): шаблон — это заготовка ответа с прайсом и
 * договором, а не архив. Число ограничивает и число оборотов к базе при
 * вставке.
 */
export const MAX_TEMPLATE_ATTACHMENTS = 5;

/**
 * Суммарный вес вложений одного шаблона.
 *
 * Намеренно меньше предела вложения письма: содержимое читается из базы
 * ЦЕЛИКОМ при каждой вставке шаблона, и двадцать мегабайт в строке
 * означали бы двадцать мегабайт из Postgres на каждое нажатие «Вставить».
 */
export const MAX_TEMPLATE_BYTES = 5 * 1024 * 1024;

/** Сколько шаблонов может завести один ящик. */
export const MAX_TEMPLATES_PER_ACCOUNT = 100;

/** Читаемый размер для сообщений об отказе: «5 МБ». */
export function formatBytes(bytes: number): string {
  if (bytes >= 1024 * 1024) return `${String(Math.round(bytes / (1024 * 1024)))} МБ`;
  if (bytes >= 1024) return `${String(Math.round(bytes / 1024))} КБ`;
  return `${String(bytes)} Б`;
}
