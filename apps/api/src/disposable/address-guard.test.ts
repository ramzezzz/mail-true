/**
 * Одноразовый адрес не уводит почту настоящего ящика.
 *
 * ------------------------------------------------------------------
 * ЧТО БЫЛО
 * ------------------------------------------------------------------
 * Занятость адреса проверялась ТОЛЬКО при заведении, а включение было
 * голым переключением поля. При этом поиск занятости смотрит на
 * действующие записи, то есть выключенной строки не видит вовсе, а
 * Postfix разбирает карту алиасов раньше карты ящиков.
 *
 * Захват чужой почты выходил в три шага: владелец заранее заводит
 * ivan@company.ru и выключает его; администратор, не видя препятствий,
 * создаёт настоящий ящик Ивана; владелец включает адрес обратно — и вся
 * входящая почта Ивана, включая письма восстановления паролей, уходит
 * постороннему. Ящик Ивана при этом открывается и выглядит исправным.
 *
 * Второе здесь же: хвост случайного имени брался из Math.random. В V8
 * это xorshift128+, общий на процесс и не предназначенный для секретов —
 * заведя несколько адресов подряд, состояние генератора восстанавливают
 * и вычисляют следующие хвосты наперёд. А неперебираемость — это ровно
 * то, ради чего хвост и нужен: приставку человек задаёт сам, и
 * секретом она не является.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { suggestLocalPart } from './name.js';

test('хвост имени не повторяется от вызова к вызову', () => {
  const seen = new Set<string>();
  for (let i = 0; i < 500; i += 1) seen.add(suggestLocalPart('shop'));
  // 24 бита на 500 имён: совпадения теоретически возможны, но единичны.
  assert.ok(seen.size > 490, `слишком много повторов: ${String(seen.size)} из 500`);
});

test('хвост берётся из криптографического источника, а не из Math.random', () => {
  /*
   * Подменяем Math.random заведомо предсказуемым: если имя от него
   * зависит, все пятьсот адресов совпадут. Так и было до правки.
   */
  const realRandom = Math.random;
  Math.random = () => 0.42;
  try {
    const seen = new Set<string>();
    for (let i = 0; i < 500; i += 1) seen.add(suggestLocalPart('shop'));
    assert.ok(seen.size > 490, 'имя предсказуемо: подменённый Math.random дал одинаковые адреса');
  } finally {
    Math.random = realRandom;
  }
});

test('свой генератор по-прежнему принимается — ради тестов', () => {
  assert.equal(
    suggestLocalPart('shop', () => 0),
    'shop-000000',
  );
});

test('хвост — ровно шесть шестнадцатеричных знаков', () => {
  for (let i = 0; i < 200; i += 1) {
    const name = suggestLocalPart('shop');
    assert.match(name, /^shop-[0-9a-f]{6}$/u, `неожиданный вид имени: ${name}`);
  }
});

test('верхняя граница генератора не даёт семизначного хвоста', () => {
  // Math.random() и криптографический источник дают значения строго
  // меньше единицы, но проверка дешевле рассуждения.
  const name = suggestLocalPart('shop', () => 0.999999999);
  assert.match(name, /^shop-[0-9a-f]{6}$/u, `хвост вышел за шесть знаков: ${name}`);
});
