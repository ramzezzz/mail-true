/**
 * Имя одноразового адреса: что разрешено, что занято навсегда и как
 * придумывается случайное.
 *
 * ------------------------------------------------------------------
 * ПОЧЕМУ НАБОР СИМВОЛОВ УЖЕ, ЧЕМ РАЗРЕШАЕТ RFC
 * ------------------------------------------------------------------
 * RFC 5321 разрешает в левой части адреса и `!#$%&'*+/=?^_`{|}~`, и точки,
 * и вообще кавычки с пробелами внутри. Заводить такое ЧЕЛОВЕКУ через
 * веб-форму — значит гарантированно получить адрес, который где-нибудь да
 * сломается: половина форм регистрации на сайтах не примет `a+b@`, а адрес
 * с точкой на конце (`shop.@`) нарушает уже сам RFC.
 *
 * Одноразовый адрес существует ровно для того, чтобы его вписали в чужую
 * форму регистрации. Поэтому здесь набор нарочно скучный: строчные буквы
 * латиницы, цифры, дефис и точка внутри. Такой адрес примут везде.
 *
 * Кириллица не разрешена намеренно: адрес с ней требует IDN/SMTPUTF8, а
 * в main.cf стоит `smtputf8_enable = no` (Dovecot ещё не умеет SMTPUTF8 в
 * LMTP). Разрешить ввод — значит завести адрес, на который письма не дойдут.
 */

/** Предел длины левой части адреса из RFC 5321. */
import { randomBytes } from 'node:crypto';
const MAX_LOCAL = 64;

/** Самое короткое имя: три знака. Короче — почти наверняка опечатка. */
const MIN_LOCAL = 3;

/**
 * Имена, которые нельзя занять никогда.
 *
 * Первые два обязательны по RFC 2142: `postmaster` обязан существовать у
 * любого домена, `abuse` — адрес для жалоб. Отдать их владельцу ящика
 * значит либо сломать почту домена, либо позволить одному человеку
 * забрать себе все жалобы на домен. Остальные — служебные имена, которые
 * администратор рано или поздно захочет завести сам, и обнаружить их
 * занятыми чужим «одноразовым» было бы дурной неожиданностью.
 *
 * Проверка идёт ДО обращения к базе: в базе этих адресов может ещё не
 * быть, и занятость по таблицам их не поймает.
 */
const RESERVED = new Set([
  'postmaster',
  'abuse',
  'admin',
  'administrator',
  'hostmaster',
  'webmaster',
  'root',
  'mailer-daemon',
  'noreply',
  'no-reply',
  'security',
  'support',
  'info',
]);

/** Разрешённый вид имени: буквы/цифры по краям, дефис и точка внутри. */
const SHAPE = /^[a-z0-9]+(?:[.-][a-z0-9]+)*$/;

export interface NameProblem {
  message: string;
}

/**
 * Проверяет имя (левую часть без `@домен`) и возвращает беду, если она есть.
 *
 * Возвращает null, когда имя годится.
 */
export function checkLocalPart(name: string): NameProblem | null {
  if (name.length < MIN_LOCAL) {
    return { message: `Имя короче ${MIN_LOCAL} знаков — так адрес не завести` };
  }
  if (name.length > MAX_LOCAL) {
    return { message: `Имя длиннее ${MAX_LOCAL} знаков — такой адрес запрещён стандартом` };
  }
  if (!SHAPE.test(name)) {
    return {
      message:
        'В имени можно использовать строчные латинские буквы, цифры, дефис и точку. ' +
        'Начинаться и заканчиваться оно должно буквой или цифрой.',
    };
  }
  if (RESERVED.has(name)) {
    return {
      message:
        `Имя «${name}» служебное и занято за доменом навсегда. ` +
        'Возьмите любое другое — например, с названием сайта, которому выдаёте адрес.',
    };
  }
  return null;
}

/**
 * Случайное число [0, 1) из криптографического источника.
 *
 * Ровно 24 бита — столько же, сколько кладётся в хвост имени: брать
 * больше незачем, а меньше нельзя.
 */
function cryptoRandom(): number {
  const buf = randomBytes(3);
  return ((buf[0]! << 16) | (buf[1]! << 8) | buf[2]!) / 0x1000000;
}

/**
 * Придумывает случайное имя вида `shop-2f4c9a`.
 *
 * ------------------------------------------------------------------
 * ПОЧЕМУ СЛУЧАЙНОЕ, А НЕ ПО ПОРЯДКУ
 * ------------------------------------------------------------------
 * Порядковые имена (`alias1@`, `alias2@`) выдают две вещи сразу: сколько у
 * человека адресов и в каком порядке он их заводил. Хуже того, они
 * ПЕРЕБИРАЮТСЯ: узнав `ivanov-1@`, спамер шлёт на `ivanov-2@` и попадает
 * к тому же человеку. Случайный хвост это закрывает.
 *
 * Приставку человек задаёт сам («shop», «forum») — она и есть ответ на
 * вопрос «кому я это выдал», который он будет читать через год.
 *
 * ------------------------------------------------------------------
 * ПОЧЕМУ НЕ Math.random
 * ------------------------------------------------------------------
 * Умолчанием стоял он, и неперебираемость, ради которой всё и делалось,
 * держалась только на нём. А `Math.random` в V8 — это xorshift128+, общий
 * на весь процесс и не предназначенный для секретов: заведя несколько
 * адресов подряд, состояние генератора восстанавливают по выданным
 * значениям, после чего следующие хвосты вычисляются наперёд. Приставка
 * при этом секретом не является вовсе — она из пометки «кому выдан».
 * Сама возможность подставить свой генератор оставлена ради тестов.
 */
export function suggestLocalPart(prefix: string, random: () => number = cryptoRandom): string {
  /*
   * Порядок здесь важнее, чем кажется: сначала обрезка, и только потом
   * чистка краёв.
   *
   * Наоборот было так: «магазин обуви на садовой» превращается в
   * `magazin-obuvi-na-...`, обрезка в 24 знака попадает ровно на дефис, и
   * к имени, уже кончающемуся дефисом, дописывался `-<хвост>` — выходило
   * `...--2f4c9a`. Проверка вида имени такое не пропускает, и человек
   * получал отказ «в имени можно использовать строчные латинские буквы…»
   * за имя, которого он не вводил: оно предлагалось само, из пометки
   * «кому выдан».
   */
  const cleaned = prefix
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .slice(0, 24)
    .replace(/^-+|-+$/g, '');
  const tail = Math.floor(random() * 0x1000000)
    .toString(16)
    .padStart(6, '0');
  const base = cleaned.length > 0 ? `${cleaned}-${tail}` : `mail-${tail}`;
  return base.slice(0, MAX_LOCAL);
}

/** Домен ящика: то, что после `@`. Адреса заводятся только в нём. */
export function domainOf(email: string): string {
  return email.slice(email.indexOf('@') + 1).toLowerCase();
}
