/**
 * История разговора с помощником — одна схема на оба чата.
 *
 * ------------------------------------------------------------------
 * ПОЧЕМУ ОНА ОТДЕЛЬНО И ПОЧЕМУ ОТВЕТ ПОМОЩНИКА ОБРЕЗАЕТСЯ, А ВОПРОС НЕТ
 * ------------------------------------------------------------------
 * Разговор нигде не хранится: история живёт в браузере и приезжает на
 * сервер с КАЖДЫМ вопросом — иначе «а подробнее?» превращается в
 * бессмыслицу. Отсюда и пределы: каждый вопрос оплачивается вместе со
 * всей историей.
 *
 * Прежняя схема ставила один предел на всё — четыре тысячи знаков на
 * реплику, — и разговор ломался НАСМЕРТЬ от собственного ответа
 * помощника. Модель отвечает длиннее предела (для подробного разбора это
 * обычное дело), ответ встаёт в историю, и следующий вопрос отбивается
 * схемой: «Некорректные данные запроса». И следующий. И все остальные —
 * потому что бракованная реплика из истории уже никуда не денется.
 * Починка была одна: закрыть окно и потерять разговор целиком.
 *
 * Разница в обращении с ролями намеренная:
 *
 *  - ВОПРОС ЧЕЛОВЕКА обрезать нельзя. Молча укоротить написанное — значит
 *    отправить в модель не то, что человек спросил, и получить ответ не
 *    на его вопрос. Поэтому слишком длинный вопрос отбивается, и
 *    отбивается СЛОВАМИ, из которых видно и предел, и что делать.
 *  - ОТВЕТ ПОМОЩНИКА обрезается. Он нужен истории как напоминание, о чём
 *    шла речь, и его хвост дешевле потерять, чем весь разговор. На экране
 *    при этом остаётся полный текст — обрезка живёт только в том, что
 *    уходит наружу.
 */
import { z } from 'zod';

/** Предел одной реплики: столько же, сколько было, но теперь только для вопроса. */
export const CHAT_TURN_MAX_CHARS = 4000;

/**
 * Потолок на реплику из истории — до обрезки.
 *
 * Нужен, чтобы запрос вообще имел границу: без него двадцать реплик по
 * мегабайту прошли бы разбор и легли в память процесса. Ответы длиннее
 * этого не бывают — предел ответа модели задаётся токенами и на порядок
 * меньше.
 */
export const CHAT_TURN_HARD_MAX_CHARS = 20_000;

/** Сколько реплик разговора уезжает на сервер. */
export const CHAT_HISTORY_MAX_TURNS = 20;

export interface ChatTurnInput {
  role: 'user' | 'assistant';
  content: string;
}

/** Обрезает ответы помощника до предела; вопросы не трогает. */
export function trimAssistantTurns(turns: readonly ChatTurnInput[]): ChatTurnInput[] {
  return turns.map((turn) =>
    turn.role === 'assistant' && turn.content.length > CHAT_TURN_MAX_CHARS
      ? { role: turn.role, content: `${turn.content.slice(0, CHAT_TURN_MAX_CHARS)}…` }
      : { role: turn.role, content: turn.content },
  );
}

export const chatHistorySchema = z.object({
  messages: z
    .array(
      z.object({
        role: z.enum(['user', 'assistant']),
        content: z.string().trim().min(1).max(CHAT_TURN_HARD_MAX_CHARS),
      }),
    )
    .min(1)
    .max(CHAT_HISTORY_MAX_TURNS)
    .transform(trimAssistantTurns)
    .refine(
      (turns) =>
        turns.every((turn) => turn.role !== 'user' || turn.content.length <= CHAT_TURN_MAX_CHARS),
      {
        message:
          `Вопрос длиннее ${String(CHAT_TURN_MAX_CHARS)} знаков. ` +
          'Сократите его или разбейте на несколько.',
      },
    ),
});
