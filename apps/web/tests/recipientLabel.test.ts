/**
 * «Кому: вам» пишется только там, где письмо и правда адресовано вам.
 *
 * ------------------------------------------------------------------
 * ЧТО БЫЛО
 * ------------------------------------------------------------------
 * Условие было «получатель ровно один», и адрес учётной записи не
 * спрашивался ни разу. У любого письма с одним адресатом подпись выходила
 * «вам» — в том числе в «Отправленных», где каждое письмо сообщало
 * человеку, что он написал его сам себе. В развёрнутой переписке строка
 * «Кому: вам» и вовсе была зашита в разметку, то есть показывалась у
 * каждого письма подряд.
 *
 * Подпись под адресом отвечает на вопрос «а мне ли это писали». Отвечать
 * на него неправдой хуже, чем не отвечать вовсе.
 */
import { describe, expect, it } from 'vitest';
import { recipientLabel } from '../src/lib/recipients';

const me = 'ivan@mail.local';

describe('подпись получателя', () => {
  it('письмо мне одному — «вам»', () => {
    expect(recipientLabel([{ address: me, name: 'Иван' }], me)).toBe('вам');
  });

  it('своё письмо коллеге не адресовано мне: показываем адрес', () => {
    // Ровно случай «Отправленных», где раньше стояло «Кому: вам».
    expect(recipientLabel([{ address: 'anna@mail.local', name: 'Анна' }], me)).toBe('Анна');
  });

  it('имени нет — показываем адрес, а не пустоту', () => {
    expect(recipientLabel([{ address: 'anna@mail.local', name: null }], me)).toBe(
      'anna@mail.local',
    );
  });

  it('регистр адреса роли не играет: тот же ящик — тот же человек', () => {
    expect(recipientLabel([{ address: 'Ivan@Mail.Local', name: null }], me)).toBe('вам');
  });

  it('я и ещё кто-то — перечисляем всех, «вам» тут неправда', () => {
    const label = recipientLabel(
      [
        { address: me, name: 'Иван' },
        { address: 'anna@mail.local', name: 'Анна' },
      ],
      me,
    );
    expect(label).toBe('Иван, Анна');
  });

  it('ящик неизвестен — не выдумываем «вам»', () => {
    // Так бывает, пока сессия ещё не приехала: подпись обязана быть
    // честной и в этот момент.
    expect(recipientLabel([{ address: me, name: 'Иван' }], '')).toBe('Иван');
  });

  it('получателей нет вовсе — подписи нет', () => {
    expect(recipientLabel([], me)).toBe('');
  });
});
