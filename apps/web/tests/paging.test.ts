/**
 * Постраничная подгрузка списка писем.
 *
 * Числа взяты с живого ящика: `GET /api/messages?folderId=inbox&limit=100`
 * отвечает `total: 187` при сотне писем на странице. Раньше интерфейс просил
 * одну страницу с `offset: 0`, `total` не использовал и подгрузки не имел —
 * восемьдесят семь писем были недостижимы вовсе.
 */

import { describe, expect, it } from 'vitest';
import {
  dedupeById,
  hasMore,
  loadedCount,
  nextPageOffset,
  markAllReadLabel,
  selectAllLabel,
  totalCount,
} from '../src/lib/paging';

/** Страница ответа: n писем при total из живого ящика. */
const page = (offset: number, count: number, total = 187) => ({
  items: Array.from({ length: count }, (_, i) => `inbox:${offset + i}`),
  total,
  offset,
  limit: 100,
});

describe('nextPageOffset', () => {
  it('первый запрос — с нулевого смещения', () => {
    expect(nextPageOffset([])).toBe(0);
  });

  it('после первой сотни из 187 просит следующую с offset 100', () => {
    expect(nextPageOffset([page(0, 100)])).toBe(100);
  });

  it('когда всё загружено — больше не просит', () => {
    expect(nextPageOffset([page(0, 100), page(100, 87)])).toBeUndefined();
  });

  it('пустая страница останавливает подгрузку, а не крутит её вечно', () => {
    expect(nextPageOffset([page(0, 100), page(100, 0)])).toBeUndefined();
  });

  it('страница пришла неполной — следующая всё равно с прежнего рубежа', () => {
    /*
     * Сервер режет позиционно: он взял ломоть `slice(0, 100)`, а до ответа
     * доехало 60 писем — остальные удалили между поиском и выборкой (в
     * списке переписок строка без единого уцелевшего письма не строится
     * вовсе). Счёт «по полученным» просил бы следующую страницу с 60, то
     * есть с заходом на уже показанное: сорок строк задваивались, а
     * сороковое с конца письмо не показывалось никогда.
     */
    expect(nextPageOffset([page(0, 60)])).toBe(100);
  });

  it('неполная страница не мешает вовремя остановиться', () => {
    // Второй ломоть — с 100-го по 187-й, дальше писем нет
    expect(nextPageOffset([page(0, 100), page(100, 80)])).toBeUndefined();
  });
});

describe('dedupeById', () => {
  it('одно и то же письмо в двух страницах показывается один раз', () => {
    /*
     * Между подгрузками пришло новое письмо, весь список сдвинулся — и то,
     * что было последним на первой странице, приехало первым на второй.
     * Двойная строка ломает и выделение (галочка ставится сразу в двух
     * местах), и ключи виртуализации: два узла с одним ключом.
     */
    const merged = dedupeById([
      { id: 'inbox:187' },
      { id: 'inbox:88' },
      { id: 'inbox:88' },
      { id: 'inbox:87' },
    ]);
    expect(merged.map((m) => m.id)).toEqual(['inbox:187', 'inbox:88', 'inbox:87']);
  });

  it('порядок не трогает и на списке без повторов ничего не меняет', () => {
    const items = [{ id: 'a' }, { id: 'b' }, { id: 'c' }];
    expect(dedupeById(items).map((m) => m.id)).toEqual(['a', 'b', 'c']);
  });
});

describe('счётчики страниц', () => {
  it('loadedCount складывает письма всех страниц', () => {
    expect(loadedCount([page(0, 100), page(100, 87)])).toBe(187);
  });

  it('totalCount берётся из ответа сервера', () => {
    expect(totalCount([page(0, 100)])).toBe(187);
    expect(totalCount([])).toBe(0);
  });

  it('hasMore честно отвечает, осталось ли что грузить', () => {
    expect(hasMore([page(0, 100)])).toBe(true);
    expect(hasMore([page(0, 100), page(100, 87)])).toBe(false);
  });
});

describe('selectAllLabel', () => {
  it('пока загружено не всё — говорит правду про число писем', () => {
    // Раньше кнопка обещала «Выделить все», а выделяла загруженную сотню
    expect(selectAllLabel(100, 187)).toBe('Выделить загруженные (100 из 187)');
  });

  it('когда загружено всё — обычное «Выделить все»', () => {
    expect(selectAllLabel(187, 187)).toBe('Выделить все');
    expect(selectAllLabel(12, 12)).toBe('Выделить все');
    expect(selectAllLabel(0, 0)).toBe('Выделить все');
  });
});

describe('markAllReadLabel', () => {
  it('пока загружено не всё — не обещает «все»', () => {
    /*
     * Та же беда, что была у соседней кнопки. В папке с четырьмя тысячами
     * непрочитанных счётчик падал на сотню и замирал: человек жал ещё раз
     * — снова сотня. Ничего не сломано, а выглядит как поломка.
     */
    expect(markAllReadLabel(100, 4000)).toBe('Отметить загруженные (100 из 4000)');
  });

  it('когда загружено всё — обычная подпись', () => {
    expect(markAllReadLabel(187, 187)).toBe('Отметить все прочитанными');
    expect(markAllReadLabel(0, 0)).toBe('Отметить все прочитанными');
  });
});
