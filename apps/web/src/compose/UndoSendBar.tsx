/**
 * Плашка «Письмо отправлено · Отменить» с обратным отсчётом.
 *
 * Отсчёт здесь — ТОЛЬКО показ. Ждёт письмо не браузер, а сервер (очередь
 * в apps/api/src/mail/deferred-send.ts), и это принципиально: закрытая
 * вкладка, уснувший телефон, перезагруженная страница отменяют лишь
 * возможность передумать — письмо всё равно уходит. Плашка, которая держала
 * бы письмо у себя таймером, теряла бы его при первом же закрытии вкладки,
 * и человек узнавал бы об этом от адресата.
 *
 * Отсюда же и поведение по истечении срока: когда счётчик доходит до нуля,
 * плашка не «отправляет», а просто исчезает — отправлять уже нечего.
 * А если человек успел нажать «Отменить» в последнюю долю секунды и не
 * успел, сервер честно отвечает «письмо уже ушло» — см. onUndo.
 */

import { useEffect, useState, type CSSProperties } from 'react';
import { IconClose } from '../mail/icons';
import styles from './UndoSendBar.module.css';

export interface UndoSendBarProps {
  /** До какого момента (ISO) отмена ещё сработает. */
  until: string;
  /** Порядковый номер плашки снизу вверх — когда писем отправили несколько. */
  index?: number;
  /** Нажали «Отменить». Ответ сервера разбирает вызывающий. */
  onUndo(): void;
  /** Срок вышел либо плашку закрыли крестиком. */
  onDismiss(): void;
  /** Отмена уже в пути — второе нажатие ничего не даст. */
  busy?: boolean;
}

/** Сколько целых секунд осталось до срока (не меньше нуля). */
export function secondsLeft(until: string, now: number): number {
  const left = Date.parse(until) - now;
  if (!Number.isFinite(left)) return 0;
  return Math.max(0, Math.ceil(left / 1000));
}

/** Высота плашки с зазором — шаг, с которым они встают друг над другом. */
const STACK_STEP = 52;

export function UndoSendBar({ until, index = 0, onUndo, onDismiss, busy }: UndoSendBarProps) {
  const [left, setLeft] = useState(() => secondsLeft(until, Date.now()));

  /**
   * Пересчёт раз в четверть секунды, а не раз в секунду.
   *
   * Секундный шаг на глаз отстаёт: между постановкой таймера и первым его
   * срабатыванием проходит почти секунда, и «5» висела бы на экране дольше
   * остальных цифр. Заодно так плашка исчезает вовремя после того, как
   * вкладка побывала в фоне: браузер там таймеры придерживает, и по
   * возвращении счётчик обязан показать правду, а не продолжить с места.
   */
  useEffect(() => {
    const timer = setInterval(() => setLeft(secondsLeft(until, Date.now())), 250);
    return () => clearInterval(timer);
  }, [until]);

  /**
   * Срок вышел — плашке больше нечего предлагать. Убирает её вызывающий:
   * вместе с ней закрывается и окно написания, которое всё это время
   * держало письмо на случай отмены.
   *
   * Пока отмена в пути (`busy`), не закрываем ничего, даже если счётчик
   * добежал до нуля. Иначе нажатие на последней доле секунды кончалось бы
   * худшим из исходов: сервер письмо отменил, а окно с текстом мы уже
   * закрыли — и написанное пропало вместе с ним.
   */
  useEffect(() => {
    if (left === 0 && !busy) onDismiss();
  }, [left, busy, onDismiss]);

  if (left === 0 && !busy) return null;

  return (
    <div
      className={styles.bar}
      style={{ '--mt-undo-offset': `${index * STACK_STEP}px` } as CSSProperties}
      /*
       * `status`, а не `alert`: плашка сообщает об удаче, а не об отказе,
       * и перебивать ею то, что человек читает, незачем. Читающие с экрана
       * узнают о ней, дочитав текущую фразу.
       */
      role="status"
      aria-live="polite"
    >
      <span className={styles.text}>Письмо отправлено</span>
      <span className={styles.countdown} aria-hidden="true">
        {Math.max(left, 1)}
      </span>
      <button
        type="button"
        className={styles.undo}
        /* Своя подпись для чтения с экрана: слово «Отменить» в почте есть
           ещё и на кнопке «закрыть письмо без сохранения», а эти два
           действия противоположны по смыслу */
        aria-label="Отменить отправку"
        onClick={onUndo}
        disabled={busy}
      >
        {/* Подпись не меняется на «Отменяем…»: кнопка узкая, и смена текста
            двигала бы её под курсором ровно в момент нажатия */}
        Отменить
      </button>
      <button
        type="button"
        className={styles.dismiss}
        /* Именно «скрыть», а не «закрыть»: крестик убирает плашку, а письмо
           после этого всё равно уходит. Обещать крестиком отмену нельзя. */
        aria-label="Скрыть сообщение"
        title="Скрыть сообщение"
        onClick={onDismiss}
      >
        <IconClose size={14} />
      </button>
    </div>
  );
}
