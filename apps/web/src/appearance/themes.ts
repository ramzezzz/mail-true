/**
 * Реестр тем оформления — единый источник истины.
 *
 * Отсюда берут значения:
 *   - переключатель темы в шапке и раздел «Оформление» настроек
 *     (названия и цвета образцов);
 *   - проверки контраста в tests/themes.test.ts — каждая тема из списка
 *     обязана проходить WCAG AA, иначе ей не место в наборе.
 *
 * Сами CSS-переменные живут в styles/themes.css: цветные темы меняют
 * ТОЛЬКО пять переменных акцента и фон страницы, компоненты о цветах
 * не знают. Значения здесь и в CSS обязаны совпадать — это тоже
 * проверяется тестом, чтобы реестр не разъехался со стилями.
 */

/**
 * Имена тем.
 *
 * У каждой темы есть ПАРА: та же личность на светлой основе и на тёмной.
 * Раньше цветные темы существовали только светлыми — человек, работающий
 * в тёмном интерфейсе, мог выбрать ровно одну расцветку («Тёмная»), и весь
 * набор оттенков был для него закрыт.
 *
 * Имя тёмного варианта ВСЕГДА кончается на `-dark`, и это не украшение:
 * на суффикс опираются стили. Тёмная основа (цвета текста, поверхностей,
 * разделителей) описана в themes.css один раз селектором
 * `[data-theme$='dark']`, а не переписана в каждой теме, и на тот же
 * суффикс смотрят места вне реестра — начертание логотипа в шапке и
 * палитра нижней строки состояния. Иначе каждая следующая тёмная тема
 * требовала бы правки в пяти файлах, о которых легко забыть.
 */
export type ThemeName =
  | 'light'
  | 'dark'
  | 'emerald'
  | 'emerald-dark'
  | 'violet'
  | 'violet-dark'
  | 'coral'
  | 'coral-dark'
  | 'lagoon'
  | 'lagoon-dark'
  | 'sunset'
  | 'sunset-dark'
  | 'wallpaper'
  | 'wallpaper-dark';

/** Явный выбор пользователя; 'system' — следовать prefers-color-scheme. */
export type ThemeSetting = ThemeName | 'system';

export interface ThemeMeta {
  id: ThemeName;
  title: string;
  /** Светлая основа, тёмная или обои — определяет базовые цвета текста. */
  kind: 'light' | 'dark' | 'wallpaper';
  /** Акцент и его ступени (hover/press) — то, что тема переопределяет. */
  accent: string;
  accentHover: string;
  accentPress: string;
  /**
   * Подложка выделенной строки списка. Нейтрально-серая, как в привычных почтовых интерфейсах
   * (#EBECEF — пипетка по эталонные снимки интерфейса), а не тон
   * акцента: тема её не красит. Тёмная берёт свой нейтральный тон.
   */
  selection: string;
  /** Фон страницы вокруг белой карточки (для обоев — усреднённый тон). */
  appBg: string;
  /** Фон карточки контента. */
  contentBg: string;
  /** Основной текст на карточке. */
  textPrimary: string;
  /** Цвет текста на акцентной кнопке. */
  onAccent: string;
}

/**
 * Общее всему тёмному семейству: карточка, текст, подложка выделения.
 *
 * Ровно тот же приём, что у светлых тем: там карточка белая у всех, и
 * цветная тема меняет только акцент и фон страницы. Здесь то же самое,
 * но от тёмной основы — иначе шесть тем разошлись бы в мелочах, а вместе
 * с ними разъехались бы и графики панели управления: их цвета посчитаны
 * ровно под карточку #232324.
 */
const DARK_BASE = {
  kind: 'dark',
  selection: '#3a3a3b',
  contentBg: '#232324',
  textPrimary: '#e1e3e6',
  /*
   * Подпись на акцентной кнопке ТЁМНАЯ, а не белая. На тёмной основе
   * акцент сам по себе светлый (иначе его не видно на карточке), и белый
   * текст на нём давал бы 1,5–2:1.
   */
  onAccent: '#15181d',
} as const;

/**
 * Тёмный близнец цветной темы: тот же тон, что у светлой, но яркость
 * поднята до нормы на тёмной карточке.
 *
 * Акценты не подобраны на глаз: у каждого взят ТОН светлого варианта
 * (например, изумрудные 163°) и поднята светлота ровно настолько, чтобы
 * контраст на карточке совпал с фирменным синим тёмной темы (6,3:1).
 * Поэтому «Изумруд» остаётся изумрудом, а не превращается в мятный.
 */
function darkTwin(
  id: ThemeName,
  title: string,
  accent: string,
  accentHover: string,
  accentPress: string,
  appBg: string,
): ThemeMeta {
  return { id, title, accent, accentHover, accentPress, appBg, ...DARK_BASE };
}

