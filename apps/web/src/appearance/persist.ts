/**
 * Отправка выбранного оформления на сервер — через регистрируемый приёмник.
 *
 * Тему меняют из двух мест (панель в шапке и страница настроек), фон — из
 * третьего, и все три должны попасть на сервер: оформление запоминается
 * за учётной записью, а не за браузером.
 *
 * Приёмник регистрируется, а не импортируется напрямую, по одной причине:
 * иначе получится кольцо импортов. Хранилище состояния (app/store.ts) и
 * фоновые картинки (wallpapers.ts) должны уметь СКАЗАТЬ «выбор изменился»,
 * а тот, кто это отправляет (sync.ts), сам применяет их же функции, когда
 * приходит ответ сервера. Кольцо в модулях ESM работает не всегда и
 * ломается молча — надёжнее развязать его здесь.
 *
 * Второе следствие того же устройства: без зарегистрированного приёмника
 * (тесты, экран входа) всё продолжает работать локально — выбор просто
 * никуда не уходит. Оформление не та вещь, ради которой можно падать.
 */

import type { ThemeSetting } from '@mail-true/shared';

export interface AppearancePatch {
  theme?: ThemeSetting;
  /** 'preset:<id>' | 'custom' */
  wallpaper?: string;
}

type AppearanceSink = (patch: AppearancePatch) => void;

let sink: AppearanceSink | null = null;

/** Подключить отправку на сервер; возвращает функцию снятия. */
export function setAppearanceSink(next: AppearanceSink | null): () => void {
  sink = next;
  return () => {
    if (sink === next) sink = null;
  };
}

/** Сказать «пользователь выбрал вот это». Отправка — дело приёмника. */
export function persistAppearance(patch: AppearancePatch): void {
  sink?.(patch);
}
