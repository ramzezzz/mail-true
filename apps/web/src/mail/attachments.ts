/**
 * Похожи ли байты на PDF.
 *
 * Единственное место, где предпросмотр отдаёт чужой файл встроенному
 * просмотрщику браузера, — поэтому здесь проверяется не заявление, а
 * содержимое. Заголовок `%PDF-` по стандарту стоит в начале, но
 * допускается мусор перед ним, поэтому ищем в первом килобайте.
 *
 * Что это даёт: отправитель не может подсунуть просмотрщику произвольные
 * байты, назвав файл `.pdf`. Не «на всякий случай» — сам просмотрщик тоже
 * чужой код, и кормить его чем попало незачем.
 */
export function looksLikePdf(bytes: Uint8Array): boolean {
  const head = bytes.subarray(0, 1024);
  const marker = [0x25, 0x50, 0x44, 0x46, 0x2d]; // %PDF-
  for (let i = 0; i + marker.length <= head.length; i += 1) {
    let hit = true;
    for (let k = 0; k < marker.length; k += 1) {
      if (head[i + k] !== marker[k]) {
        hit = false;
        break;
      }
    }
    if (hit) return true;
  }
  return false;
}

export interface DecodedText {
  text: string;
  /** Кодировка, которой удалось прочитать: показывается человеку. */
  charset: 'UTF-8' | 'windows-1251';
}

/**
 * Текстовое вложение в строку.
 *
 * Сначала UTF-8 со строгой проверкой (`fatal`), и только если байты ей не
 * являются — windows-1251. Порядок именно такой: неверно угаданная
 * кодировка не ломается, она молча показывает «ÐÐºÑ‚ ÑÐ²ÐµÑ€ÐºÐ¸», и человек
 * решает, что сломан файл. Строгий разбор превращает догадку в проверку.
 *
 * Запасная кодировка — windows-1251, а не latin1: русский `акт.txt`,
 * сохранённый «Блокнотом» лет десять назад, приходит именно в ней.
 */
export function decodeTextPart(bytes: ArrayBuffer | Uint8Array): DecodedText {
  const view = bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes);
  try {
    return { text: stripBom(new TextDecoder('utf-8', { fatal: true }).decode(view)), charset: 'UTF-8' };
  } catch {
    return { text: stripBom(new TextDecoder('windows-1251').decode(view)), charset: 'windows-1251' };
  }
}

/** Метка порядка байтов в начале файла — на экране это лишний символ. */
function stripBom(text: string): string {
  return text.startsWith('﻿') ? text.slice(1) : text;
}
