/**
 * Предпросмотр вложения: что можно показать, чего нельзя и почему.
 *
 * ------------------------------------------------------------------
 * ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ МОДУЛЬ БЕЗ РАЗМЕТКИ
 * ------------------------------------------------------------------
 * Здесь правило безопасности, а не оформление. Решение «этот файл можно
 * открыть в браузере» стоит ровно столько же, сколько такое же решение на
 * сервере (apps/api/src/mail/part-delivery.ts), и должно быть закреплено
 * проверками так же — без поднятия страницы, окна и запросов.
 *
 * ------------------------------------------------------------------
 * ЧЕМ ПОКАЗ ОТЛИЧАЕТСЯ ОТ СКАЧИВАНИЯ
 * ------------------------------------------------------------------
 * Вложение — файл от кого угодно. Если браузер откроет его КАК ДОКУМЕНТ на
 * нашем источнике, документ получит доступ к странице почты и к сессионной
 * куке: сможет прочитать ящик и отправить письмо от имени владельца.
 * Именно поэтому сервер отдаёт вложения `application/octet-stream` с
 * `Content-Disposition: attachment` и `frame-ancestors 'none'` — по прямой
 * ссылке вложение НЕ становится документом ни при каких условиях, и
 * предпросмотр этого не ослабляет: он не ссылается на маршрут выдачи вовсе.
 *
 * Вместо этого интерфейс забирает БАЙТЫ (обычный запрос с кукой, ответ —
 * поток октетов) и сам решает, чем они являются:
 *   - картинка  → `<img>` с blob-адресом. Тег `img` не выполняет ничего:
 *                 даже настоящий SVG в нём остаётся картинкой без скриптов;
 *   - PDF       → рамка со встроенным просмотрщиком браузера (см. ниже);
 *   - текст     → обычный текстовый узел React, как в «Исходном тексте
 *                 письма»: `<script>` в нём остаётся буквами на экране.
 * Тип blob-а берётся ИЗ ЭТОГО СПИСКА, а не из письма: подписать чужие байты
 * как `text/html` отправитель не сможет при всём желании.
 *
 * ------------------------------------------------------------------
 * ЧЕГО ЗДЕСЬ НЕТ И НЕ ДОЛЖНО ПОЯВИТЬСЯ
 * ------------------------------------------------------------------
 * SVG, HTML, XML — это документы, а не картинки: браузер выполняет их
 * содержимое. Их предпросмотра нет и не будет; человеку об этом говорится
 * прямо, а не показывается пустой квадрат. Офисные документы не
 * преобразуются: это отдельная служба и сотни мегабайт памяти (см. пункт 12
 * в docs/gaps.md).
 */

import { formatBytes } from '../layout/FooterStatus';

/** Чем показывать вложение. */
export type PreviewKind = 'image' | 'pdf' | 'text';

export type PreviewVerdict =
  | {
      kind: PreviewKind;
      /** Тип для blob-адреса — НАШ, а не заявленный в письме. */
      blobType: string;
      /** Предел размера для этого рода файлов, байты. */
      maxBytes: number;
    }
  | {
      kind: null;
      /** Почему показать нельзя — готовая фраза для человека. */
      reason: string;
    };

/**
 * Предел предпросмотра картинки и PDF.
 *
 * Не «на всякий случай»: письмо у нас ограничено 25 МБ, и вложение на
 * двадцать мегабайт — обычное дело. Развёрнутая в память картинка на
 * 20 МБ занимает уже не двадцать мегабайт, а ширину × высоту × 4 байта:
 * фотография 12000×9000 — это 432 МБ, и вкладка ложится вместе со всей
 * почтой. Скачать такой файл по-прежнему можно, показать — нет.
 */
export const PREVIEW_MAX_BYTES = 10 * 1024 * 1024;

/**
 * Предел предпросмотра текста — меньше, и намеренно.
 *
 * Текст показывается одним узлом, и десять мегабайт букв в нём — это
 * десятки секунд раскладки, в которые вкладка не отвечает вовсе. Журнал
 * такого размера читают не глазами в браузере.
 */
export const TEXT_PREVIEW_MAX_BYTES = 2 * 1024 * 1024;

/**
 * Растровые картинки — ровно тот же список, что разрешает показывать
 * сервер (apps/api/src/mail/part-delivery.ts). Два списка расходиться не
 * должны, поэтому каждая правка — в обоих местах и с проверкой.
 */
const IMAGE_TYPES = new Set([
  'image/png',
  'image/jpeg',
  'image/gif',
  'image/webp',
  'image/bmp',
  'image/avif',
]);

const IMAGE_EXTENSIONS = new Set(['png', 'jpg', 'jpeg', 'gif', 'webp', 'bmp', 'avif']);

/** Простой текст. HTML и XML сюда не входят — см. RISKY ниже. */
const TEXT_TYPES = new Set(['text/plain', 'text/csv', 'text/markdown']);

const TEXT_EXTENSIONS = new Set(['txt', 'csv', 'md', 'log']);

const PDF_TYPE = 'application/pdf';

/**
 * Типы, которые выглядят безобидно, а являются документами.
 *
 * Ключ — заявленный тип или расширение, значение — что сказать человеку.
 * Отдельный список нужен не ради запрета (запрет и так по умолчанию: всё,
 * чего нет в разрешительных списках, не показывается), а ради ЧЕСТНОГО
 * ответа: «не поддерживается» здесь было бы неправдой — поддержать это
 * технически несложно, мы отказываемся сознательно.
 */
const RISKY = new Map<string, string>([
  ['image/svg+xml', 'SVG — это документ со скриптами внутри, а не картинка.'],
  ['svg', 'SVG — это документ со скриптами внутри, а не картинка.'],
  ['svgz', 'SVG — это документ со скриптами внутри, а не картинка.'],
  ['text/html', 'HTML — это страница, и браузер выполнил бы её содержимое.'],
  ['html', 'HTML — это страница, и браузер выполнил бы её содержимое.'],
  ['htm', 'HTML — это страница, и браузер выполнил бы её содержимое.'],
  ['application/xhtml+xml', 'HTML — это страница, и браузер выполнил бы её содержимое.'],
  ['xhtml', 'HTML — это страница, и браузер выполнил бы её содержимое.'],
  ['text/xml', 'XML браузер открывает как документ, а не как текст.'],
  ['application/xml', 'XML браузер открывает как документ, а не как текст.'],
  ['xml', 'XML браузер открывает как документ, а не как текст.'],
]);

/** Основной тип без параметров и в нижнем регистре. */
export function baseMimeType(mimeType: string | null | undefined): string {
  return (mimeType ?? '').split(';')[0]?.trim().toLowerCase() ?? '';
}

/** Расширение имени файла в нижнем регистре, без точки; '' — если его нет. */
export function fileExtension(filename: string | null | undefined): string {
  const name = filename ?? '';
  const dot = name.lastIndexOf('.');
  if (dot <= 0 || dot === name.length - 1) return '';
  return name.slice(dot + 1).toLowerCase();
}

/**
 * Заявленному типу верить нельзя, но и игнорировать его нельзя.
 *
 * Половина отправителей помечает ВСЕ вложения `application/octet-stream`
 * (так делают старые почтовые программы и часть телефонов), и по типу
 * счёт-фактура в PDF неотличима от архива. Поэтому у безликого типа
 * решает расширение имени — но только в сторону РАЗРЕШИТЕЛЬНЫХ списков,
 * и никогда против явного запрета: `image/svg+xml` с именем `logo.png`
 * остаётся SVG.
 */
const FACELESS_TYPES = new Set(['', 'application/octet-stream', 'binary/octet-stream']);

export interface PreviewCandidate {
  filename: string;
  mimeType: string;
  size: number;
}

/**
 * Что делать с этим вложением: показать (и чем) либо не показывать (и что
 * сказать человеку).
 */
export function decidePreview(att: PreviewCandidate): PreviewVerdict {
  const type = baseMimeType(att.mimeType);
  const ext = fileExtension(att.filename);

  // Явный отказ идёт ПЕРВЫМ: заявленный тип-документ не спасает никакое имя
  const risky = RISKY.get(type) ?? (FACELESS_TYPES.has(type) ? RISKY.get(ext) : undefined);
  if (risky) {
    return { kind: null, reason: `${risky} Такие файлы мы только скачиваем.` };
  }

  const kind = previewKind(type, ext);
  if (!kind) {
    return {
      kind: null,
      reason:
        'Смотреть, не скачивая, можно картинки, PDF и простой текст. ' +
        `${ext ? `Файлы ${ext.toUpperCase()}` : 'Такие файлы'} придётся скачать.`,
    };
  }

  // Пустая часть — это не «нечего показать», это чаще всего сорванная
  // загрузка. Пустой квадрат объяснил бы это хуже, чем одна строка.
  if (att.size <= 0) {
    return { kind: null, reason: 'В этом вложении нет ни одного байта — показывать нечего.' };
  }

  const maxBytes = previewLimitFor(kind);
  if (att.size > maxBytes) {
    return {
      kind: null,
      reason:
        `Файл слишком велик для предпросмотра: ${formatBytes(att.size)} ` +
        `при пределе ${formatBytes(maxBytes)}. Скачайте его и откройте на компьютере.`,
    };
  }

  return { kind, blobType: blobTypeFor(kind, type), maxBytes };
}

/** Предел для этого рода файлов. */
function previewLimitFor(kind: PreviewKind): number {
  return kind === 'text' ? TEXT_PREVIEW_MAX_BYTES : PREVIEW_MAX_BYTES;
}

function previewKind(type: string, ext: string): PreviewKind | null {
  if (IMAGE_TYPES.has(type)) return 'image';
  if (type === PDF_TYPE) return 'pdf';
  if (TEXT_TYPES.has(type)) return 'text';
  if (!FACELESS_TYPES.has(type)) return null;
  if (IMAGE_EXTENSIONS.has(ext)) return 'image';
  if (ext === 'pdf') return 'pdf';
  if (TEXT_EXTENSIONS.has(ext)) return 'text';
  return null;
}

/**
 * Тип blob-адреса. Берётся из наших списков: заявленный тип принимается
 * только если он и сам в списке, иначе подставляется безопасный по роду.
 * Текст blob-ом не показывается вовсе — он идёт в разметку текстовым узлом.
 */
function blobTypeFor(kind: PreviewKind, declared: string): string {
  if (kind === 'pdf') return PDF_TYPE;
  if (kind === 'image') return IMAGE_TYPES.has(declared) ? declared : 'image/png';
  return 'text/plain';
}

/**
 * Есть ли у этого РОДА файлов предпросмотр — по этому признаку на карточке
 * появляется «глаз».
 *
 * Размер здесь намеренно НЕ учитывается, хотя он и решает, покажем ли мы
 * файл в итоге. Иначе снимок на 11 МБ выглядел бы как файл, который вообще
 * нельзя посмотреть, — и человек не узнал бы, что дело в размере и что
 * достаточно скачать. Открытое окно скажет это словами и предложит
 * скачивание; развернуть в память 11 МБ оно при этом не пытается, отказ
 * принимается по описи вложения, до единого запрошенного байта.
 */
export function canPreview(att: PreviewCandidate): boolean {
  const type = baseMimeType(att.mimeType);
  const ext = fileExtension(att.filename);
  if (RISKY.has(type) || (FACELESS_TYPES.has(type) && RISKY.has(ext))) return false;
  return previewKind(type, ext) !== null;
}

