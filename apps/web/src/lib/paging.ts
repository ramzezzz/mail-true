/**
 * Постраничная подгрузка списка писем.
 *
 * Сервер отдаёт не больше сотни писем за запрос и вместе с ними — `total`
 * (в живом ящике это 187 писем при limit=100). Раньше интерфейс запрашивал
 * ровно одну страницу с `offset: 0`, `total` не использовал и подгрузки не
 * имел: всё, что дальше первой сотни, было недостижимо — ни прокруткой, ни
 * кнопкой. Здесь — арифметика страниц, чтобы её можно было проверить
 * отдельно от компонентов.
 */

/** Минимум, который нужен от страницы ответа `GET /api/messages`. */
export interface PageLike {
  items: readonly unknown[];
  total: number;
  offset: number;
  limit: number;
}

/** Сколько писем уже загружено во всех полученных страницах. */
export function loadedCount(pages: readonly PageLike[]): number {
  return pages.reduce((sum, page) => sum + page.items.length, 0);
}

/** Сколько всего писем подходит под запрос (по последней странице). */
export function totalCount(pages: readonly PageLike[]): number {
  const last = pages[pages.length - 1];
  return last ? last.total : 0;
}

/**
 * Смещение следующей страницы или undefined, если загружено всё.
 *
 * Считается по ЗАПРОШЕННОМУ куску (`offset + limit`), а не по числу
 * полученных писем. Разница видна не сразу, но ломает список целиком.
 *
 * Сервер режет ПОЗИЦИОННО: он сортирует все подходящие письма и берёт
 * ломоть `slice(offset, offset + limit)`. Сколько писем из этого ломтя
 * доедет до ответа — отдельный вопрос: письмо могли удалить между поиском
 * и выборкой, а у списка переписок строка без единого уцелевшего письма
 * просто не строится. Ответ приходит короче — и счёт «по полученным»
 * просил следующую страницу с меньшего смещения, то есть С ЗАХОДОМ НА
 * УЖЕ ПОКАЗАННОЕ: строки задваивались (ломая выделение и ключи
 * виртуализации), а письмо, попавшее в перекрытие с другой стороны,
 * не показывалось вовсе.
 *
 * Повторы, которые всё-таки приходят (между подгрузками пришла новая
 * почта, и весь список сдвинулся), снимает `dedupeById` при склейке.
 */
export function nextPageOffset(pages: readonly PageLike[]): number | undefined {
  if (pages.length === 0) return 0;
  const last = pages[pages.length - 1];
  // Пустая страница — дальше идти некуда, иначе крутились бы вечно
  if (!last || last.items.length === 0) return undefined;
  const next = last.offset + last.limit;
  if (next >= last.total) return undefined;
  return next;
}

/**
 * Склейка страниц без повторов.
 *
 * Одно и то же письмо приезжает дважды, когда список сдвинулся между
 * подгрузками: пришло новое письмо — и то, что было последним на первой
 * странице, оказалось первым на второй. Двойная строка в списке — это не
 * косметика: у неё тот же идентификатор, поэтому виртуализация получает
 * два узла с одним ключом, а галочка на такой строке ставится сразу в
 * двух местах.
 *
 * Побеждает ПЕРВОЕ вхождение: оно уже нарисовано и, возможно, выделено.
 */
export function dedupeById<T extends { id: string }>(items: readonly T[]): T[] {
  const seen = new Set<string>();
  const out: T[] = [];
  for (const item of items) {
    if (seen.has(item.id)) continue;
    seen.add(item.id);
    out.push(item);
  }
  return out;
}

/** Есть ли что подгружать. */
export function hasMore(pages: readonly PageLike[]): boolean {
  return nextPageOffset(pages) !== undefined;
}

/*
 * Подписи «Показано 100 из 187» здесь больше нет: такого элемента в привычных почтовых интерфейсах
 * не существует, и из списка она убрана вместе с ней самой.
 */

/**
 * Подпись кнопки «Выделить все».
 *
 * Выделить можно только загруженные письма: у невыгруженных нет
 * идентификаторов. Пока загружено не всё, честно говорим, сколько
 * именно выделяем, — раньше кнопка обещала «все», а выделяла сотню.
 */
export function selectAllLabel(loaded: number, total: number): string {
  if (total <= loaded) return 'Выделить все';
  return `Выделить загруженные (${loaded} из ${total})`;
}

/**
 * Подпись кнопки «Отметить все прочитанными».
 *
 * Ровно та же беда, что была у соседней кнопки, и то же лечение.
 * Отметить можно только загруженные письма: у невыгруженных нет
 * идентификаторов, а отдельного «пометь всю папку» в API нет.
 *
 * Пока загружено не всё, кнопка обещала «все» и отмечала сотню: в папке с
 * четырьмя тысячами непрочитанных счётчик падал на сотню и замирал.
 * Человек жал ещё раз — снова сотня. Ничего не сломано, а выглядит как
 * поломка.
 */
export function markAllReadLabel(loaded: number, total: number): string {
  if (total <= loaded) return 'Отметить все прочитанными';
  return `Отметить загруженные (${loaded} из ${total})`;
}
