/**
 * Арифметика жестов: смахивание строки списка и «потянуть вниз — обновить».
 *
 * Вынесено из компонентов отдельным модулем нарочно. Жест — это не только
 * обработчик касания: это пороги, сопротивление и правило «доведён или нет»,
 * от которых зависит, можно ли жест отменить. Здесь их видно целиком и здесь
 * их можно проверить, не изображая палец в jsdom.
 */

/** Сдвиг, после которого жест считается доведённым и действие сработает. */
export const SWIPE_TRIGGER = 88;

/**
 * Сдвиг, с которого мы вообще перехватываем касание. Пока палец не отъехал
 * на столько, событие остаётся у прокрутки: иначе список переставал листаться
 * от малейшего дрожания пальца по горизонтали.
 */
export const SWIPE_START = 12;

/** Дальше этого строка не уезжает, сколько ни тяни. */
export const SWIPE_MAX = 132;

/** Ход «потянули вниз», после которого отпускание запускает обновление. */
export const PULL_TRIGGER = 64;

/** Дальше этого список не оттягивается. */
export const PULL_MAX = 96;

/** Что произойдёт со строкой, если отпустить палец прямо сейчас. */
export type SwipeAction = 'archive' | 'delete';

/**
 * Куда уедет письмо, если отпустить при таком сдвиге.
 *
 * `null` — жест не доведён: строка обязана вернуться на место. Это и есть
 * отмена. Отдельной кнопки «передумал» здесь не нужно — достаточно
 * не доводить палец до порога или увести его обратно.
 */
export function swipeAction(dx: number): SwipeAction | null {
  if (dx >= SWIPE_TRIGGER) return 'archive';
  if (dx <= -SWIPE_TRIGGER) return 'delete';
  return null;
}

/**
 * Насколько сдвинуть строку при таком движении пальца.
 *
 * До порога строка идёт за пальцем один к одному — иначе жест ощущается
 * ватным и непонятно, сколько ещё тянуть. За порогом ход тормозится: строка
 * упирается, и это единственный отклик, который говорит «дальше некуда,
 * отпускай».
 */
export function swipeOffset(dx: number): number {
  const sign = dx < 0 ? -1 : 1;
  const value = Math.abs(dx);
  if (value <= SWIPE_TRIGGER) return dx;
  const over = value - SWIPE_TRIGGER;
  return sign * Math.min(SWIPE_MAX, SWIPE_TRIGGER + over * 0.35);
}

/**
 * Горизонтальный ли это жест.
 *
 * Требование к перевесу (в 1.4 раза), а не просто `|dx| > |dy|`: палец
 * на телефоне никогда не идёт строго по прямой, и при равном условии
 * вертикальная прокрутка списка срывалась в смахивание строки.
 */
export function isHorizontalSwipe(dx: number, dy: number): boolean {
  return Math.abs(dx) >= SWIPE_START && Math.abs(dx) > Math.abs(dy) * 1.4;
}

/**
 * Ход «потянули вниз» с сопротивлением: палец прошёл `dy`, список отъехал
 * вдвое меньше. Оттягивание вверх не считается — там обычная прокрутка.
 */
export function pullDistance(dy: number): number {
  if (dy <= 0) return 0;
  return Math.min(PULL_MAX, dy * 0.5);
}

/** Хватит ли такого хода, чтобы отпускание обновило список. */
export function pullArmed(distance: number): boolean {
  return distance >= PULL_TRIGGER;
}
