/**
 * Кому адресовано письмо — строкой под темой.
 *
 * ------------------------------------------------------------------
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ
 * ------------------------------------------------------------------
 * Подпись нужна в двух местах — на странице письма и в развёрнутой
 * переписке, — и в обоих раньше стояло своё «вам». На странице письма по
 * условию «получатель ровно один», в переписке — просто зашитой строкой
 * в разметке. Адрес учётной записи при этом не спрашивался нигде, и в
 * «Отправленных» каждое письмо сообщало человеку, что он написал его сам
 * себе.
 *
 * Здесь это правило записано один раз: «вам» — только когда единственный
 * получатель и есть открытый ящик.
 */
import type { MailAddress } from '@mail-true/shared';

/** Что показать в строке «Кому». Пусто — получателей нет, строки не будет. */
export function recipientLabel(
  to: readonly Pick<MailAddress, 'address' | 'name'>[],
  accountAddress: string,
): string {
  const me = accountAddress.trim().toLowerCase();
  const onlyMe = me !== '' && to.length === 1 && to[0]?.address.toLowerCase() === me;
  if (onlyMe) return 'вам';
  return to.map((a) => a.name?.trim() || a.address).join(', ');
}
