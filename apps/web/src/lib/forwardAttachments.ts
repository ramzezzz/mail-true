/**
 * Перенос вложений в пересылаемое письмо.
 *
 * ------------------------------------------------------------------
 * ЗАЧЕМ ЭТО ОТДЕЛЬНЫМ ШАГОМ
 * ------------------------------------------------------------------
 * «Переслать» собирало из исходного письма только тему и цитату тела.
 * Вложения молча отбрасывались: человек открывал письмо со счётом,
 * нажимал «Переслать», писал «см. вложение» и отправлял — получатель
 * получал письмо без файла. Ни предупреждения, ни следа.
 *
 * Само письмо приложить целиком умеет соседний пункт («Переслать как
 * вложение»), но это другое действие с другим результатом: там приходит
 * .eml, который ещё надо открыть. Обычная пересылка обязана донести
 * файлы так же, как их видел отправитель.
 *
 * ------------------------------------------------------------------
 * ПОЧЕМУ ЧЕРЕЗ ЗАГРУЗКУ, А НЕ ССЫЛКОЙ
 * ------------------------------------------------------------------
 * Тем же путём, каким вложение прикрепляют руками из другого письма
 * (compose/MailAttachmentPicker.tsx): часть письма скачивается и
 * загружается обратно обычным файлом. Так пересланная копия живёт своей
 * жизнью — исходное письмо можно удалить, и пересылка от этого не
 * испортится.
 *
 * ------------------------------------------------------------------
 * ЧТО ПРИ ОТКАЗЕ
 * ------------------------------------------------------------------
 * Уже перенесённое остаётся: оно на сервере и оплачено ожиданием. О
 * непереехавших файлах говорится вслух — молчание здесь означало бы ровно
 * ту беду, которую чиним: человек уверен, что вложения на месте.
 */
import type { Message } from '@mail-true/shared';
import { api } from '../api';
import type { ComposeAttachment } from '../app/store';

export interface ForwardAttachmentsResult {
  attachments: ComposeAttachment[];
  /** Имена файлов, которые перенести не удалось. Пусто — всё на месте. */
  failed: string[];
}

/**
 * Скачивает вложения письма и загружает их обратно как файлы черновика.
 *
 * Встроенные картинки (те, что показываются прямо в теле) не переносятся:
 * они уже внутри цитируемой разметки, и вторая копия приехала бы к
 * получателю отдельным файлом с именем вида `image001.png`.
 */
export async function collectForwardAttachments(
  message: Message,
): Promise<ForwardAttachmentsResult> {
  const wanted = (message.attachments ?? []).filter((item) => !item.inline);
  const attachments: ComposeAttachment[] = [];
  const failed: string[] = [];

  for (const item of wanted) {
    try {
      const blob = await api.getMessagePart(message.id, item.partId);
      const file = new File([blob], item.filename, {
        type: item.mimeType || blob.type || 'application/octet-stream',
      });
      const uploaded = await api.uploadAttachment(file);
      attachments.push({
        id: uploaded.id,
        filename: uploaded.filename,
        size: uploaded.size,
      });
    } catch {
      // Причина каждого отказа человеку не нужна — ему нужно имя файла,
      // которого не будет в письме.
      failed.push(item.filename);
    }
  }

  return { attachments, failed };
}
