/**
 * Один признак: работаем ли на заглушечных данных.
 *
 * Вынесен в отдельный крошечный модуль намеренно. Признак нужен не только
 * выбору реализации API, но и клиентам отдельных разделов (метки,
 * уведомления, оформление, логотипы отправителей, отложенные письма) —
 * каждый из них на заглушках обязан честно сказать «возможности нет»,
 * а не стучаться в несуществующий адрес.
 *
 * Импортировать его из `api/index.ts` они не могут без последствий: тот
 * тянет за собой все реализации сразу, и проверка, которой нужно всего
 * лишь выключить заглушки, поднимала бы половину приложения. Здесь же
 * подменить нечего, кроме самого признака:
 *
 *   vi.mock('../src/api/mockFlag', () => ({ useMocks: false }));
 *
 * Значение вычисляется один раз при загрузке — как и раньше: переключать
 * режим посреди работы нельзя, иначе половина экрана осталась бы на
 * заглушках, а половина ушла бы на сервер.
 */

const flag = import.meta.env.VITE_API_MOCK as string | undefined;

/**
 * По умолчанию в dev-режиме работают заглушки, в собранном виде — нет.
 *   VITE_API_MOCK=0 — ходить в настоящий /api/* даже в dev;
 *   VITE_API_MOCK=1 — заглушки принудительно (в том числе в prod-сборке).
 */
export const useMocks = flag === '1' || (import.meta.env.DEV && flag !== '0');
