/**
 * «Чей это браузер» — отпечаток открытого ящика для Service Worker.
 *
 * ------------------------------------------------------------------
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ
 * ------------------------------------------------------------------
 * Когда включено «класть содержимое в push», работник рисует окно из
 * того, что приехало внутри push, и в сеть не выходит вовсе. Единственная
 * защита от показа чужой темы на общем компьютере — сверка отпечатка
 * ящика, который прислала страница, с тем, что пришёл в push.
 *
 * Отпечаток при этом сообщался ровно из одного места: из запроса
 * состояния раздела «Уведомления». То есть он менялся только у того, кто
 * в этот раздел ЗАШЁЛ. Вход, выход и смена ящика его не трогали, а
 * обещанного в работнике «при выходе — пустым значением» не делал вообще
 * никто.
 *
 * Отсюда живой сценарий: A включил уведомления с содержимым и закрыл
 * вкладку, не нажав «Выйти» (выход подписку снимает — тот путь закрыт);
 * наблюдение на сервере живёт ещё до суток; за тот же браузер сел B и
 * вошёл под собой. Приходит письмо A — работник сверяет его отпечаток с
 * отпечатком A, оставшимся в хранилище, сверка проходит, и B видит
 * отправителя и тему чужого письма.
 *
 * Поэтому отпечаток считается ЗДЕСЬ и сообщается на каждом изменении
 * сессии. Тем же способом, что на сервере (accountKey): первые 16 знаков
 * SHA-256 от адреса в нижнем регистре. Хэш, а не адрес: значение лежит в
 * хранилище браузера и ездит в теле push через посторонний сервер.
 */

/** Первые 16 знаков SHA-256 от адреса — тот же расчёт, что на сервере. */
export async function accountKeyOf(email: string): Promise<string | null> {
  const subtle = globalThis.crypto?.subtle;
  // Без защищённого соединения subtle недоступен. Это не отказ: без
  // отпечатка работник спросит сервер, а тот сверит сессию сам.
  if (!subtle) return null;
  const bytes = new TextEncoder().encode(email.trim().toLowerCase());
  const digest = await subtle.digest('SHA-256', bytes);
  return [...new Uint8Array(digest)]
    .map((b) => b.toString(16).padStart(2, '0'))
    .join('')
    .slice(0, 16);
}

/**
 * Сообщает работнику, чей это браузер. `null` — ничей (выход).
 *
 * Отказ здесь ничего не ломает: без отпечатка работник спросит сервер, а
 * не сможет — покажет безымянное «Новое письмо».
 */
export async function announceOwnKey(email: string | null): Promise<void> {
  if (typeof navigator === 'undefined' || !('serviceWorker' in navigator)) return;
  const key = email === null ? '' : ((await accountKeyOf(email).catch(() => null)) ?? '');
  await navigator.serviceWorker.ready
    .then((registration) => {
      registration.active?.postMessage({ type: 'mt-own-key', key });
    })
    .catch(() => undefined);
}
