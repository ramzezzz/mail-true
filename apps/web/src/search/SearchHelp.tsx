/**
 * Подсказка «как искать точнее»: список операторов с примерами.
 *
 * У mail.ru эту роль играет расширенный поиск — форма с полями «От кого»,
 * «Кому», «Тема», «Дата», «С вложениями» (docs/features-mailru.md). Форму
 * мы не повторяем намеренно: она даёт ровно те же условия, но не оставляет
 * следа. Заполнив её однажды, человек не может ни повторить поиск с чужого
 * устройства, ни переслать ссылку, ни сохранить запрос — потому что
 * запроса как текста не существует. Операторы в строке — тот же набор
 * условий, но записанный так, что его видно, можно поправить, сохранить
 * под именем и отправить ссылкой.
 *
 * Взамен формы человеку нужно знать, какие слова понимаются. Отсюда этот
 * список: он собран из той же таблицы, по которой работает разборщик
 * (packages/shared/src/search.ts), поэтому обещать несуществующий оператор
 * не может.
 *
 * Нажатие по примеру дописывает его в строку поиска: подсказку, которую
 * надо перепечатывать руками, читают один раз и больше не открывают.
 */

import { SEARCH_OPERATORS } from '@mail-true/shared';
import styles from './SearchHelp.module.css';

export interface SearchHelpProps {
  /** Дописать пример в поисковую строку. */
  onPick?: ((sample: string) => void) | undefined;
}

export function SearchHelp({ onPick }: SearchHelpProps) {
  return (
    <div className={styles.help}>
      <div className={styles.title}>Как искать точнее</div>
      <p className={styles.lead}>
        Условия пишутся прямо в строке поиска. Слова, которые не похожи ни на одно условие, ищутся
        как обычно — двоеточие в теме письма ничего не ломает.
      </p>
      <ul className={styles.list}>
        {SEARCH_OPERATORS.map((op) => (
          <li key={op.sample} className={styles.item}>
            {onPick ? (
              <button
                type="button"
                className={styles.sample}
                title="Добавить в строку поиска"
                onClick={() => onPick(op.sample)}
              >
                {op.sample}
              </button>
            ) : (
              <span className={styles.sample}>{op.sample}</span>
            )}
            <span className={styles.hint}>{op.hint}</span>
            {/* Латинский синоним нужен тем, кто пришёл из Gmail: они наберут
                `from:` не задумываясь, и отвечать им пустотой не за что. */}
            <span className={styles.latin}>{op.latin}</span>
          </li>
        ))}
      </ul>
      <p className={styles.footer}>
        Условия складываются: <b>от:волкова есть:вложение новее:1мес</b> — письма от Волковой с
        вложением за последний месяц. Несколько слов подряд берутся в кавычки:{' '}
        <b>тема:&quot;годовой отчёт&quot;</b> (ёлочки тоже понимаются).
      </p>
    </div>
  );
}
