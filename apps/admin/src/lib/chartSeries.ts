/**
 * Цвет ШТРИХОВКИ поверх заливки.
 *
 * ------------------------------------------------------------------
 * ПОЧЕМУ ЭТО ЦВЕТ КАРТОЧКИ, А НЕ БЕЛЫЙ
 * ------------------------------------------------------------------
 * Раньше штриховка была прибита белым (`rgb(255 255 255 / 55%)`) прямо в
 * коде графиков. На белой карточке это ещё как-то работало — цвета рядов
 * там тёмные, — а в тёмной теме и в графите цвета рядов СВЕТЛЫЕ: белая
 * штриховка по светло-зелёному давала контраст 1,39:1, по янтарному —
 * 1,32:1. При пороге 3:1 (WCAG 2.1, 1.4.11) это значит «не видно».
 *
 * И это не косметика. Узор — второй, нецветовой признак ряда: он для тех,
 * кто не различает красный и зелёный, и для чёрно-белой печати. Невидимый
 * узор не помогает никому: не различающий цвета человек видел два
 * одинаковых столбца ровно там, где ему обещали различие.
 *
 * Теперь штриховка — цвет ПОВЕРХНОСТИ, на которой лежит график, и это не
 * подобранное значение, а свойство: узор «прорезает» заливку до карточки.
 * Отсюда и контраст: цвета рядов уже обязаны давать к карточке не меньше
 * 4,5:1 (tests/chartContrast.test.ts), а штриховка от неё неотличима —
 * значит, тот же запас достаётся и ей, в каждой теме и без отдельной
 * подгонки при добавлении новой.
 */
export function chartPatternInk(surface: ChartSurface): string {
  return CHART_SURFACES[surface];
}

/** Узор заливки — второй, нецветовой признак ряда. */
export type ChartPattern = 'solid' | 'diagonal' | 'grid' | 'dots' | 'reverse' | 'dense';

/** Описание одного ряда данных. */
export interface ChartSeries {
  id: string;
  /** Слово в легенде — оно, а не цвет, объясняет ряд. */
  title: string;
  hue: ChartHue;
  /**
   * Штриховка линии (stroke-dasharray). Пустая строка — сплошная.
   * Различает ряды там, где цвет не работает: чёрно-белая печать,
   * дальтонизм, снимок экрана с искажёнными цветами.
   */
  dash: string;
  /** Узор заливки для столбцов, площадей и долей. */
  pattern: ChartPattern;
}

/** Цвет слота на заданной поверхности. */
export function chartColor(surface: ChartSurface, hue: ChartHue): string {
  return CHART_PALETTE[surface][hue];
}

