/**
 * Готовый шаблон файла для импорта.
 *
 * Раньше образец был показан на странице текстом, и его приходилось выделять
 * мышью и копировать — с риском утащить лишний пробел или потерять перевод
 * строки. Теперь это скачиваемый файл: открывается в Excel или LibreOffice
 * как есть, остаётся заменить строки-примеры своими.
 */

/** Имя, под которым файл сохраняется у человека. */
export const TEMPLATE_FILENAME = 'mail-true-import-template.csv';

/**
 * Заголовок и две строки-примера: одна с паролем и квотой, вторая — без,
 * чтобы сразу было видно, что оба столбца необязательны.
 */
export const TEMPLATE_ROWS: readonly string[] = [
  'email,name,password,quota',
  'ivan@mail.local,Иван Петров,parol12345,1G',
  'anna@mail.local,Анна Смирнова,,500M',
];

/**
 * Содержимое файла. Переводы строк — CRLF по RFC 4180: Excel в Windows
 * иначе показывает весь файл одной строкой.
 */
export function templateCsv(): string {
  return `${TEMPLATE_ROWS.join('\r\n')}\r\n`;
}

/**
 * Тот же текст с меткой порядка байтов. Без неё Excel читает файл в
 * системной кодировке и превращает русские имена в «ÐÐ²Ð°Ð½».
 */
export function templateCsvWithBom(): string {
  return `﻿${templateCsv()}`;
}
