/**
 * Что сказать администратору о судьбе личного файла правил ящика.
 *
 * Дефект, ради которого это вынесено из разметки и покрыто тестом:
 * состояние синхронизации несёт ДВА разных признака, а показывалось одним.
 * «Не скомпилировано» на стенде означает всего лишь, что рядом с сервером
 * приложения нет sievec, — правила при этом записаны и работают, их
 * соберёт сам Dovecot при первой доставке. Интерфейс же объявлял на это
 * «фильтры и автоответчик работать не будут», то есть пугал впустую при
 * каждом сохранении в самой обычной установке. Настоящая беда — когда
 * файл НЕ записан: тогда в ящике остались прежние правила, а человек
 * уверен, что поменял их.
 */
import type { SieveSyncState } from '../api/types';

export interface SieveNotice {
  tone: 'success' | 'info' | 'error';
  text: string;
}

export function sieveNotice(state: SieveSyncState | null): SieveNotice | null {
  if (!state) return null;

  if (!state.written) {
    return {
      tone: 'error',
      text:
        'Настройки сохранены в базе, но личный файл правил в ящике НЕ обновлён: ' +
        `${state.error || 'причина неизвестна'}. В ящике действуют прежние правила.`,
    };
  }

  if (!state.ok) {
    return {
      tone: 'info',
      text:
        `Файл правил в ящике обновлён (${String(state.activeRules)} действующих правил), ` +
        `но проверить его этим окружением нечем: ${state.error}`,
    };
  }

  return {
    tone: 'success',
    text: `Личный файл правил ящика переписан: ${String(state.activeRules)} действующих правил.`,
  };
}
