/**
 * Счёт в списках антиспама склоняется по-русски.
 *
 * ------------------------------------------------------------------
 * ЧТО БЫЛО
 * ------------------------------------------------------------------
 * Слово «балла» было приписано к числу намертво: `{scoreText(score)} балла`.
 * Списки показывали «-10 балла», «+12 балла», «+8 балла» — неграмотно ровно
 * там, где администратор взвешивает, чего стоит запись в белом или чёрном
 * списке. Замечено пользователем на живой панели.
 */
import { describe, expect, it } from 'vitest';
import { scoreWithWord } from '../src/pages/SpamPage';

describe('счёт со словом', () => {
  it('десятки — «баллов»', () => {
    expect(scoreWithWord(-10)).toBe('-10 баллов');
    expect(scoreWithWord(12)).toBe('+12 баллов');
    expect(scoreWithWord(-6)).toBe('-6 баллов');
    expect(scoreWithWord(8)).toBe('+8 баллов');
  });

  it('единица — «балл», и со знаком тоже', () => {
    expect(scoreWithWord(1)).toBe('+1 балл');
    expect(scoreWithWord(-1)).toBe('-1 балл');
    expect(scoreWithWord(21)).toBe('+21 балл');
  });

  it('двойка, тройка, четвёрка — «балла»', () => {
    expect(scoreWithWord(2)).toBe('+2 балла');
    expect(scoreWithWord(-3)).toBe('-3 балла');
    expect(scoreWithWord(24)).toBe('+24 балла');
  });

  it('от одиннадцати до четырнадцати — «баллов», а не «балл»', () => {
    // Ловушка русского счёта: последняя цифра 1, но слово множественное.
    expect(scoreWithWord(11)).toBe('+11 баллов');
    expect(scoreWithWord(-12)).toBe('-12 баллов');
    expect(scoreWithWord(14)).toBe('+14 баллов');
  });

  it('ноль — «баллов»', () => {
    expect(scoreWithWord(0)).toBe('0 баллов');
  });

  it('дробный счёт — «балла» в единственном числе', () => {
    // У 2,5 последняя цифра 5, и обычное правило дало бы «баллов»;
    // по-русски же «два с половиной балла».
    expect(scoreWithWord(2.5)).toBe('+2.5 балла');
    expect(scoreWithWord(-11.8)).toBe('-11.8 балла');
  });
});
