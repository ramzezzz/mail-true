/**
 * В журнале служб видно дату, а не только время.
 *
 * ------------------------------------------------------------------
 * ЧТО БЫЛО
 * ------------------------------------------------------------------
 * У строки показывалось «03:14:02» — и всё. Пока смотришь последние
 * минуты, разницы нет; но лента прокручивается вверх на весь файл
 * журнала, а файл живёт неделю. Отмотав к ночному отказу Postfix,
 * администратор не мог сказать, сегодняшний он или прошлого вторника, —
 * а именно этот вопрос и задают, разбираясь, почему письма не доходили
 * в конкретный день.
 *
 * Дублировать дату в каждой строке нельзя: она одинакова у сотен подряд
 * и отнимает ширину у текста сообщения. Поэтому дата стоит там, где
 * меняется, — как в переписке.
 */
import { describe, expect, it } from 'vitest';
import { dayBreaks, dayKeyOf, dayTitleOf } from '../src/pages/LogsPage';

/** Строка ленты в том виде, в каком её видит разметка. */
function line(offset: number, at: string | null) {
  return { offset, at };
}

/**
 * Момент по МЕСТНОМУ времени сервера.
 *
 * Записывать в тестах UTC нельзя: день считается по часовому поясу
 * машины, и «восьмое 23:59 UTC» в Москве — уже девятое. Тест на этом
 * ловится первым, поэтому моменты собираются местные, как их и видит
 * администратор в панели.
 */
function moment(day: number, hour: number, minute = 0): string {
  return new Date(2026, 7, day, hour, minute, 0).toISOString();
}

describe('границы суток в журнале', () => {
  it('первая строка ленты открывает день: дата видна сразу', () => {
    const breaks = dayBreaks([line(10, moment(9, 3, 14))]);
    expect(breaks.has(10)).toBe(true);
  });

  it('внутри одного дня разделитель ровно один', () => {
    const breaks = dayBreaks([
      line(1, moment(9, 3, 14)),
      line(2, moment(9, 9)),
      line(3, moment(9, 23, 59)),
    ]);
    expect([...breaks]).toEqual([1]);
  });

  it('на смене суток появляется новый разделитель', () => {
    const breaks = dayBreaks([
      line(1, moment(8, 23, 59)),
      line(2, moment(9, 0, 1)),
      line(3, moment(9, 0, 2)),
      line(4, moment(10, 0, 0)),
    ]);
    expect([...breaks]).toEqual([1, 2, 4]);
  });

  it('строка без разбираемого времени не рвёт день и не даёт пустой подписи', () => {
    const breaks = dayBreaks([
      line(1, moment(9, 10)),
      line(2, null),
      line(3, 'мусор вместо времени'),
      line(4, moment(9, 11)),
    ]);
    // Продолжение того же дня: лишнего разделителя не появилось.
    expect([...breaks]).toEqual([1]);
  });

  it('ключ дня считается по местному времени, а не по UTC', () => {
    // Ровно то, ради чего ключ собирается вручную: у сервера в Москве
    // час ночи девятого — это девятое, хотя в UTC ещё восьмое.
    const local = new Date(2026, 7, 9, 1, 0, 0);
    expect(dayKeyOf(local.toISOString())).toBe('2026-08-09');
  });

  it('подпись разделителя называет день, месяц, год и день недели', () => {
    const title = dayTitleOf(new Date(2026, 7, 9, 12, 0, 0).toISOString());
    expect(title).toContain('9');
    expect(title).toContain('август');
    expect(title).toContain('2026');
    expect(title).toContain('воскресенье');
  });
});
