#!/usr/bin/env bash
# ==================================================================
# Скачать базу «адрес → страна»
# ==================================================================
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ ШАГ, А НЕ ЧАСТЬ УСТАНОВКИ
# ------------------------------------------------------------------
# База нужна только тем, кто собирается ограничивать вход по стране или
# хотя бы видеть её в журнале. Тянуть десяток мегабайт с чужого сайта при
# каждой установке — значит делать установку зависимой от доступности
# этого сайта ради возможности, которой большинство не воспользуется.
#
# Поэтому: поставили сервер — работает без базы; захотели страну —
# запустили этот скрипт.
#
# ОТКУДА БЕРЁТСЯ
# ------------------------------------------------------------------
# DB-IP Country Lite: свободная страновая база, обновляется ежемесячно,
# скачивается БЕЗ регистрации и ключей (в отличие от MaxMind GeoLite2, где
# нужен аккаунт и лицензионный ключ — на сервере, который ставят по
# инструкции, это лишний шаг с чужим паролем).
#
# Лицензия CC BY 4.0: требуется указание источника. Оно есть в
# docs/install.md и в самом файле — первой строкой комментария.
#
# ЧТО ИМЕННО СКАЧИВАЕТСЯ
# ------------------------------------------------------------------
# Страновая, а не городская. Города, координаты и провайдер нам не нужны
# ни для одной задачи, а весит городская база в разы больше и обновлять
# её пришлось бы чаще. Мы отвечаем ровно на один вопрос: из какой страны
# пришёл вход.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
TARGET_DIR="${GEOIP_DIR:-$REPO_DIR/infra/data/geoip}"
TARGET="$TARGET_DIR/country.csv"

# Файлы называются по месяцу выпуска. Берём текущий месяц, при неудаче —
# предыдущий: новый файл выкладывают не в полночь первого числа, и в
# первые дни месяца ссылка на «этот месяц» ещё не работает.
MONTHS=("$(date -u +%Y-%m)" "$(date -u -d '1 month ago' +%Y-%m 2>/dev/null || date -u -v-1m +%Y-%m)")

mkdir -p "$TARGET_DIR"

ok=''
for month in "${MONTHS[@]}"; do
    url="https://download.db-ip.com/free/dbip-country-lite-${month}.csv.gz"
    printf 'Скачиваем базу стран за %s…\n' "$month"
    if curl -fsSL --max-time 300 "$url" -o "$TARGET_DIR/.country.csv.gz"; then
        ok="$month"
        break
    fi
    printf '  за %s не вышло, пробуем предыдущий месяц\n' "$month"
done

if [ -z "$ok" ]; then
    printf 'Не удалось скачать базу. Проверьте доступ в интернет и повторите.\n' >&2
    exit 1
fi

# Распаковываем во временный файл и подменяем целиком: сервер читает файл
# при старте, и он не должен застать его наполовину записанным.
gunzip -c "$TARGET_DIR/.country.csv.gz" > "$TARGET_DIR/.country.csv.new"
rm -f "$TARGET_DIR/.country.csv.gz"

lines="$(wc -l < "$TARGET_DIR/.country.csv.new" | tr -d ' ')"
if [ "$lines" -lt 1000 ]; then
    printf 'Скачанный файл подозрительно мал (%s строк) — не заменяем прежний.\n' "$lines" >&2
    rm -f "$TARGET_DIR/.country.csv.new"
    exit 1
fi

{
    printf '# Источник: DB-IP Country Lite (%s), лицензия CC BY 4.0, https://db-ip.com\n' "$ok"
    cat "$TARGET_DIR/.country.csv.new"
} > "$TARGET"
rm -f "$TARGET_DIR/.country.csv.new"
chmod 644 "$TARGET"

printf 'Готово: %s (%s строк, выпуск %s)\n' "$TARGET" "$lines" "$ok"
printf '\nЧтобы страна начала учитываться, задайте в infra/.env:\n'
printf '  GEOIP_LOGIN_POLICY=log      # писать страну в журнал, никого не блокировать\n'
printf '  GEOIP_LOGIN_POLICY=allow    # пускать только из стран списка\n'
printf '  GEOIP_ALLOWED_COUNTRIES=RU,BY,KZ\n'
printf 'и пересоздайте службу api (или сделайте это в панели: Настройки сервера).\n'
