step "11. Свой TLS-сертификат: одни правила на мастер и на панель"
# ==================================================================
# Свой сертификат ставят дважды: при установке и потом, когда старый
# истекает. Два набора правил на одно действие разошлись бы молча — обе
# стороны продолжали бы работать, а ловить перестала бы одна из них.
SHARED_TLS="$REPO_DIR/packages/shared/src/tls-certificate.ts"
t_ok "правила проверки живут в общем пакете" test -f "$SHARED_TLS"
t_ok "мастер первого запуска берёт правила оттуда" \
    bash -c "grep -q '@mail-true/shared/tls-certificate' '$REPO_DIR/apps/installer/src/tls.ts'"
t_ok "панель берёт правила оттуда же" \
    bash -c "grep -q '@mail-true/shared/tls-certificate' '$REPO_DIR/apps/api/src/admin/routes/tls.ts'"
# Модуль НЕ должен торчать из общего ствола пакета: packages/shared попадает
# и в браузерные сборки (почта, панель), а разбор сертификата опирается на
# node:crypto. Один экспорт из ствола — и сборка почты падает с
# «X509Certificate is not exported by __vite-browser-external», причём
# падает целиком, независимо от того, кто что импортировал. Поймано живым
# прогоном: собрать веб-интерфейс стало невозможно.
t_no "разбор сертификата не переэкспортируется из ствола общего пакета" \
    bash -c "grep -q \"export \\* from './tls-certificate\" '$REPO_DIR/packages/shared/src/index.ts'"
t_ok "у модуля есть свой путь в exports пакета" \
    bash -c "grep -q './tls-certificate' '$REPO_DIR/packages/shared/package.json'"

# Своей копии разбора быть не должно ни там, ни там: X509Certificate в
# обоих местах допустим только для чтения хранилища доверенных корней.
t_no "у мастера нет своей копии проверки пары ключ/сертификат" \
    bash -c "grep -q 'checkPrivateKey' '$REPO_DIR/apps/installer/src/tls.ts'"
t_no "у панели нет своей копии проверки пары ключ/сертификат" \
    bash -c "grep -q 'checkPrivateKey' '$REPO_DIR/apps/api/src/admin/routes/tls.ts'"

# Что именно обязана ловить проверка — по одному пункту на способ сломать
# установку сертификата вручную.
for what in 'key-mismatch' 'chain-missing' 'expired' 'names'; do
    t_ok "проверка знает про «$what»" bash -c "grep -q \"'$what'\" '$SHARED_TLS'"
done
t_ok "отказ по формату называет команду перевода из .pfx" \
    bash -c "grep -q 'openssl pkcs12' '$SHARED_TLS'"
t_ok "нехватка имён называет, что перестанет работать" \
    bash -c "grep -q 'панель управления' '$SHARED_TLS'"

# --- Приватный ключ наружу не уходит -----------------------------------
t_no "панель не отдаёт приватный ключ в ответе" \
    bash -c "grep -qE 'privateKey:|privateKeyPem:' '$REPO_DIR/apps/api/src/admin/routes/tls.ts' && grep -q 'return.*privateKey' '$REPO_DIR/apps/api/src/admin/routes/tls.ts'"
t_ok "в аудит пишется отпечаток, а не содержимое ключа" \
    bash -c "grep -q 'fingerprint256' '$REPO_DIR/apps/api/src/admin/routes/tls.ts'"

# --- Свой сертификат не перезаписывается продлением --------------------
# Иначе таймер systemd дважды в сутки однажды тихо положил бы на его место
# сертификат Let's Encrypt, а узналось бы это по звонку через неделю.
t_ok "продление отказывается трогать свой сертификат" \
    bash -c "grep -q 'MT_REPLACE_CUSTOM_CERT' '$INSTALL_DIR/renew-certs.sh'"
t_ok "install.sh не выпускает Let's Encrypt поверх своего сертификата" \
    bash -c "grep -q 'на сервере стоит свой сертификат' '$INSTALL_DIR/install.sh'"
t_ok "источник сертификата хранится рядом с ним" \
    bash -c "grep -q 'CERT_SOURCE_FILE' '$INSTALL_DIR/install.sh'"

# --- Замена доходит до служб без сокета Docker -------------------------
# Сертификат читают nginx, Postfix и Dovecot, и все трое — при старте.
# Сокета Docker у сервера приложения нет и не будет, поэтому каждая служба
# следит за файлом сама.
t_ok "nginx перечитывает сертификат сам" \
    bash -c "grep -q 'nginx -s reload' '$INFRA_DIR/nginx/watch-certs.sh'"
t_ok "postfix перечитывает сертификат сам" \
    bash -c "grep -q 'postfix reload' '$INFRA_DIR/postfix/entrypoint.sh'"
t_ok "dovecot перечитывает сертификат сам" \
    bash -c "grep -q 'doveadm reload' '$INFRA_DIR/dovecot/entrypoint.sh'"
t_ok "скрипт слежения примонтирован в nginx" \
    bash -c "grep -q 'watch-certs.sh:/docker-entrypoint.d' '$COMPOSE_FILE'"

# Бит исполнения у того, что монтируется прямо в /docker-entrypoint.d/.
#
# Штатный образ nginx выполняет оттуда только ИСПОЛНЯЕМЫЕ файлы, а
# неисполняемый молча пропускает одной строкой «Ignoring …, not
# executable» — которую никто не читает, потому что контейнер при этом
# здоров и отвечает.
#
# Цена была двойная, и обе стороны тихие: не выполнялся admin-allow.envsh
# — и ограничение панели по сетям (ADMIN_ALLOW_NETWORKS) не действовало
# вовсе, притом что .env.example обещает «остальные не увидят даже формы
# входа»; не выполнялся watch-certs.sh — и nginx никогда не перечитывал
# сертификат, продолжая отдавать старый после замены.
#
# У остальных служб бит ставит `RUN chmod +x` в их Dockerfile. У nginx
# слоя сборки нет вовсе — образ берётся как есть, поэтому единственное
# место, где бит может жить, это индекс git.
for mounted in nginx/watch-certs.sh nginx/admin-allow.envsh; do
    t_ok "$mounted исполняемый (иначе nginx его молча пропустит)" \
        test -x "$INFRA_DIR/$mounted"
done
# Ради замены сертификата сокет Docker серверу приложения так и не
# понадобился — а это была самая заманчивая причина его туда добавить.
# Ищем ЗАПУСК процессов, а не слово «docker»: в пояснениях этого файла оно
# встречается ровно затем, чтобы объяснить, почему так не сделано, — и
# первая версия проверки краснела от собственного комментария.
t_no "перезапуск служб ради сертификата не делается запуском процессов" \
    bash -c "grep -qE 'child_process|execFile|spawn\(' '$REPO_DIR/apps/api/src/admin/routes/tls.ts'"

# ==================================================================
step "Отчёт о продлении сертификата"
# ==================================================================
# ЧТО БЫЛО НЕ ТАК. Сроки сертификата панель показывала, а состояние самого
# ПРОДЛЕНИЯ — нет: заведён ли таймер, когда была последняя попытка и чем
# кончилась, не знал никто. Молчаливый отказ продления и приводит к
# истёкшему сертификату; узнают о нём по тому, что срок перестал
# отодвигаться, то есть за неделю до беды в лучшем случае.
#
# Проверяется здесь ровно то, что нельзя увидеть глазами: формат файла
# (его пишет bash, а читает TypeScript в контейнере — общего типа у них
# нет) и сохранение истории между запусками.

# Свой каталог: настоящий трогать нельзя, там живёт сертификат.
T_CERT_DIR="$(mktemp -d)"
T_CERT_DIR_SAVED="$CERT_DIR"
CERT_DIR="$T_CERT_DIR"
printf 'letsencrypt\n' > "$CERT_DIR/source"

# --- Экранирование значений -------------------------------------------
# Сообщения здесь по-русски и приходят из certbot, то есть содержат и
# кавычки, и косые черты. Одна неэкранированная кавычка делает файл
# неразбираемым целиком — панель показала бы «отчёта нет» на сервере, где
# продление работает.
t_eq "кавычка экранируется"        "$(json_escape 'а "б" в')"   'а \"б\" в'
t_eq "обратная косая экранируется" "$(json_escape 'путь\сюда')" 'путь\\сюда'
t_eq "кириллица проходит как есть" "$(json_escape 'продлён')"   'продлён'
# Перевод строки — не косметика: файл читается ПОСТРОЧНО (каждая попытка
# занимает ровно одну строку), и многострочное значение сломало бы
# сохранение истории.
t_eq "перевод строки становится пробелом" \
     "$(json_escape "$(printf 'две\nстроки')")" 'две строки'

# --- Запись и чтение ---------------------------------------------------
renew_report_write timer renew not-due '2026-11-05T00:00:00Z' 4 'срок ещё не подошёл' >/dev/null 2>&1
t_ok "отчёт создаётся" test -f "$CERT_DIR/renewal.json"
t_ok "в отчёте есть состояние таймера" \
    bash -c "grep -q '\"timer\":' '$CERT_DIR/renewal.json'"
t_ok "в отчёте есть итог попытки" \
    bash -c "grep -q '\"outcome\": \"not-due\"' '$CERT_DIR/renewal.json'"
t_ok "в отчёте есть дата окончания сертификата" \
    bash -c "grep -q '2026-11-05T00:00:00Z' '$CERT_DIR/renewal.json'"

# --- Таймера нет вовсе -------------------------------------------------
# Ровно случай «установка без systemd»: раньше об этом говорилось только
# в консоли установщика, один раз, и больше нигде.
t_ok "отсутствие автопродления записывается как kind=none" \
    bash -c "grep -q '\"kind\": \"none\"' '$CERT_DIR/renewal.json'"

# --- История переживает следующий запуск -------------------------------
# Это и была первая поломка живого прогона: отступ строки при перезаписи
# добавлялся заново, строки переставали узнаваться собственным фильтром, и
# история молча обнулялась каждый раз.
renew_report_write manual force failed '' 12 'certbot вернул код 1' >/dev/null 2>&1
t_eq "прежняя попытка сохранилась рядом с новой" \
     "$(grep -c '"at": ' "$CERT_DIR/renewal.json")" "2"
t_eq "новая попытка стоит первой" \
     "$(grep -m1 -o '"outcome": "[a-z-]*"' "$CERT_DIR/renewal.json")" '"outcome": "failed"'
t_eq "отступ не накапливается" \
     "$(grep -c '^        {"at": ' "$CERT_DIR/renewal.json")" "0"

# --- Обновление состояния таймера не добавляет попыток ------------------
renew_report_refresh >/dev/null 2>&1
t_eq "renew_report_refresh историю не трогает" \
     "$(grep -c '"at": ' "$CERT_DIR/renewal.json")" "2"

# --- Ротация -----------------------------------------------------------
for _i in $(seq 1 14); do
    renew_report_write timer renew not-due '' 1 "попытка $_i" >/dev/null 2>&1
done
t_eq "история обрезается до $RENEW_HISTORY_MAX записей" \
     "$(grep -c '"at": ' "$CERT_DIR/renewal.json")" "$RENEW_HISTORY_MAX"
t_ok "самая свежая запись осталась" \
    bash -c "grep -q 'попытка 14' '$CERT_DIR/renewal.json'"
t_no "самая старая запись вытеснена" \
    bash -c "grep -q 'попытка 1\"' '$CERT_DIR/renewal.json'"

rm -rf "$T_CERT_DIR"
CERT_DIR="$T_CERT_DIR_SAVED"

# --- Отчёт пишется при ЛЮБОМ исходе ------------------------------------
# Половина причин отказа продления — это выходы через die (нет certbot,
# нет файла сертификата, стоит свой сертификат). Записывай мы отчёт только
# в конце удачного прогона, самый важный случай не оставлял бы ни строки.
t_ok "renew-certs.sh пишет отчёт через trap на выходе" \
    bash -c "grep -q 'trap renew_finish EXIT' '$INSTALL_DIR/renew-certs.sh'"
t_ok "неудача certbot попадает в отчёт причиной" \
    bash -c "grep -q 'RENEW_OUTCOME=failed' '$INSTALL_DIR/renew-certs.sh'"
# Свой сертификат — не отказ, а решение. Крась мы этот случай красным,
# панель ругалась бы дважды в сутки на исправном сервере, и на её ругань
# перестали бы смотреть.
t_ok "свой сертификат отмечается отдельным итогом, а не отказом" \
    bash -c "grep -q 'RENEW_OUTCOME=skipped-custom' '$INSTALL_DIR/renew-certs.sh'"
t_ok "запуск по таймеру отличим от запуска руками" \
    bash -c "grep -q 'MT_RENEW_TRIGGER' '$MT_LIB_DIR/common.sh' && grep -q 'INVOCATION_ID' '$INSTALL_DIR/renew-certs.sh'"

# --- Отчёт лежит там, где его видит панель -----------------------------
# Каталог сертификатов уже примонтирован в контейнер сервера приложения;
# ни сокет Docker, ни доступ к systemd панели для чтения отчёта не нужны.
t_ok "отчёт лежит в каталоге сертификатов, а не во временном" \
    bash -c "grep -q 'RENEW_REPORT_NAME=renewal.json' '$MT_LIB_DIR/common.sh'"
t_ok "панель ищет отчёт под тем же именем" \
    bash -c "grep -q \"RENEWAL_REPORT_FILE = 'renewal.json'\" '$REPO_DIR/apps/api/src/admin/cert-renewal.ts'"
t_ok "каталог сертификатов виден серверу приложения" \
    bash -c "grep -q './data/certs:/certs$' '$COMPOSE_FILE'"
t_ok "отчёт попадает в «Наблюдение», а не только в раздел «Сертификат»" \
    bash -c "grep -q 'renewalHealthCheck' '$REPO_DIR/apps/api/src/admin/routes/monitoring.ts'"
# Кнопки «продлить сейчас» быть не может: certbot занимает 80-й порт ХОСТА,
# скрипт лежит на хосте, а у посредника закрытый список из restart/recreate.
# Ложная кнопка хуже её отсутствия — после неё человек уходит уверенным,
# что продление запущено.
t_no "панель не заводит собственного запуска продления" \
    bash -c "grep -qE \"'/tls/renew'|renewNow\" '$REPO_DIR/apps/api/src/admin/routes/tls.ts'"
t_no "посредник не научился выполнять произвольные команды" \
    bash -c "grep -qE '=> \{ (renew|exec|run) =>' '$INFRA_DIR/service-agent/agent.pl'"

# ==================================================================
step "Итог"
# ==================================================================
printf '  пройдено: %d   не пройдено: %d\n\n' "$T_PASS" "$T_FAIL"
[ "$T_FAIL" -eq 0 ] || exit 1
exit 0
