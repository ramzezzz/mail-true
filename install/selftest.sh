# --- Пустые значения в примере --------------------------------------
# Пустое значение в примере — это «работает по умолчанию» ТОЛЬКО если
# установщик его заполняет. Иначе установка с нуля молча выключает целый
# раздел: так было с QUEUE_AGENT_TOKEN — посредник к очереди Postfix не
# запускался вовсе, и раздел «Очередь» в панели отсутствовал на КАЖДОЙ
# новой установке, а узнать об этом было неоткуда.
#
# Ищем не любое упоминание ключа, а именно ЗАПИСЬ значения: env_set,
# env_ensure или строку вида "КЛЮЧ:<длина>" из списка генерируемых секретов.
# Первая версия проверки искала имя ключа где угодно в install.sh — и
# зеленела от собственного комментария, объясняющего, почему ключ важен.
#
# Исключения — только там, где ПУСТО САМО ПО СЕБЕ является осмысленным
# значением, а не забытой настройкой. Все три — списки, и у каждого
# пустота означает конкретное поведение, описанное в самом продукте:
#
#   ADMIN_ALLOW_NETWORKS    — пусто: панель отвечает отовсюду. Продукт
#                             ставят на VPS и ходят в неё из интернета;
#                             заполнять этот список за человека нельзя,
#                             иначе установка запирала бы его же снаружи.
#   FAIL2BAN_IGNORE_IPS     — пусто: никому не делается исключения. Адрес
#                             сюда вписывают осознанно, и угадать его
#                             установщику неоткуда.
#   GEOIP_ALLOWED_COUNTRIES — пусто: список стран не заполнен. Код это
#                             отдельно оговаривает: пустой список при
#                             политике allow означает «не заполнили», а
#                             не «запретить всё» (geoip/index.ts).
#
# Заполнять их установщиком было бы не «безопасным умолчанием», а
# решением за человека — и в двух случаях из трёх решением, которое
# закрывает ему доступ.
EMPTY_OK='ADMIN_ALLOW_NETWORKS FAIL2BAN_IGNORE_IPS GEOIP_ALLOWED_COUNTRIES'
EMPTY_UNSET=''
while read -r key; do
    [ -n "$key" ] || continue
    printf '%s' "$EMPTY_OK" | grep -qw "$key" && continue
    # Ищем в обоих файлах: список секретов «ключ:длина» переехал из
    # install.sh в lib/common.sh (MT_GENERATED_SECRETS), чтобы им же
    # пользовалась самопроверка и не проверяла три ключа из десяти.
    grep -qE "(env_set|env_ensure)[[:space:]]+${key}\b|\"${key}:[0-9]+\"" \
        "$INSTALL_DIR/install.sh" "$INSTALL_DIR/lib/common.sh" \
        || EMPTY_UNSET="$EMPTY_UNSET $key"
done < <(sed -n 's/^\([A-Z_0-9]\{1,\}\)=[[:space:]]*$/\1/p' "$ENV_EXAMPLE")
t_eq "пустые ключи из .env.example заполняет установщик" "${EMPTY_UNSET# }" ""

# --- Ключи примера доходят до контейнеров ---------------------------
# Ключ, который не подставляется ни в один compose-файл, не настраивает
# ничего. Так молчали MAIL_FLOW_RETENTION_DAYS и MAIL_FLOW_MAX_ROWS: код их
# читает, в примере они есть, правка в .env не делала ровно ничего, а
# таблица истории доставки продолжала расти по прежним срокам.
DEAD_KEYS=''
while read -r key; do
    [ -n "$key" ] || continue
    grep -qE "\\\$\{${key}[:}]" "$COMPOSE_FILE" "$COMPOSE_PROD" || DEAD_KEYS="$DEAD_KEYS $key"
done < <(grep -oE '^[A-Z_0-9]+=' "$ENV_EXAMPLE" | tr -d '=')
t_eq "каждый ключ .env.example подставляется хотя бы в один compose-файл" "${DEAD_KEYS# }" ""

# --- И обратная сторона: код читает — а нигде не описано --------------
# Проверка выше ловит только «ключ описан, но никуда не идёт». Обратный
# случай не ловил никто, и накопилось его втрое больше: схемы разбора
# окружения (apps/**/config.ts) читали PUSH_*, SENDER_LOGO_*, AI_ENABLED,
# COLLECTOR_* и ещё полсотни ключей, которых не было ни в этом примере,
# ни в docker-compose.yml. Настройка при этом работала — но добраться до
# неё можно было только пересборкой образа. Целые разделы продукта
# (уведомления при закрытой вкладке, логотипы отправителей) оказывались
# ненастраиваемыми на боевой установке вместе со своими выключателями.
#
# Ключ считается описанным, если его ИМЯ ВСТРЕЧАЕТСЯ в .env.example —
# строкой, закомментированной строкой (так помечены те, чьё умолчание
# «пусто») или пояснением в разделе «что настройкой не является». Условие
# ровно такое: поиск по имени в файле настроек обязан приводить к ответу,
# а не в пустоту. Либо ключ задан в compose — тогда это устройство стека
# (пути томов, имена сервисов), и в .env ему делать нечего.
UNDOC_ENV=''
while read -r key; do
    [ -n "$key" ] || continue
    grep -qF "$key" "$ENV_EXAMPLE" && continue
    grep -qE "^[[:space:]]+${key}:" "$COMPOSE_FILE" && continue
    UNDOC_ENV="$UNDOC_ENV $key"
done < <(grep -rhoE '^[[:space:]]+[A-Z][A-Z_0-9]{2,}:' \
             "$REPO_DIR"/apps/api/src/config.ts \
             "$REPO_DIR"/apps/api/src/*/config.ts \
             "$REPO_DIR"/apps/autoconfig/src/config.ts \
             "$REPO_DIR"/apps/installer/src/config.ts 2>/dev/null |
         tr -d ' :' | sort -u)
t_eq "переменные из схем окружения описаны в .env.example или заданы в compose" \
     "${UNDOC_ENV# }" ""

# --- Всё, что пишет установщик, описано в примере --------------------
# Иначе ключ существует, но найти его можно только чтением install.sh.
UNDOCUMENTED=''
while read -r key; do
    [ -n "$key" ] || continue
    grep -q "^${key}=" "$ENV_EXAMPLE" || UNDOCUMENTED="$UNDOCUMENTED $key"
done < <(grep -oE '(env_set|env_ensure) +[A-Z_0-9]+' "$INSTALL_DIR/install.sh" | awk '{print $2}' | sort -u)
t_eq "ключи, которые пишет install.sh, описаны в .env.example" "${UNDOCUMENTED# }" ""

