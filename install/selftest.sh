#!/usr/bin/env bash
# ------------------------------------------------------------------
# Юнит-тесты установщика.
#
#   bash install/selftest.sh
#
# Проверяются те места, где ошибка не видна глазами и уже приводила к
# тихим потерям: разбор ответов, пароли-заглушки, список томов для
# резервной копии, развязка infra/.env и тома базы при восстановлении.
# Docker и живой стек не нужны — это разбор данных, а не работа со стеком.
#
# Код возврата: 0 — все проверки прошли, 1 — есть провалившиеся.
# ------------------------------------------------------------------
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
. "$SCRIPT_DIR/lib/common.sh"

T_PASS=0
T_FAIL=0

t_eq() { # t_eq <что> <получено> <ожидалось>
    if [ "$2" = "$3" ]; then
        T_PASS=$((T_PASS + 1))
        printf '  [ ОК ]   %s\n' "$1"
    else
        T_FAIL=$((T_FAIL + 1))
        printf '  [ НЕТ ]  %s\n           получено: «%s»\n           ожидалось: «%s»\n' "$1" "$2" "$3"
    fi
}

t_ok() { # t_ok <что> <команда...> — команда должна вернуть 0
    local what="$1"; shift
    if "$@" >/dev/null 2>&1; then
        T_PASS=$((T_PASS + 1)); printf '  [ ОК ]   %s\n' "$what"
    else
        T_FAIL=$((T_FAIL + 1)); printf '  [ НЕТ ]  %s (ожидался успех)\n' "$what"
    fi
}

t_no() { # t_no <что> <команда...> — команда должна вернуть не 0
    local what="$1"; shift
    if "$@" >/dev/null 2>&1; then
        T_FAIL=$((T_FAIL + 1)); printf '  [ НЕТ ]  %s (ожидался отказ)\n' "$what"
    else
        T_PASS=$((T_PASS + 1)); printf '  [ ОК ]   %s\n' "$what"
    fi
}

# ==================================================================
step "1. Разбор yes/no: опечатка не должна становиться значением по умолчанию"
# ==================================================================
t_eq "yes → yes"      "$(normalize_yes_no yes)"  "yes"
t_eq "Да → yes"       "$(normalize_yes_no 'Да')" "yes"
t_eq "true → yes"     "$(normalize_yes_no true)" "yes"
t_eq "no → no"        "$(normalize_yes_no no)"   "no"
t_eq "нет → no"       "$(normalize_yes_no 'нет')" "no"
# Ровно тот случай из отчёта: опечатка молча трактовалась как «no»
t_no "опечатка «yse» отвергается"   normalize_yes_no yse
t_no "опечатка «yess» отвергается"  normalize_yes_no yess
t_no "мусор отвергается"            normalize_yes_no maybe
t_no "пустое значение отвергается"  normalize_yes_no ''

# ==================================================================
step "2. Выбор из списка: MAILTRUE_TLS"
# ==================================================================
t_eq "letsencrypt принимается"  "$(normalize_choice letsencrypt 'letsencrypt selfsigned')" "letsencrypt"
t_eq "SelfSigned приводится к нижнему регистру" \
     "$(normalize_choice SelfSigned 'letsencrypt selfsigned')" "selfsigned"
# До исправления такие значения молча становились letsencrypt
t_no "опечатка «letsencript» отвергается" normalize_choice letsencript 'letsencrypt selfsigned'
t_no "«self-signed» отвергается"          normalize_choice self-signed 'letsencrypt selfsigned'

# ==================================================================
step "3. Пароли-заглушки"
# ==================================================================
# Значение из install/answers.example.env: 19 символов, проверку длины
# проходило, и боевые серверы уезжали с общеизвестным паролем.
EXAMPLE_PW="$(sed -n "s/^MAILTRUE_ADMIN_PASSWORD=//p" "$INSTALL_DIR/answers.example.env" | tail -1 | tr -d "'\"")"
t_eq "пароль из примера длиннее 10 символов (проверку длины проходил)" \
     "$([ "${#EXAMPLE_PW}" -ge 10 ] && echo yes || echo no)" "yes"
t_ok "пароль из примера распознаётся как заглушка" is_placeholder_password "$EXAMPLE_PW"
t_ok "change-me-... распознаётся"     is_placeholder_password 'change-me-postgres'
t_ok "«password» распознаётся"        is_placeholder_password 'password'
t_no "нормальный пароль не заглушка"  is_placeholder_password 'Xy7#kq2Lm9pR'

# ==================================================================
step "4. Тома для резервной копии"
# ==================================================================
# Список томов ОДИН на backup.sh и restore.sh: раздельные перечни уже
# привели к тому, что очередь Postfix не попала в копию.
VOL_NAMES=''
for spec in "${MT_BACKUP_VOLUMES[@]}"; do VOL_NAMES="$VOL_NAMES ${spec%%:*}"; done
# api-branding — свой логотип страниц входа (OEM). Восстановить его
# неоткуда: исходник лежит у заказчика. Без него после восстановления
# обе страницы входа молча возвращаются к чужому фирменному стилю.
for want_vol in vmail rspamd-data postfix-spool redisdata api-uploads api-branding; do
    t_ok "том $want_vol входит в резервную копию" \
        bash -c "printf '%s' '$VOL_NAMES' | grep -qw '$want_vol'"
done

# Обучение антиспама живёт в Redis, а не в rspamd-data.
#
# Эта проверка сторожит не список томов, а УБЕЖДЕНИЕ, из-за которого том
# Redis считали «просто кэшем» и держали в списке исключений. Убеждение было
# ошибочным: классификатор настроен на Redis, и восстановление из копии молча
# обнуляло обучение — каждую пометку «это спам», сделанную людьми за месяцы.
# Ничто при этом не ломалось: сервер просто снова начинал ошибаться, и понять
# почему было уже невозможно.
#
# Если однажды классификатор переведут обратно в файлы, эта проверка
# покраснеет и заставит пересмотреть список томов, а не молча разъехаться.
t_ok "байесовский классификатор хранится в Redis (иначе список томов устарел)" \
    bash -c "grep -q 'backend *= *\"redis\"' '$INFRA_DIR/rspamd/local.d/classifier-bayes.conf'"

# Тома из compose, объявленные постоянными, должны быть либо в копии,
# либо осознанно исключены. Каждое исключение — решение с причиной:
#   pgdata    — в копию идёт логический дамп (pg_dump): он переносим между
#               версиями Postgres, а том — нет;
#   mailindex — индексы выводятся из самих писем, а места занимают столько же;
#   clamav-db — базы антивируса скачиваются заново за несколько минут;
#   maillogs  — журналы доставки. Это история работы, а не данные людей:
#               письма от их потери не пропадают, а объём растёт без предела.
#               Они проворачиваются на диске и доступны в разделе «Журналы»
#               админки; класть их в каждую копию значит раздувать её тем,
#               что и так есть на сервере.
#   acme-challenge — одноразовые токены подтверждения домена. Их кладёт
#               certbot на несколько секунд и тут же убирает: к моменту
#               восстановления любой такой файл заведомо просрочен, а
#               подтверждение всё равно проходит заново. Том появился
#               вместе с выпуском сертификата без остановки nginx, и
#               проверка честно покраснела, потому что в список причин
#               его тогда не внесли.
SKIP_VOLUMES='pgdata mailindex clamav-db maillogs acme-challenge'
MISSING=''
while read -r vol; do
    [ -n "$vol" ] || continue
    printf '%s' "$SKIP_VOLUMES" | grep -qw "$vol" && continue
    printf '%s' "$VOL_NAMES" | grep -qw "$vol" && continue
    MISSING="$MISSING $vol"
done < <(sed -n '/^volumes:/,$p' "$INFRA_DIR/docker-compose.yml" |
         sed -n 's/^  \([a-z0-9-]*\):[[:space:]]*$/\1/p')
t_eq "все тома данных из docker-compose.yml попадают в копию" "${MISSING# }" ""

# Полное удаление тоже держало СВОЙ перечень томов, и он отстал: в нём не
# было ни очереди Postfix, ни логотипа страниц входа, ни журналов. То есть
# «удалено полностью» оставляло на машине данные, про которые человеку
# сказали, что их больше нет.
t_no "uninstall.sh не держит свой перечень томов в коде" \
    bash -c "grep -qE 'for vol in +[a-z]' '$INSTALL_DIR/uninstall.sh'"
t_ok "uninstall.sh берёт список томов из docker-compose.yml" \
    bash -c "grep -q 'COMPOSE_VOLUMES' '$INSTALL_DIR/uninstall.sh'"

# ==================================================================
step "5. Развязка infra/.env и тома базы при восстановлении"
# ==================================================================
# Postgres принимает POSTGRES_PASSWORD только при создании пустого тома.
# Восстановление .env из копии поверх уже созданного тома ломало доступ.
BOUND_KEYS=" ${MT_VOLUME_BOUND_ENV_KEYS[*]} "
for key in POSTGRES_PASSWORD POSTGRES_USER POSTGRES_DB; do
    t_eq "$key объявлен привязанным к тому" \
         "$(case "$BOUND_KEYS" in *" $key "*) echo yes ;; *) echo no ;; esac)" "yes"
done
t_eq "ключи шифрования НЕ считаются привязанными к тому (их берём из копии)" \
     "$(case "$BOUND_KEYS" in *' AI_ENCRYPTION_KEY '*) echo yes ;; *) echo no ;; esac)" "no"

# Проверяем сам механизм подмены на временном файле .env
TMPD="$(mktemp -d)"
trap 'rm -rf "$TMPD"' EXIT
cat > "$TMPD/current.env" <<'EOF'
POSTGRES_USER=mailserver
POSTGRES_PASSWORD=new-volume-password
POSTGRES_DB=mailserver
AI_ENCRYPTION_KEY=new-key-must-be-replaced
EOF
cat > "$TMPD/backup.env" <<'EOF'
POSTGRES_USER=mailserver
POSTGRES_PASSWORD=old-backup-password
POSTGRES_DB=mailserver
AI_ENCRYPTION_KEY=key-from-backup
EOF
ENV_FILE="$TMPD/current.env"
PRESERVED=()
for key in "${MT_VOLUME_BOUND_ENV_KEYS[@]}"; do
    v="$(env_get "$key")"
    [ -n "$v" ] && PRESERVED+=("$key=$v")
done
cp "$TMPD/backup.env" "$ENV_FILE"
for pair in "${PRESERVED[@]}"; do env_set "${pair%%=*}" "${pair#*=}"; done
t_eq "пароль базы остался от действующей установки" \
     "$(env_get POSTGRES_PASSWORD)" "new-volume-password"
t_eq "ключ шифрования восстановлен из копии" \
     "$(env_get AI_ENCRYPTION_KEY)" "key-from-backup"

# ==================================================================
step "6. Скрипты остаются синтаксически корректными"
# ==================================================================
for f in install.sh backup.sh restore.sh selfcheck.sh renew-certs.sh uninstall.sh allow-reinstall.sh web-install.sh lib/common.sh; do
    t_ok "bash -n install/$f" bash -n "$INSTALL_DIR/$f"
done
# Проверка занятости портов обязана СПРАШИВАТЬ, а не просто предупреждать.
#
# Искали в install.sh — а предпусковые проверки давно живут в lib/common.sh
# (preflight_ports). Строки там не было НИКОГДА, и проверка стояла красной,
# ничего не проверяя: сам продукт вёл себя правильно всё это время.
# Красная проверка, к которой привыкли, ничем не лучше отсутствующей —
# на неё перестают смотреть, и настоящая поломка теряется среди неё.
#
# Ищем в обоих файлах: переезд кода между ними не должен снова красить
# проверку в красный, пока поведение на месте.
t_ok "занятые порты требуют подтверждения" \
    bash -c "grep -qr 'освободите занятые порты' '$INSTALL_DIR/install.sh' '$INSTALL_DIR/lib/common.sh'"
# Восстановление обязано проверять доступ к базе по паролю (по TCP)
t_ok "восстановление проверяет доступ к базе по паролю" \
    bash -c "grep -q 'psql -h postgres' '$INSTALL_DIR/restore.sh'"
t_ok "восстановление завершается ошибкой при непройденных пунктах" \
    bash -c "grep -q 'ЗАВЕРШЕНО С ОШИБКАМИ' '$INSTALL_DIR/restore.sh'"
t_ok "восстановление применяет миграции поверх дампа" \
    bash -c "grep -q 'postgres/migrations' '$INSTALL_DIR/restore.sh'"
# --only проверяется НАСТОЯЩИМ запуском, а не поиском строки в исходнике:
# именно поведение здесь и важно. Раньше принималось любое слово, и
# опечатка вроде «--only base» проходила все шаги, не восстановив ничего,
# и заканчивалась бодрым отчётом. Хуже места для тихой ошибки нет:
# восстановление запускают один раз, в аварии.
t_ok "restore.sh отвергает неизвестный раздел в --only" \
    bash -c "! bash '$INSTALL_DIR/restore.sh' /nonexistent.tar.gz --only base >/dev/null 2>&1"
t_ok "restore.sh принимает известные разделы --only" \
    bash -c "for s in db mail config; do
                out=\"\$(bash '$INSTALL_DIR/restore.sh' /nonexistent.tar.gz --only \$s 2>&1)\"
                printf '%s' \"\$out\" | grep -q 'файл не найден' || exit 1
             done"
# ------------------------------------------------------------------
# Повторный запуск установщика не портит уже настроенное
# ------------------------------------------------------------------
# Установка — не одноразовое действие: её запускают снова при обновлении,
# при починке, при переустановке поверх. Каждый такой запуск переписывал
# то, что человек задал сам, и всегда молча.
IDEM_ENV="$TMPD/idempotent.env"
cat > "$IDEM_ENV" <<'EOF'
SMTP_PORT=2525
IMAPS_PORT=9993
NGINX_HTTP_PORT=8080
EOF
#
# БЕЗ ПОДОБОЛОЧКИ. Первая версия делала эту часть в «( … )», и счётчики
# пройденного оставались внутри: проверки печатались, а в итог не
# попадали — провал прошёл бы незаметно. Поэтому ENV_FILE подменяется на
# время и возвращается обратно.
IDEM_ENV_KEEP="$ENV_FILE"
ENV_FILE="$IDEM_ENV"
# Ровно та функция, что стоит в install.sh.
env_port() {
    local key="$1" explicit="$2" fallback="$3"
    if [ -n "$explicit" ]; then env_set "$key" "$explicit"
    else env_ensure "$key" "$fallback" || true; fi
}
env_port SMTP_PORT       ''     25    >/dev/null 2>&1
env_port IMAPS_PORT      ''     993   >/dev/null 2>&1
env_port NGINX_HTTP_PORT ''     80    >/dev/null 2>&1
env_port POP3_PORT       ''     110   >/dev/null 2>&1
env_port SUBMISSION_PORT '2587' 587   >/dev/null 2>&1

t_eq "повторная установка не сбрасывает порт SMTP" "$(env_get SMTP_PORT)" "2525"
t_eq "повторная установка не сбрасывает порт IMAPS" "$(env_get IMAPS_PORT)" "9993"
t_eq "повторная установка не сбрасывает порт HTTP" "$(env_get NGINX_HTTP_PORT)" "8080"
t_eq "недостающий порт всё же заполняется умолчанием" "$(env_get POP3_PORT)" "110"
t_eq "заданное явно при запуске сильнее прежнего" "$(env_get SUBMISSION_PORT)" "2587"

ENV_FILE="$IDEM_ENV_KEEP"
rm -f "$IDEM_ENV"

# Резервный вход в панель раньше пересчитывался при каждом запуске, и
# всегда в сторону ослабления: сужение до 127.0.0.1 отменялось само.
t_ok "резервный вход в панель не пересчитывается на повторной установке" \
    bash -c "grep -q 'elif \[ -z \"\\\$(env_get ADMIN_LOCAL_BIND)\" \]' '$INSTALL_DIR/install.sh'"
# Публичный адрес читался только из окружения (load_env идёт ниже), и без
# сети записывался пустым — стирая уже выясненное значение.
t_ok "публичный адрес берётся и из infra/.env, а не только из окружения" \
    bash -c "grep -q 'MAIL_PUBLIC_IPV4=\"\\\$(env_get MAIL_PUBLIC_IPV4)\"' '$INSTALL_DIR/install.sh'"
# create-mailbox.sh делает upsert: повторный запуск возвращал пароль ящика
# к тому, что лежит в файле ответов, — уже после смены его через панель.
t_ok "повторная установка не меняет пароль существующего ящика" \
    bash -c "grep -q 'пароль не трогаем' '$INSTALL_DIR/install.sh'"
# Согласие на необратимое удаление не должно приходить из переменной,
# которую выставила соседняя команда.
t_ok "удаление не наследует согласие из окружения" \
    bash -c "grep -q '^MT_ASSUME_YES=0' '$INSTALL_DIR/uninstall.sh'"

# --- Журналы и пробы служб ------------------------------------------
# Проворот журнала Dovecot обязан восстанавливать права: после него файл
# заводит сам Dovecot — от root и с маской 077, — а читает его сервер
# приложения под другим пользователем. Без этого шага «Журналы почты» и
# история входов владельца ящика молча пустели после первого проворота.
t_ok "проворот журнала Dovecot восстанавливает права на новый файл"      bash -c 'B=$(grep -A 20 "doveadm log reopen" "$0/dovecot/entrypoint.sh"); printf "%s" "$B" | grep -q "touch" && printf "%s" "$B" | grep -q "chmod 644"' "$INFRA_DIR"
# Проворот журнала Postfix не должен зависеть от необязательной
# возможности: он жил внутри посредника очереди, а тот запускается только
# при заданном секрете — стек по документированному пути оставался без
# проворота вовсе.
t_ok "проворот журнала Postfix не зависит от секрета посредника очереди"      bash -c "sed -n '1,/Посредник к очереди/p' '$INFRA_DIR/postfix/entrypoint.sh' | grep -q MAILLOG_MAX_BYTES"
t_ok "проба Postfix стучится в порты, а не проверяет собственный PID"      bash -c "! grep -q 'kill -0 .*master.pid' '$INFRA_DIR/docker-compose.yml'"
# Выпуск сертификата — единственное действие посредника, собиравшее
# «docker run» руками, и единственное, не проверявшее состояние запуска:
# при неопознанном каталоге проекта он тихо раскладывал сертификат в
# /data/certs и отвечал успехом.
t_ok "выпуск сертификата не работает при неопознанном каталоге проекта"      bash -c "awk '/^sub do_certbot/,/my \@domains;/' '$INFRA_DIR/service-agent/agent.pl' | grep -q 'STARTUP_ERROR'"

t_ok "самопроверка ловит пароль-заглушку администратора" \
    bash -c "grep -q 'заглушка из примера' '$INSTALL_DIR/selfcheck.sh'"

# ==================================================================
step "7. Согласованность infra/.env.example, compose и установщика"
# ==================================================================
# Тут ломается тише всего: ключ есть в примере, человек его правит, а он
# никуда не подставляется — или наоборот, установщик пишет ключ, которого
# в примере нет, и о нём неоткуда узнать. Ни одна живая проверка этого не
# ловит: стек поднимается, почта ходит, настройка просто не действует.

# --- Концы строк ----------------------------------------------------
# infra/.env.example один раз уже уехал с CRLF. Установщик копирует его в
# infra/.env, docker compose «\r» отбрасывает (контейнеры работают), а bash
# сохраняет: POSTGRES_USER в скриптах становится «mailserver» с невидимым
# хвостом, и psql отвечает «role does not exist» на КАЖДУЮ миграцию при
# исправной базе. Установка с нуля разваливалась целиком, не сказав ни слова.
t_no "в infra/.env.example нет концов строк Windows (CRLF)" \
    grep -q $'\r' "$ENV_EXAMPLE"

# И то же самое для всего, что исполняется или разбирается на сервере.
# Это не вкусовщина: infra/test-delivery.sh был сохранён целиком в CRLF и
# не разбирался bash-ом ВООБЩЕ — «syntax error near unexpected token $'do\r'».
# Проверка доставки, которой полагается ловить поломки почты, сама не
# запускалась, и заметить это можно было только запустив её вручную.
#
# Смотрим то, что уходит в КОММИТ, а не рабочее дерево. На Windows git при
# выгрузке сам разворачивает LF в CRLF (core.autocrlf), поэтому проверка по
# файлам на диске краснела бы у каждого разработчика на Windows — при том
# что в репозитории и на сервере заказчика концы строк правильные. Ложная
# тревога в проверке хуже отсутствующей проверки: её перестают читать.
CRLF_FILES=''
if git -C "$REPO_DIR" rev-parse --git-dir >/dev/null 2>&1; then
    # `git ls-files --eol` показывает концы строк ИМЕННО В ИНДЕКСЕ (колонка
    # i/), без преобразований. Ни `grep` по файлу, ни `git show` тут не
    # годятся: на Windows git разворачивает LF в CRLF при выгрузке и обратно
    # при показе, и проверка краснела бы у каждого разработчика на Windows
    # при совершенно исправном репозитории. Ложная тревога хуже отсутствующей
    # проверки: её перестают читать.
    while read -r eol_index _eol_work _attr path; do
        case "$path" in
            *.sh|*.pl|*.yml|*.template|*.conf|*.cf|*.env.example) ;;
            *) continue ;;
        esac
        [ "$eol_index" = 'i/crlf' ] && CRLF_FILES="$CRLF_FILES $path"
    done < <(git -C "$REPO_DIR" ls-files --eol install infra)
    t_eq "в скриптах и конфигах install/ и infra/ нет CRLF (в индексе git)" "${CRLF_FILES# }" ""
else
    # Вне репозитория (распакованный архив) сверять не с чем — и это не повод
    # объявлять проверку пройденной молча.
    printf '  [ .. ]   проверка CRLF пропущена: каталог не под git
'
fi

# И то же самое функционально: load_env обязан пережить CRLF-файл.
CRLF_ENV="$(mktemp)"
printf 'POSTGRES_USER=mailserver\r\nMAIL_DOMAIN=example.test\r\n' > "$CRLF_ENV"
( ENV_FILE="$CRLF_ENV"; load_env
  [ "${#POSTGRES_USER}" = "10" ] ) >/dev/null 2>&1
t_eq "load_env вычищает \\r из значений (иначе psql не найдёт роль)" \
     "$( ENV_FILE="$CRLF_ENV"; load_env >/dev/null 2>&1; printf '%s' "${#POSTGRES_USER}" )" "10"
rm -f "$CRLF_ENV"

# --- Опасное значение в infra/.env ----------------------------------
# Файл читают два разборщика: compose берёт остаток строки, а скрипты
# обслуживания его ИСПОЛНЯЮТ (load_env). Из-за второго значение без
# кавычек было и поломкой, и дырой:
#
#   * «FAIL2BAN_IGNORE_IPS=1.2.3.4 5.6.7.8» (формат из .env.example)
#     превращался в попытку выполнить «5.6.7.8» — код 127, и падали ВСЕ
#     скрипты обслуживания, включая автопродление сертификата по таймеру;
#   * «x;команда» выполнялась при первом же чтении файла, а renew-certs.sh
#     запускается от root.
#
# Проверяем настоящим исполнением, а не видом строки.
DANGER_ENV="$(mktemp)"
DANGER_MARK="$(mktemp -u)"
( ENV_FILE="$DANGER_ENV"
  env_set PROVIDER_NAME "Почта Компании"
  env_set EVIL "x;touch $DANGER_MARK"
  env_set SIMPLE mail.example.ru ) >/dev/null 2>&1

t_eq "значение с пробелом переживает оборот через infra/.env"      "$( ENV_FILE="$DANGER_ENV"; env_get PROVIDER_NAME )" "Почта Компании"
t_eq "простое значение пишется без кавычек — файл остаётся привычным"      "$(grep '^SIMPLE=' "$DANGER_ENV")" "SIMPLE=mail.example.ru"
t_ok "исполнение infra/.env не падает на значении с пробелом"      bash -c "set -euo pipefail; set -a; . <(tr -d '' < '$DANGER_ENV'); set +a; [ \"\$PROVIDER_NAME\" = 'Почта Компании' ]"
( set -a; . <(tr -d '' < "$DANGER_ENV") ; set +a ) >/dev/null 2>&1
t_ok "команда из значения НЕ выполняется при чтении infra/.env"      bash -c "[ ! -e '$DANGER_MARK' ]"
rm -f "$DANGER_ENV" "$DANGER_MARK"

