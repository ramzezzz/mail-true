#!/usr/bin/env bash
# ------------------------------------------------------------------
# Применить миграции базы к уже работающему стеку.
#
#   bash install/apply-migrations.sh [кто]
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ ВХОД.
#
# Обновление продукта из панели («Обновления» → «Обновить продукт»)
# делало ровно три вещи: fetch, merge --ff-only, пересборка и подъём
# стека. Миграций среди них не было — ни одной строки. То есть новый код
# сервера приложения оставался поверх СТАРОЙ схемы, причём насовсем:
# Postgres выполняет каталог миграций сам только при создании пустого
# тома, а apply_migrations вызывался лишь из install.sh, restore.sh и
# selftest.sh.
#
# Это ровно та ситуация, против которой написан порядок шагов в
# install.sh («новый код запускался против СТАРОЙ схемы»), и ровно то,
# что документация обещает делать при обновлении. Раздел панели после
# такого обновления честно покажет красное «Не применено миграций: N», а
# сам экран обновления отрапортует зелёным «Обновление закончено» — и
# чинить придётся по ssh.
#
# Второй реализации применения миграций здесь НЕТ намеренно: журнал,
# контрольные суммы, отметка initdb и особый случай базовой схемы — это
# apply_migrations из install/lib/common.sh, и он один. Этот файл только
# даёт до него добраться одной командой.
#
# Код возврата: 0 — схема соответствует продукту, 1 — что-то не приехало.
# ------------------------------------------------------------------
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
. "$SCRIPT_DIR/lib/common.sh"

WHO="${1:-apply-migrations.sh}"

load_env

step "Схема базы данных"
apply_migrations "$WHO" || true

if [ -n "$MT_MIG_FAILED" ]; then
    printf '\n'
    printf '  Схема базы применена НЕ ПОЛНОСТЬЮ:%s\n' "$MT_MIG_FAILED"
    printf '  Часть разделов панели будет отвечать ошибкой, пока это не исправлено.\n'
    printf '  Посмотреть полную ошибку и применить вручную:\n\n'
    printf '    docker compose -f infra/docker-compose.yml exec -T postgres \\\n'
    printf '      psql -v ON_ERROR_STOP=1 -U %s -d %s \\\n' "$POSTGRES_USER" "$POSTGRES_DB"
    printf '      < infra/postgres/migrations/<файл>\n\n'
    die "база не соответствует версии продукта"
fi

if [ "$MT_MIG_APPLIED" -gt 0 ]; then
    ok "миграций применено: $MT_MIG_APPLIED"
else
    ok "новых миграций нет — схема уже соответствует продукту"
fi
