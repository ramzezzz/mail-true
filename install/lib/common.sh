# ВИДИТ ЛИ DOCKER КАТАЛОГ ПРОЕКТА
#
# Поймано на живой установке. `snap install docker` (пакет Canonical)
# ставит Docker в изоляции snap, а ей видны только домашние каталоги:
# /opt для неё не существует. Выглядит это дико и уводит в сторону —
# файл лежит на месте, `ls -la infra/docker-compose.yml` его показывает,
# а docker отвечает:
#
#   open /opt/mailtrue/infra/docker-compose.yml: no such file or directory
#
# Человек идёт искать пропавший файл (его нет смысла искать) вместо того
# чтобы менять Docker. Причём проверки выше рапортуют «Docker работает» —
# он и правда работает, просто не там, где лежит проект.
#
# Проверяем не «snap ли это», а ровно то, что нужно: может ли docker
# прочитать файл из каталога проекта. Так ловится и любая другая
# изоляция — контейнеризованный CLI, чужой namespace, права.
#
# Дальше по-другому и нельзя: конфигурация Postfix, Dovecot и Rspamd
# монтируется в контейнеры прямо отсюда, каталогами. Не видит файла —
# не увидит и конфигов, и стек развалится на первом же контейнере.
# ------------------------------------------------------------------

# docker_from_snap — Docker поставлен из snap?
docker_from_snap() {
    local bin real
    bin="$(command -v docker 2>/dev/null || true)"
    [ -n "$bin" ] || return 1
    real="$(readlink -f "$bin" 2>/dev/null || true)"
    case "$bin$real" in */snap/*) return 0 ;; esac
    have snap && snap list docker >/dev/null 2>&1
}

# docker_sees_repo — 0, если docker читает файлы из каталога проекта.
docker_sees_repo() {
    local probe="$REPO_DIR/.mt-docker-probe.yml" out rc
    printf 'services:\n  probe:\n    image: hello-world\n' > "$probe" 2>/dev/null || return 0
    out="$(docker compose -f "$probe" config -q 2>&1)"
    rc=$?
    rm -f "$probe"
    [ "$rc" -eq 0 ] && return 0
    # Не всякая ошибка означает невидимость: у compose своих поводов хватает.
    # Реагируем только на «файла нет» и «доступа нет» — их проба вызвать
    # не может, файл только что записан рядом.
    case "$out" in
        *'no such file'*|*'No such file'*|*'not found'*|*'permission denied'*|*'Permission denied'*)
            return 1
            ;;
    esac
    return 0
}

# require_docker_sees_repo — проверка с внятным объяснением вместо «нет файла».
require_docker_sees_repo() {
    if docker_sees_repo; then
        ok "Docker читает каталог проекта"
        return 0
    fi
    if docker_from_snap; then
        die "Docker установлен из snap, а snap-пакету видны только домашние каталоги —
       каталога $REPO_DIR для него не существует.

       Со стороны это выглядит так, будто пропали файлы: они на месте, но
       docker отвечает «no such file or directory». Стек в таком Docker не
       поднимется в принципе — конфигурация Postfix, Dovecot и Rspamd
       монтируется в контейнеры прямо из этого каталога.

       Замените Docker на официальный:
         sudo snap remove --purge docker
         curl -fsSL https://get.docker.com | sudo sh
       и повторите запуск."
    fi
    die "Docker не может прочитать файлы из каталога $REPO_DIR.

       Проверьте, что docker работает на этой же машине и от имени
       пользователя, которому виден этот каталог:
         docker context ls
         sudo docker compose -f '$COMPOSE_FILE' config -q"
}

# ------------------------------------------------------------------
# Установка официального Docker (репозиторий download.docker.com).
# Живёт здесь, а не в install.sh: тем же самым лечится snap-Docker,
# а на него натыкается и мастер первого запуска (web-install.sh).
# ------------------------------------------------------------------
install_docker() {
    step "Установка Docker"
    have apt-get || die "нет apt-get — поставьте Docker вручную: https://docs.docker.com/engine/install/"
    export DEBIAN_FRONTEND=noninteractive
    apt-get update -qq
    apt-get install -y -qq ca-certificates curl gnupg >/dev/null
    install -m 0755 -d /etc/apt/keyrings
    local repo_id="${OS_ID:-ubuntu}"
    case "$repo_id" in ubuntu|debian) : ;; *) repo_id=ubuntu ;; esac
    curl -fsSL "https://download.docker.com/linux/$repo_id/gpg" -o /etc/apt/keyrings/docker.asc
    chmod a+r /etc/apt/keyrings/docker.asc
    local codename
    codename="${VERSION_CODENAME:-jammy}"
    printf 'deb [arch=%s signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/%s %s stable\n' \
        "$(dpkg --print-architecture)" "$repo_id" "$codename" > /etc/apt/sources.list.d/docker.list
    apt-get update -qq
    apt-get install -y -qq docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin >/dev/null
    if have systemctl; then
        systemctl enable --now docker >/dev/null 2>&1 || true
    fi
    ok "Docker установлен"
}

# ------------------------------------------------------------------
# ensure_docker_native — снять snap-Docker и поставить официальный.
#
# Установщик не оставляет это человеку: сам snap-Docker выглядит рабочим
# («Docker работает (29.6.1)»), а установка падает через шаг с сообщением
# про несуществующий файл. Разбираться в этом человеку не за что.
#
# Единственное, чего мы делать не вправе, — молча снести чужие контейнеры:
# `snap remove --purge` уносит вместе с пакетом всё, что в нём работало.
# Поэтому: пусто — чиним сразу; есть чужое — спрашиваем, а в
# неинтерактивном режиме отказываемся и объясняем.
# ------------------------------------------------------------------
ensure_docker_native() {
    docker_from_snap || return 0

    local containers=''
    containers="$(docker ps -aq 2>/dev/null | grep -c . || true)"
    containers="${containers:-0}"

    warn "Docker установлен из snap — с ним почтовый сервер работать не будет"
    hint "snap-пакету видны только домашние каталоги: каталога $REPO_DIR"
    hint "для него не существует, а конфигурация Postfix, Dovecot и Rspamd"
    hint "монтируется в контейнеры прямо оттуда"

    if [ "$containers" != "0" ]; then
        hint "в snap-Docker сейчас $containers контейнер(ов) — при замене они пропадут"
        if ! confirm "Снять snap-Docker вместе с его контейнерами и поставить официальный?"; then
            die "установка прервана: snap-Docker несовместим с почтовым сервером.
       Перенесите нужное из его контейнеров и повторите запуск, либо
       сделайте замену вручную:
         sudo snap remove --purge docker
         curl -fsSL https://get.docker.com | sudo sh"
        fi
    else
        info "чужих контейнеров в нём нет — заменяем на официальный Docker"
    fi

    have snap || die "snap-Docker найден, но команды snap нет — уберите его вручную"
    snap remove --purge docker >/dev/null 2>&1 || snap remove docker >/dev/null 2>&1 ||
        die "не удалось снять snap-Docker: sudo snap remove --purge docker"
    ok "snap-Docker снят"

    # Ссылки /snap/bin остаются в PATH текущей оболочки — обновляем поиск.
    hash -r 2>/dev/null || true
    install_docker

    docker info >/dev/null 2>&1 ||
        die "официальный Docker установлен, но демон не отвечает: systemctl status docker"
}

# ------------------------------------------------------------------
# ЧУЖОЙ ПОЧТОВЫЙ СЕРВЕР НА МАШИНЕ
#
# Ubuntu ставит postfix или exim4 «прицепом» к другим пакетам, и он
# молча занимает 25-й порт (а postfix — ещё и 465-й). Наш Postfix в
# контейнере эти порты не получит, и стек не поднимется.
#
# Отключаем сами: это обратимо (служба остаётся в системе, включается
# обратно одной командой), а без этого установка всё равно упирается в
# занятый порт. Пакет НЕ удаляем — удаление необратимо, о нём только
# говорим.
# ------------------------------------------------------------------
handle_foreign_mta() {
    local units='postfix exim4 sendmail opensmtpd nullmailer msmtpd'
    local unit active='' installed=''

    for unit in $units; do
        if have systemctl && systemctl is-active --quiet "$unit" 2>/dev/null; then
            active="$active $unit"
        elif have dpkg-query && dpkg-query -W -f='${Status}' "$unit" 2>/dev/null | grep -q 'ok installed'; then
            installed="$installed $unit"
        fi
    done

    if [ -n "$active" ] && [ "$(id -u)" -ne 0 ]; then
        # Бывает в --prepare-only: проверки разрешено гонять и не от root.
        warn "на сервере уже работает почтовая служба:$active"
        hint "отключить её без root нельзя — сделайте это перед установкой:"
        for unit in $active; do hint "  sudo systemctl disable --now $unit"; done
        return 0
    fi

    if [ -n "$active" ]; then
        warn "на сервере уже работает почтовая служба:$active"
        hint "она держит 25-й порт, и наш Postfix не запустится — отключаем"
        local failed=''
        for unit in $active; do
            if systemctl disable --now "$unit" >/dev/null 2>&1; then
                ok "служба $unit остановлена и убрана из автозапуска"
            else
                failed="$failed $unit"
            fi
        done
        if [ -n "$failed" ]; then
            fail "не удалось отключить:$failed"
            hint "сделайте вручную и повторите запуск:"
            for unit in $failed; do hint "  systemctl disable --now $unit"; done
            if ! confirm "Продолжить установку несмотря на это?"; then
                die "установка прервана: сначала уберите чужой почтовый сервер"
            fi
        else
            hint "пакеты остались в системе; если они не нужны:$active — apt-get purge -y$active"
        fi
        # Порт освобождается не мгновенно: дать службе доиграть остановку.
        sleep 1
    elif [ -n "$installed" ]; then
        warn "установлены пакеты почтовых служб:$installed (сейчас не запущены)"
        hint "если они вам не нужны, лучше убрать: apt-get purge -y$installed"
    else
        ok "чужих почтовых служб (postfix/exim/sendmail) не установлено"
    fi
}

# ------------------------------------------------------------------
# ensure_prereqs — инструменты, без которых нечем проверять.
# На голой Ubuntu Server нет ни curl, ни dig, а без ss не видно,
# кто занял порты.
# ------------------------------------------------------------------
ensure_prereqs() {
    local missing=()
    have curl    || missing+=(curl)
    have openssl || missing+=(openssl)
    have dig     || missing+=(dnsutils)
    have ss      || missing+=(iproute2)
    if [ "${#missing[@]}" -eq 0 ]; then
        return 0
    fi
    if ! have apt-get; then
        warn "не хватает: ${missing[*]}, а apt-get нет — поставьте вручную"
        return 0
    fi
    info "доустанавливаем: ${missing[*]}"
    DEBIAN_FRONTEND=noninteractive apt-get update -qq >/dev/null 2>&1 || true
    DEBIAN_FRONTEND=noninteractive apt-get install -y -qq "${missing[@]}" >/dev/null 2>&1 || true
}

# ------------------------------------------------------------------
# PREFLIGHT — всё, что нужно узнать о машине ДО установки.
#
# Один набор проверок на обе точки входа. Раньше он жил только в
# install.sh, и мастер первого запуска (web-install.sh) начинал сразу с
# Docker: человек, поднимающий сервер через браузер, узнавал про чужой
# Postfix, нехватку памяти и закрытый исходящий 25-й порт в лучшем
# случае потом, в худшем — не узнавал вовсе. Плюс мастер отправлял за
# установкой Docker в консольный установщик, то есть «установка одной
# командой» превращалась в две разные команды.
#
# OS_ID и VERSION_CODENAME остаются глобальными намеренно: их читает
# install_docker, когда подключает репозиторий Docker.
# ------------------------------------------------------------------
preflight_system() {
    [ "$(id -u)" -eq 0 ] && ensure_prereqs

    # --- Операционная система --------------------------------------
    OS_NAME='неизвестна'; OS_ID=''; OS_VER=''
    if [ -r /etc/os-release ]; then
        # shellcheck disable=SC1091
        . /etc/os-release
        OS_NAME="${PRETTY_NAME:-$NAME}"; OS_ID="${ID:-}"; OS_VER="${VERSION_ID:-}"
    fi
    case "$OS_ID:$OS_VER" in
        ubuntu:22.04) ok "ОС: $OS_NAME (целевая система)" ;;
        ubuntu:24.04|ubuntu:20.04|debian:12|debian:11)
            ok "ОС: $OS_NAME"
            info "проект рассчитан на Ubuntu Server 22.04, но эта система тоже подойдёт" ;;
        *)
            warn "ОС: $OS_NAME — не Ubuntu 22.04"
            hint "проверялось на Ubuntu Server 22.04; на других системах возможны сюрпризы" ;;
    esac

    # --- Архитектура -----------------------------------------------
    local arch; arch="$(uname -m)"
    case "$arch" in
        x86_64|aarch64) ok "архитектура: $arch" ;;
        *) warn "архитектура $arch — образы стека собраны под x86_64 и aarch64" ;;
    esac

    # --- Память ----------------------------------------------------
    local ram_mb=0
    if [ -r /proc/meminfo ]; then
        ram_mb=$(awk '/^MemTotal:/ {printf "%d", $2/1024}' /proc/meminfo)
    fi
    if [ "$ram_mb" -ge "$MT_MIN_RAM_MB" ]; then
        ok "память: ${ram_mb} МБ (стек в простое занимает около 310 МБ)"
    else
        warn "память: ${ram_mb} МБ — рекомендуется от ${MT_MIN_RAM_MB} МБ"
        hint "стек поднимется и на меньшем объёме, но запаса на письма и поиск не останется"
    fi

    # --- Место на диске --------------------------------------------
    local disk_gb
    disk_gb=$(df -BG --output=avail "$REPO_DIR" 2>/dev/null | tail -1 | tr -dc '0-9' || echo 0)
    disk_gb="${disk_gb:-0}"
    if [ "$disk_gb" -ge "$MT_MIN_DISK_GB" ]; then
        ok "свободно на диске: ${disk_gb} ГБ"
    else
        warn "свободно на диске: ${disk_gb} ГБ — рекомендуется от ${MT_MIN_DISK_GB} ГБ"
        hint "образы стека занимают около 1.5 ГБ, остальное — письма и индексы поиска"
    fi

    # --- Чужой MTA --------------------------------------------------
    # ДО проверки портов, а не после неё. Раньше было наоборот, и на
    # машине с системным Postfix человек сначала получал вопрос «порт 25
    # занят процессом master, всё равно продолжать?», отвечал «нет» — и
    # установка обрывалась, так и не показав, что это за «master» и что
    # с ним делать: совет печатался следующим шагом.
    handle_foreign_mta

    preflight_ports
    preflight_outbound_25
}

# preflight_ports — свободны ли порты, которые займёт стек.
preflight_ports() {
    local stack_running=0 busy=0 port listener proc ports_re
    if have docker && docker compose -f "$COMPOSE_FILE" ps -q 2>/dev/null | grep -q .; then
        stack_running=1
    fi

    if [ "${SKIP_PORT_CHECK:-0}" = "1" ]; then
        info "проверка портов пропущена (--skip-port-check)"
        return 0
    fi
    if ! have ss && ! have netstat; then
        warn "нет ни ss, ни netstat — занятость портов проверить нечем"
        return 0
    fi

    for port in "${MT_REQUIRED_PORTS[@]}"; do
        listener="$(port_listener "$port")"
        if [ -z "$listener" ]; then
            ok "порт $port свободен"
        elif [ "$stack_running" = "1" ] && printf '%s' "$listener" | grep -qi 'docker'; then
            ok "порт $port занят нашим же стеком (повторная установка)"
        else
            proc=$(printf '%s' "$listener" | sed -n 's/.*users:((\("[^"]*"\).*/\1/p' | tr -d '"')
            if [ -n "$proc" ]; then
                fail "порт $port занят процессом «$proc»"
            else
                fail "порт $port занят (имя процесса определить не удалось)"
                hint "кто именно: fuser -v $port/tcp  или  lsof -i :$port"
            fi
            busy=1
        fi
    done

    if [ "$busy" = "1" ]; then
        # Раньше здесь было только предупреждение, и установка шла дальше
        # до падения `docker compose up` с сырой ошибкой про занятый порт.
        # Спрашиваем: продолжать почти всегда бессмысленно.
        fail "часть портов занята чужими процессами — стек не сможет их открыть"
        # Список для подсказки строится из MT_REQUIRED_PORTS, а не пишется
        # руками: переписанный отдельно, он уже разошёлся с проверкой —
        # 465-й проверяли, а в подсказке его не было.
        ports_re="$(printf '%s|' "${MT_REQUIRED_PORTS[@]}")"
        hint "посмотреть кто: ss -ltnp | grep -E ':(${ports_re%|})\\b'"
        hint "освободите порты или запустите с --skip-port-check, если знаете, что делаете"
        if ! confirm "Всё равно продолжить установку (стек, скорее всего, не поднимется)?"; then
            die "установка прервана: сначала освободите занятые порты"
        fi
    fi
}

# preflight_outbound_25 — уходит ли почта наружу.
# Самая частая причина «письма не уходят»: хостер закрывает исходящий
# 25-й. Проверяем заранее, чтобы это не выяснилось через неделю.
preflight_outbound_25() {
    if [ "${SKIP_PORT_CHECK:-0}" = "1" ]; then
        info "проверка исходящего 25-го порта пропущена"
        return 0
    fi
    local mx
    for mx in gmail-smtp-in.l.google.com alt1.aspmx.l.google.com mx.yandex.ru; do
        if tcp_probe "$mx" 25 6; then
            ok "исходящий порт 25 открыт — письма смогут уходить наружу"
            return 0
        fi
    done
    if tcp_probe 1.1.1.1 443 5; then
        fail "исходящий порт 25 закрыт: соединение с чужими MX не устанавливается"
        hint "Интернет при этом работает — значит порт режет провайдер или хостер."
        hint "Это самая частая причина «почта приходит, но не уходит»."
        hint "Что делать: написать в поддержку хостинга и попросить открыть"
        hint "исходящий TCP/25 (обычно открывают после короткой переписки),"
        hint "либо настроить отправку через внешний релей (docs/install.md)."
        if ! confirm "Продолжить установку?"; then
            die "установка прервана"
        fi
    else
        warn "не удалось проверить исходящий 25-й порт: сеть недоступна вообще"
    fi
}

# ------------------------------------------------------------------
# ensure_docker — довести Docker до пригодного состояния.
# Ставит, если нет; запускает, если стоит и молчит; меняет snap-версию
# на официальную; проверяет compose и видимость каталога проекта.
# ------------------------------------------------------------------
ensure_docker() {
    ensure_docker_native

    if ! have docker; then
        info "Docker не установлен — ставим официальный"
        install_docker
    elif ! docker info >/dev/null 2>&1; then
        warn "Docker установлен, но демон не отвечает — пробуем запустить"
        have systemctl && systemctl start docker >/dev/null 2>&1 || true
    fi

    docker info >/dev/null 2>&1 ||
        die "демон Docker не отвечает — проверьте: systemctl status docker"
    ok "Docker работает ($(docker version --format '{{.Server.Version}}' 2>/dev/null))"

    local compose_ver
    compose_ver="$(docker compose version --short 2>/dev/null | tr -d 'v' || true)"
    [ -n "$compose_ver" ] || die "нет плагина docker compose (пакет docker-compose-plugin)"
    version_ge "$compose_ver" "$MT_MIN_COMPOSE" ||
        die "docker compose $compose_ver слишком старый, нужен от $MT_MIN_COMPOSE"
    ok "docker compose $compose_ver"

    require_docker_sees_repo
}

# require_root — установщику нужен root (docker, apt, порты <1024, certbot).
require_root() {
    if [ "$(id -u)" -ne 0 ]; then
        die "запускать нужно от root: sudo bash $0 $*"
    fi
}

# ------------------------------------------------------------------
# private_ip — адрес сервера в локальной сети, если он есть.
#
# Нужен резервному входу в панель: почти всегда администратор сидит в той
# же сети, и вход по адресу должен работать сразу, не открываясь при этом
# в интернет. Пусто — значит частного адреса у машины нет (обычный VPS),
# и слушать резервный вход будет только сама машина.
#
# Берётся первый частный адрес, НЕ принадлежащий Docker: у docker0 и
# сетей стека адреса тоже частные (172.17.0.1, 172.28.0.1), и повесить
# резервный вход на них означало бы «доступно только контейнерам».
# ------------------------------------------------------------------
private_ip() {
    have ip || return 0
    ip -4 -o addr show scope global 2>/dev/null |
        awk '{ print $2, $4 }' |
        grep -vE '^(docker|br-|veth|virbr)' |
        awk '{ split($2, a, "/"); print a[1] }' |
        grep -E '^(10\.|192\.168\.|172\.(1[6-9]|2[0-9]|3[01])\.)' |
        head -1 || true
}

# public_ip — внешний IPv4 сервера (по маршруту наружу, затем по сервису).
public_ip() {
    local ip=''
    if have ip; then
        # «|| true» обязателен: без маршрута наружу `ip route get` вернёт
        # единицу, pipefail протащит её в подстановку, и set -e оборвёт
        # установку молча. Пустой адрес здесь — штатный случай, ниже его
        # спрашивают у внешнего сервиса.
        ip=$(ip -4 route get 1.1.1.1 2>/dev/null | sed -n 's/.*src \([0-9.]*\).*/\1/p' | head -1 || true)
    fi
    case "$ip" in
        10.*|192.168.*|172.1[6-9].*|172.2[0-9].*|172.3[01].*|127.*|'')
            # За NAT локальный адрес бесполезен — спрашиваем снаружи
            if have curl; then
                local ext
                ext=$(curl -fsS --max-time 5 https://api.ipify.org 2>/dev/null || true)
                if [ -n "$ext" ]; then ip="$ext"; fi
            fi
            ;;
    esac
    printf '%s' "$ip"
}

# resolve_a <имя> — A-записи имени через getent/dig, по одной на строку.
resolve_a() {
    local name="$1"
    if have dig; then
        dig +short A "$name" 2>/dev/null | grep -E '^[0-9.]+$' || true
    elif have getent; then
        getent ahostsv4 "$name" 2>/dev/null | awk '{print $1}' | sort -u || true
    fi
}

# is_fqdn <имя> — грубая проверка доменного имени.
is_fqdn() {
    [[ "$1" =~ ^[a-zA-Z0-9]([a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?(\.[a-zA-Z0-9]([a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?)+$ ]]
}

# subnet_contains <подсеть вида 172.28.0.0/16> <адрес> — 0, если адрес лежит
# в подсети. Сравниваем только по маске /16 (первые два октета): именно такой
# формат у DOCKER_SUBNET, и разбирать произвольную маску тут нечем и незачем.
#
# Нужна не для красоты: подсеть стека задаётся одним ключом, а фиксированные
# адреса внутри неё — двумя другими (RESOLVER_IP, DOVECOT_IP). Поменяв только
# подсеть, человек получал отказ docker «no configured subnet contains IP
# address 172.28.0.54», где нет ни имени файла, ни имени настройки.
subnet_contains() {
    local subnet="$1" ip="$2" prefix
    prefix="${subnet%.*.*/*}"          # 172.28.0.0/16 → 172.28
    [ -n "$prefix" ] || return 1
    case "$ip" in "$prefix".*) return 0 ;; *) return 1 ;; esac
}

# is_email <адрес>
is_email() {
    [[ "$1" =~ ^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$ ]]
}

