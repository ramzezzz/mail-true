# env_get <ключ> [файл] — значение переменной из .env (пусто, если нет).
# Кавычки снимаются: значения в infra/.env могут быть записаны в них, и
# это не прихоть. Файл ИСПОЛНЯЕТСЯ (см. load_env), поэтому всё, что
# содержит пробел или знак «;», обязано быть процитировано — иначе
# «FAIL2BAN_IGNORE_IPS=1.2.3.4 5.6.7.8» роняет скрипт с кодом 127, а
# «x;команда» выполняется. Пишет так посредник (env_quoted в agent.pl);
# читателю остаётся снять обрамление.
env_get() {
    local key="$1" file="${2:-$ENV_FILE}" value
    [ -f "$file" ] || return 0
    value="$(sed -n "s/^${key}=//p" "$file" | tail -1 | tr -d '\r')"
    case "$value" in
        \'*\')
            value="${value#\'}"; value="${value%\'}"
            # Внутренняя кавычка записана приёмом «закрыть — вставить —
            # открыть»: '\''. Без обратной замены значение читалось бы с
            # этим мусором внутри, хотя bash при исполнении файла видит
            # ровно одну кавычку.
            value="$(printf '%s' "$value" | sed "s/'\\\\''/'/g")"
            ;;
        \"*\") value="${value#\"}"; value="${value%\"}" ;;
    esac
    printf '%s' "$value"
}

# env_set <ключ> <значение> [файл] — задать или заменить строку в .env.
#
# Значение с пробелом или знаком оболочки записывается В КАВЫЧКАХ, по той
# же причине, что и у посредника: файл исполняется скриптами обслуживания.
# Простые значения (домен, число, base64-секрет) остаются как были — иначе
# первая же правка расставила бы кавычки по всему файлу и разошлась бы с
# тем, что человек видит в .env.example.
env_set() {
    local key="$1" value="$2" file="${3:-$ENV_FILE}" tmp
    case "$value" in
        *[\ \;\&\|\<\>\(\)\`\$\"\']*)
            # Одиночная кавычка внутри: закрыть, вставить экранированную,
            # открыть снова — приём, понятный и bash, и docker compose.
            value="'$(printf '%s' "$value" | sed "s/'/'\\\\''/g")'"
            ;;
    esac
    tmp="$(mktemp)"
    if [ -f "$file" ] && grep -q "^${key}=" "$file"; then
        # Значение подставляем через awk, чтобы не экранировать спецсимволы sed
        awk -v k="$key" -v v="$value" '
            index($0, k "=") == 1 && !done { print k "=" v; done = 1; next }
            { print }
        ' "$file" > "$tmp"
    else
        if [ -f "$file" ]; then cat "$file" > "$tmp"; fi
        printf '%s=%s\n' "$key" "$value" >> "$tmp"
    fi
    cat "$tmp" > "$file"
    rm -f "$tmp"
    chmod 600 "$file"
}

# env_ensure <ключ> <значение по умолчанию> — задать, только если пусто.
# Это и есть идемпотентность: уже сгенерированные секреты не перезаписываются.
env_ensure() {
    local key="$1" value="$2" current
    current="$(env_get "$key")"
    if [ -z "$current" ]; then
        env_set "$key" "$value"
        return 0   # значение было создано
    fi
    return 1       # значение уже было
}

# load_env — загрузить infra/.env в окружение текущего процесса.
#
# Возврат каретки вычищается НАМЕРЕННО, и это не перестраховка.
# infra/.env.example однажды оказался сохранён с концами строк Windows
# (CRLF), а установщик копирует его в infra/.env как есть. Дальше расходятся
# два мира: docker compose свой разбор .env от «\r» чистит и контейнеры
# получают верные значения, а bash — нет. В результате POSTGRES_USER внутри
# скриптов становился «mailserver» с невидимым хвостом, и psql отвечал
# «role "mailserver" does not exist» — при полностью здоровой базе.
# Установка с нуля разваливалась целиком (миграции, домен, ящик и учётная
# запись администратора), а причина не была видна ни в одном сообщении.
#
# Сам файл при этом не трогаем: правка чужого файла ради своего удобства —
# отдельный способ удивить человека. Про CRLF в .env говорит selfcheck.sh.
load_env() {
    [ -f "$ENV_FILE" ] || die "нет файла $ENV_FILE — сначала выполните install/install.sh"
    set -a
    # shellcheck disable=SC1090,SC1091
    . <(tr -d '\r' < "$ENV_FILE")
    set +a
}

