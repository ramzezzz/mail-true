    if [ "${CLAMAV_ENABLED:-false}" = "true" ]; then
        args+=(--profile clamav)
    fi
    printf '%s\n' "${args[@]}"
}

# dc <аргументы docker compose>
dc() {
    local args=()
    mapfile -t args < <(compose_args)
    docker compose "${args[@]}" "$@"
}

# service_state <сервис> — строка вида "running healthy" / "exited".
service_state() {
    dc ps --format '{{.State}} {{.Health}}' "$1" 2>/dev/null | head -1
}

# wait_healthy <таймаут секунд> <сервисы...>
wait_healthy() {
    local timeout="$1"; shift
    local services=("$@") deadline waiting state svc
    deadline=$(( $(date +%s) + timeout ))
    while :; do
        waiting=()
        for svc in "${services[@]}"; do
            state="$(service_state "$svc")"
            # ВНИМАНИЕ: «unhealthy» содержит в себе «healthy».
            #
            # Раньше первой стояла ветка `*healthy*`, и она совпадала со
            # строкой «running unhealthy» — то есть больная служба
            # засчитывалась как готовая, а ветка `*unhealthy*` ниже была
            # недостижима. Цена: установщик писал «все сервисы здоровы»
            # при мёртвом Dovecot и шёл дальше, а самопроверка отвечала
            # «работает и здоров» на сломанном стеке.
            #
            # Поэтому «плохие» состояния проверяются ПЕРВЫМИ, и только
            # потом — «здоров».
            case "$state" in
                *unhealthy*|*starting*)  waiting+=("$svc") ;;
                *healthy*)               : ;;
                running*)                : ;;  # без пробы — считаем готовым
                *)                       waiting+=("$svc") ;;
            esac
        done
        if [ "${#waiting[@]}" -eq 0 ]; then return 0; fi
        if [ "$(date +%s)" -ge "$deadline" ]; then
            printf '  не дождались: %s\n' "${waiting[*]}" >&2
            return 1
        fi
        printf '\r     ждём готовности: %-60s' "${waiting[*]}"
        sleep 3
    done
}

# ==================================================================
# Миграции схемы
# ==================================================================
#
# ЧТО БЫЛО НЕ ТАК. Журнала применённых миграций не существовало.
# install.sh и restore.sh перебирали каталог и применяли ВСЕ файлы при
# каждом запуске, полагаясь на их идемпотентность. Пока миграция состоит
# из CREATE ... IF NOT EXISTS, это почти бесплатно; но 0008 переписывает
# историю доставки UPDATE-ом, и она выполнялась заново при каждом
# обновлении продукта — долгий блокирующий проход по таблице ради строк,
# которые уже исправлены прошлым разом.
#
# И главное: ответить на вопрос «какие миграции здесь применены» было
# нечем. Ответ добывался косвенно — «посмотрим, появилась ли таблица».
#
# Теперь ведётся таблица schema_migrations (см. миграцию 0000): имя файла,
# номер, имя, контрольная сумма и время. Применяется только то, чего в
# журнале нет либо чья контрольная сумма разошлась с файлом.
#
# ПРО КОНТРОЛЬНУЮ СУММУ. Считается по байтам файла. Смена окончаний строк
# при повторном клоне репозитория меняет сумму — тогда файл применится
# ещё раз. Это безопасно (все они идемпотентны) и лучше обратной ошибки:
# исправленный после выпуска файл обязан примениться, а не быть пропущен
# по совпадению имени.
#
# ------------------------------------------------------------------
# ПРО БАЗОВУЮ СХЕМУ (0001_baseline.sql) И КАТАЛОГ legacy/
# ------------------------------------------------------------------
# Раньше рабочий каталог состоял из 36 файлов — по одному на каждый шаг
# разработки. Теперь их два: журнал (0000) и вся схема разом
# (0001_baseline.sql). Старые файлы никуда не делись, они лежат в
# postgres/migrations/legacy/ и участвуют РОВНО в одном случае, описанном
# ниже. Подробный разбор свёртки — в шапке самой базовой схемы.
#
# Базовая схема отличается от обычной миграции тем, что её нельзя просто
# «применить, если её нет в журнале». На работающем сервере всё, что в ней
# написано, уже есть, и выполнение пятидесяти CREATE TABLE и семидесяти
# CREATE INDEX по живой базе — это блокировки каталога и минуты ожидания
# ради нулевого результата. Поэтому решение принимается по состоянию базы:
#
#   1. В журнале уже есть строка про 0001_baseline.sql — не делаем ничего.
#      Это обычный случай второго и всех последующих обновлений.
#
#   2. Строки нет, и база ПУСТА (нет таблицы virtual_users) — установка
#      с нуля: выполняем файл и записываем в журнал.
#
#   3. Строки нет, а схема в базе есть — это сервер, обновляющийся
#      с версии, где миграции ещё лежали россыпью. Здесь и нужен legacy/:
#      применяем оттуда всё, чего нет в журнале (сервер мог остановиться
#      на любом файле — хоть на 0015), и только потом отмечаем базовую
#      схему применённой БЕЗ выполнения.
#
# Пункт 3 — это ровно то поведение, что было до свёртки, и он же ответ
# на вопрос «а что будет, если сервер пропустил полгода обновлений».
# Отметить базовую схему применённой не глядя было бы короче и НЕВЕРНО:
# сервер может стоять на 0015, и такая отметка тихо пропустила бы два
# десятка настоящих миграций — то есть ровно тот отказ, ради которого
# журнал и заводился.
#
# Каталог legacy/ можно будет удалить, когда все стенды пройдут пункт 3
# хотя бы раз. После этого пункт 3 останется без лекарства: установщик
# честно скажет, что схему довести нечем, вместо того чтобы соврать
# отметкой. Postgres при первичной инициализации тома в подкаталоги не
# заходит, а сверка схемы в панели считает только верхний уровень —
# для них legacy/ не существует.

# psql_migrate <аргументы psql> — psql в контейнере базы, тихо и со
# строгой остановкой на первой ошибке.
psql_migrate() {
    dc exec -T postgres psql -v ON_ERROR_STOP=1 \
        -U "$POSTGRES_USER" -d "$POSTGRES_DB" -q "$@"
}

# Имя файла базовой схемы. Отдельной переменной, потому что правило для
# него особое (см. разбор выше) и повторяется в трёх местах.
MT_BASELINE_FILE='0001_baseline.sql'

# _mig_record <имя файла> <сумма> <кто> — отметка в журнале.
#
# ON CONFLICT нужен для случая «файл поправили после выпуска»: строка уже
# есть, но с прежней суммой.
#
# Запрос подаётся ЧЕРЕЗ stdin, а не ключом -c, и это не стиль. В аргументе
# -c psql подстановку своих переменных (:'fn') НЕ делает — строка уходит
# на сервер как есть, и Postgres отвечает «syntax error at or near ":"».
# Поймано живым прогоном: схема накатывалась, а журнал оставался пустым,
# то есть весь смысл затеи пропадал молча. Подстановка работает только
# для потока ввода и файлов, поэтому запрос идёт сюда.
_mig_record() {
    local mig_name="$1" sum="$2" who="$3" ver name
    # 0007_mail_flow.sql -> версия 0007, имя mail_flow
    ver="${mig_name%%_*}"
    name="${mig_name#*_}"; name="${name%.sql}"
    printf '%s\n' \
        "INSERT INTO schema_migrations (filename, version, name, checksum, applied_by)
         VALUES (:'fn', :'ver', :'nm', :'ck', :'who')
         ON CONFLICT (filename) DO UPDATE
            SET checksum = EXCLUDED.checksum,
                version  = EXCLUDED.version,
                name     = EXCLUDED.name,
                applied_at = now(),
                applied_by = EXCLUDED.applied_by;" |
    psql_migrate \
        -v fn="$mig_name" -v ver="$ver" -v nm="$name" \
        -v ck="$sum" -v who="$who" >/dev/null 2>"$errfile"
}

# _mig_db_has_schema — есть ли в базе схема продукта.
#
# Признак — таблица virtual_users: она появилась самой первой миграцией
# и есть на любом работающем сервере, каким бы старым он ни был. Проверять
# «пуст ли журнал» здесь нельзя: журнал завели недавно, и сервер, стоящий
# с прошлого месяца, имеет полную схему при пустом журнале.
_mig_db_has_schema() {
    local got
    got="$(dc exec -T postgres psql -U "$POSTGRES_USER" -d "$POSTGRES_DB" -qtA \
        -c "SELECT to_regclass('public.virtual_users') IS NOT NULL" 2>/dev/null |
        tr -d '\r' | tr -d '[:space:]')"
    [ "$got" = "t" ]
}

# _mig_apply_file <файл> <кто> — применить один файл, если он ещё не
# применён или изменился. Читает $known, обновляет счётчики.
_mig_apply_file() {
    local mig="$1" who="$2" mig_name sum
    mig_name="$(basename "$mig")"
    sum="$(sha256sum "$mig" | cut -d' ' -f1)"

    if printf '%s\n' "$known" | grep -qxF "$mig_name|$sum"; then
        MT_MIG_SKIPPED=$((MT_MIG_SKIPPED + 1))
        return 0
    fi

    if psql_migrate < "$mig" >/dev/null 2>"$errfile"; then
        # Запись в журнал — отдельным шагом и только после успеха.
        if _mig_record "$mig_name" "$sum" "$who"; then
            ok "миграция $mig_name применена"
        else
            # Схема применилась, а запись о ней — нет. Молчать нельзя:
            # в следующий раз файл применится снова. Это безопасно
            # (идемпотентность), но человек должен знать, почему.
            warn "миграция $mig_name применена, но не записана в журнал"
            sed -n '1,3p' "$errfile" | sed 's/^/           /'
        fi
        MT_MIG_APPLIED=$((MT_MIG_APPLIED + 1))
        return 0
    fi

    fail "миграция $mig_name не применилась"
    # Причина почти всегда в первой строке ответа psql. Раньше она
    # уходила в /dev/null, и человеку оставалось гадать.
    sed -n '1,5p' "$errfile" | sed 's/^/           /'
    MT_MIG_FAILED="$MT_MIG_FAILED $mig_name"
    return 1
}

# _mig_baseline <файл базовой схемы> <кто> — три случая из разбора выше.
_mig_baseline() {
    local mig="$1" who="$2" mig_name sum legacy before
    mig_name="$(basename "$mig")"
    sum="$(sha256sum "$mig" | cut -d' ' -f1)"

    # (1) Уже отмечена — обычное обновление, делать нечего.
    if printf '%s\n' "$known" | grep -q "^$mig_name|"; then
        MT_MIG_SKIPPED=$((MT_MIG_SKIPPED + 1))
        # Сумма разошлась с файлом — дописываем настоящую, но файл НЕ
        # выполняем. Базовая схема после выпуска не правится (об этом
        # сказано в её шапке), поэтому расхождение означает либо смену
        # окончаний строк при клоне, либо отметку, поставленную самим
        # файлом при первичной инициализации тома (там вместо суммы
        # стоит слово 'initdb').
        #
        # Правится ТОЛЬКО сумма: applied_by и applied_at остаются как
        # были. Кто и когда завёл схему — это факт, и переписывать его
        # оттого, что мы уточнили контрольную сумму, нельзя: на сервере,
        # поставленном с нуля, в журнале должно остаться честное 'initdb',
        # а не 'install.sh' от первого же обновления.
        if ! printf '%s\n' "$known" | grep -qxF "$mig_name|$sum"; then
            printf '%s\n' \
                "UPDATE schema_migrations SET checksum = :'ck' WHERE filename = :'fn';" |
                psql_migrate -v fn="$mig_name" -v ck="$sum" >/dev/null 2>"$errfile" || true
        fi
        return 0
    fi

    # (2) База пуста — обычная установка с нуля.
    if ! _mig_db_has_schema; then
        _mig_apply_file "$mig" "$who"
        return
    fi

    # (3) Схема есть, а отметки нет: сервер обновляется с версии, где
    # миграции лежали россыпью. Доводим его старыми файлами.
    legacy="$(dirname "$mig")/legacy"
    if [ -d "$legacy" ]; then
        before="$MT_MIG_APPLIED"
        for mig in "$legacy"/*.sql; do
            [ -f "$mig" ] || continue
            _mig_apply_file "$mig" "$who" || true
        done
        if [ "$MT_MIG_APPLIED" -gt "$before" ]; then
            info "сервер отставал: доведён старыми миграциями из legacy/ ($((MT_MIG_APPLIED - before)) шт.)"
        fi
        if [ -n "$MT_MIG_FAILED" ]; then
            # Отмечать базовую схему применённой, когда доезд не удался,
            # нельзя: это и есть то самое молчаливое враньё о состоянии
            # схемы, ради предотвращения которого журнал заводился.
            fail "базовая схема НЕ отмечена: сначала должны примениться старые миграции"
            return 1
        fi
    else
        warn "каталог legacy/ удалён: считаем, что схема уже полная"
        warn "если сервер пропускал обновления, проверьте схему до продолжения"
    fi

    if _mig_record "$mig_name" "$sum" "$who/marked"; then
        ok "базовая схема $mig_name отмечена применённой (в базе она уже есть)"
    else
        warn "базовую схему не удалось отметить в журнале — при следующем запуске проверка повторится"
        sed -n '1,3p' "$errfile" | sed 's/^/           /'
    fi
    return 0
}

# apply_migrations <кто> — применяет неприменённые миграции каталога.
#
# <кто> попадает в журнал в колонку applied_by: install.sh или restore.sh.
# Суффикс /marked означает «схема уже была на месте, файл не выполнялся».
# Печатает по строке на файл. Возвращает 0, если всё применилось;
# 1 — если хоть одна упала (имена — в MT_MIG_FAILED).
apply_migrations() {
    local who="${1:-install.sh}"
    local mig mig_name known errfile
    local dir="$INFRA_DIR/postgres/migrations"
    local registry="$dir/0000_schema_migrations.sql"

    MT_MIG_FAILED=''
    MT_MIG_APPLIED=0
    MT_MIG_SKIPPED=0

    errfile="$(mktemp)"

    # Сам журнал — раньше всего и всегда: применять по нему нельзя,
    # пока его нет. Файл идемпотентен, лишний прогон ничего не стоит.
    if [ -f "$registry" ]; then
        if ! psql_migrate < "$registry" >/dev/null 2>"$errfile"; then
            fail "не удалось завести журнал миграций (schema_migrations)"
            sed -n '1,5p' "$errfile" | sed 's/^/           /'
            rm -f "$errfile"
            MT_MIG_FAILED=' 0000_schema_migrations.sql'
            return 1
        fi
    fi

    # Уже применённое — одним запросом: "имя|сумма" по строке.
    known="$(dc exec -T postgres psql -U "$POSTGRES_USER" -d "$POSTGRES_DB" -qtA \
        -c "SELECT filename || '|' || checksum FROM schema_migrations" 2>/dev/null | tr -d '\r')"

    # Перебирается только верхний уровень каталога: подкаталог legacy/ —
    # архив, из которого берут файлы лишь при доезде (см. _mig_baseline).
    for mig in "$dir"/*.sql; do
        [ -f "$mig" ] || continue
        mig_name="$(basename "$mig")"

        if [ "$mig_name" = "$MT_BASELINE_FILE" ]; then
            _mig_baseline "$mig" "$who" || true
            continue
        fi

        _mig_apply_file "$mig" "$who" || true
    done

    rm -f "$errfile"

    if [ "$MT_MIG_SKIPPED" -gt 0 ]; then
        info "уже применено ранее: $MT_MIG_SKIPPED миграций (по журналу schema_migrations)"
    fi
    [ -z "$MT_MIG_FAILED" ]
}

# ------------------------------------------------------------------
# Автопродление сертификата Let's Encrypt (таймер systemd).
#
# Сертификат живёт 90 дней. Без продления почта в один день просто
# перестаёт приниматься чужими серверами, и причина («срок истёк»)
# видна только в чужих журналах.
#
# Функция общая, потому что заводить таймер приходится из двух мест:
# install/install.sh при установке из консоли и install/renew-certs.sh
# --install-timer — после установки из браузера. Веб-установщик работает
# в контейнере, а systemd живёт на хосте: изнутри контейнера таймер
# завести нечем, и это единственное, что мастер первого запуска
# договаривает словами вместо того, чтобы сделать сам.
#
# install_cert_timer <каталог install/> — 0, если таймер включён.
# ------------------------------------------------------------------
install_cert_timer() {
    local dir="$1"
    if ! have systemctl || [ ! -d /etc/systemd/system ]; then
        return 1
    fi
    # MT_RENEW_TRIGGER=timer — чтобы в отчёте о продлении было видно, ЧЕМ
    # запущен очередной прогон. Разница не косметическая: «последний раз
    # продление запускали руками месяц назад» и «таймер отработал ночью» —
    # это два разных ответа на вопрос «работает ли автопродление», и без
    # пометки они выглядят одинаково. Запасной признак (переменная
    # INVOCATION_ID, которую systemd задаёт любому своему юниту) есть в
    # самом renew-certs.sh: на серверах, где юнит завели прошлой версией
    # установщика, этой строки в файле нет.
    cat > /etc/systemd/system/mailtrue-certs.service <<EOF
[Unit]
Description=Mail.True: продление TLS-сертификата Let's Encrypt
After=docker.service

[Service]
Type=oneshot
Environment=MT_RENEW_TRIGGER=timer
ExecStart=/bin/bash $dir/renew-certs.sh
EOF
    cat > /etc/systemd/system/mailtrue-certs.timer <<'EOF'
[Unit]
Description=Mail.True: проверка срока TLS-сертификата дважды в сутки

[Timer]
OnCalendar=*-*-* 03,15:17:00
RandomizedDelaySec=30m
Persistent=true

[Install]
WantedBy=timers.target
EOF
    systemctl daemon-reload >/dev/null 2>&1 || true
    systemctl enable --now mailtrue-certs.timer >/dev/null 2>&1
}

# ==================================================================
# ОТЧЁТ О ПРОДЛЕНИИ СЕРТИФИКАТА
# ==================================================================
#
# ЧЕГО НЕ ХВАТАЛО. Сроки сертификата панель показывала и раньше — на
# дашборде и в «Наблюдении», причём честно, из живого рукопожатия. Но на
# вопрос «а продлится ли он сам» ответить было нечем: заведён ли таймер,
# когда он в последний раз отработал и чем кончил, не знал никто. Именно
# молчаливый отказ продления и приводит к истёкшему сертификату, а узнают
# о нём по тому, что срок перестал отодвигаться, — в лучшем случае за
# неделю до беды.
#
# ГДЕ ЛЕЖИТ И ПОЧЕМУ ИМЕННО ТАМ. Рядом с самим сертификатом,
# infra/data/certs/renewal.json:
#
#   * этот каталог УЖЕ примонтирован в контейнер сервера приложения на
#     чтение и запись (ради раздела «Сертификат»), поэтому панель читает
#     отчёт тем же способом, что и сертификат, — без нового монтирования,
#     без сокета Docker и без посредников;
#   * infra/data в репозиторий не входит (.gitignore), значит обновление
#     продукта — git pull, пересборка образов, docker compose up — отчёта
#     не касается. Ровно как не касается самого сертификата;
#   * потерять отчёт отдельно от сертификата невозможно: это один каталог.
#     Временный каталог (/tmp, /run) не годится по первому же перезапуску
#     машины, а install/state — по обновлению продукта из другого клона.
#
# ФОРМАТ. JSON, и его читают ДВЕ разные программы: сервер приложения (там
# есть разбор) и этот же скрипт (там разбора нет и не будет — разбирать
# JSON средствами bash значит завести третий формат в третьем месте).
# Поэтому вид файла жёсткий: каждая попытка занимает РОВНО ОДНУ строку с
# четырьмя пробелами отступа, и при следующей записи прежние строки
# переносятся в новый файл как есть, без разбора. Если файл кто-то
# поправил руками и строки перестали узнаваться — история обнулится, но
# новая запись пройдёт: потерять историю неприятно, потерять текущий
# результат — хуже.

# Имя файла отчёта и сколько попыток храним. Десять — это пять суток
# работы таймера: достаточно, чтобы увидеть «ломается каждый раз» против
# «один раз не повезло», и мало, чтобы файл оставался читаемым глазами.
RENEW_REPORT_NAME=renewal.json
RENEW_HISTORY_MAX=10

# renew_report_path — полный путь к отчёту.
renew_report_path() { printf '%s/%s' "$CERT_DIR" "$RENEW_REPORT_NAME"; }

# json_escape <строка> — значение для JSON, БЕЗ обрамляющих кавычек.
#
# Перевод строки и табуляция заменяются пробелом, а не экранируются: файл
# читается построчно (см. выше), и многострочное значение сломало бы
# ровно тот способ, которым сохраняется история. Управляющие символы
# выбрасываются. Всё остальное, включая кириллицу, проходит как есть —
# сообщения здесь по-русски.
json_escape() {
    printf '%s' "${1:-}" \
        | LC_ALL=C tr '\n\r\t' '   ' \
        | LC_ALL=C tr -d '\000-\037\177' \
        | LC_ALL=C sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'
}

# renew_time_iso <значение systemd> — время в виде 2026-08-07T15:17:00Z.
#
# systemd отдаёт временны́е свойства по-разному в зависимости от версии:
# то строкой «Fri 2026-08-07 15:17:00 UTC», то числом микросекунд от
# начала эпохи. Принимаем оба, на непонятное отвечаем пустотой — «не
# знаю» честнее выдуманной даты.
renew_time_iso() {
    local raw="${1:-}" secs
    case "$raw" in
        ''|0|'n/a'|'infinity') return 0 ;;
    esac
    if printf '%s' "$raw" | grep -qE '^[0-9]+$'; then
        secs=$(( raw / 1000000 ))
        [ "$secs" -gt 0 ] || return 0
        date -u -d "@$secs" +%Y-%m-%dT%H:%M:%SZ 2>/dev/null || true
    else
        date -u -d "$raw" +%Y-%m-%dT%H:%M:%SZ 2>/dev/null || true
    fi
}

# cert_valid_to_iso <файл сертификата> — «действует до» в ISO 8601.
cert_valid_to_iso() {
    local file="${1:-}" raw
    [ -f "$file" ] || return 0
    raw="$(openssl x509 -in "$file" -noout -enddate 2>/dev/null | sed 's/^notAfter=//')"
    [ -n "$raw" ] || return 0
    date -u -d "$raw" +%Y-%m-%dT%H:%M:%SZ 2>/dev/null || true
}

# renew_timer_json — состояние автопродления объектом JSON.
#
# Спрашивается У СИСТЕМЫ при каждой записи, а не запоминается при
# установке. Иначе отчёт врал бы ровно в том случае, ради которого он
# заведён: таймер выключили — а в файле по-прежнему «включено».
#
# Обратная сторона у этого есть, и её закрывает не отчёт, а панель:
# состояние обновляется только когда скрипт запускается. Выключенный
# таймер запускать скрипт перестаёт, поэтому «включено» в старом отчёте
# ловится не по этому полю, а по возрасту последней попытки.
renew_timer_json() {
    local unit=mailtrue-certs.timer kind=none enabled=false next='' detail=''
    if have systemctl && [ -f "/etc/systemd/system/$unit" ]; then
        kind=systemd
        local is_enabled is_active
        is_enabled="$(systemctl is-enabled "$unit" 2>/dev/null || true)"
        is_active="$(systemctl is-active "$unit" 2>/dev/null || true)"
        if [ "$is_enabled" = "enabled" ] && [ "$is_active" = "active" ]; then
            enabled=true
            detail='Таймер systemd: проверка дважды в сутки (03:17 и 15:17 плюс случайная задержка до 30 минут)'
        else
            detail="Юнит $unit на месте, но systemd показывает его как «${is_enabled:-?}/${is_active:-?}» — продление не запустится"
        fi
        next="$(renew_time_iso "$(systemctl show "$unit" -p NextElapseUSecRealtime --value 2>/dev/null || true)")"
    elif crontab -l 2>/dev/null | grep -q 'renew-certs\.sh'; then
        # Запасной путь из подсказки установщика: «systemd нет — добавьте
        # в cron». Пропустить его значило бы объявить отказом работающее
        # автопродление на машине без systemd.
        kind=cron
        enabled=true
        detail='Продление заведено в cron суперпользователя, а не в systemd'
    else
        detail='Автопродления нет: ни юнита systemd, ни записи в cron'
    fi
    printf '{"kind": "%s", "unit": "%s", "enabled": %s, "nextRunAt": "%s", "detail": "%s"}' \
        "$kind" "$unit" "$enabled" "$(json_escape "$next")" "$(json_escape "$detail")"
}

# renew_report_history — прежние попытки, по одной в строке, БЕЗ отступа
# и без запятой в конце.
#
# Отступ снимается обязательно, а не для красоты: при записи он ставится
# заново. Первая версия его оставляла, и каждый прогон добавлял четыре
# пробела — на втором записи переставали узнаваться собственным же
# фильтром, и история молча обнулялась каждый раз. Ровно тот сорт
# поломки, ради которого этот отчёт и заведён.
renew_report_history() {
    local file
    file="$(renew_report_path)"
    [ -f "$file" ] || return 0
    grep -E '^[[:space:]]*\{"at": "' "$file" 2>/dev/null \
        | sed -e 's/^[[:space:]]*//' -e 's/,[[:space:]]*$//' || true
}

# renew_report_save [строка новой попытки] — записать отчёт целиком.
# Без аргумента обновляется только состояние таймера, история остаётся.
renew_report_save() {
    # cert_source, а не source: одноимённая переменная рядом со встроенной
    # командой оболочки читается как ошибка при каждом взгляде на файл.
    local attempt="${1:-}" file tmp line cert_source i last
    file="$(renew_report_path)"
    mkdir -p "$CERT_DIR" 2>/dev/null || return 1

    local items=()
    if [ -n "$attempt" ]; then items+=("$attempt"); fi
    while IFS= read -r line; do
        [ -n "$line" ] || continue
        [ "${#items[@]}" -lt "$RENEW_HISTORY_MAX" ] || break
        items+=("$line")
    done < <(renew_report_history)

    # Наличие файла проверяется ОТДЕЛЬНО, а не глушится через 2>/dev/null.
    # Перенаправление ввода разбирается раньше, чем перенаправление вывода
    # ошибок, поэтому «No such file or directory» от отсутствующего файла
    # печатается мимо любого 2>/dev/null и попадает человеку на экран
    # посреди работы установщика. Поймано живым прогоном.
    cert_source=''
    if [ -f "$CERT_DIR/source" ]; then
        cert_source="$(tr -d '[:space:]' < "$CERT_DIR/source")"
    fi

    # Через временный файл: отчёт читает панель, и половина файла,
    # попавшая под чтение, выглядела бы как «отчёта нет» — то есть как
    # тревога на ровном месте.
    tmp="$file.new"
    {
        printf '{\n'
        printf '  "version": 1,\n'
        printf '  "updatedAt": "%s",\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
        printf '  "certSource": "%s",\n' "$(json_escape "$cert_source")"
        printf '  "timer": %s,\n' "$(renew_timer_json)"
        printf '  "attempts": [\n'
        last=$(( ${#items[@]} - 1 ))
        for i in "${!items[@]}"; do
            if [ "$i" -lt "$last" ]; then
                printf '    %s,\n' "${items[$i]}"
            else
                printf '    %s\n' "${items[$i]}"
            fi
        done
        printf '  ]\n'
        printf '}\n'
    } > "$tmp" 2>/dev/null || { rm -f "$tmp"; return 1; }

    mv -f "$tmp" "$file" 2>/dev/null || { rm -f "$tmp"; return 1; }
    # 644, а не 600: файл читает сервер приложения из контейнера, и в нём
    # нет ничего тайного — время, итог и дата окончания сертификата.
    chmod 644 "$file" 2>/dev/null || true
    return 0
}

# renew_report_write <откуда> <режим> <итог> <действует до> <секунд> <словами>
#
#   откуда — timer | manual | install
#   режим  — renew | force | deploy | timer
#   итог   — renewed | not-due | deployed | issued | failed | skipped-custom
renew_report_write() {
    local secs="${5:-0}" attempt
    case "$secs" in *[!0-9]*|'') secs=0 ;; esac
    attempt="$(printf \
        '{"at": "%s", "trigger": "%s", "mode": "%s", "outcome": "%s", "validTo": "%s", "seconds": %s, "message": "%s"}' \
        "$(date -u +%Y-%m-%dT%H:%M:%SZ)" \
        "$(json_escape "${1:-}")" "$(json_escape "${2:-}")" "$(json_escape "${3:-}")" \
        "$(json_escape "${4:-}")" "$secs" "$(json_escape "${6:-}")")"
    renew_report_save "$attempt"
}

# renew_report_refresh — обновить состояние таймера, не добавляя попытки.
renew_report_refresh() { renew_report_save ''; }

# ==================================================================
# Отметка «сервер установлен»
# ==================================================================
#
# Её ставит последним шагом install/install.sh, читает веб-установщик
# (apps/installer), снимает install/allow-reinstall.sh.
#
# Отметок две, и обе нужны. INSTALL_COMPLETED_AT лежит в infra/.env —
# то есть в каталоге проекта, который можно потерять целиком (или
# развернуть заново рядом со СТАРЫМИ томами, где лежит вся почта).
# Строка в install_state лежит в самой базе — ровно там, где живёт то,
# что переустановка способна испортить, и потерять её, не потеряв заодно
# повод для осторожности, невозможно.
#
# Правило чтения: установлено, если нашлась ЛЮБАЯ из двух. Ошибиться в
# сторону «уже установлено» дёшево (человек снимет отметку одной
# командой), в обратную — нет.

# install_mark_env — время из infra/.env или пусто.
install_mark_env() {
    env_get INSTALL_COMPLETED_AT
}

# install_mark_db — время из таблицы install_state или пусто.
# Молчит, если базы нет: отсутствие ответа — это не «не установлено»,
# а «спросить не удалось», и решает по совокупности вызывающий.
install_mark_db() {
    dc exec -T postgres psql -U "${POSTGRES_USER:-}" -d "${POSTGRES_DB:-}" -qtA \
        -c "SELECT completed_at FROM install_state WHERE id" 2>/dev/null | tr -d '\r' | head -1 || true
}

# install_mark_clear — снять обе отметки. Печатает, что именно сняла.
install_mark_clear() {
    local had_env had_db
    had_env="$(install_mark_env)"
    if [ -n "$had_env" ]; then
        env_set INSTALL_COMPLETED_AT ''
        ok "отметка в infra/.env снята (была $had_env)"
    else
        info "в infra/.env отметки не было"
    fi

    had_db="$(install_mark_db)"
    if [ -n "$had_db" ]; then
        if dc exec -T postgres psql -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$POSTGRES_DB" \
               -qtA -c "DELETE FROM install_state" >/dev/null 2>&1; then
            ok "отметка в базе снята (была $had_db)"
        else
            fail "отметку в базе снять не удалось — веб-установщик по-прежнему откажется работать"
            return 1
        fi
    else
        info "в базе отметки не было (или база не отвечает)"
    fi
    return 0
}

