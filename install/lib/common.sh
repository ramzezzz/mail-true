# compose_args — набор -f для основного файла и боевого переопределения.
compose_args() {
    local args=(-f "$COMPOSE_FILE")
    if [ -f "$COMPOSE_PROD" ] && [ "${MT_USE_PROD_OVERRIDE:-1}" = "1" ]; then
        args+=(-f "$COMPOSE_PROD")
