#!/usr/bin/env bash
# ------------------------------------------------------------------
# Снять отметку «сервер установлен».
#
#   sudo bash install/allow-reinstall.sh          # спросит подтверждение
#   sudo bash install/allow-reinstall.sh --yes    # без вопросов
#
# ------------------------------------------------------------------
# ЗАЧЕМ ОТДЕЛЬНАЯ КОМАНДА, А НЕ КНОПКА В БРАУЗЕРЕ
# ------------------------------------------------------------------
# Веб-установщик поднимается с сокетом Docker — то есть с правом
# пересоздавать контейнеры на этой машине. Закончив работу, он ставит
# отметку и отказывается запускаться снова. Отметка — единственное, что
# отделяет работающий сервер от «мастера первого запуска», прошедшего
# второй раз: тот заново сгенерировал бы пароль Postgres, а том базы
# принимает пароль только при создании — доступ к базе потеряли бы разом
# api, postfix и dovecot, причём при полностью исправной базе.
#
# Кнопка «переустановить» внутри самого установщика означала бы, что
# защиты нет вовсе: до входа он открыт всем, кто дотянулся до порта.
# Поэтому снятие отметки живёт там, куда веб-доступа нет по определению —
# в консоли сервера, у того, у кого и так есть root.
#
# Что эта команда НЕ делает: она не трогает ни письма, ни базу, ни
# infra/.env, кроме одной строки. Она только разрешает установщику
# запуститься ещё раз. Полное удаление — install/uninstall.sh.
# ------------------------------------------------------------------
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
. "$SCRIPT_DIR/lib/common.sh"

ASSUME_YES=0
case "${1:-}" in
    --yes|-y) ASSUME_YES=1 ;;
    '')       : ;;
    *)        die "неизвестный ключ: ${1:-} (допустим только --yes)" ;;
esac
[ "$ASSUME_YES" = "1" ] && MT_ASSUME_YES=1

[ -f "$ENV_FILE" ] || die "нет файла $ENV_FILE — этот сервер ещё не устанавливали"
load_env

step "Отметка «сервер установлен»"

MARK_ENV="$(install_mark_env)"
MARK_DB="$(install_mark_db)"

if [ -z "$MARK_ENV" ] && [ -z "$MARK_DB" ]; then
    ok "отметки нет ни в infra/.env, ни в базе — веб-установщик и так запустится"
    exit 0
fi

[ -n "$MARK_ENV" ] && info "infra/.env: установлен $MARK_ENV"
[ -n "$MARK_DB" ]  && info "база:       установлен $MARK_DB"

printf '\n'
printf '  Сняв отметку, вы разрешите веб-установщику пройти мастер первого\n'
printf '  запуска на ЭТОМ сервере ещё раз. Он умеет менять пароли служб —\n'
printf '  в том числе пароль Postgres, который том базы принимает только\n'
printf '  при создании. Расхождение пароля в infra/.env с паролем внутри\n'
printf '  базы выглядит так: база «здорова», а api, postfix и dovecot\n'
printf '  разом теряют доступ.\n'
printf '\n'
printf '  Делайте это, только если действительно ставите сервер заново.\n'
printf '  Перед этим полезно снять копию:  sudo bash install/backup.sh\n\n'

if ! confirm "Снять отметку «установлено»?"; then
    die "отметка оставлена на месте"
fi

install_mark_clear

printf '\n'
info "теперь установщик можно поднять снова:"
info "  docker compose -f infra/docker-compose.yml --profile installer up -d installer"
info "  docker compose -f infra/docker-compose.yml logs installer   # ключ доступа"
printf '\n'
exit 0
